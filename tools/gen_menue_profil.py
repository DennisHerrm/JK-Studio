# -*- coding: utf-8 -*-
"""Menue-Editor M5b Punkt 4: ein Mod-Profil (*.jksprofile) aus dem Quellcode einer Mod erzeugen.

Vergleicht die UI-Quellen der Mod mit denen des Grundspiels (OpenJK code/ui bzw. codemp/ui) und
schreibt, was die Mod zusaetzlich kennt:
  - itemDef/menuDef-Schluesselwoerter (itemParseKeywords/menuParseKeywords) mit der Art ihres
    Werts (aus dem ersten *_Parse-Aufruf des Handlers),
  - Ownerdraw- und Feeder-Nummern (#define UI_/CG_/FEEDER_ in menudef.h),
  - uiScripts (Q_stricmp(name, "...") in UI_RunMenuScript) mit der Zahl der Woerter, die der
    Zweig danach liest (String_Parse/Int_Parse/Float_Parse auf args),
  - Cvar-Vorgaben (cvarTable),
  - Menuelisten ("ui/....txt" in ui_main, ohne HUD-Listen).

Aufruf (nur lesen; geschrieben wird nur die Ausgabedatei):
  python tools/gen_menue_profil.py --quelle <mod> --basis <openjk> --name "Meine Mod" --spiel ja
         [--dialekt sp|mp] --aus meine_mod.jksprofile
"""
import argparse
import os
import re
import sys

ARTEN = [  # (Muster im Handler, Art) - der erste Treffer zaehlt
    # codemp: PC_*_Parse, code/ui (SP): PC_Parse*
    (r"PC_Script_Parse|Script_Parse", "script"),
    (r"PC_Rect_Parse|Rect_Parse|PC_ParseRect", "rect"),
    (r"PC_Color_Parse|Color_Parse|PC_ParseColor", "color"),
    (r"PC_Float_Parse|Float_Parse|PC_ParseFloat", "float"),
    (r"PC_Int_Parse|Int_Parse|PC_ParseInt", "int"),
    (r"PC_String_Parse|String_Parse|PC_ParseStringMem|PC_ParseString", "string"),
    (r"PC_ReadToken|trap->PC_ReadToken|trap_PC_ReadToken|COM_ParseExt", "token"),
]


def lies(pfad):
    with open(pfad, "rb") as f:
        return f.read().decode("latin-1")


def finde(wurzel, unterordner, namen):
    """Erste Datei mit einem der Namen unter wurzel/<unterordner>, sonst irgendwo unter wurzel."""
    for n in namen:
        p = os.path.join(wurzel, unterordner, n)
        if os.path.isfile(p):
            return p
    for d, _, dateien in os.walk(wurzel):
        for n in namen:
            if n in dateien:
                return os.path.join(d, n)
    return None


def schluessel(text, tabelle):
    m = re.search(tabelle + r"\s*\[\s*\]\s*=\s*\{(.*?)\n\s*\}\s*;", text, re.S)
    if not m:
        return {}
    return dict(re.findall(r'\{\s*"([A-Za-z0-9_]+)"\s*,\s*&?([A-Za-z0-9_]+)', m.group(1)))


def art(text, handler):
    """Art des ersten Werts und Zahl der gelesenen Werte (mehr als einer: von Hand pruefen)."""
    m = re.search(r"\b" + re.escape(handler) + r"\s*\([^;{]*\)\s*\{(.*?)\n\}", text, re.S)
    if not m:
        return "token", 1
    rumpf = re.sub(r"/\*.*?\*/|//[^\n]*", "", m.group(1), flags=re.S)   # auskommentierte Aufrufe zaehlen nicht
    best = None
    zahl = 0
    for muster, a in ARTEN:
        alle = list(re.finditer(muster, rumpf))
        zahl += len(alle)
        if alle and (best is None or alle[0].start() < best[0]):
            best = (alle[0].start(), a)
    return (best[1] if best else "none"), zahl


def defines(text, vorsilbe):
    return {n: int(w, 0) for n, w in re.findall(r"#define\s+(" + vorsilbe + r"[A-Z0-9_]+)\s+(0x[0-9a-fA-F]+|\d+)\b", text)}


def uiskripte(text):
    treffer = list(re.finditer(r'Q_stricmp\s*\(\s*name\s*,\s*"([^"]+)"\s*\)\s*==\s*0', text))
    v = {}
    for i, t in enumerate(treffer):
        ende = treffer[i + 1].start() if i + 1 < len(treffer) else len(text)
        stueck = text[t.end():ende]
        v.setdefault(t.group(1), len(re.findall(r"\b(?:String_Parse|Int_Parse|Float_Parse)\s*\(\s*args", stueck)))
    return v


def cvars(text):
    return dict(re.findall(r'\{\s*&\w+\s*,\s*"([^"]+)"\s*,\s*"([^"]*)"', text))


def menuelisten(text):
    v = []
    for n in re.findall(r'"(ui/[A-Za-z0-9_\-]+\.txt)"', text):
        if "hud" not in n.lower() and n not in v:
            v.append(n)
    return v


def wert(s):
    if s and not re.search(r'[\s"\\]', s):
        return s
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def profil(quelle, basis, name, spiel, dialekt):
    ordner = "codemp/ui" if dialekt == "mp" else "code/ui"
    shared = [n for n in (["ui_shared.c", "ui_shared.cpp"] if dialekt == "mp" else ["ui_shared.cpp", "ui_shared.c"])]
    main = ["ui_main.c", "ui_main.cpp"] if dialekt == "mp" else ["ui_main.cpp", "ui_main.c"]
    texte = {}
    for wer, wurzel in (("mod", quelle), ("basis", basis)):
        t = {}
        for art_, namen in (("shared", shared), ("main", main), ("menudef", ["menudef.h"])):
            p = finde(wurzel, ordner, namen)
            t[art_] = lies(p) if p else ""
        texte[wer] = t
    mod, bas = texte["mod"], texte["basis"]
    if not mod["shared"]:
        sys.exit("ui_shared der Mod nicht gefunden unter " + quelle)
    z = ["// JK Studio mod profile, generated by tools/gen_menue_profil.py from the mod's source", "jksprofile 1",
         "name " + wert(name), "game " + spiel]
    for n in menuelisten(mod["main"]) or menuelisten(mod["shared"]):
        z.append("menulist %s %s" % (dialekt, wert(n)))
    for tab, kenn in (("itemParseKeywords", "itemkey"), ("menuParseKeywords", "menukey")):
        alt = {k.lower() for k in schluessel(bas["shared"], tab)}
        for k, h in sorted(schluessel(mod["shared"], tab).items()):
            if k.lower() not in alt:
                a, zahl = art(mod["shared"], h)
                if zahl > 1:
                    z.append("// %s (%s) reads %d values - the profile keeps the first kind; check by hand" % (k, h, zahl))
                z.append("%s %s %s" % (kenn, k, a))
    for vorsilbe, kenn in (("(?:UI_|CG_)", "ownerdraw"), ("FEEDER_", "feeder")):
        alt = defines(bas["menudef"], vorsilbe)
        for n, w in sorted(defines(mod["menudef"], vorsilbe).items(), key=lambda x: x[1]):
            if n not in alt:
                z.append("%s %d %s" % (kenn, w, n))
    alt = {k.lower() for k in uiskripte(bas["main"])}
    for n, w in sorted(uiskripte(mod["main"]).items()):
        if n.lower() not in alt:
            z.append("uiscript %s %d" % (wert(n), w))
    alt = cvars(bas["main"])
    for n, w in sorted(cvars(mod["main"]).items()):
        if n not in alt:
            z.append("cvar %s %s" % (wert(n), wert(w)))
    return "\n".join(z) + "\n"


def main():
    a = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    a.add_argument("--quelle", required=True)
    a.add_argument("--basis", required=True)
    a.add_argument("--name", required=True)
    a.add_argument("--spiel", default="ja", choices=["ja", "jk2", "md"])
    a.add_argument("--dialekt", default="sp", choices=["sp", "mp"])
    a.add_argument("--aus", required=True)
    o = a.parse_args()
    t = profil(o.quelle, o.basis, o.name, o.spiel, o.dialekt)
    with open(o.aus, "w", encoding="utf-8", newline="\n") as f:
        f.write(t)
    print("%s: %d Zeilen" % (o.aus, t.count("\n")))


if __name__ == "__main__":
    main()
