std::string affect(const std::string& zeilen) {
    return "affect ( \"held\", /*@AFFECT_TYPE*/ FLUSH )\r\n{\r\n"
           "\tset ( /*@SET_TYPES*/ \"SET_BEHAVIOR_STATE\", \"BS_CINEMATIC\" );\r\n" +
           zeilen + "}\r\n\r\n";
}
std::string halten(const std::string& anim) {
    return "\tset ( /*@SET_TYPES*/ \"SET_ANIM_BOTH\", \"" + anim + "\" );\r\n"
           "\tset ( /*@SET_TYPES*/ \"SET_ANIM_HOLDTIME_BOTH\", -1 );\r\n";
}
