// Die Randkanten einer Dreiecksgruppe zu einem Ring; false, wenn sie keinen einfachen Ring bilden.
bool ringAus(const Netz& nz, const std::vector<int>& dreiecke, std::vector<int>& kantenFolge) {
    std::vector<char> inGruppe(uz(nz.dreiecke()), 0);
    for (const int d : dreiecke) { inGruppe[uz(d)] = 1; }
    std::vector<int> rand;
    for (const int d : dreiecke) {
        for (int k = d * 3; k < d * 3 + 3; ++k) {
            const int g = nz.kanten[uz(k)].gegen;
            if (g < 0 || inGruppe[uz(g / 3)] == 0) { rand.push_back(k); }
        }
    }
    if (rand.size() < 3U) { return false; }
    std::unordered_map<int, int> vonPunkt;   // Anfangspunkt -> Kante
    for (const int k : rand) {
        if (!vonPunkt.emplace(nz.kanten[uz(k)].punkt, k).second) { return false; }   // Punkt zweimal am Rand
    }
    kantenFolge.clear();
    int k = rand[0];
    for (std::size_t s = 0; s < rand.size(); ++s) {
        kantenFolge.push_back(k);
        const int naechsterPunkt = nz.kanten[uz(nz.kanten[uz(k)].naechste)].punkt;
        const auto it = vonPunkt.find(naechsterPunkt);
        if (it == vonPunkt.end()) { return false; }
        k = it->second;
    }
    return k == rand[0] && kantenFolge.size() == rand.size();
}

