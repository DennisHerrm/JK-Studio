void polyZurueck(const PolyNetz& n, Inhalt& in) {
    for (std::size_t t = 0; t < in.teile.size() && t < n.teilBeruehrt.size(); ++t) {
        if (n.teilBeruehrt[t] == 0) { continue; }
        Teil& teil = in.teile[t];
        if (teil.istTag()) { continue; }
        if (teil.stufen.size() <= uz(n.stufe)) { teil.stufen.resize(uz(n.stufe) + 1U); }
        Netz alt = teil.stufen[uz(n.stufe)];
        // Punkte des Teils in der Reihenfolge des Netzes
        std::unordered_map<int, int> lokal;
        for (std::size_t p = 0; p < n.punkte.size(); ++p) {
            if (n.punkte[p].teil == zi(t) && !n.punkte[p].weg) { lokal.emplace(zi(p), zi(lokal.size())); }
        }
        std::vector<Ecke> ecken;
        std::vector<int> punktVon;
        std::vector<std::vector<int>> eckenAmPunkt(lokal.size());
        std::vector<std::uint32_t> idx;
        std::vector<int> polyVon;
        int poly = 0;
        for (const PFlaeche& f : n.flaechen) {
            if (f.weg || f.teil != zi(t) || f.ecken.size() < 3U) { continue; }
            std::vector<std::uint32_t> eNr(f.ecken.size());
            for (std::size_t i = 0; i < f.ecken.size(); ++i) {
                const auto it = lokal.find(f.ecken[i].punkt);
                if (it == lokal.end()) { continue; }
                Ecke e = f.ecken[i].e;
                std::memcpy(e.ort, n.punkte[uz(f.ecken[i].punkt)].ort, sizeof e.ort);
                int nr = -1;
                for (const int c : eckenAmPunkt[uz(it->second)]) {
                    if (eckeGleich(ecken[uz(c)], e)) {
                        nr = c;
                        break;
                    }
                }
                if (nr < 0) {
                    nr = zi(ecken.size());
                    ecken.push_back(e);
                    punktVon.push_back(it->second);
                    eckenAmPunkt[uz(it->second)].push_back(nr);
                }
                eNr[i] = static_cast<std::uint32_t>(nr);
            }
            const std::vector<std::array<int, 3>> dr = dreieckeGueltig(f) ? f.dreiecke : teilenVieleck(n, f);
            for (const auto& d : dr) {
                for (const int j : d) { idx.push_back(eNr[uz(j)]); }
                polyVon.push_back(poly);
            }
            ++poly;
        }
        Netz neu;
        neu.aufbauen(std::move(ecken), idx, punktVon);
        neu.polyVon = std::move(polyVon);
        // was nicht zur Geometrie gehoert, bleibt (Knochenverweise der Datei; die UV-Marken passen nicht mehr)
        neu.dateiRefs = alt.dateiRefs;
        neu.dateiRefsAufgeloest = alt.dateiRefsAufgeloest;
        teil.stufen[uz(n.stufe)] = std::move(neu);
    }
    ++in.netzStand;
}

