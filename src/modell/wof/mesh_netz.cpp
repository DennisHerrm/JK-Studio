V newell(const PolyNetz& n, const PFlaeche& f) {
    V s;
    const int k = zi(f.ecken.size());
    for (int i = 0; i < k; ++i) {
        const V a = ort(n, f.ecken[uz(i)].punkt);
        const V b = ort(n, f.ecken[uz((i + 1) % k)].punkt);
        s.x += (a.y - b.y) * (a.z + b.z);
        s.y += (a.z - b.z) * (a.x + b.x);
        s.z += (a.x - b.x) * (a.y + b.y);
    }
    return s;
}

V mitte(const PolyNetz& n, const PFlaeche& f) {
    V s;
    for (const PEcke& e : f.ecken) { s = s + ort(n, e.punkt); }
    return f.ecken.empty() ? s : s * (1.0 / static_cast<double>(f.ecken.size()));
}

int eckeMit(const PFlaeche& f, int punkt) {
    for (std::size_t i = 0; i < f.ecken.size(); ++i) {
        if (f.ecken[i].punkt == punkt) { return zi(i); }
    }
    return -1;
}

int neuerPunkt(PolyNetz& n, V o, int teil) {
    PPunkt p;
    vNach(o, p.ort);
    p.teil = teil;
    n.punkte.push_back(p);
    return zi(n.punkte.size()) - 1;
}

Ecke mischen(const Ecke& a, const Ecke& b, double t) {
    Ecke e = a;
    const float tf = static_cast<float>(t);
    for (int k = 0; k < 2; ++k) { e.uv[k] = a.uv[k] + (b.uv[k] - a.uv[k]) * tf; }
    V nn{a.normale[0] + (b.normale[0] - a.normale[0]) * t, a.normale[1] + (b.normale[1] - a.normale[1]) * t,
         a.normale[2] + (b.normale[2] - a.normale[2]) * t};
    nn = einheit(nn);
    vNach(nn, e.normale);
    // WL BlendInfluences: die Einfluesse beider gewichtet zusammen, die vier groessten (iMAX_G2_BONEWEIGHTS_PER_VERT),
    // Summe wieder 1
    std::map<int, double> w;
    for (int k = 0; k < 4; ++k) {
        if (a.gewicht[k] > 0.0F) { w[a.knochen[k]] += a.gewicht[k] * (1.0 - t); }
        if (b.gewicht[k] > 0.0F) { w[b.knochen[k]] += b.gewicht[k] * t; }
    }
    std::vector<std::pair<double, int>> l;
    for (const auto& [kn, g] : w) {
        if (g > 0.0) { l.emplace_back(g, kn); }
    }
    std::stable_sort(l.begin(), l.end(), [](const auto& x, const auto& y) { return x.first > y.first; });
    if (l.size() > 4U) { l.resize(4U); }
    double sum = 0.0;
    for (const auto& x : l) { sum += x.first; }
    for (int k = 0; k < 4; ++k) {
        e.knochen[k] = 0;
        e.gewicht[k] = 0.0F;
    }
    for (std::size_t k = 0; k < l.size(); ++k) {
        e.knochen[k] = static_cast<std::uint8_t>(l[k].second);
        e.gewicht[k] = sum > 0.0 ? static_cast<float>(l[k].first / sum) : 0.0F;
    }
    if (l.empty()) { e.gewicht[0] = 1.0F; }   // starr wie eine .md3 (ausMd3: Knochen 0, Gewicht 1)
    e.ausDatei = false;
    e.dateiPack = 0;
    std::memset(e.dateiGewicht, 0, sizeof e.dateiGewicht);
    e.dateiIndex = -1;
    return e;
}

bool eckeGleich(const Ecke& a, const Ecke& b) {
    return std::memcmp(a.normale, b.normale, sizeof a.normale) == 0 && std::memcmp(a.uv, b.uv, sizeof a.uv) == 0 &&
           std::memcmp(a.knochen, b.knochen, sizeof a.knochen) == 0 && std::memcmp(a.gewicht, b.gewicht, sizeof a.gewicht) == 0 &&
           a.dateiPack == b.dateiPack && std::memcmp(a.dateiGewicht, b.dateiGewicht, sizeof a.dateiGewicht) == 0 && a.ausDatei == b.ausDatei &&
           a.dateiIndex == b.dateiIndex;
}

