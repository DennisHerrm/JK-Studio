UvAbbild uvAbbild(const PolyNetz& n, const PFlaeche& f) {
    UvAbbild a;
    const int k = zi(f.ecken.size());
    if (k < 3) { return a; }
    // die drei Ecken mit der groessten Flaeche (gut gestellt)
    int bi = 0, bj = 1, bk = 2;
    double best = -1.0;
    for (int i = 0; i < k; ++i) {
        for (int j = i + 1; j < k; ++j) {
            for (int m = j + 1; m < k; ++m) {
                const double fl = laenge(kreuz(ort(n, f.ecken[uz(j)].punkt) - ort(n, f.ecken[uz(i)].punkt), ort(n, f.ecken[uz(m)].punkt) - ort(n, f.ecken[uz(i)].punkt)));
                if (fl > best) {
                    best = fl;
                    bi = i;
                    bj = j;
                    bk = m;
                }
            }
            if (k > 12) { break; }   // grosse Vielecke: der Faecher von i reicht
        }
    }
    if (!(best > 1e-12)) { return a; }
    const V p0 = ort(n, f.ecken[uz(bi)].punkt), p1 = ort(n, f.ecken[uz(bj)].punkt), p2 = ort(n, f.ecken[uz(bk)].punkt);
    a.o = p0;
    a.u = einheit(p1 - p0);
    a.v = einheit(kreuz(kreuz(a.u, p2 - p0), a.u));
    const double s1 = punkt(p1 - p0, a.u), t1 = punkt(p1 - p0, a.v);
    const double s2 = punkt(p2 - p0, a.u), t2 = punkt(p2 - p0, a.v);
    const double det = s1 * t2 - s2 * t1;
    if (std::abs(det) < 1e-12) { return a; }
    for (int c = 0; c < 2; ++c) {
        const double u0 = f.ecken[uz(bi)].e.uv[c], u1 = f.ecken[uz(bj)].e.uv[c], u2 = f.ecken[uz(bk)].e.uv[c];
        // uv = u0 + A s + B t mit (s1,t1) -> u1-u0, (s2,t2) -> u2-u0
        const double A = ((u1 - u0) * t2 - (u2 - u0) * t1) / det;
        const double B = ((u2 - u0) * s1 - (u1 - u0) * s2) / det;
        a.m[c][0] = A;
        a.m[c][1] = B;
        a.m[c][2] = u0;
    }
    a.gut = true;
    return a;
}

void uvBei(const UvAbbild& a, V o, float uv[2]) {
    const double s = punkt(o - a.o, a.u), t = punkt(o - a.o, a.v);
    for (int c = 0; c < 2; ++c) { uv[c] = static_cast<float>(a.m[c][0] * s + a.m[c][1] * t + a.m[c][2]); }
}

