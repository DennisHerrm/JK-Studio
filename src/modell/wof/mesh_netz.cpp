void betragAnwenden(PolyNetz& n, const Plan& p, float betrag) {
    const double b = std::clamp(static_cast<double>(betrag), static_cast<double>(p.betragMin), static_cast<double>(p.betragMax));
    for (const Bewegung& m : p.bewegungen) {
        if (m.punkt < 0 || uz(m.punkt) >= n.punkte.size()) { continue; }
        for (int k = 0; k < 3; ++k) { n.punkte[uz(m.punkt)].ort[k] = static_cast<float>(m.basis[k] + b * m.richtung[k]); }
        if (uz(m.punkt) < n.punktFlaechen.size()) {
            for (const int f : n.punktFlaechen[uz(m.punkt)]) {
                n.flaechen[uz(f)].neu = true;
                n.beruehren(n.flaechen[uz(f)].teil);
            }
        }
    }
    for (const UvBewegung& u : p.uvBewegungen) {
        if (u.flaeche < 0 || uz(u.flaeche) >= n.flaechen.size()) { continue; }
        PFlaeche& f = n.flaechen[uz(u.flaeche)];
        const int e = u.punkt >= 0 ? eckeMit(f, u.punkt) : u.ecke;
        if (e < 0 || uz(e) >= f.ecken.size()) { continue; }
        for (int k = 0; k < 2; ++k) { f.ecken[uz(e)].e.uv[k] = static_cast<float>(u.basis[k] + b * u.richtung[k]); }
    }
}

void normalenNeu(PolyNetz& n, float knickGrad) {
    if (n.punktFlaechen.size() != n.punkte.size()) { n.kantenBauen(); }
    const double knick = static_cast<double>(knickGrad) * 3.14159265358979323846 / 180.0;
    std::vector<V> fn(n.flaechen.size());
    for (std::size_t f = 0; f < n.flaechen.size(); ++f) {
        if (!n.flaechen[f].weg) { fn[f] = einheit(newell(n, n.flaechen[f]) * -1.0); }   // aussen: gegen Newell (Uhrzeigersinn)
    }
    std::vector<char> punktNeu(n.punkte.size(), 0);
    for (const PFlaeche& f : n.flaechen) {
        if (f.weg || !f.neu) { continue; }
        for (const PEcke& e : f.ecken) { punktNeu[uz(e.punkt)] = 1; }
    }
    for (std::size_t fi = 0; fi < n.flaechen.size(); ++fi) {
        PFlaeche& f = n.flaechen[fi];
        if (f.weg) { continue; }
        const int k = zi(f.ecken.size());
        for (int i = 0; i < k; ++i) {
            const int p = f.ecken[uz(i)].punkt;
            if (punktNeu[uz(p)] == 0) { continue; }
            // gemittelt ueber die Vielecke am Punkt, deren Normale hoechstens `knick` abweicht, gewichtet nach dem Winkel
            // der Ecke (WL FinishTool re-shade; Kanten ueber kDefaultShadingAngle sind hart)
            V s;
            for (const int gi : n.punktFlaechen[uz(p)]) {
                const PFlaeche& g = n.flaechen[uz(gi)];
                if (winkel(fn[fi], fn[uz(gi)]) > knick + 1e-9) { continue; }
                const int j = eckeMit(g, p);
                const V a = ort(n, punktVon(g, j - 1)) - ort(n, p);
                const V b = ort(n, punktVon(g, j + 1)) - ort(n, p);
                s = s + fn[uz(gi)] * winkel(a, b);
            }
            if (laenge(s) <= 0.0) { s = fn[fi]; }
            vNach(einheit(s), f.ecken[uz(i)].e.normale);
            n.beruehren(f.teil);
        }
        f.neu = false;
    }
}

