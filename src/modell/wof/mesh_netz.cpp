// Ohrenschneiden in der Ebene des Vielecks (die Ecken im Uhrzeigersinn von aussen; die Ebene nach -Newell)
std::vector<std::array<int, 3>> mi::teilenVieleck(const PolyNetz& n, const PFlaeche& f) {
    std::vector<std::array<int, 3>> out;
    const int k = zi(f.ecken.size());
    if (k < 3) { return out; }
    if (k == 3) { return {{0, 1, 2}}; }
    const V nn = einheit(newell(n, f));
    V ax = std::abs(nn.x) < 0.9 ? V{1, 0, 0} : V{0, 1, 0};
    const V u = einheit(kreuz(nn, ax));
    const V v = kreuz(nn, u);
    std::vector<std::array<double, 2>> p(uz(k));
    for (int i = 0; i < k; ++i) {
        const V o = ort(n, f.ecken[uz(i)].punkt);
        p[uz(i)] = {punkt(o, u), punkt(o, v)};
    }
    const auto kreuz2 = [&](int a, int b, int c) {
        return (p[uz(b)][0] - p[uz(a)][0]) * (p[uz(c)][1] - p[uz(a)][1]) - (p[uz(b)][1] - p[uz(a)][1]) * (p[uz(c)][0] - p[uz(a)][0]);
    };
    std::vector<int> rest(uz(k));
    for (int i = 0; i < k; ++i) { rest[uz(i)] = i; }
    int schutz = k * k;
    while (rest.size() > 3U && schutz-- > 0) {
        bool geschnitten = false;
        const int m = zi(rest.size());
        for (int i = 0; i < m; ++i) {
            const int a = rest[uz((i + m - 1) % m)], b = rest[uz(i)], c = rest[uz((i + 1) % m)];
            if (kreuz2(a, b, c) <= 0.0) { continue; }   // nicht konvex (Newell gegen den Uhrzeiger in u,v)
            bool leer = true;
            for (int j = 0; j < m && leer; ++j) {
                const int q = rest[uz(j)];
                if (q == a || q == b || q == c) { continue; }
                leer = !(kreuz2(a, b, q) > 0.0 && kreuz2(b, c, q) > 0.0 && kreuz2(c, a, q) > 0.0);
            }
            if (!leer) { continue; }
            out.push_back({a, b, c});
            rest.erase(rest.begin() + i);
            geschnitten = true;
            break;
        }
        if (!geschnitten) {   // entartet: Faecher
            for (std::size_t i = 1; i + 1 < rest.size(); ++i) { out.push_back({rest[0], rest[i], rest[i + 1]}); }
            return out;
        }
    }
    if (rest.size() == 3U) { out.push_back({rest[0], rest[1], rest[2]}); }
    return out;
}

