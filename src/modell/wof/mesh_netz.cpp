int eckenNachZurueck(const PolyNetz& n, int teil) {
    std::unordered_map<int, std::vector<const Ecke*>> am;
    int z = 0;
    for (const PFlaeche& f : n.flaechen) {
        if (f.weg || f.teil != teil) { continue; }
        for (const PEcke& c : f.ecken) {
            auto& l = am[c.punkt];
            bool da = false;
            for (const Ecke* e : l) { da = da || eckeGleich(*e, c.e); }
            if (!da) {
                l.push_back(&c.e);
                ++z;
            }
        }
    }
    return z;
}

std::vector<TeilGrenze> grenzenPruefen(const Inhalt& in, int stufe) {
    std::vector<TeilGrenze> out;
    for (std::size_t t = 0; t < in.teile.size(); ++t) {
        const Teil& teil = in.teile[t];
        TeilGrenze g;
        g.teil = zi(t);
        // MAX_QPATH 64 (q_shared.h): Name und Shader stehen in char[64] mit der Null (mdxmSurfHierarchy_t, md3Surface_t)
        g.nameZuLang = teil.name.size() >= 64U;
        g.shaderZuLang = teil.shader.size() >= 64U;
        if (uz(stufe) < teil.stufen.size()) { g.mass = mass(teil.stufen[uz(stufe)]); }
        // Ein Tag ist genau ein Dreieck: G2_ProcessSurfaceBolt liest die ersten drei Ecken (G2_surfaces.cpp)
        if (teil.istTag()) {
            for (const Netz& nz : teil.stufen) { g.tagKeinDreieck = g.tagKeinDreieck || nz.dreiecke() != 1; }
        }
        out.push_back(g);
    }
    return out;
}

void stufenAngleichen(Inhalt& in, int von) {
    for (Teil& t : in.teile) {
        if (uz(von) >= t.stufen.size()) { continue; }
        for (std::size_t s = 0; s < t.stufen.size(); ++s) {
            if (zi(s) != von) { t.stufen[s] = t.stufen[uz(von)]; }
        }
    }
    ++in.netzStand;
}

