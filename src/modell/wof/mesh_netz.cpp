std::pair<int, int> kantenPaar(int a, int b) { return {std::min(a, b), std::max(a, b)}; }

void PAuswahl::sortieren() {
    std::sort(punkte.begin(), punkte.end());
    punkte.erase(std::unique(punkte.begin(), punkte.end()), punkte.end());
    for (auto& k : kanten) { k = kantenPaar(k.first, k.second); }
    std::sort(kanten.begin(), kanten.end());
    kanten.erase(std::unique(kanten.begin(), kanten.end()), kanten.end());
    std::sort(flaechen.begin(), flaechen.end());
    flaechen.erase(std::unique(flaechen.begin(), flaechen.end()), flaechen.end());
}

std::vector<std::pair<int, int>> randSchleife(const PolyNetz& n, int kante) {
    std::vector<std::pair<int, int>> out;
    if (!n.istRand(kante)) { return out; }
    // WL GrowBorder: alle Randkanten, die ueber gemeinsame Punkte an der Kante haengen
    std::vector<char> drin(n.kanten.size(), 0);
    std::vector<int> offen = {kante};
    drin[uz(kante)] = 1;
    while (!offen.empty()) {
        const int k = offen.back();
        offen.pop_back();
        out.emplace_back(n.kanten[uz(k)].a, n.kanten[uz(k)].b);
        for (const int p : {n.kanten[uz(k)].a, n.kanten[uz(k)].b}) {
            for (const int fi : n.punktFlaechen[uz(p)]) {
                const PFlaeche& f = n.flaechen[uz(fi)];
                const int i = eckeMit(f, p);
                for (const int j : {i, i - 1}) {
                    const int ka = n.kanteVon(punktVon(f, j), punktVon(f, j + 1));
                    if (ka >= 0 && drin[uz(ka)] == 0 && n.istRand(ka)) {
                        drin[uz(ka)] = 1;
                        offen.push_back(ka);
                    }
                }
            }
        }
    }
    std::sort(out.begin(), out.end());
    return out;
}

std::vector<int> element(const PolyNetz& n, int flaeche) {
    std::vector<int> out;
    if (flaeche < 0 || uz(flaeche) >= n.flaechen.size() || n.flaechen[uz(flaeche)].weg) { return out; }
    std::vector<char> drin(n.flaechen.size(), 0);
    std::vector<int> offen = {flaeche};
    drin[uz(flaeche)] = 1;
    while (!offen.empty()) {
        const int fi = offen.back();
        offen.pop_back();
        out.push_back(fi);
        const PFlaeche& f = n.flaechen[uz(fi)];
        for (int i = 0; i < zi(f.ecken.size()); ++i) {
            const int k = n.kanteVon(punktVon(f, i), punktVon(f, i + 1));
            if (k < 0) { continue; }
            for (const auto& [g, gi] : n.kanten[uz(k)].seiten) {
                (void)gi;
                if (drin[uz(g)] == 0) {
                    drin[uz(g)] = 1;
                    offen.push_back(g);
                }
            }
        }
    }
    std::sort(out.begin(), out.end());
    return out;
}

std::vector<int> kantenRing(const PolyNetz& n, int kante) {
    // WL SelectRing / Max Ring: ueber jedes Viereck zur gegenueberliegenden Kante, in beide Richtungen
    std::vector<int> out;
    if (kante < 0 || uz(kante) >= n.kanten.size()) { return out; }
    std::vector<char> drin(n.kanten.size(), 0);
    drin[uz(kante)] = 1;
    out.push_back(kante);
    for (const auto& start : n.kanten[uz(kante)].seiten) {
        auto [fi, i] = start;
        while (true) {
            const PFlaeche& f = n.flaechen[uz(fi)];
            if (f.ecken.size() != 4U) { break; }
            const int g = n.kanteVon(punktVon(f, i + 2), punktVon(f, i + 3));
            if (g < 0 || drin[uz(g)] != 0) { break; }
            drin[uz(g)] = 1;
            out.push_back(g);
            // weiter auf die andere Seite von g
            const auto& s = n.kanten[uz(g)].seiten;
            int naechste = -1;
            int ni = -1;
            for (const auto& [h, hi] : s) {
                if (h != fi) {
                    naechste = h;
                    ni = hi;
                }
            }
            if (naechste < 0) { break; }
            fi = naechste;
            i = ni;
        }
    }
    return out;
}

std::vector<int> kantenSchleife(const PolyNetz& n, int kante) {
    // WL SelectLoop / Max Loop: an Punkten mit vier Kanten (Vierecke) geradeaus weiter
    std::vector<int> out;
    if (kante < 0 || uz(kante) >= n.kanten.size()) { return out; }
    std::vector<char> drin(n.kanten.size(), 0);
    drin[uz(kante)] = 1;
    out.push_back(kante);
    for (int richtung = 0; richtung < 2; ++richtung) {
        int k = kante;
        int p = richtung == 0 ? n.kanten[uz(kante)].b : n.kanten[uz(kante)].a;
        while (true) {
            const auto& fl = n.punktFlaechen[uz(p)];
            if (fl.size() != 4U) { break; }
            // die Kante gegenueber: teilt mit k kein Vieleck
            std::vector<int> ks;
            for (const int fi : fl) {
                const PFlaeche& f = n.flaechen[uz(fi)];
                if (f.ecken.size() != 4U) {
                    ks.clear();
                    break;
                }
                const int i = eckeMit(f, p);
                for (const int j : {i, i - 1}) {
                    const int kk = n.kanteVon(punktVon(f, j), punktVon(f, j + 1));
                    if (kk >= 0 && std::find(ks.begin(), ks.end(), kk) == ks.end()) { ks.push_back(kk); }
                }
            }
            if (ks.size() != 4U) { break; }
            int weiter = -1;
            for (const int kk : ks) {
                if (kk == k) { continue; }
                bool teilt = false;
                for (const auto& [f1, i1] : n.kanten[uz(kk)].seiten) {
                    (void)i1;
                    for (const auto& [f2, i2] : n.kanten[uz(k)].seiten) {
                        (void)i2;
                        teilt = teilt || f1 == f2;
                    }
                }
                if (!teilt) { weiter = kk; }
            }
            if (weiter < 0 || drin[uz(weiter)] != 0) { break; }
            drin[uz(weiter)] = 1;
            out.push_back(weiter);
            p = n.kanten[uz(weiter)].a == p ? n.kanten[uz(weiter)].b : n.kanten[uz(weiter)].a;
            k = weiter;
        }
    }
    return out;
}

std::vector<int> auswahlPunkte(const PolyNetz& n, const PAuswahl& a) {
    std::vector<int> p = a.punkte;
    for (const auto& k : a.kanten) {
        p.push_back(k.first);
        p.push_back(k.second);
    }
    for (const int f : a.flaechen) {
        if (f < 0 || uz(f) >= n.flaechen.size()) { continue; }
        for (const PEcke& e : n.flaechen[uz(f)].ecken) { p.push_back(e.punkt); }
    }
    std::sort(p.begin(), p.end());
    p.erase(std::unique(p.begin(), p.end()), p.end());
    return p;
}

