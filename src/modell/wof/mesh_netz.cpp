bool dreieckeGueltig(const PFlaeche& f) {
    if (f.dreiecke.size() + 2U != f.ecken.size()) { return false; }
    for (const auto& d : f.dreiecke) {
        for (const int i : d) {
            if (i < 0 || uz(i) >= f.ecken.size()) { return false; }
        }
    }
    return true;
}

