PolyNetz polyAus(const Inhalt& in, int stufe) {
    PolyNetz n;
    n.stufe = stufe;
    n.teilBeruehrt.assign(in.teile.size(), 0);
    n.teilPunkte.assign(in.teile.size(), 0);
    n.flaecheVonDreieck.assign(in.teile.size(), {});
    for (std::size_t t = 0; t < in.teile.size(); ++t) {
        const Teil& teil = in.teile[t];
        n.teilPunkte[t] = zi(n.punkte.size());
        if (teil.istTag() || uz(stufe) >= teil.stufen.size()) { continue; }
        const Netz& nz = teil.stufen[uz(stufe)];
        const int basis = zi(n.punkte.size());
        n.punkte.resize(n.punkte.size() + uz(nz.punktZahl));
        for (std::size_t e = 0; e < nz.ecken.size(); ++e) {
            PPunkt& p = n.punkte[uz(basis + nz.punktVon[e])];
            std::memcpy(p.ort, nz.ecken[e].ort, sizeof p.ort);
        }
        for (int p = basis; p < zi(n.punkte.size()); ++p) { n.punkte[uz(p)].teil = zi(t); }
        n.punktEcke.resize(n.punkte.size(), {-1, -1});
        for (std::size_t e = nz.ecken.size(); e-- > 0;) { n.punktEcke[uz(basis + nz.punktVon[e])] = {zi(t), zi(e)}; }
        n.flaecheVonDreieck[t].assign(uz(nz.dreiecke()), -1);
        // Gruppen: Netz::polyVon (in der Reihenfolge des ersten Dreiecks), sonst jedes Dreieck
        const int dz = nz.dreiecke();
        const bool mitPoly = nz.polyVon.size() == uz(dz);
        std::vector<std::vector<int>> gruppen;
        if (mitPoly) {
            std::unordered_map<int, int> nr;
            for (int d = 0; d < dz; ++d) {
                const auto [it, neu] = nr.emplace(nz.polyVon[uz(d)], zi(gruppen.size()));
                if (neu) { gruppen.emplace_back(); }
                gruppen[uz(it->second)].push_back(d);
            }
        } else {
            for (int d = 0; d < dz; ++d) { gruppen.push_back({d}); }
        }
        const auto dreieckAlsFlaeche = [&](int d) {
            PFlaeche f;
            f.teil = zi(t);
            for (int k = d * 3; k < d * 3 + 3; ++k) {
                PEcke c;
                c.punkt = basis + nz.kanten[uz(k)].punkt;
                c.e = nz.ecken[uz(nz.kanten[uz(k)].ecke)];
                f.ecken.push_back(c);
            }
            f.dreiecke.push_back({0, 1, 2});
            n.flaecheVonDreieck[t][uz(d)] = zi(n.flaechen.size());
            n.flaechen.push_back(std::move(f));
        };
        for (const std::vector<int>& g : gruppen) {
            std::vector<int> ring;
            if (g.size() == 1U || !ringAus(nz, g, ring)) {
                for (const int d : g) { dreieckAlsFlaeche(d); }
                continue;
            }
            PFlaeche f;
            f.teil = zi(t);
            std::unordered_map<int, int> eckeVonPunkt;
            for (const int k : ring) {
                PEcke c;
                c.punkt = basis + nz.kanten[uz(k)].punkt;
                c.e = nz.ecken[uz(nz.kanten[uz(k)].ecke)];
                eckeVonPunkt[nz.kanten[uz(k)].punkt] = zi(f.ecken.size());
                f.ecken.push_back(c);
            }
            bool ok = true;
            for (const int d : g) {
                std::array<int, 3> tri{};
                for (int j = 0; j < 3; ++j) {
                    const auto it = eckeVonPunkt.find(nz.kanten[uz(d * 3 + j)].punkt);
                    if (it == eckeVonPunkt.end()) {
                        ok = false;
                        break;
                    }
                    tri[uz(j)] = it->second;
                }
                if (!ok) { break; }
                f.dreiecke.push_back(tri);
            }
            if (!ok || f.dreiecke.size() + 2U != f.ecken.size()) {   // Punkte innen: kein einfaches Vieleck
                for (const int d : g) { dreieckAlsFlaeche(d); }
                continue;
            }
            for (const int d : g) { n.flaecheVonDreieck[t][uz(d)] = zi(n.flaechen.size()); }
            n.flaechen.push_back(std::move(f));
        }
    }
    n.kantenBauen();
    return n;
}

