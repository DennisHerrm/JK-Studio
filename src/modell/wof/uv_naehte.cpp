constexpr float kUnendlich = std::numeric_limits<float>::max();

bool istKante(const UvNetz& n, int h) {
    const int g = n.gegen[uz(h)];
    return g < 0 || h < g;
}

V3 kantenNormale(const UvNetz& n, int h) {
    V3 s = n.normale[uz(h)];
    if (const int g = n.gegen[uz(h)]; g >= 0) { s = s + n.normale[uz(g)]; }
    const float l = laenge(s);
    return l > 0.0F ? s * (1.0F / l) : V3{};
}

float kantenKosten(float l, V3 normale, const NahtWegOptionen& o) {
    const float zu = punkt(normale, o.sichtbar);
    return l * (1.0F + o.verdecktGewicht * std::clamp(0.5F + 0.5F * zu, 0.0F, 1.0F));
}

struct Schritt {
    int nach = -1;
    int kante = -1;
    float laenge = 0.0F;
    float kosten = 0.0F;
};

struct Graph {
    std::vector<std::vector<Schritt>> schritte;
    std::vector<int> punkte;
};

Graph graphVon(const UvNetz& n, const std::vector<int>& kanten, const NahtWegOptionen& o) {
    Graph g;
    g.schritte.resize(n.ort.size());
    for (const int h : kanten) {
        const int a = n.von[uz(h)];
        const int b = n.nach(h);
        if (a == b) { continue; }
        const float l = laenge(n.ort[uz(b)] - n.ort[uz(a)]);
        const float k = kantenKosten(l, kantenNormale(n, h), o);
        g.schritte[uz(a)].push_back(Schritt{b, h, l, k});
        g.schritte[uz(b)].push_back(Schritt{a, h, l, k});
        g.punkte.push_back(a);
        g.punkte.push_back(b);
    }
    g.punkte = sortiert(std::move(g.punkte));
    return g;
}

// Dijkstra (WL walkRegion; mit Ziel = FindSeamPath)
void laufen(const Graph& g, const std::vector<int>& starts, bool nachKosten, std::vector<float>& beste, std::vector<int>& kamVon, std::vector<int>& kamUeber,
            const std::vector<u8>* ziel, int* erreicht) {
    beste.assign(g.schritte.size(), kUnendlich);
    kamVon.assign(g.schritte.size(), -1);
    kamUeber.assign(g.schritte.size(), -1);
    std::vector<std::pair<float, int>> schlange;
    const auto billiger = [](const std::pair<float, int>& a, const std::pair<float, int>& b) { return a.first != b.first ? a.first > b.first : a.second > b.second; };
    for (const int s : starts) {
        if (beste[uz(s)] != 0.0F) {
            beste[uz(s)] = 0.0F;
            schlange.emplace_back(0.0F, s);
        }
    }
    std::make_heap(schlange.begin(), schlange.end(), billiger);
    if (erreicht != nullptr) { *erreicht = -1; }
    while (!schlange.empty()) {
        std::pop_heap(schlange.begin(), schlange.end(), billiger);
        const auto [kosten, p] = schlange.back();
        schlange.pop_back();
        if (kosten > beste[uz(p)]) { continue; }
        if (ziel != nullptr && (*ziel)[uz(p)] != 0) {
            *erreicht = p;
            return;
        }
        for (const Schritt& s : g.schritte[uz(p)]) {
            const float weiter = kosten + (nachKosten ? s.kosten : s.laenge);
            if (weiter >= beste[uz(s.nach)]) { continue; }
            beste[uz(s.nach)] = weiter;
            kamVon[uz(s.nach)] = p;
            kamUeber[uz(s.nach)] = s.kante;
            schlange.emplace_back(weiter, s.nach);
            std::push_heap(schlange.begin(), schlange.end(), billiger);
        }
    }
}

int fernster(const Graph& g, const std::vector<float>& beste) {
    int aus = -1;
    float weit = -1.0F;
    for (const int p : g.punkte) {
        if (beste[uz(p)] != kUnendlich && beste[uz(p)] > weit) {
            weit = beste[uz(p)];
            aus = p;
        }
    }
    return aus;
}

std::vector<int> wegZurueck(int bis, const std::vector<int>& kamVon, const std::vector<int>& kamUeber) {
    std::vector<int> aus;
    for (int p = bis; kamVon[uz(p)] >= 0; p = kamVon[uz(p)]) { aus.push_back(kamUeber[uz(p)]); }
    std::reverse(aus.begin(), aus.end());
    return aus;
}

std::vector<int> kantenDerDreiecke(const UvNetz& n, std::span<const int> dreiecke) {
    std::vector<int> aus;
    for (const int d : dreiecke) {
        for (int k = 0; k < 3; ++k) {
            const int h = d * 3 + k;
            const int g = n.gegen[uz(h)];
            aus.push_back(g >= 0 ? std::min(h, g) : h);
        }
    }
    return sortiert(std::move(aus));
}

