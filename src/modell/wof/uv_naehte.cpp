NahtWeg nahtWeg(const UvNetz& n, int vonKante, int nachKante, const NahtWegOptionen& o) {
    NahtWeg aus;
    if (vonKante < 0 || nachKante < 0 || vonKante >= n.kanten() || nachKante >= n.kanten()) {
        aus.gestoppt = true;
        return aus;
    }
    std::vector<int> alle;
    for (int h = 0; h < n.kanten(); ++h) {
        if (istKante(n, h)) { alle.push_back(h); }
    }
    const Graph g = graphVon(n, alle, o);
    std::vector<u8> ziel(n.ort.size(), 0);
    ziel[uz(n.von[uz(nachKante)])] = 1;
    ziel[uz(n.nach(nachKante))] = 1;
    std::vector<float> beste;
    std::vector<int> kamVon;
    std::vector<int> kamUeber;
    int erreicht = -1;
    laufen(g, {n.nach(vonKante)}, true, beste, kamVon, kamUeber, &ziel, &erreicht);
    if (erreicht < 0) {
        aus.gestoppt = true;
        return aus;
    }
    aus.kanten = wegZurueck(erreicht, kamVon, kamUeber);
    return aus;
}

NahtWeg schliessendeNaht(const UvNetz& n, std::span<const int> dreiecke, const NahtWegOptionen& o) {
    NahtWeg aus;
    aus.gestoppt = true;
    if (dreiecke.empty()) { return aus; }
    const Graph g = graphVon(n, kantenDerDreiecke(n, dreiecke), o);
    if (g.punkte.size() < 2U) { return aus; }
    std::vector<float> beste;
    std::vector<int> kamVon;
    std::vector<int> kamUeber;
    // die zwei geodaetisch fernsten Punkte, dann der billigste Weg zwischen ihnen um die verdeckte Seite
    laufen(g, {g.punkte.front()}, false, beste, kamVon, kamUeber, nullptr, nullptr);
    const int von = fernster(g, beste);
    if (von < 0) { return aus; }
    laufen(g, {von}, false, beste, kamVon, kamUeber, nullptr, nullptr);
    const int bis = fernster(g, beste);
    if (bis < 0 || von == bis) { return aus; }
    laufen(g, {von}, true, beste, kamVon, kamUeber, nullptr, nullptr);
    aus.kanten = wegZurueck(bis, kamVon, kamUeber);
    aus.gestoppt = aus.kanten.empty();
    return aus;
}

NahtWeg ringNaht(const UvNetz& n, const UvInseln& in, int insel, const NahtWegOptionen& o) {
    NahtWeg aus;
    aus.gestoppt = true;
    if (insel < 0 || insel >= in.zahl) { return aus; }
    struct Schleife {
        std::vector<int> punkte;
        float laenge = 0.0F;
    };
    std::vector<Schleife> schl;
    const std::span<const int> rand = in.randVon(insel);
    for (std::size_t start = 0; start < rand.size();) {
        Schleife s;
        const int erster = n.von[uz(rand[start])];
        std::size_t k = start;
        for (; k < rand.size(); ++k) {
            const int h = rand[k];
            s.punkte.push_back(n.von[uz(h)]);
            s.laenge += laenge(n.ort[uz(n.nach(h))] - n.ortVon(h));
            if (n.nach(h) == erster) { break; }
        }
        schl.push_back(std::move(s));
        start = k + 1;
    }
    if (schl.size() < 2U) { return aus; }
    std::sort(schl.begin(), schl.end(), [](const Schleife& a, const Schleife& b) { return a.laenge > b.laenge; });
    std::vector<int> d(in.dreieckeVon(insel).begin(), in.dreieckeVon(insel).end());
    const Graph g = graphVon(n, kantenDerDreiecke(n, d), o);
    std::vector<u8> ziel(n.ort.size(), 0);
    for (const int p : schl[1].punkte) { ziel[uz(p)] = 1; }
    std::vector<float> beste;
    std::vector<int> kamVon;
    std::vector<int> kamUeber;
    int erreicht = -1;
    laufen(g, schl[0].punkte, true, beste, kamVon, kamUeber, &ziel, &erreicht);
    if (erreicht < 0) { return aus; }
    aus.kanten = wegZurueck(erreicht, kamVon, kamUeber);
    aus.gestoppt = aus.kanten.empty();
    return aus;
}

std::vector<int> knochenFaltung(const std::vector<Rolle>& rollen, const std::vector<int>& eltern, bool* glieder) {
    // Die Rollen von WL (record.h RigRole) fuer die eigenen: Upper (Ober-), Lower (Unter-), End (Hand, Fuss) halten an;
    // Twist, Pad, Hock, Toe, Neck, Clavicle, None und eine Wirbel-Kette fallen in ihren Elternknochen (WL foldOf).
    enum class Wl : std::uint8_t { None, Body, Spine, Neck, Head, Clavicle, Upper, Lower, End, Toe, Twist, Prop };
    const auto wl = [&](int k) {
        if (k < 0 || uz(k) >= rollen.size()) { return Wl::None; }
        switch (rollen[uz(k)]) {
            case Rolle::Becken: return Wl::Body;
            case Rolle::Wirbel: return Wl::Spine;
            case Rolle::Hals: return Wl::Neck;
            case Rolle::Kopf: return Wl::Head;
            case Rolle::Schluessel: return Wl::Clavicle;
            case Rolle::Oberarm:
            case Rolle::Oberschenkel: return Wl::Upper;
            case Rolle::Unterarm:
            case Rolle::Unterschenkel: return Wl::Lower;
            case Rolle::Hand:
            case Rolle::Fuss: return Wl::End;
            case Rolle::Zehen: return Wl::Toe;
            case Rolle::OberarmTwist:
            case Rolle::UnterarmTwist:
            case Rolle::OberschenkelTwist: return Wl::Twist;
            case Rolle::Sonstige: return Wl::Prop;
            case Rolle::Keine:
            case Rolle::Wurzel:
            case Rolle::Bewegung:
            case Rolle::Gesicht:
            case Rolle::Finger:
            case Rolle::Anhang:
            case Rolle::TagKnochen: break;
        }
        return Wl::None;
    };
    const int zahl = static_cast<int>(std::max(rollen.size(), eltern.size()));
    const auto elternVon = [&](int k) { return k >= 0 && uz(k) < eltern.size() ? eltern[uz(k)] : -1; };
    std::vector<int> aus(uz(zahl), -1);
    bool irgend = false;
    for (int k = 0; k < zahl; ++k) {
        int lauf = k;
        for (int wache = 0; wache < 64; ++wache) {
            const Wl r = wl(lauf);
            if (r == Wl::Upper || r == Wl::Lower || r == Wl::End) {
                irgend = true;
                break;
            }
            const int e = elternVon(lauf);
            const bool reitet = r == Wl::Twist || r == Wl::Toe || r == Wl::Neck || r == Wl::Clavicle || r == Wl::None ||
                                (r == Wl::Spine && e >= 0 && e < zahl && wl(e) == Wl::Spine);
            if (!reitet || e < 0 || e >= zahl || e == lauf) { break; }
            lauf = e;
        }
        aus[uz(k)] = lauf;
    }
    if (glieder != nullptr) { *glieder = irgend; }
    return aus;
}

SkelettNaehte naehteAusSkelett(UvNetz& n, std::span<const int> dreiecke, const std::vector<int>& faltung, std::span<const int> spiegel, V3 vorn) {
    SkelettNaehte aus;
    std::vector<u8> drin(uz(n.dreiecke()), dreiecke.empty() ? 1 : 0);
    for (const int d : dreiecke) { drin[uz(d)] = 1; }
    std::vector<int> teilVon(uz(n.dreiecke()), -1);
    std::vector<int> teile;
    for (int d = 0; d < n.dreiecke(); ++d) {
        // der staerkste Knochen der drei Ecken (WL: forVertex ueber die Ecken der Flaeche)
        int knochen = -1;
        float gewicht = 0.0F;
        for (int k = 0; k < 3; ++k) {
            const int h = d * 3 + k;
            for (int j = 0; j < 4; ++j) {
                if (n.gewicht[uz(h)][uz(j)] > gewicht) {
                    gewicht = n.gewicht[uz(h)][uz(j)];
                    knochen = n.knochen[uz(h)][uz(j)];
                }
            }
        }
        const int t = knochen >= 0 && uz(knochen) < faltung.size() ? faltung[uz(knochen)] : -1;
        teilVon[uz(d)] = t;
        if (t >= 0 && drin[uz(d)] != 0) { teile.push_back(t); }
    }
    teile = sortiert(std::move(teile));
    aus.teile = static_cast<int>(teile.size());
    std::vector<int> schn;
    double verdeckt = 0.0;
    double gesamt = 0.0;
    for (int h = 0; h < n.kanten(); ++h) {
        const int g = n.gegen[uz(h)];
        if (g < 0 || h > g || drin[uz(h / 3)] == 0 || drin[uz(g / 3)] == 0) { continue; }
        if (teilVon[uz(h / 3)] == teilVon[uz(g / 3)]) { continue; }
        schn.push_back(h);
        const float l = laenge(n.ort[uz(n.nach(h))] - n.ortVon(h));
        gesamt += l;
        if (punkt(kantenNormale(n, h), vorn) <= 0.0F) { verdeckt += l; }
    }
    markieren(n, schn, true);
    NahtWegOptionen o;
    o.sichtbar = vorn;
    const std::vector<int> grenze0 = schn;
    for (const int t : teile) {
        std::vector<int> rand;
        for (const int h : grenze0) {
            const int g = n.gegen[uz(h)];
            if (teilVon[uz(h / 3)] == t || (g >= 0 && teilVon[uz(g / 3)] == t)) { rand.push_back(h); }
        }
        if (rand.size() < 2U) { continue; }
        int vonK = rand.front();
        int bisK = rand.back();
        float beste = -1.0F;
        for (std::size_t i = 0; i < rand.size(); ++i) {
            const V3 pi = n.ortVon(rand[i]);
            for (std::size_t j = i + 1; j < rand.size(); ++j) {
                const float d = laenge(n.ortVon(rand[j]) - pi);
                if (d > beste) {
                    beste = d;
                    vonK = rand[i];
                    bisK = rand[j];
                }
            }
        }
        const NahtWeg w = nahtWeg(n, vonK, bisK, o);
        if (w.gestoppt || w.kanten.empty()) { continue; }
        markieren(n, w.kanten, true);
        for (const int h : w.kanten) {
            const float l = laenge(n.ort[uz(n.nach(h))] - n.ortVon(h));
            gesamt += l;
            if (punkt(kantenNormale(n, h), vorn) <= 0.0F) { verdeckt += l; }
            schn.push_back(h);
        }
    }
    aus.schnitte = static_cast<int>(schn.size()) + spiegelMarken(n, spiegel);
    aus.verdecktAnteil = gesamt > 0.0 ? static_cast<float>(verdeckt / gesamt) : 0.0F;
    return aus;
}

int spiegelMarken(UvNetz& n, std::span<const int> spiegel) {
    if (spiegel.empty()) { return 0; }
    std::map<std::pair<int, int>, int> kanteVon;   // (Punkt a, Punkt b) gerichtet -> Halbkante
    for (int h = 0; h < n.kanten(); ++h) { kanteVon.emplace(std::make_pair(n.von[uz(h)], n.nach(h)), h); }
    std::vector<int> dazu;
    for (int h = 0; h < n.kanten(); ++h) {
        if (n.naht[uz(h)] == 0 || !istKante(n, h)) { continue; }
        const int a = n.von[uz(h)];
        const int b = n.nach(h);
        if (uz(a) >= spiegel.size() || uz(b) >= spiegel.size() || spiegel[uz(a)] < 0 || spiegel[uz(b)] < 0) { continue; }
        auto it = kanteVon.find({spiegel[uz(a)], spiegel[uz(b)]});
        if (it == kanteVon.end()) { it = kanteVon.find({spiegel[uz(b)], spiegel[uz(a)]}); }
        if (it == kanteVon.end()) { continue; }
        if (n.naht[uz(it->second)] == 0) { dazu.push_back(it->second); }
    }
    dazu = sortiert(std::move(dazu));
    markieren(n, dazu, true);
    return static_cast<int>(dazu.size());
}

int naehteNachWinkel(UvNetz& n, std::span<const int> dreiecke, float grad) {
    std::vector<u8> drin(uz(n.dreiecke()), dreiecke.empty() ? 1 : 0);
    for (const int d : dreiecke) { drin[uz(d)] = 1; }
    const auto normaleVon = [&](int d) {
        const V3 nn = kreuz(n.ortVon(d * 3 + 1) - n.ortVon(d * 3), n.ortVon(d * 3 + 2) - n.ortVon(d * 3));
        const float l = laenge(nn);
        return l > 0.0F ? nn * (1.0F / l) : V3{};
    };
    const float grenze = grad * 0.01745329252F;
    std::vector<int> schn;
    for (int h = 0; h < n.kanten(); ++h) {
        const int g = n.gegen[uz(h)];
        if (g < 0 || h > g || (drin[uz(h / 3)] == 0 && drin[uz(g / 3)] == 0)) { continue; }
        const float c = std::clamp(punkt(normaleVon(h / 3), normaleVon(g / 3)), -1.0F, 1.0F);
        if (std::acos(c) > grenze) { schn.push_back(h); }
    }
    markieren(n, schn, true);
    return static_cast<int>(schn.size());
}

std::vector<int> punktSpiegel(const UvNetz& n, float toleranz) {
    std::vector<int> aus(n.ort.size(), -1);
    const float zelle = std::max(toleranz, 1e-4F);
    using Schl = std::tuple<long, long, long>;
    std::multimap<Schl, int> raster;
    const auto schl = [&](float x, float y, float z) {
        return Schl{std::lround(std::floor(x / zelle)), std::lround(std::floor(y / zelle)), std::lround(std::floor(z / zelle))};
    };
    for (std::size_t p = 0; p < n.ort.size(); ++p) { raster.emplace(schl(n.ort[p].x, n.ort[p].y, n.ort[p].z), static_cast<int>(p)); }
    // Ein Punkt liegt in genau einem Teil; liegen Punkte zweier Teile am selben Ort (die Naht zwischen Kopf und Hals),
    // gewinnt bei gleichem Abstand der Punkt im eigenen Teil - ueber Teile hinweg (linker und rechter Arm) gilt der Ort.
    std::vector<int> teilVon(n.ort.size(), -1);
    for (int h = 0; h < n.kanten(); ++h) { teilVon[uz(n.von[uz(h)])] = n.teil[uz(h)]; }
    for (std::size_t p = 0; p < n.ort.size(); ++p) {
        const V3 z{-n.ort[p].x, n.ort[p].y, n.ort[p].z};
        const Schl s = schl(z.x, z.y, z.z);
        float beste = toleranz * toleranz;
        bool eigenes = false;
        for (long dx = -1; dx <= 1; ++dx) {
            for (long dy = -1; dy <= 1; ++dy) {
                for (long dz = -1; dz <= 1; ++dz) {
                    const auto b = raster.equal_range(Schl{std::get<0>(s) + dx, std::get<1>(s) + dy, std::get<2>(s) + dz});
                    for (auto it = b.first; it != b.second; ++it) {
                        const V3 q = n.ort[uz(it->second)];
                        const float d = punkt(q - z, q - z);
                        const bool gleich = teilVon[uz(it->second)] == teilVon[p];
                        if (d < beste || (d == beste && (gleich || !eigenes) && aus[p] >= 0) || (d <= beste && aus[p] < 0)) {
                            beste = d;
                            aus[p] = it->second;
                            eigenes = gleich;
                        }
                    }
                }
            }
        }
    }
    return aus;
}

