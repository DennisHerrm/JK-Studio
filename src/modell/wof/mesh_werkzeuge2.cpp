Plan symmetrisieren(PolyNetz& n, const SymmetrieParam& sp, const std::vector<int>& teile) {
    Plan p;
    n.kantenBauen();
    const int ax = std::clamp(sp.achse, 0, 2);
    const double vz = sp.vonPlus ? 1.0 : -1.0;
    const double eps = std::max(static_cast<double>(weldSchwelleVorgabe(n)), 1e-6);
    const auto imTeil = [&](int t) { return teile.empty() || std::find(teile.begin(), teile.end(), t) != teile.end(); };
    const auto c = [&](int pt) { return static_cast<double>(n.punkte[uz(pt)].ort[ax]) * vz; };
    bool quelle = false;
    for (const PFlaeche& f : n.flaechen) {
        if (f.weg || !imTeil(f.teil)) { continue; }
        for (const PEcke& e : f.ecken) { quelle = quelle || c(e.punkt) > eps; }
    }
    if (!quelle) {
        p.grund = Ablehnung::KeineQuelle;
        return p;
    }
    // 1. Kanten, die die Ebene kreuzen, an der Ebene teilen
    std::vector<std::pair<int, int>> kreuzt;
    for (const PKante& k : n.kanten) {
        if (!imTeil(n.punkte[uz(k.a)].teil)) { continue; }
        const double ca = c(k.a), cb = c(k.b);
        if ((ca > eps && cb < -eps) || (ca < -eps && cb > eps)) { kreuzt.emplace_back(k.a, k.b); }
    }
    for (const auto& [a, b] : kreuzt) {
        const double ca = c(a), cb = c(b);
        const double t = ca / (ca - cb);
        V o = ort(n, a) + (ort(n, b) - ort(n, a)) * t;
        if (ax == 0) { o.x = 0.0; }
        if (ax == 1) { o.y = 0.0; }
        if (ax == 2) { o.z = 0.0; }
        const int q = neuerPunkt(n, o, n.punkte[uz(a)].teil);
        // wie inKanteEinsetzen (Teil A), hier ohne UV-Bewegung
        n.kantenBauen();
        for (const int fi : std::vector<int>(n.punktFlaechen[uz(a)])) {
            PFlaeche& f = n.flaechen[uz(fi)];
            const int i = eckeMit(f, a);
            const int kk = zi(f.ecken.size());
            if (punktVon(f, i + 1) == b) {
                PEcke e{q, mischen(f.ecken[uz(i)].e, f.ecken[uz((i + 1) % kk)].e, t)};
                f.ecken.insert(f.ecken.begin() + i + 1, e);
                flaecheGeaendert(f);
            } else if (punktVon(f, i - 1) == b) {
                const int j = (i + kk - 1) % kk;
                PEcke e{q, mischen(f.ecken[uz(i)].e, f.ecken[uz(j)].e, t)};
                f.ecken.insert(f.ecken.begin() + i, e);
                flaecheGeaendert(f);
            }
        }
    }
    n.kantenBauen();
    // 2. Vielecke mit Punkten auf beiden Seiten an zwei Ebenen-Punkten teilen
    for (std::size_t fi = 0; fi < n.flaechen.size(); ++fi) {
        if (n.flaechen[fi].weg || !imTeil(n.flaechen[fi].teil)) { continue; }
        bool plus = false, minus = false;
        std::vector<int> auf;
        for (std::size_t i = 0; i < n.flaechen[fi].ecken.size(); ++i) {
            const double v = c(n.flaechen[fi].ecken[i].punkt);
            plus = plus || v > eps;
            minus = minus || v < -eps;
            if (std::abs(v) <= eps) { auf.push_back(zi(i)); }
        }
        if (!plus || !minus || auf.size() < 2U) { continue; }
        PFlaeche& f = n.flaechen[fi];
        const int kk = zi(f.ecken.size());
        const int i = auf[0], j = auf[1];
        if ((i + 1) % kk == j || (j + 1) % kk == i) { continue; }
        std::vector<PEcke> a1, a2;
        for (int x = i;; x = (x + 1) % kk) {
            a1.push_back(f.ecken[uz(x)]);
            if (x == j) { break; }
        }
        for (int x = j;; x = (x + 1) % kk) {
            a2.push_back(f.ecken[uz(x)]);
            if (x == i) { break; }
        }
        const int teil = f.teil;
        f.ecken = std::move(a1);
        flaecheGeaendert(f);
        (void)neueFlaeche(n, std::move(a2), teil);
    }
    // 3. die Gegenseite weg, Ebenen-Punkte genau auf die Ebene
    for (PFlaeche& f : n.flaechen) {
        if (f.weg || !imTeil(f.teil)) { continue; }
        for (const PEcke& e : f.ecken) {
            if (c(e.punkt) < -eps) {
                f.weg = true;
                n.beruehren(f.teil);
                break;
            }
        }
    }
    for (PPunkt& pt : n.punkte) {
        if (!pt.weg && imTeil(pt.teil) && std::abs(static_cast<double>(pt.ort[ax])) <= eps) { pt.ort[ax] = 0.0F; }
    }
    // 4. die Quellseite gespiegelt (Umlauf umgedreht, Normale gespiegelt, UV gleich, Knochen ueber den Spiegel)
    std::map<int, int> spiegel;
    const std::size_t alt = n.flaechen.size();
    for (std::size_t fi = 0; fi < alt; ++fi) {
        if (n.flaechen[fi].weg || !imTeil(n.flaechen[fi].teil)) { continue; }
        bool aufEbene = true;
        for (const PEcke& e : n.flaechen[fi].ecken) { aufEbene = aufEbene && n.punkte[uz(e.punkt)].ort[ax] == 0.0F; }
        if (aufEbene) { continue; }
        std::vector<PEcke> m;
        for (auto it = n.flaechen[fi].ecken.rbegin(); it != n.flaechen[fi].ecken.rend(); ++it) {
            PEcke e = *it;
            if (n.punkte[uz(e.punkt)].ort[ax] != 0.0F) {
                auto sp2 = spiegel.find(e.punkt);
                if (sp2 == spiegel.end()) {
                    V o = ort(n, e.punkt);
                    if (ax == 0) { o.x = -o.x; }
                    if (ax == 1) { o.y = -o.y; }
                    if (ax == 2) { o.z = -o.z; }
                    sp2 = spiegel.emplace(e.punkt, neuerPunkt(n, o, n.punkte[uz(e.punkt)].teil)).first;
                }
                e.punkt = sp2->second;
            }
            e.e.normale[ax] = -e.e.normale[ax];
            for (int k = 0; k < 4; ++k) {
                if (uz(e.e.knochen[k]) < sp.knochenSpiegel.size() && sp.knochenSpiegel[uz(e.e.knochen[k])] >= 0) {
                    e.e.knochen[k] = static_cast<std::uint8_t>(sp.knochenSpiegel[uz(e.e.knochen[k])]);
                }
            }
            e.e.dateiIndex = -1;
            e.e.ausDatei = false;
            m.push_back(e);
        }
        (void)neueFlaeche(n, std::move(m), n.flaechen[fi].teil);
        ++p.geaendert;
    }
    for (PFlaeche& f : n.flaechen) {
        if (!f.weg && imTeil(f.teil)) { n.beruehren(f.teil); }
    }
    fertig(n, p);
    return p;
}

