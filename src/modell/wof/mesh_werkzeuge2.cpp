Plan zuVierecken(PolyNetz& n, const std::vector<int>& flaechen, const QuadParam& qp) {
    Plan p;
    n.kantenBauen();
    std::vector<char> gewollt(n.flaechen.size(), flaechen.empty() ? 1 : 0);
    for (const int f : flaechen) {
        if (f >= 0 && uz(f) < n.flaechen.size()) { gewollt[uz(f)] = 1; }
    }
    const double fw = static_cast<double>(qp.flaechenWinkel) * kPi / 180.0;
    const double sw = static_cast<double>(qp.formWinkel) * kPi / 180.0;
    struct Kandidat {
        double kosten;
        int kante;
    };
    std::vector<Kandidat> ks;
    for (std::size_t e = 0; e < n.kanten.size(); ++e) {
        const PKante& k = n.kanten[e];
        if (k.seiten.size() != 2U) { continue; }
        const auto [fa, ia] = k.seiten[0];
        const auto [fb, ib] = k.seiten[1];
        const PFlaeche& A = n.flaechen[uz(fa)];
        const PFlaeche& B = n.flaechen[uz(fb)];
        if (fa == fb || gewollt[uz(fa)] == 0 || gewollt[uz(fb)] == 0 || A.ecken.size() != 3U || B.ecken.size() != 3U) { continue; }
        // A: x -> y an ia, dazu c; B: y -> x an ib, dazu d
        const int x = punktVon(A, ia), y = punktVon(A, ia + 1), c = punktVon(A, ia + 2), d = punktVon(B, ib + 2);
        if (c == d) { continue; }
        if (qp.naehteAchten) {
            const Ecke& ax = A.ecken[uz(ia)].e;
            const Ecke& ay = A.ecken[uz((ia + 1) % 3)].e;
            const Ecke& by = B.ecken[uz(ib)].e;
            const Ecke& bx = B.ecken[uz((ib + 1) % 3)].e;
            if (!gleicheEcke(ax, bx) || !gleicheEcke(ay, by)) { continue; }   // UV-Naht oder harte Kante
        }
        // das Viereck im Uhrzeigersinn wie die Datei: y, c, x, d
        const std::array<V, 4> q{ort(n, y), ort(n, c), ort(n, x), ort(n, d)};
        const QuadForm qf = quadForm(q);
        const double knick = winkel(newell(n, A), newell(n, B));
        if (!qf.konvex || knick > fw || qf.schlimmsteEcke > sw) { continue; }
        ks.push_back({qf.kosten, zi(e)});
    }
    std::stable_sort(ks.begin(), ks.end(), [](const Kandidat& a, const Kandidat& b) { return a.kosten != b.kosten ? a.kosten < b.kosten : a.kante < b.kante; });
    std::vector<char> genommen(n.flaechen.size(), 0);
    for (const Kandidat& kd : ks) {
        const PKante& k = n.kanten[uz(kd.kante)];
        const auto [fa, ia] = k.seiten[0];
        const auto [fb, ib] = k.seiten[1];
        if (genommen[uz(fa)] != 0 || genommen[uz(fb)] != 0) { continue; }
        genommen[uz(fa)] = genommen[uz(fb)] = 1;
        PFlaeche& A = n.flaechen[uz(fa)];
        PFlaeche& B = n.flaechen[uz(fb)];
        // Viereck: A ab ia+1 (y, c, x), dann B nach x (d); die beiden Dreiecke bleiben die Teilung (dieselbe Diagonale)
        std::vector<PEcke> e = {A.ecken[uz((ia + 1) % 3)], A.ecken[uz((ia + 2) % 3)], A.ecken[uz(ia)], B.ecken[uz((ib + 2) % 3)]};
        A.ecken = std::move(e);
        A.dreiecke = {{0, 1, 2}, {2, 3, 0}};   // y c x | x d y - die Dreiecke der Datei
        B.weg = true;
        n.beruehren(A.teil);
        ++p.geaendert;
    }
    for (std::size_t f = 0; f < n.flaechen.size(); ++f) {
        if (!n.flaechen[f].weg && gewollt[f] != 0) { p.auswahl.flaechen.push_back(zi(f)); }
    }
    if (p.geaendert == 0) { p.grund = Ablehnung::LeereAuswahl; }
    fertig(n, p);
    return p;
}

