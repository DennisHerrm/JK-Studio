Plan bridgeRaender(PolyNetz& n, std::pair<int, int> ersteKante, std::pair<int, int> zweiteKante, int segmente, int verdrehen) {
    Plan p;
    n.kantenBauen();
    std::vector<int> l1, f1, l2, f2;
    if (!randRing(n, ersteKante, l1, f1) || !randRing(n, zweiteKante, l2, f2)) {
        p.grund = Ablehnung::LeereAuswahl;
        return p;
    }
    if (std::find(l1.begin(), l1.end(), l2[0]) != l1.end()) {
        p.grund = Ablehnung::GleicheSchleife;
        return p;
    }
    if (l1.size() != l2.size()) {
        p.grund = Ablehnung::Ungleich;
        return p;
    }
    if (n.punkte[uz(l1[0])].teil != n.punkte[uz(l2[0])].teil) {
        p.grund = Ablehnung::VerschiedeneTeile;
        return p;
    }
    const int k = zi(l1.size());
    segmente = std::clamp(segmente, 1, 64);
    // Paarung gegenlaeufig: p_i <-> q_(s - i); s mit der kleinsten Summe der Verbindungen, dann verdreht
    int bestS = 0;
    double best = 1e300;
    for (int s = 0; s < k; ++s) {
        double sum = 0.0;
        for (int i = 0; i < k; ++i) { sum += laenge(ort(n, l1[uz(i)]) - ort(n, l2[uz(((s - i) % k + k) % k)])); }
        if (sum < best) {
            best = sum;
            bestS = s;
        }
    }
    const int s = ((bestS + verdrehen) % k + k) % k;
    const auto q = [&](int i) { return l2[uz(((s - i) % k + k) % k)]; };
    if (segmente == 1) {
        // eine Verbindung, die es schon als Kante gibt, bekaeme eine dritte Seite (WL WouldPinch)
        for (int i = 0; i < k; ++i) {
            if (n.kanteVon(l1[uz(i)], q(i)) >= 0) {
                p.grund = Ablehnung::WuerdeKneifen;
                return p;
            }
        }
    }
    const auto eckeAm = [&](const std::vector<int>& l, const std::vector<int>& fl, int pt) {
        const std::size_t i = uz(static_cast<int>(std::find(l.begin(), l.end(), pt) - l.begin()));
        const PFlaeche& f = n.flaechen[uz(fl[i])];
        const int e = eckeMit(f, pt);
        return e >= 0 ? f.ecken[uz(e)].e : Ecke{};
    };
    const int teil = n.punkte[uz(l1[0])].teil;
    // die Ringe: Stufe 0 die erste Schleife, Stufe `segmente` die zweite
    std::vector<std::vector<int>> r(uz(segmente) + 1U, std::vector<int>(uz(k)));
    std::vector<std::vector<Ecke>> re(uz(segmente) + 1U, std::vector<Ecke>(uz(k)));
    for (int i = 0; i < k; ++i) {
        r[0][uz(i)] = l1[uz(i)];
        r[uz(segmente)][uz(i)] = q(i);
        re[0][uz(i)] = eckeAm(l1, f1, l1[uz(i)]);
        re[uz(segmente)][uz(i)] = eckeAm(l2, f2, q(i));
        for (int j = 1; j < segmente; ++j) {
            const double t = static_cast<double>(j) / static_cast<double>(segmente);
            r[uz(j)][uz(i)] = neuerPunkt(n, ort(n, l1[uz(i)]) + (ort(n, q(i)) - ort(n, l1[uz(i)])) * t, teil);
            re[uz(j)][uz(i)] = mischen(re[0][uz(i)], re[uz(segmente)][uz(i)], t);
        }
    }
    for (int j = 0; j < segmente; ++j) {
        for (int i = 0; i < k; ++i) {
            const int i1 = (i + 1) % k;
            std::vector<PEcke> w(4);
            w[0] = PEcke{r[uz(j)][uz(i1)], re[uz(j)][uz(i1)]};
            w[1] = PEcke{r[uz(j)][uz(i)], re[uz(j)][uz(i)]};
            w[2] = PEcke{r[uz(j) + 1U][uz(i)], re[uz(j) + 1U][uz(i)]};
            w[3] = PEcke{r[uz(j) + 1U][uz(i1)], re[uz(j) + 1U][uz(i1)]};
            p.auswahl.flaechen.push_back(neueFlaeche(n, std::move(w), teil));
            ++p.geaendert;
        }
    }
    for (const int x : l1) {
        for (const int f : n.punktFlaechen[uz(x)]) { n.flaechen[uz(f)].neu = true; }
    }
    for (const int x : l2) {
        for (const int f : n.punktFlaechen[uz(x)]) { n.flaechen[uz(f)].neu = true; }
    }
    fertig(n, p);
    return p;
}

Plan bridgeFlaechen(PolyNetz& n, int erste, int zweite, int segmente, int verdrehen) {
    Plan p;
    if (erste < 0 || zweite < 0 || erste == zweite || uz(erste) >= n.flaechen.size() || uz(zweite) >= n.flaechen.size()) {
        p.grund = Ablehnung::LeereAuswahl;
        return p;
    }
    PolyNetz k = n;
    const std::pair<int, int> e1{punktVon(k.flaechen[uz(erste)], 0), punktVon(k.flaechen[uz(erste)], 1)};
    const std::pair<int, int> e2{punktVon(k.flaechen[uz(zweite)], 0), punktVon(k.flaechen[uz(zweite)], 1)};
    k.flaechen[uz(erste)].weg = true;
    k.flaechen[uz(zweite)].weg = true;
    k.beruehren(k.flaechen[uz(erste)].teil);
    p = bridgeRaender(k, e1, e2, segmente, verdrehen);
    if (!p.abgelehnt()) { n = std::move(k); }
    return p;
}

