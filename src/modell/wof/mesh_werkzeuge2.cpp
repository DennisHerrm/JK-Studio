float weldSchwelleVorgabe(const PolyNetz& n) {
    V lo{1e30, 1e30, 1e30}, hi{-1e30, -1e30, -1e30};
    bool da = false;
    for (const PPunkt& p : n.punkte) {
        if (p.weg) { continue; }
        da = true;
        lo = V{std::min(lo.x, static_cast<double>(p.ort[0])), std::min(lo.y, static_cast<double>(p.ort[1])), std::min(lo.z, static_cast<double>(p.ort[2]))};
        hi = V{std::max(hi.x, static_cast<double>(p.ort[0])), std::max(hi.y, static_cast<double>(p.ort[1])), std::max(hi.z, static_cast<double>(p.ort[2]))};
    }
    return da ? static_cast<float>(laenge(hi - lo) * 1e-5 * 100.0) : 0.0F;
}

Plan weld(PolyNetz& n, const std::vector<int>& punkte, float schwelle) {
    n.kantenBauen();
    std::vector<int> sel;
    for (const int x : punkte) {
        if (x >= 0 && uz(x) < n.punkte.size() && !n.punkte[uz(x)].weg) { sel.push_back(x); }
    }
    std::sort(sel.begin(), sel.end());
    sel.erase(std::unique(sel.begin(), sel.end()), sel.end());
    // Gruppen ueber die Schwelle (Vereinigung), nur im selben Teil
    std::vector<int> wurzel(sel.size());
    std::iota(wurzel.begin(), wurzel.end(), 0);
    const auto finde = [&](int i) {
        while (wurzel[uz(i)] != i) { i = wurzel[uz(i)] = wurzel[uz(wurzel[uz(i)])]; }
        return i;
    };
    const double s2 = static_cast<double>(schwelle) * static_cast<double>(schwelle);
    for (std::size_t i = 0; i < sel.size(); ++i) {
        for (std::size_t j = i + 1; j < sel.size(); ++j) {
            if (n.punkte[uz(sel[i])].teil != n.punkte[uz(sel[j])].teil) { continue; }
            const V d = ort(n, sel[i]) - ort(n, sel[j]);
            if (punkt(d, d) <= s2) { wurzel[uz(finde(zi(i)))] = finde(zi(j)); }
        }
    }
    std::map<int, std::vector<int>> g;
    for (std::size_t i = 0; i < sel.size(); ++i) { g[finde(zi(i))].push_back(sel[i]); }
    std::vector<std::vector<int>> gruppen;
    for (auto& [w, l] : g) {
        (void)w;
        if (l.size() >= 2U) { gruppen.push_back(l); }
    }
    Plan p = gruppenLegen(n, gruppen, false);
    if (p.grund == Ablehnung::LeereAuswahl && !sel.empty()) { p.belassen = zi(sel.size()); }
    return p;
}

Plan targetWeld(PolyNetz& n, int quelle, int ziel) {
    n.kantenBauen();
    Plan p;
    if (quelle < 0 || ziel < 0 || quelle == ziel || uz(quelle) >= n.punkte.size() || uz(ziel) >= n.punkte.size()) {
        p.grund = Ablehnung::LeereAuswahl;
        return p;
    }
    if (n.punkte[uz(quelle)].teil != n.punkte[uz(ziel)].teil) {
        p.grund = Ablehnung::VerschiedeneTeile;
        return p;
    }
    // 3ds Max Target Weld: nur zwei Punkte, die eine Kante verbindet (Autodesk-Hilfe "Editable Poly (Vertex)")
    if (n.kanteVon(quelle, ziel) < 0) {
        p.grund = Ablehnung::NichtBenachbart;
        return p;
    }
    return gruppenLegen(n, {{ziel, quelle}}, true);
}

Plan mergen(PolyNetz& n, const std::vector<int>& punkte, MergeArt art) {
    n.kantenBauen();
    if (art != MergeArt::Mitte) {
        // Blender Merge At First / At Last: alle gewaehlten auf den ersten bzw. letzten (in der Reihenfolge der Auswahl)
        std::vector<int> g;
        for (const int x : punkte) {
            if (x >= 0 && uz(x) < n.punkte.size()) { g.push_back(x); }
        }
        if (g.size() < 2U) {
            Plan p;
            p.grund = Ablehnung::LeereAuswahl;
            return p;
        }
        const int ziel = art == MergeArt::Erster ? g.front() : g.back();
        std::vector<int> grp = {ziel};
        for (const int x : g) {
            if (x != ziel && n.punkte[uz(x)].teil == n.punkte[uz(ziel)].teil) { grp.push_back(x); }
        }
        return gruppenLegen(n, {grp}, true);
    }
    // WL PlanCollapse: jede zusammenhaengende Gruppe (ueber Kanten zwischen gewaehlten Punkten) ein Punkt
    std::set<int> sel(punkte.begin(), punkte.end());
    std::set<int> besucht;
    std::vector<std::vector<int>> gruppen;
    for (const int s0 : sel) {
        if (besucht.count(s0) != 0U || s0 < 0 || uz(s0) >= n.punkte.size()) { continue; }
        std::vector<int> grp;
        std::vector<int> offen = {s0};
        besucht.insert(s0);
        while (!offen.empty()) {
            const int x = offen.back();
            offen.pop_back();
            grp.push_back(x);
            for (const int fi : n.punktFlaechen[uz(x)]) {
                const PFlaeche& f = n.flaechen[uz(fi)];
                const int i = eckeMit(f, x);
                for (const int y : {punktVon(f, i - 1), punktVon(f, i + 1)}) {
                    if (sel.count(y) != 0U && besucht.insert(y).second) { offen.push_back(y); }
                }
            }
        }
        gruppen.push_back(grp);
    }
    return gruppenLegen(n, gruppen, false);
}

