// Punkte ersetzen (alt -> neu), doppelte Nachbarn zusammenziehen, Vielecke unter drei Ecken fallen weg
void ersetzen(PolyNetz& n, const std::map<int, int>& zu) {
    for (PFlaeche& f : n.flaechen) {
        if (f.weg) { continue; }
        bool trifft = false;
        for (PEcke& c : f.ecken) {
            const auto it = zu.find(c.punkt);
            if (it != zu.end()) {
                c.punkt = it->second;
                trifft = true;
            }
        }
        if (!trifft) { continue; }
        std::vector<PEcke> e;
        for (const PEcke& c : f.ecken) {
            if (e.empty() || e.back().punkt != c.punkt) { e.push_back(c); }
        }
        while (e.size() > 1U && e.front().punkt == e.back().punkt) { e.pop_back(); }
        f.ecken = std::move(e);
        flaecheGeaendert(f);
        n.beruehren(f.teil);
        if (f.ecken.size() < 3U) { f.weg = true; }
    }
    for (const auto& [a, b] : zu) {
        if (a != b) { n.punkte[uz(a)].weg = true; }
    }
}

// Ein Versuch auf einer Kopie: gueltig -> uebernehmen, sonst Ablehnung (das Netz bleibt unberuehrt)
bool uebernehmenWennGueltig(PolyNetz& n, PolyNetz& kopie, Plan& p, Ablehnung sonst) {
    kopie.kantenBauen();
    if (!kopie.pruefen()) {
        p.grund = sonst;
        return false;
    }
    n = std::move(kopie);
    return true;
}

// Die Gruppen zusammenlegen: jede behaelt ihren mittigsten Punkt (oder `fest`), im Schwerpunkt (oder am festen Punkt)
Plan gruppenLegen(PolyNetz& n, const std::vector<std::vector<int>>& gruppen, bool amFesten) {
    Plan p;
    PolyNetz k = n;
    std::map<int, int> zu;
    for (const std::vector<int>& g : gruppen) {
        if (g.size() < 2U) { continue; }
        V s;
        for (const int x : g) { s = s + ort(k, x); }
        s = s * (1.0 / static_cast<double>(g.size()));
        int halter = g[0];
        if (!amFesten) {
            double best = 1e300;
            for (const int x : g) {
                const double d = laenge(ort(k, x) - s);
                if (d < best) {
                    best = d;
                    halter = x;
                }
            }
            vNach(s, k.punkte[uz(halter)].ort);
        }
        for (const int x : g) {
            if (x != halter) { zu[x] = halter; }
        }
        ++p.geaendert;
        p.auswahl.punkte.push_back(halter);
        for (const int f : k.punktFlaechen[uz(halter)]) { k.flaechen[uz(f)].neu = true; }
    }
    if (zu.empty()) {
        p.grund = Ablehnung::LeereAuswahl;
        return p;
    }
    ersetzen(k, zu);
    if (!uebernehmenWennGueltig(n, k, p, Ablehnung::WuerdeKneifen)) { return p; }
    for (PFlaeche& f : n.flaechen) {
        if (f.weg) { continue; }
        for (const PEcke& c : f.ecken) {
            if (std::find(p.auswahl.punkte.begin(), p.auswahl.punkte.end(), c.punkt) != p.auswahl.punkte.end()) { f.neu = true; }
        }
    }
    fertig(n, p);
    return p;
}

// Die geordnete Randschleife an einer Randkante: Punkte in der Richtung ihrer Vielecke (p[i] -> p[i+1] laeuft in einem
// Vieleck), mit dem Vieleck je Kante
bool randRing(const PolyNetz& n, std::pair<int, int> kante, std::vector<int>& punkte, std::vector<int>& flaechen) {
    const int k = n.kanteVon(kante.first, kante.second);
    if (k < 0 || !n.istRand(k)) { return false; }
    std::map<int, std::pair<int, int>> weiter;   // von -> (nach, Vieleck)
    for (const PKante& x : n.kanten) {
        if (x.seiten.size() != 1U) { continue; }
        const auto [fi, i] = x.seiten[0];
        weiter.emplace(punktVon(n.flaechen[uz(fi)], i), std::pair<int, int>{punktVon(n.flaechen[uz(fi)], i + 1), fi});
    }
    const auto [f0, i0] = n.kanten[uz(k)].seiten[0];
    const int start = punktVon(n.flaechen[uz(f0)], i0);
    punkte.clear();
    flaechen.clear();
    int x = start;
    for (std::size_t s = 0; s <= weiter.size(); ++s) {
        const auto it = weiter.find(x);
        if (it == weiter.end()) { return false; }
        punkte.push_back(x);
        flaechen.push_back(it->second.second);
        x = it->second.first;
        if (x == start) { return punkte.size() >= 3U; }
    }
    return false;
}

