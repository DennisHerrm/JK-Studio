Plan entfernen(PolyNetz& n, const PAuswahl& a, PEbene ebene, bool aufraeumen) {
    Plan p;
    if (ebene == PEbene::Vieleck || ebene == PEbene::Element) { return loeschen(n, a, ebene); }
    n.kantenBauen();
    PolyNetz k = n;
    std::set<int> endpunkte;
    if (ebene == PEbene::Kante || ebene == PEbene::Rand) {
        if (a.kanten.empty()) {
            p.grund = Ablehnung::LeereAuswahl;
            return p;
        }
        for (const auto& [x, y] : a.kanten) {
            const int ki = k.kanteVon(x, y);
            if (ki < 0) { continue; }
            if (k.istRand(ki)) {
                p.grund = Ablehnung::Rand;   // WL BorderEdgeRemove: Remove schliesst eine Flaeche, ein Loch hat nichts
                return p;
            }
        }
        for (const auto& [x, y] : a.kanten) {
            const int ki = k.kanteVon(x, y);
            if (ki < 0 || k.kanten[uz(ki)].seiten.size() != 2U) { continue; }
            const auto [fa, ia] = k.kanten[uz(ki)].seiten[0];
            const auto [fb, ib] = k.kanten[uz(ki)].seiten[1];
            if (fa == fb) {
                ++p.belassen;
                continue;
            }
            const PFlaeche& A = k.flaechen[uz(fa)];
            const PFlaeche& B = k.flaechen[uz(fb)];
            const int ka = zi(A.ecken.size()), kb = zi(B.ecken.size());
            // A hat x -> y an ia; B hat y -> x an ib: A von ia+1 bis ia, B von ib+2 bis ib-1
            std::vector<PEcke> e;
            for (int s = 0; s < ka; ++s) { e.push_back(A.ecken[uz((ia + 1 + s) % ka)]); }
            for (int s = 0; s < kb - 2; ++s) { e.push_back(B.ecken[uz((ib + 2 + s) % kb)]); }
            std::set<int> pt;
            bool doppelt = false;
            for (const PEcke& c : e) { doppelt = doppelt || !pt.insert(c.punkt).second; }
            if (doppelt) {
                ++p.belassen;
                continue;
            }
            k.flaechen[uz(fa)].ecken = std::move(e);
            flaecheGeaendert(k.flaechen[uz(fa)]);
            k.flaechen[uz(fb)].weg = true;
            k.beruehren(k.flaechen[uz(fa)].teil);
            endpunkte.insert(x);
            endpunkte.insert(y);
            ++p.geaendert;
            p.auswahl.flaechen.push_back(fa);
            k.kantenBauen();
        }
    } else {   // Punkte: alle Vielecke am Punkt werden eines ueber seinen Ring
        if (a.punkte.empty()) {
            p.grund = Ablehnung::LeereAuswahl;
            return p;
        }
        for (const int v : a.punkte) {
            if (v < 0 || uz(v) >= k.punkte.size() || k.punkte[uz(v)].weg) { continue; }
            const std::vector<int> fl = k.punktFlaechen[uz(v)];
            if (fl.size() < 2U) {
                ++p.belassen;
                continue;
            }
            // je Vieleck die Ecken nach v bis vor v; verketten ueber den gemeinsamen Nachbarn
            std::map<int, std::vector<PEcke>> stueck;   // erster Punkt -> Stueck
            bool rand = false;
            for (const int fi : fl) {
                const PFlaeche& f = k.flaechen[uz(fi)];
                const int i = eckeMit(f, v);
                const int kk = zi(f.ecken.size());
                std::vector<PEcke> s;
                for (int t = 1; t < kk; ++t) { s.push_back(f.ecken[uz((i + t) % kk)]); }
                rand = rand || !stueck.emplace(s.front().punkt, s).second;
            }
            std::vector<PEcke> e;
            int x = stueck.begin()->first;
            const int start = x;
            bool zu = false;
            for (std::size_t t = 0; t <= stueck.size() && !rand; ++t) {
                const auto it = stueck.find(x);
                if (it == stueck.end()) { break; }
                for (std::size_t c = 0; c + 1 < it->second.size(); ++c) { e.push_back(it->second[c]); }
                x = it->second.back().punkt;
                if (x == start) {
                    zu = true;
                    break;
                }
            }
            std::set<int> pt;
            bool doppelt = false;
            for (const PEcke& c : e) { doppelt = doppelt || !pt.insert(c.punkt).second; }
            if (!zu || doppelt || e.size() < 3U) {
                ++p.belassen;   // am Rand oder der Ring wiederholt einen Punkt (WL WouldRepeatVertex)
                continue;
            }
            k.flaechen[uz(fl[0])].ecken = std::move(e);
            flaecheGeaendert(k.flaechen[uz(fl[0])]);
            k.beruehren(k.flaechen[uz(fl[0])].teil);
            for (std::size_t t = 1; t < fl.size(); ++t) { k.flaechen[uz(fl[t])].weg = true; }
            k.punkte[uz(v)].weg = true;
            p.auswahl.flaechen.push_back(fl[0]);
            ++p.geaendert;
            k.kantenBauen();
        }
    }
    if (aufraeumen) {
        // 3ds Max Strg+Backspace: Punkte, an denen danach nur zwei Kanten haengen, gehen mit
        for (const int v : endpunkte) {
            if (k.punkte[uz(v)].weg) { continue; }
            std::set<int> nachbarn;
            for (const int fi : k.punktFlaechen[uz(v)]) {
                const PFlaeche& f = k.flaechen[uz(fi)];
                const int i = eckeMit(f, v);
                nachbarn.insert(punktVon(f, i - 1));
                nachbarn.insert(punktVon(f, i + 1));
            }
            if (nachbarn.size() != 2U) { continue; }
            bool geht = true;
            for (const int fi : k.punktFlaechen[uz(v)]) { geht = geht && k.flaechen[uz(fi)].ecken.size() > 3U; }
            if (!geht) { continue; }
            for (const int fi : k.punktFlaechen[uz(v)]) {
                PFlaeche& f = k.flaechen[uz(fi)];
                f.ecken.erase(f.ecken.begin() + eckeMit(f, v));
                flaecheGeaendert(f);
            }
            k.punkte[uz(v)].weg = true;
            k.kantenBauen();
        }
    }
    if (p.geaendert == 0) {
        p.grund = Ablehnung::WuerdeDoppeln;
        return p;
    }
    if (!uebernehmenWennGueltig(n, k, p, Ablehnung::WuerdeKneifen)) { return p; }
    fertig(n, p);
    return p;
}

Plan loeschen(PolyNetz& n, const PAuswahl& a, PEbene ebene) {
    Plan p;
    n.kantenBauen();
    std::set<int> weg;
    if (ebene == PEbene::Punkt) {
        for (const int v : a.punkte) {
            if (v >= 0 && uz(v) < n.punktFlaechen.size()) { weg.insert(n.punktFlaechen[uz(v)].begin(), n.punktFlaechen[uz(v)].end()); }
        }
    } else if (ebene == PEbene::Kante || ebene == PEbene::Rand) {
        for (const auto& [x, y] : a.kanten) {
            const int k = n.kanteVon(x, y);
            if (k < 0) { continue; }
            for (const auto& [f, i] : n.kanten[uz(k)].seiten) {
                (void)i;
                weg.insert(f);
            }
        }
    } else {
        for (const int f : a.flaechen) {
            if (f >= 0 && uz(f) < n.flaechen.size() && !n.flaechen[uz(f)].weg) { weg.insert(f); }
        }
    }
    if (weg.empty()) {
        p.grund = Ablehnung::LeereAuswahl;
        return p;
    }
    if (zi(weg.size()) >= n.lebendeFlaechen()) {
        p.grund = Ablehnung::AlleFlaechen;
        return p;
    }
    for (const int f : weg) {
        n.flaechen[uz(f)].weg = true;
        n.beruehren(n.flaechen[uz(f)].teil);
        ++p.geaendert;
    }
    fertig(n, p);
    return p;
}

// --- Detach -------------------------------------------------------------------------------------------------------

Plan detach(PolyNetz& n, const std::vector<int>& flaechen, int neuerTeil) {
    Plan p;
    n.kantenBauen();
    std::set<int> sel;
    for (const int f : flaechen) {
        if (f >= 0 && uz(f) < n.flaechen.size() && !n.flaechen[uz(f)].weg) { sel.insert(f); }
    }
    if (sel.empty()) {
        p.grund = Ablehnung::LeereAuswahl;
        return p;
    }
    const int alterTeil = n.flaechen[uz(*sel.begin())].teil;
    for (const int f : sel) {
        if (n.flaechen[uz(f)].teil != alterTeil) {
            p.grund = Ablehnung::VerschiedeneTeile;
            return p;
        }
    }
    if (neuerTeil < 0 && zi(sel.size()) >= n.lebendeFlaechen()) {
        p.grund = Ablehnung::AlleFlaechen;
        return p;
    }
    if (neuerTeil >= 0 && uz(neuerTeil) >= n.teilBeruehrt.size()) {
        n.teilBeruehrt.resize(uz(neuerTeil) + 1U, 0);
        n.teilPunkte.resize(uz(neuerTeil) + 1U, zi(n.punkte.size()));
    }
    const int ziel = neuerTeil >= 0 ? neuerTeil : alterTeil;
    std::map<int, int> kopie;
    for (const int fi : sel) {
        for (PEcke& c : n.flaechen[uz(fi)].ecken) {
            const int v = c.punkt;
            bool geteilt = false;
            for (const int g : n.punktFlaechen[uz(v)]) { geteilt = geteilt || sel.count(g) == 0U; }
            if (geteilt) {
                auto it = kopie.find(v);
                if (it == kopie.end()) { it = kopie.emplace(v, neuerPunkt(n, ort(n, v), ziel)).first; }
                c.punkt = it->second;
            } else {
                n.punkte[uz(v)].teil = ziel;
            }
        }
        n.flaechen[uz(fi)].teil = ziel;
        flaecheGeaendert(n.flaechen[uz(fi)]);
        p.auswahl.flaechen.push_back(fi);
        ++p.geaendert;
    }
    n.beruehren(alterTeil);
    n.beruehren(ziel);
    // die Normalen bleiben (die Ecken behalten ihre Werte); nur die Topologie trennt sich
    for (const int fi : sel) { n.flaechen[uz(fi)].neu = false; }
    fertig(n, p);
    return p;
}

