std::vector<std::vector<int>> stapelFinden(const UvNetz& n, const UvInseln& in) {
    std::vector<std::vector<int>> aus;
    if (in.zahl == 0) { return aus; }
    const auto kleiner = [](V2 a, V2 b) { return a.x != b.x ? a.x < b.x : a.y < b.y; };
    std::vector<std::vector<V2>> schl(uz(in.zahl));
    for (int i = 0; i < in.zahl; ++i) {
        for (const int d : in.dreieckeVon(i)) {
            for (int k = 0; k < 3; ++k) { schl[uz(i)].push_back(n.uv[uz(d * 3 + k)]); }
        }
        std::sort(schl[uz(i)].begin(), schl[uz(i)].end(), kleiner);
        schl[uz(i)].erase(std::unique(schl[uz(i)].begin(), schl[uz(i)].end(), [](V2 a, V2 b) { return a.x == b.x && a.y == b.y; }), schl[uz(i)].end());
    }
    constexpr float kGleich = 1.0F / 131072.0F;   // WL kSame
    const auto gleichePunkte = [](const std::vector<V2>& a, const std::vector<V2>& b) {
        if (a.size() != b.size()) { return false; }
        std::vector<u8> benutzt(b.size(), 0);
        for (const V2 p : a) {
            auto it = std::lower_bound(b.begin(), b.end(), p.x - kGleich, [](V2 q, float u) { return q.x < u; });
            bool gefunden = false;
            for (; it != b.end() && it->x <= p.x + kGleich; ++it) {
                const std::size_t k = static_cast<std::size_t>(it - b.begin());
                if (benutzt[k] == 0 && std::abs(it->y - p.y) <= kGleich) {
                    benutzt[k] = 1;
                    gefunden = true;
                    break;
                }
            }
            if (!gefunden) { return false; }
        }
        return true;
    };
    std::vector<u8> genommen(uz(in.zahl), 0);
    for (int i = 0; i < in.zahl; ++i) {
        if (genommen[uz(i)] != 0 || schl[uz(i)].empty()) { continue; }
        std::vector<int> gruppe{i};
        for (int j = i + 1; j < in.zahl; ++j) {
            if (genommen[uz(j)] == 0 && gleichePunkte(schl[uz(i)], schl[uz(j)])) {
                genommen[uz(j)] = 1;
                gruppe.push_back(j);
            }
        }
        if (gruppe.size() > 1U) { aus.push_back(std::move(gruppe)); }
    }
    return aus;
}

PackErgebnis packen(UvNetz& n, const UvInseln& in, const PackOptionen& o) {
    PackErgebnis aus;
    if (in.zahl == 0 || o.aufloesung <= 0) { return aus; }
    const int res = o.aufloesung;
    std::vector<int> wurzel(uz(in.zahl));
    for (int i = 0; i < in.zahl; ++i) { wurzel[uz(i)] = i; }
    const auto finde = [&](int i) {
        while (wurzel[uz(i)] != i) {
            wurzel[uz(i)] = wurzel[uz(wurzel[uz(i)])];
            i = wurzel[uz(i)];
        }
        return i;
    };
    const auto vereinen = [&](int a, int b) {
        a = finde(a);
        b = finde(b);
        if (a != b) { wurzel[uz(std::max(a, b))] = std::min(a, b); }
    };
    if (o.stapelHalten) {
        for (const std::vector<int>& st : stapelFinden(n, in)) {
            for (const int i : st) { vereinen(st.front(), i); }
        }
    }
    std::unordered_map<int, int> ersteVon;
    for (int i = 0; i < in.zahl && uz(i) < o.gruppeVon.size(); ++i) {
        const int g = o.gruppeVon[uz(i)];
        if (g < 0) { continue; }
        const auto [bei, neu] = ersteVon.emplace(g, i);
        if (!neu) { vereinen(bei->second, i); }
    }
    std::vector<std::vector<int>> gruppen;
    std::vector<int> gruppeVon(uz(in.zahl), -1);
    for (int i = 0; i < in.zahl; ++i) {
        const int top = finde(i);
        if (gruppeVon[uz(top)] < 0) {
            gruppeVon[uz(top)] = static_cast<int>(gruppen.size());
            gruppen.emplace_back();
        }
        gruppeVon[uz(i)] = gruppeVon[uz(top)];
        gruppen[uz(gruppeVon[uz(i)])].push_back(i);
    }
    const auto bewegt = [&](int insel) {
        if (o.gepinntBleibt && inselGepinnt(n, in, insel)) { return false; }
        if (o.beweglich.empty()) { return inselFrei(n, in, insel); }
        return uz(insel) < o.beweglich.size() && o.beweglich[uz(insel)] != 0;
    };
    std::vector<u8> gruppeFrei(gruppen.size(), 1);
    for (std::size_t g = 0; g < gruppen.size(); ++g) {
        for (const int i : gruppen[g]) {
            if (!bewegt(i)) {
                gruppeFrei[g] = 0;
                break;
            }
        }
    }
    std::vector<u8> belegt(uz(res) * uz(res), 0);
    bool irgendFest = false;
    for (std::size_t g = 0; g < gruppen.size(); ++g) {
        if (gruppeFrei[g] != 0) { continue; }
        irgendFest = true;
        const UvKasten k = kastenVon(n, in, gruppen[g].front());
        if (o.kachelnAbweisen && !k.leer && (k.tief.x < -0.001F || k.tief.y < -0.001F || k.hoch.x > 1.001F || k.hoch.y > 1.001F)) {
            aus.kachelnAbgewiesen = true;
        }
        const Abdruck marke = abdruckVon(gestaltVon(n, in, gruppen[g]), static_cast<float>(res), 0, 0.0F);
        if (marke.leer()) { continue; }
        const int bx = static_cast<int>(std::floor(marke.ursprung.x * static_cast<float>(res))) - 2;
        const int by = static_cast<int>(std::floor(marke.ursprung.y * static_cast<float>(res))) - 2;
        for (int y = 0; y < marke.hoehe; ++y) {
            for (int x = 0; x < marke.breite; ++x) {
                if (marke.maske[uz(y * marke.breite + x)] == 0) { continue; }
                const int tx = bx + x;
                const int ty = by + y;
                if (tx < 0 || ty < 0 || tx >= res || ty >= res) { continue; }
                belegt[uz(ty) * uz(res) + uz(tx)] = 1;
            }
        }
    }
    if (aus.kachelnAbgewiesen && irgendFest) { return aus; }
    aus.kachelnAbgewiesen = false;
    std::vector<int> folge;
    for (std::size_t g = 0; g < gruppen.size(); ++g) {
        if (gruppeFrei[g] != 0) { folge.push_back(static_cast<int>(g)); }
    }
    std::vector<float> flaecheVon(gruppen.size(), 0.0F);
    std::vector<float> bodenVon(gruppen.size(), 0.0F);
    std::vector<int> erstesVon(gruppen.size(), 1 << 30);
    for (std::size_t g = 0; g < gruppen.size(); ++g) {
        for (const int i : gruppen[g]) {
            const float f = flaechenVon(n, in, i).uv;
            flaecheVon[g] += f;
            bodenVon[g] = std::max(bodenVon[g], f);
            const std::span<const int> d = in.dreieckeVon(i);
            if (!d.empty()) { erstesVon[g] = std::min(erstesVon[g], d.front()); }
        }
    }
    std::sort(folge.begin(), folge.end(), [&](int a, int b) {
        if (flaecheVon[uz(a)] != flaecheVon[uz(b)]) { return flaecheVon[uz(a)] > flaecheVon[uz(b)]; }
        return erstesVon[uz(a)] < erstesVon[uz(b)];
    });
    if (folge.empty()) { return aus; }
    using Laeufe = std::vector<std::vector<std::pair<int, int>>>;
    const auto laeufeVon = [&]() {
        Laeufe l(uz(res));
        for (int x = 0; x < res; ++x) {
            for (int y = 0; y < res;) {
                if (belegt[uz(y) * uz(res) + uz(x)] == 0) {
                    ++y;
                    continue;
                }
                int ende = y;
                while (ende + 1 < res && belegt[uz(ende + 1) * uz(res) + uz(x)] != 0) { ++ende; }
                l[uz(x)].emplace_back(y, ende);
                y = ende + 1;
            }
        }
        return l;
    };
    const auto tiefsterBei = [&](const Abdruck& a, int x, const Laeufe& l, int grenze, int& blocker) {
        const auto schieben = [&](int c, int& y) {
            if (a.tief[uz(c)] == kKein) { return false; }
            const int von = y + a.tief[uz(c)];
            const int bis = y + a.hoch[uz(c)];
            const auto& spalte = l[uz(x + c)];
            const auto lauf = std::lower_bound(spalte.begin(), spalte.end(), von, [](const std::pair<int, int>& r, int zeile) { return r.second < zeile; });
            if (lauf == spalte.end() || lauf->first > bis) { return false; }
            y = lauf->second + 1 - a.tief[uz(c)];
            return true;
        };
        int y = 0;
        for (bool weiter = true; weiter;) {
            if (y >= grenze) { return kKein; }
            weiter = blocker >= x && blocker < x + a.breite && schieben(blocker - x, y);
            for (int c = 0; c < a.breite && !weiter; ++c) {
                if (schieben(c, y)) {
                    weiter = true;
                    blocker = x + c;
                }
            }
            if (y + a.hoehe > res) { return kKein; }
        }
        return y;
    };
    std::vector<std::vector<float>> winkel(gruppen.size());
    std::vector<Gestalt> gestalten(gruppen.size());
    constexpr float kHalbPi = 1.57079632679F;
    for (const int g : folge) {
        if (!o.drehen) {
            winkel[uz(g)].push_back(0.0F);
        } else {
            const float h = hauptWinkel(n, in, gruppen[uz(g)]);
            winkel[uz(g)].push_back(h);
            for (int k = 1; k < 4; ++k) { winkel[uz(g)].push_back(h + kHalbPi * static_cast<float>(k)); }
            winkel[uz(g)].push_back(0.0F);
        }
        gestalten[uz(g)] = gestaltVon(n, in, gruppen[uz(g)]);
    }
    struct Platz {
        int gruppe = 0;
        float winkel = 0.0F;
        V2 mitte{};
        V2 weg{};
    };
    const double freieTexel = static_cast<double>(std::count(belegt.begin(), belegt.end(), u8{0}));
    const auto versuch = [&](float massstab, std::vector<Platz>& plaetze, std::vector<int>* uebrig) {
        plaetze.clear();
        Laeufe laeufe = laeufeVon();
        const double texel = static_cast<double>(res) * massstab;
        double frei = freieTexel;
        double noetig = 0.0;
        for (const int g : folge) { noetig += static_cast<double>(bodenVon[uz(g)]) * texel * texel; }
        for (const int g : folge) {
            if (uebrig == nullptr && noetig > frei) { return false; }
            noetig -= static_cast<double>(bodenVon[uz(g)]) * texel * texel;
            bool gesetzt = false;
            float besterWinkel = 0.0F;
            int besterX = 0;
            int besterY = 0;
            int besteOben = kKein;
            V2 besterUrsprung{};
            Abdruck gewaehlt;
            bool irgendAbdruck = false;
            const V2 mitte = gestalten[uz(g)].mitte;
            for (const float w : winkel[uz(g)]) {
                Abdruck a = abdruckVon(gestalten[uz(g)], static_cast<float>(res) * massstab, o.abstand, w, false);
                if (a.leer()) { continue; }
                irgendAbdruck = true;
                if (a.breite > res || a.hoehe > res) { continue; }
                int hoehe = 0;
                for (int c = 0; c < a.breite; ++c) {
                    if (a.hoch[uz(c)] != kKein) { hoehe = std::max(hoehe, a.hoch[uz(c)]); }
                }
                bool besser = false;
                int blocker = kKein;
                for (int x = 0; x + a.breite <= res; ++x) {
                    const int grenze = besteOben == kKein ? res : (besteOben > hoehe ? besteOben - hoehe : 0);
                    const int y = tiefsterBei(a, x, laeufe, grenze, blocker);
                    if (y == kKein) { continue; }
                    besteOben = y + hoehe;
                    besterWinkel = w;
                    besterX = x;
                    besterY = y;
                    besterUrsprung = a.ursprung;
                    gesetzt = besser = true;
                }
                if (besser) { gewaehlt = std::move(a); }
            }
            if (!irgendAbdruck) { continue; }
            if (!gesetzt) {
                if (uebrig == nullptr) { return false; }
                uebrig->push_back(g);
                continue;
            }
            const float rand = static_cast<float>(o.abstand + 2);
            const V2 weg{(static_cast<float>(besterX) + rand) / static_cast<float>(res) - besterUrsprung.x * massstab - mitte.x * (1.0F - massstab),
                         (static_cast<float>(besterY) + rand) / static_cast<float>(res) - besterUrsprung.y * massstab - mitte.y * (1.0F - massstab)};
            plaetze.push_back(Platz{g, besterWinkel, mitte, weg});
            frei -= static_cast<double>(gewaehlt.bedeckt);
            for (int c = 0; c < gewaehlt.breite; ++c) {
                if (gewaehlt.hoch[uz(c)] == kKein) { continue; }
                auto& spalte = laeufe[uz(besterX + c)];
                spalte.emplace_back(besterY + gewaehlt.tief[uz(c)], besterY + gewaehlt.hoch[uz(c)]);
                std::sort(spalte.begin(), spalte.end());
                std::vector<std::pair<int, int>> zus;
                for (const auto& r : spalte) {
                    if (!zus.empty() && r.first <= zus.back().second + 1) {
                        zus.back().second = std::max(zus.back().second, r.second);
                    } else {
                        zus.push_back(r);
                    }
                }
                spalte = std::move(zus);
            }
        }
        return true;
    };
    std::vector<Platz> plaetze;
    float massstab = 1.0F;
    float decke = 1.0F;
    bool passt = !o.skalieren;
    if (!o.skalieren) {
        std::vector<int> uebrig;
        (void)versuch(massstab, plaetze, &uebrig);
        for (const int g : uebrig) { aus.nichtGesetzt.insert(aus.nichtGesetzt.end(), gruppen[uz(g)].begin(), gruppen[uz(g)].end()); }
        std::sort(aus.nichtGesetzt.begin(), aus.nichtGesetzt.end());
    } else {
        double noetig = 0.0;
        for (const int g : folge) { noetig += static_cast<double>(bodenVon[uz(g)]) * res * res; }
        decke = noetig > freieTexel ? static_cast<float>(std::sqrt(freieTexel / noetig)) : 1.0F;
        passt = decke >= 1.0F && versuch(massstab, plaetze, nullptr);
    }
    if (!passt) {
        float tief = 0.0F;
        float hoch = decke;
        std::vector<Platz> passend;
        for (int schritt = 0; schritt < 8; ++schritt) {
            const float mitte = (tief + hoch) * 0.5F;
            if (versuch(mitte, plaetze, nullptr)) {
                tief = mitte;
                passend = plaetze;
            } else {
                hoch = mitte;
            }
        }
        if (tief <= 0.0F) { return aus; }
        plaetze = std::move(passend);
        massstab = tief;
    }
    aus.skaliert = massstab;
    for (const Platz& p : plaetze) {
        gruppeBewegen(n, in, gruppen[uz(p.gruppe)], p.mitte, massstab, p.winkel, p.weg);
        ++aus.gesetzt;
    }
    float bedeckt = 0.0F;
    for (int i = 0; i < in.zahl; ++i) { bedeckt += flaechenVon(n, in, i).uv; }
    aus.bedeckung = std::clamp(bedeckt, 0.0F, 1.0F);
    return aus;
}

float inselAusrichten(UvNetz& n, const UvInseln& in, int insel) {
    std::vector<V2> pkt;
    for (const int h : eckenDerInsel(in, insel)) { pkt.push_back(n.uv[uz(h)]); }
    const auto kleiner = [](V2 a, V2 b) { return a.x != b.x ? a.x < b.x : a.y < b.y; };
    std::sort(pkt.begin(), pkt.end(), kleiner);
    pkt.erase(std::unique(pkt.begin(), pkt.end(), [](V2 a, V2 b) { return a.x == b.x && a.y == b.y; }), pkt.end());
    if (pkt.size() < 3U) { return 0.0F; }
    const auto dreh = [](V2 o, V2 a, V2 b) { return (a.x - o.x) * (b.y - o.y) - (a.y - o.y) * (b.x - o.x); };
    std::vector<V2> huelle(pkt.size() * 2);
    std::size_t k = 0;
    for (const V2 p : pkt) {
        while (k >= 2 && dreh(huelle[k - 2], huelle[k - 1], p) <= 0.0F) { --k; }
        huelle[k++] = p;
    }
    for (std::size_t i = pkt.size() - 1, unten = k + 1; i-- > 0;) {
        while (k >= unten && dreh(huelle[k - 2], huelle[k - 1], pkt[i]) <= 0.0F) { --k; }
        huelle[k++] = pkt[i];
    }
    huelle.resize(k > 1 ? k - 1 : k);
    const auto kastenBei = [&](float bogen) {
        const float c = std::cos(bogen);
        const float s = std::sin(bogen);
        float tx = 1e30F;
        float ty = 1e30F;
        float hx = -1e30F;
        float hy = -1e30F;
        for (const V2 p : huelle) {
            const float x = p.x * c - p.y * s;
            const float y = p.x * s + p.y * c;
            tx = std::min(tx, x);
            hx = std::max(hx, x);
            ty = std::min(ty, y);
            hy = std::max(hy, y);
        }
        return V2{hx - tx, hy - ty};
    };
    constexpr float kViertel = 1.57079632679F;
    float bester = 0.0F;
    float besteFlaeche = kastenBei(0.0F).x * kastenBei(0.0F).y;
    for (std::size_t i = 0; i < huelle.size(); ++i) {
        const V2 a = huelle[i];
        const V2 b = huelle[(i + 1) % huelle.size()];
        float t = -std::atan2(b.y - a.y, b.x - a.x);
        t -= kViertel * std::round(t / kViertel);
        const V2 kk = kastenBei(t);
        if (kk.x * kk.y < besteFlaeche * (1.0F - 1e-5F)) {
            besteFlaeche = kk.x * kk.y;
            bester = t;
        }
    }
    const V2 kk = kastenBei(bester);
    if (kk.y > kk.x * (1.0F + 1e-5F)) { bester += bester > 0.0F ? -kViertel : kViertel; }
    if (std::abs(bester) < 1e-6F) { return 0.0F; }
    inselDrehen(n, in, insel, bester, V2{});
    return bester;
}

std::vector<int> inFreienPlatz(UvNetz& n, const UvInseln& in, std::span<const u8> beweglich, std::span<const int> gruppeVon, int aufloesung, int abstand) {
    PackOptionen o;
    o.aufloesung = aufloesung;
    o.abstand = abstand;
    o.beweglich.assign(beweglich.begin(), beweglich.end());
    o.gruppeVon.assign(gruppeVon.begin(), gruppeVon.end());
    o.skalieren = false;
    o.kachelnAbweisen = false;
    o.stapelHalten = false;
    return packen(n, in, o).nichtGesetzt;
}

StapelErgebnis stapeln(UvNetz& n, const UvInseln& in, int erste, int andere, std::span<const int> spiegel) {
    StapelErgebnis aus;
    if (erste < 0 || andere < 0 || erste >= in.zahl || andere >= in.zahl || erste == andere) {
        aus.abgewiesen = 1;
        return aus;
    }
    const std::span<const int> ersteD = in.dreieckeVon(erste);
    const std::span<const int> andereD = in.dreieckeVon(andere);
    aus.ersteDreiecke = static_cast<int>(ersteD.size());
    aus.andereDreiecke = static_cast<int>(andereD.size());
    if (ersteD.size() != andereD.size() || andereD.empty()) {
        aus.abgewiesen = aus.andereDreiecke;
        return aus;
    }
    std::unordered_multimap<int, int> ersteEckeBei;   // Punkt -> Halbkante der ersten Insel
    for (const int d : ersteD) {
        for (int k = 0; k < 3; ++k) { ersteEckeBei.emplace(n.von[uz(d * 3 + k)], d * 3 + k); }
    }
    std::vector<std::pair<int, int>> paarung;   // Ecke der anderen -> Ecke der ersten
    if (!spiegel.empty()) {
        const auto zwilling = [&](int h) {
            const int p = n.von[uz(h)];
            return uz(p) < spiegel.size() ? spiegel[uz(p)] : -1;
        };
        std::vector<std::pair<int, int>> versuch;
        std::unordered_set<int> genommen;
        int richtung = 0;   // +1 gleich herum, -1 umgekehrt
        std::vector<int> ohne;
        for (const int d : andereD) {
            const int meine[3] = {d * 3, d * 3 + 1, d * 3 + 2};
            bool getroffen = false;
            for (auto [bei, ende] = ersteEckeBei.equal_range(zwilling(meine[0])); bei != ende && !getroffen; ++bei) {
                const int kand = bei->second / 3;
                if (genommen.contains(kand)) { continue; }
                const int ihre[3] = {kand * 3, kand * 3 + 1, kand * 3 + 2};
                const int start = bei->second - kand * 3;
                for (const int weg : {1, -1}) {
                    if (getroffen || (richtung != 0 && weg != richtung)) { continue; }
                    const auto partner = [&](int i) { return ihre[weg > 0 ? (start + i) % 3 : (start + 3 - i % 3) % 3]; };
                    bool rund = true;
                    for (int i = 0; i < 3 && rund; ++i) { rund = n.von[uz(partner(i))] == zwilling(meine[i]); }
                    if (rund) {
                        getroffen = true;
                        richtung = weg;
                        genommen.insert(kand);
                        for (int i = 0; i < 3; ++i) { versuch.emplace_back(meine[i], partner(i)); }
                    }
                }
            }
            if (!getroffen) { ohne.push_back(d); }
        }
        bool ganz = richtung != 0 && ohne.size() * 2U <= andereD.size();
        if (ganz && !ohne.empty()) {
            // die uebrigen Dreiecke ueber Nachbarn mit zwei gemeinsamen Zwillingen (WL: fanSigns, gleiche UV je Partner)
            const auto faecher = [&](std::span<const std::pair<int, int>> ring, int& plus, int& minus) {
                for (std::size_t k = 1; k + 1 < ring.size(); ++k) {
                    const V2 a = n.uv[uz(ring[0].second)];
                    const V2 b = n.uv[uz(ring[k].second)];
                    const V2 c = n.uv[uz(ring[k + 1].second)];
                    const float f = (b.x - a.x) * (c.y - a.y) - (b.y - a.y) * (c.x - a.x);
                    plus += f > 0.0F ? 1 : 0;
                    minus += f < 0.0F ? 1 : 0;
                }
            };
            int plus = 0;
            int minus = 0;
            for (std::size_t anf = 0; anf < versuch.size(); anf += 3) { faecher(std::span<const std::pair<int, int>>(versuch).subspan(anf, 3), plus, minus); }
            const bool aufwaerts = plus >= minus;
            std::vector<int> zw;
            std::vector<std::pair<int, int>> ring;
            for (const int d : ohne) {
                zw.clear();
                ring.clear();
                for (int k = 0; k < 3; ++k) { zw.push_back(zwilling(d * 3 + k)); }
                std::sort(zw.begin(), zw.end());
                for (int k = 0; k < 3; ++k) {
                    const int h = d * 3 + k;
                    int von = -1;
                    bool einig = true;
                    for (auto [bei, ende] = ersteEckeBei.equal_range(zwilling(h)); bei != ende && einig; ++bei) {
                        const int kand = bei->second / 3;
                        if (genommen.contains(kand)) { continue; }
                        int geteilt = 0;
                        for (int j = 0; j < 3; ++j) { geteilt += std::binary_search(zw.begin(), zw.end(), n.von[uz(kand * 3 + j)]) ? 1 : 0; }
                        if (geteilt < 2) { continue; }
                        if (von < 0) {
                            von = bei->second;
                        } else {
                            einig = std::memcmp(&n.uv[uz(von)], &n.uv[uz(bei->second)], sizeof(V2)) == 0;
                        }
                    }
                    if (von < 0 || !einig) {
                        ganz = false;
                        break;
                    }
                    ring.emplace_back(h, von);
                }
                int auf = 0;
                int ab = 0;
                if (ganz) {
                    faecher(ring, auf, ab);
                    ganz = (aufwaerts ? ab : auf) == 0;
                }
                if (!ganz) { break; }
                versuch.insert(versuch.end(), ring.begin(), ring.end());
            }
        }
        if (ganz) {
            paarung = std::move(versuch);
            aus.ueberSpiegel = true;
        }
    }
    if (paarung.empty()) {
        // Seite an Seite ab der laengsten Randkante beider Inseln, in beiden Richtungen versucht
        const auto laengste = [&](int insel) {
            int beste = -1;
            float bl = -1.0F;
            for (const int h : in.randVon(insel)) {
                const float l = laenge(n.ort[uz(n.nach(h))] - n.ortVon(h));
                if (l > bl) {
                    bl = l;
                    beste = h;
                }
            }
            return beste;
        };
        const int saatErste = laengste(erste);
        const int saatAndere = laengste(andere);
        if (saatErste < 0 || saatAndere < 0) {
            aus.abgewiesen = aus.andereDreiecke;
            return aus;
        }
        for (int richtung = 0; richtung < 2 && paarung.empty(); ++richtung) {
            std::unordered_map<int, int> eckPaar;
            std::vector<std::pair<int, int>> schlange;
            schlange.emplace_back(saatAndere, richtung == 0 ? saatErste : UvNetz::naechste(saatErste));
            std::unordered_map<int, int> dreiPaar;
            bool ok = true;
            while (!schlange.empty() && ok) {
                const auto [a, b] = schlange.back();
                schlange.pop_back();
                const int da = a / 3;
                const int db = b / 3;
                const auto gesehen = dreiPaar.find(da);
                if (gesehen != dreiPaar.end()) {
                    if (gesehen->second != db) { ok = false; }
                    continue;
                }
                dreiPaar.emplace(da, db);
                int la = a;
                int lb = b;
                do {
                    eckPaar[la] = lb;
                    const int qa = n.gegen[uz(la)];
                    const int qb = n.gegen[uz(lb)];
                    const bool innenA = qa >= 0 && in.inselVonDreieck(qa / 3) == andere;
                    const bool innenB = qb >= 0 && in.inselVonDreieck(qb / 3) == erste;
                    if (innenA != innenB) {
                        ok = false;
                        break;
                    }
                    if (innenA) { schlange.emplace_back(UvNetz::naechste(qa), UvNetz::naechste(qb)); }
                    la = UvNetz::naechste(la);
                    lb = UvNetz::naechste(lb);
                } while (la != a && ok);
            }
            if (ok && dreiPaar.size() == andereD.size()) {
                for (const auto& e : eckPaar) { paarung.emplace_back(e.first, e.second); }
            }
        }
    }
    if (paarung.empty()) {
        aus.abgewiesen = aus.andereDreiecke;
        return aus;
    }
    const int ecken = static_cast<int>(andereD.size()) * 3;
    if (static_cast<int>(paarung.size()) < ecken) {
        aus.abgewiesen = ecken - static_cast<int>(paarung.size());
        return aus;
    }
    for (const auto& [a, b] : paarung) { n.uv[uz(a)] = n.uv[uz(b)]; }
    return aus;
}

