UvKasten kastenVon(const UvNetz& n, const UvInseln& in, int insel) {
    UvKasten k;
    for (const int h : eckenDerInsel(in, insel)) {
        const V2 w = n.uv[uz(h)];
        if (k.leer) {
            k.tief = k.hoch = w;
            k.leer = false;
            continue;
        }
        k.tief.x = std::min(k.tief.x, w.x);
        k.tief.y = std::min(k.tief.y, w.y);
        k.hoch.x = std::max(k.hoch.x, w.x);
        k.hoch.y = std::max(k.hoch.y, w.y);
    }
    return k;
}

bool inselFrei(const UvNetz& n, const UvInseln& in, int insel) {
    const std::span<const int> d = in.dreieckeVon(insel);
    if (d.empty()) { return false; }
    return std::all_of(d.begin(), d.end(), [&](int x) { return n.frei[uz(x)] != 0; });
}

bool inselGepinnt(const UvNetz& n, const UvInseln& in, int insel) {
    const std::span<const int> d = in.dreieckeVon(insel);
    if (d.empty()) { return false; }
    for (const int x : d) {
        for (int k = 0; k < 3; ++k) {
            if (n.pin[uz(x * 3 + k)] == 0) { return false; }
        }
    }
    return true;
}

void inselVersetzen(UvNetz& n, const UvInseln& in, int insel, float massstab, V2 weg) {
    const UvKasten k = kastenVon(n, in, insel);
    if (k.leer) { return; }
    const V2 m{(k.tief.x + k.hoch.x) * 0.5F, (k.tief.y + k.hoch.y) * 0.5F};
    for (const int h : eckenDerInsel(in, insel)) {
        V2& w = n.uv[uz(h)];
        w.x = m.x + (w.x - m.x) * massstab + weg.x;
        w.y = m.y + (w.y - m.y) * massstab + weg.y;
    }
}

void inselDrehen(UvNetz& n, const UvInseln& in, int insel, float bogen, V2 weg) {
    const UvKasten k = kastenVon(n, in, insel);
    if (k.leer) { return; }
    const V2 m{(k.tief.x + k.hoch.x) * 0.5F, (k.tief.y + k.hoch.y) * 0.5F};
    const float s = std::sin(bogen);
    const float c = std::cos(bogen);
    for (const int h : eckenDerInsel(in, insel)) {
        const float dx = n.uv[uz(h)].x - m.x;
        const float dy = n.uv[uz(h)].y - m.y;
        n.uv[uz(h)] = V2{m.x + dx * c - dy * s + weg.x, m.y + dx * s + dy * c + weg.y};
    }
}

float texelDichte(const UvNetz& n, const UvInseln& in, int insel, int aufloesung) {
    const InselFlaeche fl = flaechenVon(n, in, insel);
    if (fl.welt <= 0.0F || fl.uv <= 0.0F) { return 0.0F; }
    return static_cast<float>(aufloesung) * std::sqrt(fl.uv / fl.welt);
}

float mittlereDichte(const UvNetz& n, const UvInseln& in, int aufloesung, bool nurFeste) {
    std::vector<float> w;
    for (int i = 0; i < in.zahl; ++i) {
        if (nurFeste && inselFrei(n, in, i)) { continue; }
        const float d = texelDichte(n, in, i, aufloesung);
        if (d > 0.0F) { w.push_back(d); }
    }
    if (w.empty()) { return 0.0F; }
    std::sort(w.begin(), w.end());
    return w[w.size() / 2];
}

void inStreifen(UvNetz& n, const UvInseln& in, int insel, float dichte, int aufloesung) {
    const float jetzt = texelDichte(n, in, insel, aufloesung);
    const float sk = jetzt > 0.0F && dichte > 0.0F ? dichte / jetzt : 1.0F;
    inselVersetzen(n, in, insel, sk, V2{});
    constexpr float kStreifen = 1.0F;   // der Ablagestreifen u in [1, 2) neben der Kachel (WL kStripLow)
    constexpr float kLuecke = 0.02F;
    float oben = 0.0F;
    for (int i = 0; i < in.zahl; ++i) {
        if (i == insel) { continue; }
        const UvKasten k = kastenVon(n, in, i);
        if (k.leer || k.hoch.x < kStreifen) { continue; }
        oben = std::max(oben, k.hoch.y);
    }
    const UvKasten meine = kastenVon(n, in, insel);
    if (meine.leer) { return; }
    inselVersetzen(n, in, insel, 1.0F, V2{kStreifen + kLuecke - meine.tief.x, oben + kLuecke - meine.tief.y});
}

void dichteAngleichen(UvNetz& n, const UvInseln& in, std::span<const int> inseln, float dichte, int aufloesung) {
    if (dichte <= 0.0F) { return; }
    for (const int i : inseln) {
        const float jetzt = texelDichte(n, in, i, aufloesung);
        if (jetzt <= 0.0F) { continue; }
        inselVersetzen(n, in, i, dichte / jetzt, V2{});
    }
}

