constexpr int kKein = -1;

struct Abdruck {
    int breite = 0;
    int hoehe = 0;
    std::vector<u8> maske;
    std::vector<int> tief;
    std::vector<int> hoch;
    V2 ursprung{};
    long long bedeckt = 0;
    [[nodiscard]] bool leer() const { return bedeckt == 0; }
};

void verbreitern(Abdruck& a, int abstand) {
    if (abstand == 0 || a.maske.empty()) { return; }
    std::vector<u8> zug(a.maske.size(), 0);
    for (int y = 0; y < a.hoehe; ++y) {
        for (int x = 0; x < a.breite; ++x) {
            if (a.maske[uz(y * a.breite + x)] == 0) { continue; }
            const int von = std::max(x - abstand, 0);
            const int bis = std::min(a.breite - 1, x + abstand);
            for (int k = von; k <= bis; ++k) { zug[uz(y * a.breite + k)] = 1; }
        }
    }
    std::fill(a.maske.begin(), a.maske.end(), u8{0});
    for (int y = 0; y < a.hoehe; ++y) {
        for (int x = 0; x < a.breite; ++x) {
            if (zug[uz(y * a.breite + x)] == 0) { continue; }
            const int von = std::max(y - abstand, 0);
            const int bis = std::min(a.hoehe - 1, y + abstand);
            for (int k = von; k <= bis; ++k) { a.maske[uz(k * a.breite + x)] = 1; }
        }
    }
}

void profil(Abdruck& a) {
    a.tief.assign(uz(a.breite), kKein);
    a.hoch.assign(uz(a.breite), kKein);
    a.bedeckt = 0;
    for (int y = 0; y < a.hoehe; ++y) {
        for (int x = 0; x < a.breite; ++x) {
            if (a.maske[uz(y * a.breite + x)] == 0) { continue; }
            ++a.bedeckt;
            if (a.tief[uz(x)] == kKein) { a.tief[uz(x)] = y; }
            a.hoch[uz(x)] = y;
        }
    }
}

// WL profileOnly: nur die Spaltenprofile, um den Abstand verbreitert
void nurProfil(Abdruck& a, int abstand) {
    const std::vector<int> tief = a.tief;
    const std::vector<int> hoch = a.hoch;
    a.bedeckt = 0;
    for (int x = 0; x < a.breite; ++x) {
        const int von = std::max(x - abstand, 0);
        const int bis = std::min(a.breite - 1, x + abstand);
        int t = kKein;
        int h = 0;
        for (int k = von; k <= bis; ++k) {
            if (tief[uz(k)] != kKein) {
                t = t == kKein ? tief[uz(k)] : std::min(t, tief[uz(k)]);
                h = std::max(h, hoch[uz(k)]);
            }
        }
        if (t == kKein) {
            a.tief[uz(x)] = a.hoch[uz(x)] = kKein;
            continue;
        }
        a.tief[uz(x)] = std::max(t - abstand, 0);
        a.hoch[uz(x)] = std::min(a.hoehe - 1, h + abstand);
        a.bedeckt += a.hoch[uz(x)] - a.tief[uz(x)] + 1;
    }
}

struct Gestalt {
    std::vector<V2> ecken;   // je Dreieck drei
    V2 mitte{};
};

Gestalt gestaltVon(const UvNetz& n, const UvInseln& in, std::span<const int> gruppe) {
    Gestalt g;
    UvKasten ganz;
    for (const int i : gruppe) {
        const UvKasten k = kastenVon(n, in, i);
        if (k.leer) { continue; }
        if (ganz.leer) {
            ganz = k;
            continue;
        }
        ganz.tief.x = std::min(ganz.tief.x, k.tief.x);
        ganz.tief.y = std::min(ganz.tief.y, k.tief.y);
        ganz.hoch.x = std::max(ganz.hoch.x, k.hoch.x);
        ganz.hoch.y = std::max(ganz.hoch.y, k.hoch.y);
    }
    if (ganz.leer) { return g; }
    g.mitte = V2{(ganz.tief.x + ganz.hoch.x) * 0.5F, (ganz.tief.y + ganz.hoch.y) * 0.5F};
    for (const int i : gruppe) {
        for (const int d : in.dreieckeVon(i)) {
            for (int k = 0; k < 3; ++k) { g.ecken.push_back(n.uv[uz(d * 3 + k)]); }
        }
    }
    return g;
}

Abdruck abdruckVon(const Gestalt& g, float texel, int abstand, float bogen, bool maske = true) {
    Abdruck a;
    if (g.ecken.empty()) { return a; }
    const V2 m = g.mitte;
    const float s = std::sin(bogen);
    const float c = std::cos(bogen);
    const auto drehen = [&](V2 w) {
        const float dx = w.x - m.x;
        const float dy = w.y - m.y;
        return V2{m.x + dx * c - dy * s, m.y + dx * s + dy * c};
    };
    UvKasten k;
    for (const V2 e : g.ecken) {
        const V2 w = drehen(e);
        if (k.leer) {
            k.tief = k.hoch = w;
            k.leer = false;
            continue;
        }
        k.tief.x = std::min(k.tief.x, w.x);
        k.tief.y = std::min(k.tief.y, w.y);
        k.hoch.x = std::max(k.hoch.x, w.x);
        k.hoch.y = std::max(k.hoch.y, w.y);
    }
    const int rand = abstand + 2;
    a.ursprung = k.tief;
    a.breite = std::max(static_cast<int>(std::ceil(k.breite() * texel)) + 2 * rand, 1);
    a.hoehe = std::max(static_cast<int>(std::ceil(k.hoehe() * texel)) + 2 * rand, 1);
    if (static_cast<long long>(a.breite) * a.hoehe > 64LL * 1024 * 1024) {
        a.breite = a.hoehe = 0;
        return a;
    }
    if (maske) {
        a.maske.assign(uz(a.breite) * uz(a.hoehe), 0);
    } else {
        a.tief.assign(uz(a.breite), kKein);
        a.hoch.assign(uz(a.breite), 0);
    }
    const auto setzen = [&](V2 w) {
        const V2 t = drehen(w);
        return V2{(t.x - k.tief.x) * texel + static_cast<float>(rand), (t.y - k.tief.y) * texel + static_cast<float>(rand)};
    };
    for (std::size_t i = 0; i + 2 < g.ecken.size(); i += 3) {
        const V2 p0 = setzen(g.ecken[i]);
        const V2 p1 = setzen(g.ecken[i + 1]);
        const V2 p2 = setzen(g.ecken[i + 2]);
        const auto setze = [&](int x, int y) {
            if (maske) {
                a.maske[uz(y * a.breite + x)] = 1;
                return;
            }
            a.tief[uz(x)] = a.tief[uz(x)] == kKein ? y : std::min(a.tief[uz(x)], y);
            a.hoch[uz(x)] = std::max(a.hoch[uz(x)], y);
        };
        rasterDreieck(a.breite, a.hoehe, p0, p1, p2, true, setze);
        // Abweichung von WL (footprintOf): auch die Texel unter den drei Kanten. Der Ring von RasterTriangle liegt in
        // baryzentrischen Einheiten; ein Splitter-Dreieck (fast ohne Flaeche, aber lang) bekam so keinen Texel, galt als leer,
        // wurde nicht gesetzt und blieb auf anderen Inseln liegen (Selbsttest uv_a2: Sturmtruppler, Insel aus einem Dreieck,
        // UV-Flaeche 0,000002, 0,15 lang, nach "Packen - Alles" auf zwei anderen).
        for (const auto& [q0, q1] : {std::pair{p0, p1}, std::pair{p1, p2}, std::pair{p2, p0}}) {
            const float l = std::max(std::abs(q1.x - q0.x), std::abs(q1.y - q0.y));
            const int schritte = std::max(1, static_cast<int>(std::ceil(l * 2.0F)));
            for (int j = 0; j <= schritte; ++j) {
                const float f = static_cast<float>(j) / static_cast<float>(schritte);
                const int x = static_cast<int>(std::floor(q0.x + (q1.x - q0.x) * f));
                const int y = static_cast<int>(std::floor(q0.y + (q1.y - q0.y) * f));
                if (x >= 0 && y >= 0 && x < a.breite && y < a.hoehe) { setze(x, y); }
            }
        }
    }
    if (!maske) {
        nurProfil(a, abstand);
        return a;
    }
    verbreitern(a, abstand);
    profil(a);
    return a;
}

// WL principalAngle: die Hauptachse der UV-Punkte
float hauptWinkel(const UvNetz& n, const UvInseln& in, std::span<const int> gruppe) {
    double sx = 0.0;
    double sy = 0.0;
    int zahl = 0;
    for (const int i : gruppe) {
        for (const int d : in.dreieckeVon(i)) {
            for (int k = 0; k < 3; ++k) {
                sx += n.uv[uz(d * 3 + k)].x;
                sy += n.uv[uz(d * 3 + k)].y;
                ++zahl;
            }
        }
    }
    if (zahl == 0) { return 0.0F; }
    const double mx = sx / zahl;
    const double my = sy / zahl;
    double xx = 0.0;
    double yy = 0.0;
    double xy = 0.0;
    for (const int i : gruppe) {
        for (const int d : in.dreieckeVon(i)) {
            for (int k = 0; k < 3; ++k) {
                const double dx = n.uv[uz(d * 3 + k)].x - mx;
                const double dy = n.uv[uz(d * 3 + k)].y - my;
                xx += dx * dx;
                yy += dy * dy;
                xy += dx * dy;
            }
        }
    }
    return static_cast<float>(-0.5 * std::atan2(2.0 * xy, xx - yy));
}

void gruppeBewegen(UvNetz& n, const UvInseln& in, std::span<const int> gruppe, V2 mitte, float massstab, float bogen, V2 weg) {
    const float s = std::sin(bogen);
    const float c = std::cos(bogen);
    for (const int i : gruppe) {
        for (const int h : eckenDerInsel(in, i)) {
            const float dx = (n.uv[uz(h)].x - mitte.x) * massstab;
            const float dy = (n.uv[uz(h)].y - mitte.y) * massstab;
            n.uv[uz(h)] = V2{mitte.x + dx * c - dy * s + weg.x, mitte.y + dx * s + dy * c + weg.y};
        }
    }
}

