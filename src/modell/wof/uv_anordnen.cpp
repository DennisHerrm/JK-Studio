std::vector<int> eckenDerInsel(const UvInseln& in, int insel) {
    std::vector<int> aus;
    for (const int d : in.dreieckeVon(insel)) {
        for (int k = 0; k < 3; ++k) { aus.push_back(d * 3 + k); }
    }
    return aus;   // aufsteigend: die Dreiecke einer Insel stehen aufsteigend
}

