Plan connectKanten(PolyNetz& n, const std::vector<std::pair<int, int>>& kanten, int segmente) {
    Plan p;
    n.kantenBauen();
    segmente = std::clamp(segmente, 1, 64);
    // die neuen Punkte je Kante (in Richtung first -> second)
    std::map<std::pair<int, int>, std::vector<int>> aufKante;   // ungerichtetes Paar -> Punkte von min nach max
    for (const auto& [a, b] : kanten) {
        const int k = n.kanteVon(a, b);
        if (k < 0 || aufKante.count(kantenPaar(a, b)) != 0U) { continue; }
        const V pa = ort(n, a), pb = ort(n, b);
        std::vector<int> neu;
        std::vector<double> ts;
        for (int s = 0; s < segmente; ++s) {
            const double t = static_cast<double>(s + 1) / static_cast<double>(segmente + 1);
            const int q = neuerPunkt(n, pa + (pb - pa) * t, n.punkte[uz(a)].teil);
            neu.push_back(q);
            ts.push_back(t);
            // Slide: alle Punkte um ein Feld entlang der Kante (bei +-1 erreicht der erste/letzte das Ende)
            Bewegung m;
            m.punkt = q;
            vNach(pa + (pb - pa) * t, m.basis);
            vNach((pb - pa) * (1.0 / static_cast<double>(segmente + 1)), m.richtung);
            p.bewegungen.push_back(m);
        }
        inKanteEinsetzen(n, a, b, neu, ts, &p.uvBewegungen, 1.0 / static_cast<double>(segmente + 1));
        if (a > b) { std::reverse(neu.begin(), neu.end()); }
        aufKante[kantenPaar(a, b)] = neu;
    }
    if (aufKante.empty()) {
        p.grund = Ablehnung::LeereAuswahl;
        return p;
    }
    p.betragMin = -1.0F;
    p.betragMax = 1.0F;
    // Vielecke mit genau zwei gewaehlten Kanten: die Punkte verbinden (der i-te der einen mit dem gegenueberliegenden)
    std::set<int> neuePunkte;
    for (const auto& [k, v] : aufKante) {
        (void)k;
        neuePunkte.insert(v.begin(), v.end());
    }
    std::map<int, std::vector<std::pair<int, int>>> jeFlaeche;   // Vieleck -> Kanten (Paare)
    for (const auto& [k, v] : aufKante) {
        (void)v;
        // ein Vieleck traegt die geteilte Kante als a, Punkte..., b
        const std::vector<int>& pkt = aufKante[k];
        for (const auto& [fi, i] : seitenVon(n, k.first, pkt.front())) {
            (void)i;
            jeFlaeche[fi].push_back(k);
        }
    }
    // UvBewegungen zeigen auf Ecken-Nummern, die das Teilen verschiebt: vorher in Punkt-Bezug umschreiben
    struct UvP {
        int flaeche, punkt;
        float basis[2], richtung[2];
    };
    std::vector<UvP> uvp;
    for (const UvBewegung& u : p.uvBewegungen) {
        UvP x{};
        x.flaeche = u.flaeche;
        x.punkt = u.punkt;
        std::memcpy(x.basis, u.basis, sizeof x.basis);
        std::memcpy(x.richtung, u.richtung, sizeof x.richtung);
        uvp.push_back(x);
    }
    std::map<int, std::vector<int>> flaechenNachTeilung;   // altes Vieleck -> alle Teile
    for (auto& [fi, ks] : jeFlaeche) {
        std::sort(ks.begin(), ks.end());
        ks.erase(std::unique(ks.begin(), ks.end()), ks.end());
        flaechenNachTeilung[fi] = {fi};
        if (ks.size() != 2U) {
            if (ks.size() > 2U) { ++p.belassen; }
            continue;
        }
        // Punkte der beiden Kanten in der Reihenfolge des Vielecks
        const PFlaeche& f = n.flaechen[uz(fi)];
        std::vector<int> erste, zweite;
        const std::set<int> e1(aufKante[ks[0]].begin(), aufKante[ks[0]].end());
        const std::set<int> e2(aufKante[ks[1]].begin(), aufKante[ks[1]].end());
        for (const PEcke& c : f.ecken) {
            if (e1.count(c.punkt) != 0U) { erste.push_back(c.punkt); }
            if (e2.count(c.punkt) != 0U) { zweite.push_back(c.punkt); }
        }
        if (erste.size() != zweite.size()) { continue; }
        std::vector<int> teile = {fi};
        for (std::size_t s = 0; s < erste.size(); ++s) {
            const int x = erste[s], y = zweite[zweite.size() - 1U - s];
            for (const int t : teile) {
                const int i = eckeMit(n.flaechen[uz(t)], x), j = eckeMit(n.flaechen[uz(t)], y);
                if (i < 0 || j < 0) { continue; }
                const int neu = teileFlaeche(n, t, i, j);
                if (neu >= 0) {
                    teile.push_back(neu);
                    p.auswahl.kanten.push_back(kantenPaar(x, y));
                    ++p.geaendert;
                }
                break;
            }
        }
        flaechenNachTeilung[fi] = teile;
    }
    // UV-Bewegungen auf die Teile verteilen
    p.uvBewegungen.clear();
    for (const UvP& x : uvp) {
        const auto it = flaechenNachTeilung.find(x.flaeche);
        const std::vector<int> ziel = it == flaechenNachTeilung.end() ? std::vector<int>{x.flaeche} : it->second;
        for (const int t : ziel) {
            const int e = eckeMit(n.flaechen[uz(t)], x.punkt);
            if (e < 0) { continue; }
            UvBewegung u;
            u.flaeche = t;
            u.ecke = e;
            u.punkt = x.punkt;
            std::memcpy(u.basis, x.basis, sizeof u.basis);
            std::memcpy(u.richtung, x.richtung, sizeof u.richtung);
            p.uvBewegungen.push_back(u);
        }
    }
    if (p.auswahl.kanten.empty()) {
        for (const int q : neuePunkte) { p.auswahl.punkte.push_back(q); }
    }
    fertig(n, p);
    return p;
}

Plan connectPunkte(PolyNetz& n, const std::vector<int>& punkte) {
    Plan p;
    n.kantenBauen();
    std::set<int> sel(punkte.begin(), punkte.end());
    std::set<int> flaechen;
    for (const int x : sel) {
        if (x >= 0 && uz(x) < n.punktFlaechen.size()) {
            for (const int f : n.punktFlaechen[uz(x)]) { flaechen.insert(f); }
        }
    }
    bool zwei = false;
    for (const int fi : flaechen) {
        // aufeinanderfolgende gewaehlte Ecken, die noch keine Kante teilen (3ds Max: ein Sechseck 0, 2, 4 -> Dreieck)
        std::vector<int> g;
        for (const PEcke& c : n.flaechen[uz(fi)].ecken) {
            if (sel.count(c.punkt) != 0U) { g.push_back(c.punkt); }
        }
        if (g.size() < 2U) { continue; }
        zwei = true;
        std::vector<std::pair<int, int>> paare;
        for (std::size_t i = 0; i < g.size(); ++i) {
            if (g.size() == 2U && i == 1U) { break; }
            paare.emplace_back(g[i], g[(i + 1) % g.size()]);
        }
        std::vector<int> teile = {fi};
        for (const auto& [x, y] : paare) {
            for (const int t : teile) {
                const int i = eckeMit(n.flaechen[uz(t)], x), j = eckeMit(n.flaechen[uz(t)], y);
                if (i < 0 || j < 0) { continue; }
                const int neu = teileFlaeche(n, t, i, j);
                if (neu >= 0) {
                    teile.push_back(neu);
                    p.auswahl.kanten.push_back(kantenPaar(x, y));
                    ++p.geaendert;
                    break;
                }
            }
        }
    }
    if (!zwei) {
        p.grund = sel.empty() ? Ablehnung::LeereAuswahl : Ablehnung::NichtEinVieleck;
        return p;
    }
    if (p.geaendert == 0) {
        p.grund = Ablehnung::SchonVerbunden;
        return p;
    }
    fertig(n, p);
    return p;
}

Plan loopCut(PolyNetz& n, std::pair<int, int> kante, int segmente) {
    n.kantenBauen();
    const int k = n.kanteVon(kante.first, kante.second);
    Plan p;
    if (k < 0) {
        p.grund = Ablehnung::LeereAuswahl;
        return p;
    }
    // der Ring, jede Kante gleich ausgerichtet (im Viereck laeuft die gegenueberliegende Kante i+3 -> i+2)
    std::vector<std::pair<int, int>> ring;
    std::set<int> drin;
    ring.push_back(kante);
    drin.insert(k);
    bool viereck = false;
    for (int seite = 0; seite < 2; ++seite) {
        std::pair<int, int> jetzt = kante;
        if (seite == 1) { std::swap(jetzt.first, jetzt.second); }
        int kommend = -1;
        while (true) {
            // das Vieleck, in dem die Kante jetzt.first -> jetzt.second laeuft
            int fi = -1, i = -1;
            for (const auto& [g, gi] : seitenVon(n, jetzt.first, jetzt.second)) {
                if (g != kommend && n.flaechen[uz(g)].ecken[uz(gi)].punkt == jetzt.first) {
                    fi = g;
                    i = gi;
                }
            }
            if (fi < 0 || n.flaechen[uz(fi)].ecken.size() != 4U) { break; }
            viereck = true;
            const PFlaeche& f = n.flaechen[uz(fi)];
            const std::pair<int, int> gegen{punktVon(f, i + 3), punktVon(f, i + 2)};
            const int kg = n.kanteVon(gegen.first, gegen.second);
            if (kg < 0 || drin.count(kg) != 0U) { break; }
            drin.insert(kg);
            ring.push_back(seite == 0 ? gegen : std::pair<int, int>{gegen.second, gegen.first});
            // weiter: im Nachbarn laeuft die Kante gegen.first -> gegen.second
            jetzt = gegen;
            kommend = fi;
        }
    }
    if (!viereck) {
        p.grund = Ablehnung::KeinViereck;
        return p;
    }
    return connectKanten(n, ring, segmente);
}

Plan schnitt(PolyNetz& n, const SchnittPunkt& von, const SchnittPunkt& nach) {
    Plan p;
    n.kantenBauen();
    // Kantenpunkte zuerst einsetzen
    const auto punktAus = [&](const SchnittPunkt& s) -> int {
        if (s.punkt >= 0) { return s.punkt; }
        const int k = n.kanteVon(s.kante.first, s.kante.second);
        if (k < 0) { return -1; }
        const double t = std::clamp(static_cast<double>(s.t), 0.0, 1.0);
        if (t <= 1e-6) { return s.kante.first; }
        if (t >= 1.0 - 1e-6) { return s.kante.second; }
        const V a = ort(n, s.kante.first), b = ort(n, s.kante.second);
        const int q = neuerPunkt(n, a + (b - a) * t, n.punkte[uz(s.kante.first)].teil);
        inKanteEinsetzen(n, s.kante.first, s.kante.second, {q}, {t}, nullptr, 0.0);
        ++p.geaendert;
        return q;
    };
    const int a = punktAus(von);
    const int b = punktAus(nach);
    if (a < 0 || b < 0 || a == b) {
        p.grund = Ablehnung::LeereAuswahl;
        return p;
    }
    // ein Vieleck mit beiden Punkten
    int ziel = -1;
    for (const int fi : n.punktFlaechen[uz(a)]) {
        if (eckeMit(n.flaechen[uz(fi)], b) >= 0) { ziel = fi; }
    }
    if (ziel < 0) {
        p.grund = Ablehnung::NichtEinVieleck;
        if (p.geaendert > 0) {   // der Kantenpunkt bleibt (Max setzt ihn auch, wenn der Schnitt endet)
            p.grund = Ablehnung::Keine;
            p.auswahl.punkte.push_back(b);
            fertig(n, p);
        }
        return p;
    }
    if (n.kanteVon(a, b) >= 0) {
        p.auswahl.punkte.push_back(b);
        if (p.geaendert == 0) { p.grund = Ablehnung::SchonVerbunden; }
        fertig(n, p);
        return p;
    }
    const int i = eckeMit(n.flaechen[uz(ziel)], a), j = eckeMit(n.flaechen[uz(ziel)], b);
    if (teileFlaeche(n, ziel, i, j) < 0) {
        p.grund = Ablehnung::SchonVerbunden;
        return p;
    }
    ++p.geaendert;
    p.auswahl.kanten.push_back(kantenPaar(a, b));
    p.auswahl.punkte.push_back(b);   // der naechste Schnitt beginnt hier (Max Cut laeuft weiter)
    fertig(n, p);
    return p;
}

