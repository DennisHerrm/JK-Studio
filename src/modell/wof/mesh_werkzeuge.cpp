namespace {

// Die Kopien der Randpunkte jeder Region wandern nach innen (vorzeichen +1) bzw. aussen (-1)
void einrueckBewegungen(PolyNetz& n, const std::vector<std::vector<int>>& rs, const std::vector<std::map<int, int>>& kopien, double vorzeichen,
                        const std::vector<std::vector<RandKante>>& raenderNeu, Plan& p) {
    for (std::size_t ri = 0; ri < rs.size(); ++ri) {
        const std::map<int, V> dir = einrueckRichtungen(n, raenderNeu[ri]);
        std::vector<UvAbbild> abb;
        for (const int fi : rs[ri]) { abb.push_back(uvAbbild(n, n.flaechen[uz(fi)])); }
        for (const auto& [alt, neu] : kopien[ri]) {
            (void)alt;
            const auto it = dir.find(neu);
            if (it == dir.end()) { continue; }
            Bewegung m;
            m.punkt = neu;
            std::memcpy(m.basis, n.punkte[uz(neu)].ort, sizeof m.basis);
            vNach(it->second * vorzeichen, m.richtung);
            p.bewegungen.push_back(m);
            // die UV der Ecke in jedem Vieleck der Region wandert in seiner Quellflaeche mit (WL Resample)
            for (std::size_t q = 0; q < rs[ri].size(); ++q) {
                const int fi = rs[ri][q];
                const PFlaeche& f = n.flaechen[uz(fi)];
                const int e = eckeMit(f, neu);
                if (e < 0 || !abb[q].gut) { continue; }
                float u0[2], u1[2];
                uvBei(abb[q], vAus(m.basis), u0);
                uvBei(abb[q], vAus(m.basis) + vAus(m.richtung), u1);
                UvBewegung u;
                u.flaeche = fi;
                u.ecke = e;
                u.punkt = neu;
                for (int c = 0; c < 2; ++c) {
                    u.basis[c] = f.ecken[uz(e)].e.uv[c];
                    u.richtung[c] = u1[c] - u0[c];
                }
                p.uvBewegungen.push_back(u);
            }
        }
    }
}

}  // namespace

Plan inset(PolyNetz& n, const std::vector<int>& flaechen, InsetArt art) {
    Plan p;
    n.kantenBauen();
    const auto rs = regionen(n, flaechen, art == InsetArt::JeVieleck);
    if (rs.empty()) {
        p.grund = Ablehnung::LeereAuswahl;
        return p;
    }
    const auto kopien = hebeRegionen(n, rs, p);
    std::vector<std::vector<RandKante>> raender;
    for (const auto& r : rs) { raender.push_back(regionsRand(n, r)); }
    einrueckBewegungen(n, rs, kopien, 1.0, raender, p);
    for (const auto& r : rs) {
        for (const int f : r) { p.auswahl.flaechen.push_back(f); }
    }
    p.betragMin = 0.0F;
    betragGrenzen(n, p);
    fertig(n, p);
    return p;
}

Plan bevel(PolyNetz& n, const std::vector<int>& flaechen, ExtrudeArt art, float hoehe) {
    Plan p = extrudeFlaechen(n, flaechen, art);
    if (p.abgelehnt()) { return p; }
    betragAnwenden(n, p, hoehe);
    // der Umriss: die Kopien am Rand der gehobenen Regionen nach aussen (Max Bevel Outline: + groesser)
    const auto rs = regionen(n, p.auswahl.flaechen, art == ExtrudeArt::JeVieleck);
    std::vector<std::vector<RandKante>> raender;
    std::vector<std::map<int, int>> kopien;
    for (const auto& r : rs) {
        raender.push_back(regionsRand(n, r));
        std::map<int, int> k;
        for (const RandKante& x : raender.back()) {
            k[x.a] = x.a;
            k[x.b] = x.b;
        }
        kopien.push_back(k);
    }
    Plan q;
    q.auswahl = p.auswahl;
    q.geaendert = p.geaendert;
    q.zurueckgefallen = p.zurueckgefallen;
    einrueckBewegungen(n, rs, kopien, -1.0, raender, q);
    betragGrenzen(n, q);
    fertig(n, q);
    return q;
}

