Plan chamferKanten(PolyNetz& n, const std::vector<std::pair<int, int>>& kanten, int segmente, float profil) {
    Plan p;
    n.kantenBauen();
    std::set<std::pair<int, int>> g;
    std::set<int> b;
    for (const auto& [x, y] : kanten) {
        const int k = n.kanteVon(x, y);
        if (k < 0) { continue; }
        if (n.istRand(k)) {
            p.grund = Ablehnung::Rand;   // WL BorderEdgeChamfer: die Regeln brauchen eine Flaeche auf jeder Seite
            return p;
        }
        g.insert(kantenPaar(x, y));
        b.insert(x);
        b.insert(y);
    }
    if (g.empty()) {
        p.grund = Ablehnung::LeereAuswahl;
        return p;
    }
    return chamferKern(n, b, g, true, std::clamp(segmente, 1, 64), profil);
}

Plan chamferPunkte(PolyNetz& n, const std::vector<int>& punkte) {
    n.kantenBauen();
    std::set<int> b;
    for (const int x : punkte) {
        if (x >= 0 && uz(x) < n.punkte.size() && !n.punktFlaechen[uz(x)].empty()) { b.insert(x); }
    }
    if (b.empty()) {
        Plan p;
        p.grund = Ablehnung::LeereAuswahl;
        return p;
    }
    return chamferKern(n, b, {}, false, 1, 0.5F);
}

