// Kern von Chamfer an Kanten und Punkten (WL PlanChamferEdges/PlanChamferVertices)
Plan chamferKern(PolyNetz& n, const std::set<int>& beruehrt, const std::set<std::pair<int, int>>& gewaehlt, bool kantenModus, int segmente, float profil) {
    Plan p;
    const auto istGewaehlt = [&](int a, int b) { return gewaehlt.count(kantenPaar(a, b)) != 0U; };
    // je beruehrtem Punkt: ein Punkt auf jeder ungewaehlten Kante, ein Gehrungspunkt je Vieleck mit zwei gewaehlten
    std::map<std::pair<int, int>, int> aufKante;   // (Punkt, anderer Punkt) -> neuer Punkt
    std::map<std::pair<int, int>, int> gehrung;    // (Punkt, Vieleck) -> neuer Punkt
    std::map<int, std::vector<int>> ring;          // Punkt -> neue Punkte
    std::vector<UvAbbild> abbild(n.flaechen.size());
    std::vector<char> abbildDa(n.flaechen.size(), 0);
    const auto abb = [&](int fi) -> const UvAbbild& {
        if (abbildDa[uz(fi)] == 0) {
            abbild[uz(fi)] = uvAbbild(n, n.flaechen[uz(fi)]);
            abbildDa[uz(fi)] = 1;
        }
        return abbild[uz(fi)];
    };
    for (const int v : beruehrt) {
        const V pv = ort(n, v);
        std::map<int, double> laengeAuf;   // anderer Punkt -> Faktor (1 / sin theta, der kleinste gewinnt)
        for (const int fi : n.punktFlaechen[uz(v)]) {
            const PFlaeche& f = n.flaechen[uz(fi)];
            const int i = eckeMit(f, v);
            const int vor = punktVon(f, i - 1), nach = punktVon(f, i + 1);
            for (const int w : {vor, nach}) {
                if (istGewaehlt(v, w)) { continue; }
                double fak = 1.0;
                const int andere = w == vor ? nach : vor;
                if (kantenModus && istGewaehlt(v, andere)) {
                    const double th = winkel(ort(n, w) - pv, ort(n, andere) - pv);
                    if (th >= kPi / 180.0 && th <= kPi * 179.0 / 180.0) { fak = 1.0 / std::sin(th); }
                }
                auto it = laengeAuf.find(w);
                if (it == laengeAuf.end()) {
                    laengeAuf[w] = fak;
                } else {
                    it->second = std::min(it->second, fak);   // die naehere von zwei Versetzungen gewinnt
                }
            }
        }
        for (const auto& [w, fak] : laengeAuf) {
            const int neu = neuerPunkt(n, pv, n.punkte[uz(v)].teil);
            aufKante[{v, w}] = neu;
            ring[v].push_back(neu);
            Bewegung m;
            m.punkt = neu;
            vNach(pv, m.basis);
            vNach(einheit(ort(n, w) - pv) * fak, m.richtung);
            p.bewegungen.push_back(m);
        }
        if (kantenModus) {
            for (const int fi : n.punktFlaechen[uz(v)]) {
                const PFlaeche& f = n.flaechen[uz(fi)];
                const int i = eckeMit(f, v);
                const int vor = punktVon(f, i - 1), nach = punktVon(f, i + 1);
                if (!istGewaehlt(v, vor) || !istGewaehlt(v, nach)) { continue; }
                // der Punkt, an dem sich die beiden versetzten Linien treffen: x = (w1 + w2) / (1 + w1.w2)
                const V c = mitte(n, f);
                const auto innen = [&](int w) {
                    const V d = einheit(ort(n, w) - pv);
                    V x = c - pv;
                    return einheit(x - d * punkt(x, d));
                };
                const V w1 = innen(vor), w2 = innen(nach);
                const double nn = 1.0 + punkt(w1, w2);
                const int neu = neuerPunkt(n, pv, n.punkte[uz(v)].teil);
                gehrung[{v, fi}] = neu;
                ring[v].push_back(neu);
                Bewegung m;
                m.punkt = neu;
                vNach(pv, m.basis);
                vNach(nn > 1e-6 ? (w1 + w2) * (1.0 / nn) : V{}, m.richtung);
                p.bewegungen.push_back(m);
            }
        }
    }
    // --- Blender-Teil Anfang (GPL-2.0-or-later, bmesh_bevel.cc; siehe Kopf) ---
    // MRESTE 3b: was Blenders Segmente vom alten Netz brauchen (selcount, tri_corner_test, Normalen fuer pipe_test)
    FaseInfo info;
    const bool mitSegmenten = kantenModus && segmente > 1;
    if (mitSegmenten) {
        const float r = fase::superR(std::max(profil, 0.01F));
        for (const int v : beruehrt) {
            std::set<int> nachbarn;
            std::vector<V>& nrm = info.normalen[v];
            for (const int fi : n.punktFlaechen[uz(v)]) {
                const PFlaeche& f = n.flaechen[uz(fi)];
                const int i = eckeMit(f, v);
                nachbarn.insert(punktVon(f, i - 1));
                nachbarn.insert(punktVon(f, i + 1));
                nrm.push_back(aussen(n, f));
            }
            int sel = 0;
            for (const int w : nachbarn) { sel += istGewaehlt(v, w) ? 1 : 0; }
            info.gewaehlt[v] = sel;
            // tri_corner_test (bmesh_bevel.cc:4634); BM_edge_calc_face_angle_signed_ex: Winkel der Normalen, negativ
            // an einer hohlen Kante (die andere Flaeche liegt vor der Ebene der ersten), ohne zwei Flaechen 0
            int tt = 0;
            const auto ri = ring.find(v);
            if (ri != ring.end() && ri->second.size() == 3U) {
                int inEbene = 0;
                double summe = 0.0;
                for (const int w : nachbarn) {
                    double ang = 0.0;
                    const int k = n.kanteVon(v, w);
                    if (k >= 0 && n.kanten[uz(k)].seiten.size() == 2U) {
                        const PFlaeche& f1 = n.flaechen[uz(n.kanten[uz(k)].seiten[0].first)];
                        const PFlaeche& f2 = n.flaechen[uz(n.kanten[uz(k)].seiten[1].first)];
                        const V n1 = aussen(n, f1), n2 = aussen(n, f2);
                        ang = winkel(n1, n2);
                        if (punkt(n1, mitte(n, f2) - ort(n, v)) > 0.0) { ang = -ang; }
                    }
                    const double absAng = std::fabs(ang);
                    if (absAng <= kPi / 4.0) {
                        ++inEbene;
                    } else if (absAng >= 3.0 * kPi / 4.0) {
                        tt = -1;
                        break;
                    }
                    summe += ang;
                }
                if (tt == 0) {
                    const double diff = std::fabs(std::fabs(summe) - 3.0 * kPi / 2.0);
                    if (inEbene != zi(nachbarn.size()) - 3 || (r == fase::kRQuadrat && diff > kPi / 16.0) || diff > kPi / 4.0) {
                        tt = -1;
                    } else if (nachbarn.size() == 3U && sel == 3) {
                        tt = 1;
                    }
                }
            }
            info.triTest[v] = tt;
        }
    }
    // --- Blender-Teil Ende ---
    std::unordered_map<int, const Bewegung*> bew;
    for (const Bewegung& b : p.bewegungen) { bew[b.punkt] = &b; }
    // die Vielecke an den beruehrten Punkten: die Ecke v wird zur Liste ihrer neuen Punkte
    std::map<std::pair<int, int>, std::vector<int>> ersatz;   // (Vieleck, Punkt) -> neue Punkte in der Reihenfolge des Vielecks
    std::map<std::pair<int, int>, std::pair<int, int>> nachbarnIn;   // (Vieleck, Punkt) -> (vor, nach) im alten Vieleck
    std::vector<std::vector<PEcke>> neueEcken(n.flaechen.size());
    std::vector<char> geaendert(n.flaechen.size(), 0);
    const std::size_t alteFlaechen = n.flaechen.size();
    for (std::size_t fi = 0; fi < alteFlaechen; ++fi) {
        const PFlaeche& f = n.flaechen[fi];
        if (f.weg) { continue; }
        bool trifft = false;
        for (const PEcke& c : f.ecken) { trifft = trifft || beruehrt.count(c.punkt) != 0U; }
        if (!trifft) { continue; }
        geaendert[fi] = 1;
        const int k = zi(f.ecken.size());
        for (int i = 0; i < k; ++i) {
            const PEcke& c = f.ecken[uz(i)];
            if (beruehrt.count(c.punkt) == 0U) {
                neueEcken[fi].push_back(c);
                continue;
            }
            const int v = c.punkt;
            const int vor = punktVon(f, i - 1), nach = punktVon(f, i + 1);
            nachbarnIn[{zi(fi), v}] = {vor, nach};
            std::vector<int> liste;
            if (kantenModus && istGewaehlt(v, vor) && istGewaehlt(v, nach)) {
                liste.push_back(gehrung[{v, zi(fi)}]);
            } else {
                if (!istGewaehlt(v, vor)) { liste.push_back(aufKante[{v, vor}]); }
                if (!istGewaehlt(v, nach)) { liste.push_back(aufKante[{v, nach}]); }
            }
            ersatz[{zi(fi), v}] = liste;
            for (const int q : liste) {
                PEcke e = c;
                e.punkt = q;
                neueEcken[fi].push_back(e);
            }
        }
    }
    // UV der neuen Ecken wandert in ihrem Vieleck mit
    for (std::size_t fi = 0; fi < alteFlaechen; ++fi) {
        if (geaendert[fi] == 0) { continue; }
        const UvAbbild& a = abb(zi(fi));
        n.flaechen[fi].ecken = neueEcken[fi];
        flaecheGeaendert(n.flaechen[fi]);
        n.beruehren(n.flaechen[fi].teil);
        for (std::size_t e = 0; e < n.flaechen[fi].ecken.size(); ++e) {
            const auto it = bew.find(n.flaechen[fi].ecken[e].punkt);
            if (it == bew.end() || !a.gut) { continue; }
            float u0[2], u1[2];
            uvBei(a, vAus(it->second->basis), u0);
            uvBei(a, vAus(it->second->basis) + vAus(it->second->richtung), u1);
            UvBewegung u;
            u.flaeche = zi(fi);
            u.ecke = zi(e);
            u.punkt = n.flaechen[fi].ecken[e].punkt;
            for (int c = 0; c < 2; ++c) {
                u.basis[c] = n.flaechen[fi].ecken[e].e.uv[c];
                u.richtung[c] = u1[c] - u0[c];
            }
            p.uvBewegungen.push_back(u);
        }
    }
    // Streifen je gewaehlter Kante: [X1, X2, Y2, Y1] (X1/Y1 aus dem Vieleck mit a -> b, X2/Y2 aus dem mit b -> a)
    std::vector<std::vector<PEcke>> streifen;
    std::vector<int> streifenTeil;
    if (kantenModus) {
        for (const auto& [a, b] : gewaehlt) {
            // die Vielecke an a-b (vor dem Umbau): eines mit a -> b, eines mit b -> a
            int f1 = -1, f2 = -1;
            for (const int fi : n.punktFlaechen[uz(a)]) {
                if (uz(fi) >= alteFlaechen) { continue; }
                if (ersatz.count({fi, a}) == 0U || ersatz.count({fi, b}) == 0U) { continue; }
                // Richtung aus der neuen Eckenliste: der letzte Ersatz von a gefolgt vom ersten Ersatz von b?
                const std::vector<int>& ra = ersatz[{fi, a}];
                const std::vector<int>& rb = ersatz[{fi, b}];
                if (ra.empty() || rb.empty()) { continue; }
                const PFlaeche& f = n.flaechen[uz(fi)];
                const int ia = eckeMit(f, ra.back());
                if (ia >= 0 && punktVon(f, ia + 1) == rb.front()) {
                    f1 = fi;
                } else {
                    const int ib = eckeMit(f, rb.back());
                    if (ib >= 0 && punktVon(f, ib + 1) == ra.front()) { f2 = fi; }
                }
            }
            if (f1 < 0 || f2 < 0) { continue; }
            const PFlaeche& F1 = n.flaechen[uz(f1)];
            const PFlaeche& F2 = n.flaechen[uz(f2)];
            const int x1 = ersatz[{f1, a}].back(), y1 = ersatz[{f1, b}].front();
            const int y2 = ersatz[{f2, b}].back(), x2 = ersatz[{f2, a}].front();
            std::vector<PEcke> s;
            const auto dazu = [&](const PFlaeche& f, int pt) {
                const int e = eckeMit(f, pt);
                if (e < 0) { return; }
                if (!s.empty() && s.back().punkt == pt) { return; }
                s.push_back(f.ecken[uz(e)]);
            };
            dazu(F1, x1);
            dazu(F2, x2);
            dazu(F2, y2);
            dazu(F1, y1);
            if (s.size() >= 2U && s.front().punkt == s.back().punkt) { s.pop_back(); }
            if (s.size() >= 3U) {
                streifen.push_back(std::move(s));
                streifenTeil.push_back(F1.teil);
                if (mitSegmenten) {
                    // je Ende die Kante und ihre Nachbarkanten in F1 (Start) und F2 (Ende) wie EdgeHalf prev/next
                    const auto ende = [&](int v, int anderes, int s1, int s2) {
                        const auto andererNachbar = [&](int fi) {
                            const auto [vor, nach] = nachbarnIn[{fi, v}];
                            return vor == anderes ? nach : vor;
                        };
                        const int w1 = andererNachbar(f1), w2 = andererNachbar(f2);
                        FaseEnde e;
                        e.x1 = s1;
                        e.x2 = s2;
                        e.k.v = ort(n, v);
                        e.k.anderes = ort(n, anderes);
                        e.k.dVor = ort(n, w1) - e.k.v;
                        e.k.dNach = ort(n, w2) - e.k.v;
                        e.k.vorGefast = istGewaehlt(v, w1);
                        e.k.nachGefast = istGewaehlt(v, w2);
                        e.k.gewaehlt = info.gewaehlt[v];
                        if (s1 != s2) { info.enden.push_back(e); }
                    };
                    ende(a, b, x1, x2);
                    ende(b, a, y1, y2);
                }
            }
        }
    }
    for (std::size_t i = 0; i < streifen.size(); ++i) {
        const int f = neueFlaeche(n, streifen[i], streifenTeil[i]);
        p.auswahl.flaechen.push_back(f);
        ++p.geaendert;
    }
    for (const int v : beruehrt) { n.punkte[uz(v)].weg = true; }
    n.kantenBauen();
    // Flicken: der Rand aus Kanten zwischen Ringpunkten eines Punkts, mit nur einer Seite, als Ring geschlossen
    for (const auto& [v, rp] : ring) {
        if (rp.size() < 3U) { continue; }
        std::set<int> rs(rp.begin(), rp.end());
        std::map<int, std::pair<int, int>> weiter;   // von -> (nach, Vieleck): die Kante laeuft im Vieleck von -> nach
        for (const PKante& k : n.kanten) {
            if (k.seiten.size() != 1U || rs.count(k.a) == 0U || rs.count(k.b) == 0U) { continue; }
            const auto [fi, i] = k.seiten[0];
            const PFlaeche& f = n.flaechen[uz(fi)];
            weiter[punktVon(f, i)] = {punktVon(f, i + 1), fi};
        }
        if (weiter.size() < 3U) { continue; }
        // der Flicken laeuft gegen die Kanten der Nachbarn: nach -> von
        std::vector<int> folge;
        int start = weiter.begin()->first;
        int x = start;
        bool zu = false;
        for (std::size_t s = 0; s <= weiter.size(); ++s) {
            folge.push_back(x);
            const auto it = weiter.find(x);
            if (it == weiter.end()) { break; }
            x = it->second.first;
            if (x == start) {
                zu = true;
                break;
            }
        }
        if (!zu || folge.size() < 3U) { continue; }
        std::reverse(folge.begin(), folge.end());
        std::vector<PEcke> fl;
        int teil = n.punkte[uz(v)].teil;
        for (const int q : folge) {
            const int g = weiter[q].second;
            const int e = eckeMit(n.flaechen[uz(g)], q);
            PEcke c;
            c.punkt = q;
            if (e >= 0) { c.e = n.flaechen[uz(g)].ecken[uz(e)].e; }
            fl.push_back(c);
            teil = n.flaechen[uz(g)].teil;
        }
        const int f = neueFlaeche(n, std::move(fl), teil);
        if (!kantenModus) { p.auswahl.flaechen.push_back(f); }
        if (mitSegmenten) { info.flicken[v] = f; }
        n.kantenBauen();
    }
    if (!kantenModus) {
        for (const auto& [v, rp] : ring) {
            (void)v;
            for (const int q : rp) { p.auswahl.punkte.push_back(q); }
        }
    }
    if (mitSegmenten) { segmentieren(n, p, segmente, profil, info); }
    p.betragMin = 0.0F;
    betragGrenzen(n, p);
    fertig(n, p);
    return p;
}

