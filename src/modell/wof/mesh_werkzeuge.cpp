// interp_weights_poly_v2 (BLI math_geom.cc): Mittelwert-Koordinaten des Orts im Vieleck, in dessen Ebene (axis_dominant_v3_to_m3;
// die Gewichte haengen nicht von der Drehung in der Ebene ab)
std::vector<double> mittelwertGewichte(const AlteFlaeche& f, V ort) {
    const int n = zi(f.orte.size());
    std::vector<double> w(uz(n), 0.0);
    if (n < 3) { return w; }
    const V z = einheit(f.normale);
    const V hilf = std::fabs(z.x) < 0.9 ? V{1.0, 0.0, 0.0} : V{0.0, 1.0, 0.0};
    const V ax = einheit(kreuz(hilf, z));
    const V ay = kreuz(z, ax);
    std::vector<std::array<double, 2>> v;
    for (const V& q : f.orte) { v.push_back({punkt(q, ax), punkt(q, ay)}); }
    const std::array<double, 2> co{punkt(ort, ax), punkt(ort, ay)};
    struct Dir {
        double x = 0.0, y = 0.0, len = 0.0;
    };
    const auto dir = [&](int i) {   // DIR_V2_SET(d, v[i], co)
        Dir d;
        d.x = v[uz(i)][0] - co[0];
        d.y = v[uz(i)][1] - co[1];
        d.len = std::sqrt(d.x * d.x + d.y * d.y);
        return d;
    };
    const auto halbTan = [](const Dir& a, const Dir& b) {   // mean_value_half_tan_v2
        const double flaeche = a.x * b.y - a.y * b.x;
        if (flaeche != 0.0) {
            const double r = (a.len * b.len - (a.x * b.x + a.y * b.y)) / flaeche;
            if (std::isfinite(r)) { return r; }
        }
        return 0.0;
    };
    const auto anteil = [&](int a, int b) {   // line_point_factor_v2
        const double ux = v[uz(b)][0] - v[uz(a)][0], uy = v[uz(b)][1] - v[uz(a)][1];
        const double d = ux * ux + uy * uy;
        return d == 0.0 ? 0.0 : ((co[0] - v[uz(a)][0]) * ux + (co[1] - v[uz(a)][1]) * uy) / d;
    };
    const auto abstandQ = [&](int a, int b) {   // dist_squared_to_line_segment_v2
        const double t = std::clamp(anteil(a, b), 0.0, 1.0);
        const double px = v[uz(a)][0] + (v[uz(b)][0] - v[uz(a)][0]) * t - co[0];
        const double py = v[uz(a)][1] + (v[uz(b)][1] - v[uz(a)][1]) * t - co[1];
        return px * px + py * py;
    };
    constexpr double kEps = 1e-5;   // "take care, low values cause #36105"
    int iCurr = n - 1;
    int iNext = 0;
    Dir dCurr = dir(n - 2);
    Dir dNext = dir(n - 1);
    double htVor = halbTan(dCurr, dNext);
    double summe = 0.0;
    int treffer = 0;   // 1: auf einem Punkt (IS_POINT_IX), 2: auf einer Seite (IS_SEGMENT_IX)
    while (iNext < n) {
        if (dNext.len < kEps) {
            treffer = 1;
            break;
        }
        if (abstandQ(iCurr, iNext) < kEps * kEps) {
            treffer = 2;
            break;
        }
        dCurr = dNext;
        dNext = dir(iNext);
        const double ht = halbTan(dCurr, dNext);
        w[uz(iCurr)] = (htVor + ht) / dCurr.len;
        summe += w[uz(iCurr)];
        iCurr = iNext++;
        htVor = ht;
    }
    if (treffer != 0) {
        std::fill(w.begin(), w.end(), 0.0);
        if (treffer == 1) {
            w[uz(iCurr)] = 1.0;
        } else {
            const double fac = std::clamp(anteil(iCurr, iNext), 0.0, 1.0);
            w[uz(iCurr)] = 1.0 - fac;
            w[uz(iNext)] = fac;
        }
    } else if (summe != 0.0) {
        for (double& x : w) { x /= summe; }
    }
    return w;
}

// BM_loop_interp_from_face (bmesh_interp.cc): UV und Gewichte (CustomData_bmesh_interp der Ecken- und Punktdaten) mit
// den Mittelwert-Koordinaten gemischt; die Normale rechnet normalenNeu danach aus der Form (wie Blender)
Ecke eckeInFlaeche(const AlteFlaeche& f, V ort) {
    const std::vector<double> w = mittelwertGewichte(f, ort);
    std::size_t best = 0;
    for (std::size_t i = 1; i < w.size(); ++i) {
        if (w[i] > w[best]) { best = i; }
    }
    Ecke e = f.ecken[best];
    double uv[2] = {0.0, 0.0};
    V nn;
    std::map<int, double> g;
    for (std::size_t i = 0; i < w.size(); ++i) {
        const Ecke& c = f.ecken[i];
        for (int k = 0; k < 2; ++k) { uv[k] += w[i] * static_cast<double>(c.uv[k]); }
        nn = nn + V{c.normale[0], c.normale[1], c.normale[2]} * w[i];
        for (int k = 0; k < 4; ++k) {
            if (c.gewicht[k] > 0.0F) { g[c.knochen[k]] += static_cast<double>(c.gewicht[k]) * w[i]; }
        }
    }
    for (int k = 0; k < 2; ++k) { e.uv[k] = static_cast<float>(uv[k]); }
    if (laenge(nn) > 0.0) { vNach(einheit(nn), e.normale); }
    // die vier groessten Einfluesse, Summe 1 (iMAX_G2_BONEWEIGHTS_PER_VERT, wie mischen)
    std::vector<std::pair<double, int>> l;
    for (const auto& [kn, x] : g) {
        if (x > 0.0) { l.emplace_back(x, kn); }
    }
    std::stable_sort(l.begin(), l.end(), [](const auto& x, const auto& y) { return x.first > y.first; });
    if (l.size() > 4U) { l.resize(4U); }
    double sum = 0.0;
    for (const auto& x : l) { sum += x.first; }
    for (int k = 0; k < 4; ++k) {
        e.knochen[k] = 0;
        e.gewicht[k] = 0.0F;
    }
    for (std::size_t k = 0; k < l.size(); ++k) {
        e.knochen[k] = static_cast<std::uint8_t>(l[k].second);
        e.gewicht[k] = sum > 0.0 ? static_cast<float>(l[k].first / sum) : 0.0F;
    }
    return e;
}

// CustomData_data_equals fuer CD_PROP_FLOAT2 (blenkernel customdata.cc layerEqual_propfloat2): Abstand im Quadrat < 0,00001
bool uvGleich(const float a[2], const float b[2]) {
    const double du = static_cast<double>(a[0]) - b[0], dv = static_cast<double>(a[1]) - b[1];
    return du * du + dv * dv < 0.00001;
}
// compare_v2v2(..., STD_UV_CONNECT_LIMIT = 0,0001) in determine_uv_vert_connectivity (:764)
bool uvVerbunden(const float a[2], const float b[2]) {
    return std::fabs(a[0] - b[0]) <= 0.0001F && std::fabs(a[1] - b[1]) <= 0.0001F;
}

Kreis kreisUm(const PolyNetz& n, int v, const std::set<std::pair<int, int>>& gewaehlt) {
    Kreis k;
    const std::vector<int>& fl = n.punktFlaechen[uz(v)];
    if (fl.empty()) { return k; }
    std::map<int, std::pair<int, int>> vonVor;   // Vorgaenger -> (Vieleck, Nachfolger)
    for (const int fi : fl) {
        const PFlaeche& f = n.flaechen[uz(fi)];
        const int i = eckeMit(f, v);
        const int vor = punktVon(f, i - 1);
        if (vonVor.count(vor) != 0U) { return Kreis{}; }
        vonVor[vor] = {fi, punktVon(f, i + 1)};
    }
    const int start = vonVor.begin()->first;
    int x = start;
    for (std::size_t s = 0; s < fl.size(); ++s) {
        const auto it = vonVor.find(x);
        if (it == vonVor.end()) { return Kreis{}; }
        k.w.push_back(x);
        k.fNach.push_back(it->second.first);
        k.gefast.push_back(gewaehlt.count(kantenPaar(v, x)) != 0U ? 1 : 0);
        x = it->second.second;
    }
    k.zu = x == start;
    if (!k.zu) { return Kreis{}; }
    return k;
}

// BM_face_point_inside_test: in der Ebene des Vielecks (axis_dominant_v3_to_m3), isect_point_poly_v2
bool punktInFlaeche(const AlteFlaeche& f, V o) {
    const V z = einheit(f.normale);
    const V hilf = std::fabs(z.x) < 0.9 ? V{1.0, 0.0, 0.0} : V{0.0, 1.0, 0.0};
    const V ax = einheit(kreuz(hilf, z));
    const V ay = kreuz(z, ax);
    const double px = punkt(o, ax), py = punkt(o, ay);
    bool drin = false;
    const std::size_t k = f.orte.size();
    for (std::size_t i = 0, j = k - 1; i < k; j = i++) {
        const double xi = punkt(f.orte[i], ax), yi = punkt(f.orte[i], ay);
        const double xj = punkt(f.orte[j], ax), yj = punkt(f.orte[j], ay);
        if ((yi > py) != (yj > py) && px < (xj - xi) * (py - yi) / (yj - yi) + xi) { drin = !drin; }
    }
    return drin;
}
V aufStrecke(V o, V a, V b) {   // closest_to_line_segment_v3
    const V d = b - a;
    const double dd = punkt(d, d);
    return a + d * (dd > 0.0 ? std::clamp(punkt(o - a, d) / dd, 0.0, 1.0) : 0.0);
}
// die zwei Kanten des Vielecks am Punkt v (get_incident_edges :4891) als Orte (v, Nachbar)
std::array<std::array<V, 2>, 2> kantenAm(const AlteFlaeche& f, int v) {
    std::array<std::array<V, 2>, 2> r{};
    const std::size_t k = f.punkte.size();
    for (std::size_t i = 0; i < k; ++i) {
        if (f.punkte[i] != v) { continue; }
        r[0] = {f.orte[i], f.orte[(i + k - 1) % k]};
        r[1] = {f.orte[i], f.orte[(i + 1) % k]};
    }
    return r;
}
V naehereKante(V o, const std::array<std::array<V, 2>, 2>& e) {   // find_closer_edge (:4913), gezogen
    const V s1 = aufStrecke(o, e[0][0], e[0][1]);
    const V s2 = aufStrecke(o, e[1][0], e[1][1]);
    return punkt(s1 - o, s1 - o) < punkt(s2 - o, s2 - o) ? s1 : s2;
}

// choose_rep_face (:1211): der Reihe nach kleinere UV-Insel, gewaehlte Flaeche, kleinere Materialnummer (hier der Teil),
// Mitte der Huelle (BM_face_calc_center_bounds) z, x, y; je Stufe gewinnt ein eindeutiges Minimum
int vertreterWahl(const FaseInfo& info, const std::vector<int>& kandidaten) {
    const std::size_t nf = kandidaten.size();
    std::vector<std::array<double, 6>> wert(nf);
    std::vector<char> lebt(nf, 0);
    int zahl = 0;
    for (std::size_t f = 0; f < nf; ++f) {
        const int fi = kandidaten[f];
        const auto it = fi >= 0 ? info.alte.find(fi) : info.alte.end();
        if (it == info.alte.end()) { continue; }
        lebt[f] = 1;
        ++zahl;
        V lo = it->second.orte[0], hi = it->second.orte[0];
        for (const V& o : it->second.orte) {
            lo = V{std::min(lo.x, o.x), std::min(lo.y, o.y), std::min(lo.z, o.z)};
            hi = V{std::max(hi.x, o.x), std::max(hi.y, o.y), std::max(hi.z, o.z)};
        }
        const V c = (lo + hi) * 0.5;
        wert[f] = {info.komponente.empty() ? 0.0 : static_cast<double>(info.komponente[uz(fi)]),
                   info.gewaehlteFlaechen.count(fi) != 0U ? 0.0 : 1.0,
                   static_cast<double>(it->second.teil),
                   c.z,
                   c.x,
                   c.y};
    }
    int best = -1;
    for (std::size_t w = 0; zahl > 1 && w < 6; ++w) {
        for (std::size_t f = 0; f < nf; ++f) {
            if (lebt[f] == 0 || zi(f) == best) { continue; }
            if (best == -1) {
                best = zi(f);
                continue;
            }
            if (wert[f][w] < wert[uz(best)][w]) {
                best = zi(f);
                for (std::size_t i = f; i-- > 0;) {
                    if (lebt[i] != 0) {
                        lebt[i] = 0;
                        --zahl;
                    }
                }
            } else if (wert[f][w] > wert[uz(best)][w]) {
                lebt[f] = 0;
                --zahl;
            }
        }
    }
    if (best == -1) {
        for (std::size_t f = 0; f < nf && best == -1; ++f) {
            if (lebt[f] != 0) { best = zi(f); }
        }
    }
    return best == -1 ? (nf > 0 ? kandidaten[0] : -1) : kandidaten[uz(best)];
}

// Der Plan bewegt jeden neuen Punkt linear mit dem Betrag. Die Entscheidungen am Punkt (innen, naehere Kante) und die
// Richtung der UV fallen bei einem kleinen Betrag, an dem die Lage nur von den Kanten am Punkt abhaengt (beim Betrag 1 laege
// ein Punkt schon jenseits der Nachbarecken): ein Tausendstel der kuerzesten Kante der alten Vielecke am Punkt.
double kleinerBetrag(const FaseInfo& info, int v) {
    double kurz = 0.0;
    for (const auto& [fi, af] : info.alte) {
        (void)fi;
        const std::size_t k = af.punkte.size();
        for (std::size_t i = 0; i < k; ++i) {
            if (af.punkte[i] != v) { continue; }
            for (const std::size_t j : {(i + 1) % k, (i + k - 1) % k}) {
                const double l = laenge(af.orte[j] - af.orte[i]);
                if (l > 0.0 && (kurz == 0.0 || l < kurz)) { kurz = l; }
            }
        }
    }
    return 1e-3 * (kurz > 0.0 ? kurz : 1.0);
}

// frep_for_center_poly (:5034) mit is_bad_uv_poly (:5013, projected_boundary_area :4968: die Randpunkte in der Ebene der
// Flaeche, die ausserhalb auf die naehere ihrer zwei Kanten am Punkt gezogen; Flaeche unter BEVEL_EPSILON_BIG = 1e-4).
// Die Flaeche gilt beim Betrag 1: gemessen beim kleinen Betrag t, geteilt durch t^2.
int vertreterMitte(const FaseInfo& info, int v, const std::function<V(int)>& beiT, double t) {
    const auto ki = info.kreise.find(v);
    const auto ri = info.rand.find(v);
    if (ki == info.kreise.end() || ri == info.rand.end()) { return -1; }
    const Kreis& k = ki->second;
    const int d = zi(k.w.size());
    int sel = 0;
    for (const char g : k.gefast) { sel += g != 0 ? 1 : 0; }
    const bool alle = sel == 1;
    int irgendeine = -1;
    std::vector<int> wahl;
    for (int i = 0; i < d; ++i) {
        if (k.gefast[uz(i)] == 0 && !alle) { continue; }
        const int f = vertreterWahl(info, {k.fNach[uz((i + d - 1) % d)], k.fNach[uz(i)]});
        if (f < 0) { continue; }
        if (irgendeine < 0) { irgendeine = f; }
        if (std::find(wahl.begin(), wahl.end(), f) != wahl.end()) { continue; }
        const AlteFlaeche& af = info.alte.at(f);
        const auto kanten = kantenAm(af, v);
        const V z = einheit(af.normale);
        const V hilf = std::fabs(z.x) < 0.9 ? V{1.0, 0.0, 0.0} : V{0.0, 1.0, 0.0};
        const V ax = einheit(kreuz(hilf, z));
        const V ay = kreuz(z, ax);
        std::vector<std::array<double, 2>> pr;
        int innen = 0;
        for (const RandPunkt& r : ri->second) {
            V o = beiT(r.punkt);
            if (innen < 3 && punktInFlaeche(af, o)) {
                ++innen;
            } else {
                o = naehereKante(o, kanten);
            }
            pr.push_back({punkt(o, ax), punkt(o, ay)});
        }
        double flaeche = 0.0;
        for (std::size_t a = 0; a < pr.size(); ++a) {
            const auto& p0 = pr[a];
            const auto& p1 = pr[(a + 1) % pr.size()];
            flaeche += p0[0] * p1[1] - p1[0] * p0[1];
        }
        if (std::fabs(flaeche) * 0.5 / (t * t) < 1e-4) { continue; }
        wahl.push_back(f);
    }
    if (wahl.empty()) { return irgendeine; }
    return vertreterWahl(info, wahl);
}

// die UV allein wie eckeInFlaeche, in double (die Richtung der UV entsteht aus zwei nahen Orten)
void uvInFlaeche(const AlteFlaeche& f, V ort, double out[2]) {
    const std::vector<double> w = mittelwertGewichte(f, ort);
    out[0] = out[1] = 0.0;
    for (std::size_t i = 0; i < w.size(); ++i) {
        for (int k = 0; k < 2; ++k) { out[k] += w[i] * static_cast<double>(f.ecken[i].uv[k]); }
    }
}

void segmentieren(PolyNetz& n, Plan& p, int segmente, float profil, FaseInfo& info) {
    const fase::Abstaende abst = fase::abstaende(segmente, std::max(profil, 0.01F));
    std::unordered_map<int, std::size_t> bewVon;
    for (std::size_t i = 0; i < p.bewegungen.size(); ++i) { bewVon[p.bewegungen[i].punkt] = i; }
    const auto beiT = [&](int q, double t) {   // Ort beim Betrag t
        const Bewegung& b = p.bewegungen[bewVon.at(q)];
        return vAus(b.basis) + vAus(b.richtung) * t;
    };
    const auto bei1 = [&](int q) {   // Ort beim Betrag 1
        const Bewegung& b = p.bewegungen[bewVon.at(q)];
        return vAus(b.basis) + vAus(b.richtung);
    };
    const auto neuBei = [&](V v, V ziel, int teil) {
        const int q = neuerPunkt(n, v, teil);
        Bewegung m;
        m.punkt = q;
        vNach(v, m.basis);
        vNach(ziel - v, m.richtung);
        p.bewegungen.push_back(m);
        bewVon[q] = p.bewegungen.size() - 1U;
        return q;
    };
    const auto schluessel = [](int a, int b) { return a < b ? std::pair<int, int>{a, b} : std::pair<int, int>{b, a}; };
    // das Profil eines Streifenendes von `von` zum anderen Ringpunkt
    const auto profilVon = [&](const FaseEnde& e, int von) {
        fase::Profil pr;
        if (von == e.x1) {
            fase::kantenProfil(pr, bei1(e.x1), bei1(e.x2), e.k, abst.r);
        } else {
            fase::KantenDaten k = e.k;
            std::swap(k.dVor, k.dNach);
            std::swap(k.vorGefast, k.nachGefast);
            fase::kantenProfil(pr, bei1(e.x2), bei1(e.x1), k, abst.r);
        }
        return pr;
    };
    std::map<std::pair<int, int>, std::vector<std::size_t>> endenVon;   // Ringpunktpaar -> Streifenenden
    for (std::size_t i = 0; i < info.enden.size(); ++i) {
        const FaseEnde& e = info.enden[i];
        if (bewVon.count(e.x1) == 0U || bewVon.count(e.x2) == 0U) { continue; }
        endenVon[schluessel(e.x1, e.x2)].push_back(i);
    }
    std::map<std::pair<int, int>, std::vector<int>> boegen;   // (A, B) mit A < B -> Punkte von A nach B ohne A und B
    std::set<int> gitterFlaechen;
    // 1. die Ecken mit Gitter (ihre Randpunkte gibt das Gitter vor, wie bevel_build_rings)
    for (const auto& [v, fl] : info.flicken) {
        const auto gw = info.gewaehlt.find(v);
        if (gw == info.gewaehlt.end() || gw->second < 2 || n.flaechen[uz(fl)].weg) { continue; }
        const PFlaeche alt = n.flaechen[uz(fl)];
        const int m = zi(alt.ecken.size());
        bool alleBewegt = m >= 3;
        for (const PEcke& c : alt.ecken) { alleBewegt = alleBewegt && bewVon.count(c.punkt) != 0U; }
        if (!alleBewegt) { continue; }
        // Blenders Reihenfolge (gegen den Uhrzeiger von aussen) ist die umgekehrte des Vielecks
        std::vector<int> rp;
        for (int i = m - 1; i >= 0; --i) {
            rp.push_back(alt.ecken[uz(i)].punkt);
        }
        fase::EckDaten ed;
        ed.v = ort(n, v);
        const double tKlein = kleinerBetrag(info, v);
        ed.gewaehlt = gw->second;
        const auto tt = info.triTest.find(v);
        ed.triTest = tt == info.triTest.end() ? 0 : tt->second;
        std::vector<int> kanteVon(uz(m), -1);   // je Seite das Streifenende (oder -1: gerade)
        for (int i = 0; i < m; ++i) {
            const int a = rp[uz(i)], b = rp[uz((i + 1) % m)];
            fase::Profil pr;
            const auto it = endenVon.find(schluessel(a, b));
            if (it != endenVon.end() && it->second.size() == 1U) {
                kanteVon[uz(i)] = zi(it->second[0]);
                pr = profilVon(info.enden[it->second[0]], a);
            } else {
                fase::linienProfil(pr, bei1(a), bei1(b));
            }
            fase::berechnen(pr, abst);
            ed.seiten.push_back(std::move(pr));
        }
        // je Randpunkt i: efirst = die Kante der Seite i - 1, elast = ebev = die Kante der Seite i (build_boundary :3239);
        // e1->fnext ist das alte Vieleck des Randpunkts mit der Kante e1, ebev->fprev (boundvert_rep_face :843) das mit ebev
        const auto vieleckMit = [&](int q, int nachbar) {
            const auto it = info.ringFlaechen.find(q);
            if (it == info.ringFlaechen.end()) { return -1; }
            for (const RingFlaeche& r : it->second) {
                if (r.vor == nachbar || r.nach == nachbar) { return r.flaeche; }
            }
            return -1;
        };
        std::vector<int> vertreter(uz(m), -1);
        for (int i = 0; i < m; ++i) {
            fase::RandKanten r;
            const int k1 = kanteVon[uz((i + m - 1) % m)], k2 = kanteVon[uz(i)];
            if (k1 >= 0) {
                r.e1 = true;
                r.e1a = info.enden[uz(k1)].k.v;
                r.e1b = info.enden[uz(k1)].k.anderes;
                const int f1 = vieleckMit(rp[uz(i)], info.enden[uz(k1)].anderes);
                if (f1 >= 0) { r.normale = info.alte.at(f1).normale; }
            }
            if (k2 >= 0) {
                r.e2 = true;
                r.e2a = info.enden[uz(k2)].k.v;
                r.e2b = info.enden[uz(k2)].k.anderes;
                vertreter[uz(i)] = vieleckMit(rp[uz(i)], info.enden[uz(k2)].anderes);
            }
            if (vertreter[uz(i)] < 0) {
                const auto it = info.ringFlaechen.find(rp[uz(i)]);
                if (it != info.ringFlaechen.end() && !it->second.empty()) { vertreter[uz(i)] = it->second.front().flaeche; }
            }
            ed.rand.push_back(r);
        }
        // pipe_test (:3979): drei Seiten mit Kante, die erste und dritte Kante auf einer Geraden, alle Vielecke parallel dazu
        if ((m == 3 || m == 4) && (ed.gewaehlt == 3 || ed.gewaehlt == 4)) {
            for (int i = 0; i < m && ed.pipe < 0; ++i) {
                const int e1 = kanteVon[uz(i)], e2 = kanteVon[uz((i + 1) % m)], e3 = kanteVon[uz((i + 2) % m)];
                if (e1 < 0 || e2 < 0 || e3 < 0) { continue; }
                const V d1 = einheit(info.enden[uz(e1)].k.v - info.enden[uz(e1)].k.anderes);
                const V d3 = einheit(info.enden[uz(e3)].k.anderes - info.enden[uz(e3)].k.v);
                if (winkel(d1, d3) >= 2.0 * kPi / 180.0) { continue; }
                bool parallel = true;
                const auto nv = info.normalen.find(v);
                if (nv != info.normalen.end()) {
                    for (const V& q : nv->second) { parallel = parallel && std::fabs(punkt(d1, q)) <= 1e-4; }
                }
                if (!parallel) { break; }
                ed.pipe = i;
                ed.pipeA = info.enden[uz(e1)].k.v;
                ed.pipeB = info.enden[uz(e1)].k.anderes;
            }
        }
        const fase::Gitter g = fase::eckenGitter(ed, abst);
        const int ns = g.ns;
        const int ns2 = ns / 2;
        const int teil = alt.teil;
        // die Randpunkte jeder Seite aus dem Gitter
        std::vector<std::vector<int>> rand(uz(m));
        for (int i = 0; i < m; ++i) {
            const int a = rp[uz(i)], b = rp[uz((i + 1) % m)];
            std::vector<int> ids;
            for (int k = 1; k < ns; ++k) {
                int ci = 0, cj = 0, ck = 0;
                g.kanon(i, 0, k, ci, cj, ck);
                ids.push_back(neuBei(ed.v, g.at(ci, cj, ck), teil));
            }
            rand[uz(i)] = ids;
            if (a > b) { std::reverse(ids.begin(), ids.end()); }
            boegen[schluessel(a, b)] = ids;
        }
        std::map<std::array<int, 3>, int> innen;
        const auto id = [&](int i, int j, int k) {
            int ci = 0, cj = 0, ck = 0;
            g.kanon(i, j, k, ci, cj, ck);
            if (cj == 0) { return ck == 0 ? rp[uz(ci)] : rand[uz(ci)][uz(ck - 1)]; }
            if (ck == 0) { return rand[uz((ci + m - 1) % m)][uz(ns - cj - 1)]; }
            const std::array<int, 3> s = {ci, cj, ck};
            const auto it = innen.find(s);
            if (it != innen.end()) { return it->second; }
            const int q = neuBei(ed.v, g.at(ci, cj, ck), teil);
            innen[s] = q;
            return q;
        };
        // Ecken-Daten wie bevel_build_rings (:5629) mit bev_create_ngon (:907): jede Ecke in ihrer Vertreter-Flaeche
        // (BM_loop_interp_from_face), vorher auf die Kante se gezogen (closest_to_line_segment_v3). Der Ort waechst linear
        // mit dem Betrag und ist bei 0 der alte Punkt; die UV wandert mit (Betrag 0: die UV der Ecke am alten Punkt).
        struct GitterEcke {
            int punkt = -1;
            int vertreter = -1;
            float uv0[2]{};
            float uvR[2]{};
        };
        std::vector<std::pair<int, std::vector<GitterEcke>>> gitterEcken;   // neues Vieleck -> seine Ecken
        const auto eckeBei = [&](int q, int fr, int kante, GitterEcke& ge) {
            PEcke c;
            c.punkt = q;
            ge.punkt = q;
            ge.vertreter = fr;
            if (fr < 0) { return c; }
            const AlteFlaeche& af = info.alte.at(fr);
            const auto gezogen = [&](V o) {   // closest_to_line_segment_v3 auf die alte Kante
                if (kante < 0) { return o; }
                const V a = info.enden[uz(kante)].k.v, d = info.enden[uz(kante)].k.anderes - a;
                const double dd = punkt(d, d);
                return a + d * (dd > 0.0 ? std::clamp(punkt(o - a, d) / dd, 0.0, 1.0) : 0.0);
            };
            c.e = eckeInFlaeche(af, gezogen(beiT(q, tKlein)));
            double d0[2], d1[2];
            uvInFlaeche(af, gezogen(ed.v), d0);
            uvInFlaeche(af, gezogen(beiT(q, tKlein)), d1);
            for (int z = 0; z < 2; ++z) {
                ge.uv0[z] = static_cast<float>(d0[z]);
                ge.uvR[z] = static_cast<float>((d1[z] - d0[z]) / tKlein);
                c.e.uv[z] = ge.uv0[z];
            }
            return c;
        };
        n.flaechen[uz(fl)].weg = true;
        const int ungerade = ns % 2;
        // ungerade Segmentzahl (:5584): frep_beats_next je Randpunkt (choose_rep_face zwischen ihm und dem naechsten) und
        // center_frep; e->is_seam der gefasten Kanten (Streifenenden kanteVon)
        std::vector<char> schlaegtNaechsten(uz(m), 0);
        int mitteVertreter = -1;
        if (ungerade != 0) {
            mitteVertreter = vertreterMitte(info, v, [&](int q) { return beiT(q, tKlein); }, tKlein);
            for (int i = 0; i < m; ++i) {
                const int f1 = vertreter[uz(i)], f2 = vertreter[uz((i + 1) % m)];
                schlaegtNaechsten[uz(i)] = vertreterWahl(info, {f1, f2}) == f1 ? 1 : 0;
            }
        }
        const bool punktNaht = info.mitNaht.count(v) != 0U;
        const auto istNaht = [&](int kante) {
            return kante >= 0 && info.naht.count(kantenPaar(v, info.enden[uz(kante)].anderes)) != 0U;
        };
        // snap_edge_for_center_vmesh_vert (:5408)
        const auto mitteZiehen = [&](int i, int ePrev, int eNext) {
            const int vi = (i + m - 1) % m, ni = (i + 1) % m;
            if (schlaegtNaechsten[uz(vi)] != 0 && vertreter[uz(vi)] == mitteVertreter) { return ePrev; }
            if (schlaegtNaechsten[uz(i)] == 0 && vertreter[uz(ni)] == mitteVertreter) { return eNext; }
            return -1;
        };
        std::vector<int> mitteEcke(uz(m), -1), mitteKante(uz(m), -1), mitteFlaeche(uz(m), -1);
        for (int i = 0; i < m; ++i) {
            const int f = vertreter[uz(i)], f2 = vertreter[uz((i + 1) % m)];
            const int bme = kanteVon[uz(i)], bmePrev = kanteVon[uz((i + m - 1) % m)], bmeNext = kanteVon[uz((i + 1) % m)];
            const int fc = ungerade != 0 ? (schlaegtNaechsten[uz(i)] != 0 ? f : f2) : -1;
            const int b1 = istNaht(bmePrev) ? bmePrev : -1, b2 = istNaht(bme) ? bme : -1, b3 = istNaht(bmeNext) ? bmeNext : -1;
            for (int j = 0; j < ns2; ++j) {
                for (int k = 0; k < ns2 + ungerade; ++k) {
                    // Blender (i,j,k), (i,j,k+1), (i,j+1,k+1), (i,j+1,k) gegen den Uhrzeiger - hier umgekehrt
                    int fr[4] = {f, f, f, f};
                    int se[4] = {-1, -1, -1, -1};
                    if (ungerade == 0) {
                        if (k == ns2 - 1) { se[1] = bme; }
                        if (j == ns2 - 1 && bmePrev >= 0) { se[3] = bmePrev; }
                        se[2] = se[1] >= 0 ? se[1] : se[3];
                    } else {
                        // snap_edges_for_vmesh_vert (:5453) mit eprev = b1, enext = b2, enextnext = b3
                        for (int c = 0; c < 4; ++c) {
                            const int jj = c < 2 ? j : j + 1;
                            const int kk = (c == 0 || c == 3) ? k : k + 1;
                            if (jj < ns2 && kk == ns2) {
                                if (schlaegtNaechsten[uz(i)] == 0) { se[c] = b2; }
                            } else if (jj < ns2 && kk == ns2 + 1) {
                                if (schlaegtNaechsten[uz(i)] != 0) { se[c] = b2; }
                            } else if (jj == ns2 && kk < ns2) {
                                if (schlaegtNaechsten[uz((i + m - 1) % m)] != 0) { se[c] = b1; }
                            } else if (jj == ns2 && kk == ns2) {
                                se[c] = mitteZiehen(i, b1, b2);
                            } else if (jj == ns2 && kk == ns2 + 1) {
                                se[c] = mitteZiehen((i + 1) % m, b2, b3);
                            }
                        }
                        if (k == ns2) {
                            // die Mittelspalte: an einer Naht (oder ohne gefaste Kante) ganz in fc, sonst halb f, halb f2
                            if (bme < 0 || istNaht(bme)) {
                                fr[0] = fr[1] = fr[2] = fr[3] = fc;
                            } else {
                                fr[1] = fr[2] = f2;
                            }
                            if (j == ns2 - 1) {
                                mitteEcke[uz(i)] = id(i, j + 1, k);
                                mitteKante[uz(i)] = se[3];
                                mitteFlaeche[uz(i)] = punktNaht ? mitteVertreter : f;
                            }
                        }
                    }
                    std::vector<GitterEcke> ge(4);
                    std::vector<PEcke> q = {eckeBei(id(i, j + 1, k), fr[3], se[3], ge[0]), eckeBei(id(i, j + 1, k + 1), fr[2], se[2], ge[1]),
                                            eckeBei(id(i, j, k + 1), fr[1], se[1], ge[2]), eckeBei(id(i, j, k), fr[0], se[0], ge[3])};
                    const int nf = neueFlaeche(n, std::move(q), teil);
                    gitterFlaechen.insert(nf);
                    gitterEcken.emplace_back(nf, std::move(ge));
                }
            }
        }
        if (ungerade != 0) {
            // die Mitte (:5714): je Randpunkt die Ecke (i, ns/2, ns/2) in center_face_interps, gezogen wie die Ecke 3 des
            // Vierecks (i, ns/2 - 1, ns/2)
            std::vector<PEcke> mitte;
            std::vector<GitterEcke> ge;
            for (int i = m - 1; i >= 0; --i) {
                GitterEcke g1;
                mitte.push_back(eckeBei(mitteEcke[uz(i)], mitteFlaeche[uz(i)], mitteKante[uz(i)], g1));
                ge.push_back(g1);
            }
            const int nf = neueFlaeche(n, std::move(mitte), teil);
            gitterFlaechen.insert(nf);
            gitterEcken.emplace_back(nf, std::move(ge));
        }
        // die Ecken fuer bevel_merge_uvs (uvVertreter)
        for (const auto& [nf, liste] : gitterEcken) {
            for (const GitterEcke& g1 : liste) {
                if (g1.vertreter < 0) { continue; }
                UvEintrag u;
                u.flaeche = nf;
                u.punkt = g1.punkt;
                u.vertreter = g1.vertreter;
                for (int z = 0; z < 2; ++z) {
                    u.uv0[z] = g1.uv0[z];
                    u.uvR[z] = g1.uvR[z];
                }
                info.eintraege.push_back(u);
            }
        }
        p.geaendert += zi(gitterFlaechen.size());
    }
    // 2. die uebrigen Streifenenden: ein Profil, oder zwei gemittelt (weld, build_vmesh)
    for (const auto& [key, liste] : endenVon) {
        if (boegen.count(key) != 0U) { continue; }
        const FaseEnde& e0 = info.enden[liste[0]];
        fase::Profil p1 = profilVon(e0, key.first);
        std::vector<V> pkt;
        if (liste.size() == 2U) {
            fase::Profil p2 = profilVon(info.enden[liste[1]], key.second);
            fase::weldEbenen(p1, p2, e0.k.v);
            fase::berechnen(p1, abst);
            fase::berechnen(p2, abst);
            pkt = fase::weldPunkte(p1, p2, abst);
        } else {
            if (e0.k.gewaehlt == 1) { fase::endEbene(p1, e0.k.v); }   // build_boundary_terminal_edge (edgecount >= 3)
            fase::berechnen(p1, abst);
            for (int k = 1; k < segmente; ++k) { pkt.push_back(fase::profilPunkt(p1, k, segmente, abst)); }
        }
        std::vector<int> ids;
        const int teil = n.punkte[uz(key.first)].teil;
        for (const V& q : pkt) { ids.push_back(neuBei(e0.k.v, q, teil)); }
        boegen[key] = ids;
    }
    const auto bogen = [&](int a, int b) {   // A, Bogen ..., B
        std::vector<int> folge{a};
        const auto it = boegen.find(schluessel(a, b));
        if (it != boegen.end()) {
            if (a < b) {
                folge.insert(folge.end(), it->second.begin(), it->second.end());
            } else {
                folge.insert(folge.end(), it->second.rbegin(), it->second.rend());
            }
        }
        folge.push_back(b);
        return folge;
    };
    // die Streifen in Vierecke
    std::vector<int> neueAuswahl;
    std::set<int> streifenNeu;
    for (const int f : p.auswahl.flaechen) {
        const PFlaeche alt = n.flaechen[uz(f)];
        if (alt.ecken.size() != 4U) {
            neueAuswahl.push_back(f);
            streifenNeu.insert(f);
            continue;
        }
        const std::vector<int> oben = bogen(alt.ecken[0].punkt, alt.ecken[1].punkt);    // X1 .. X2
        const std::vector<int> unten = bogen(alt.ecken[3].punkt, alt.ecken[2].punkt);   // Y1 .. Y2
        if (oben.size() != unten.size() || oben.size() < 3U) {
            neueAuswahl.push_back(f);
            streifenNeu.insert(f);
            continue;
        }
        n.flaechen[uz(f)].weg = true;
        const int k = zi(oben.size()) - 1;
        const auto sv = info.streifenVon.find(f);
        if (sv != info.streifenVon.end()) { info.streifen[sv->second].vierecke.clear(); }
        const auto ecke = [k](const PEcke& c0, const PEcke& c1, int punktNr, int i) {
            PEcke e;
            e.punkt = punktNr;
            e.e = mischen(c0.e, c1.e, static_cast<double>(i) / static_cast<double>(k));
            return e;
        };
        for (int s = 0; s < k; ++s) {
            std::vector<PEcke> q = {ecke(alt.ecken[0], alt.ecken[1], oben[uz(s)], s), ecke(alt.ecken[0], alt.ecken[1], oben[uz(s + 1)], s + 1),
                                    ecke(alt.ecken[3], alt.ecken[2], unten[uz(s + 1)], s + 1), ecke(alt.ecken[3], alt.ecken[2], unten[uz(s)], s)};
            const int nf = neueFlaeche(n, std::move(q), alt.teil);
            neueAuswahl.push_back(nf);
            streifenNeu.insert(nf);
            if (sv != info.streifenVon.end()) { info.streifen[sv->second].vierecke.push_back(nf); }
        }
        p.geaendert += k - 1;
    }
    p.auswahl.flaechen = neueAuswahl;
    // die Bogenpunkte in jede andere Flaeche mit einer Endkante; ihre UV wandert mit denselben Anteilen wie der Ort
    std::map<std::pair<int, int>, UvBewegung> uvVon;   // (Flaeche, Punkt)
    for (const UvBewegung& u : p.uvBewegungen) { uvVon[{u.flaeche, u.punkt}] = u; }
    std::vector<UvBewegung> uvNeu;
    for (std::size_t fi = 0; fi < n.flaechen.size(); ++fi) {
        PFlaeche& f = n.flaechen[fi];
        if (f.weg || streifenNeu.count(zi(fi)) != 0U || gitterFlaechen.count(zi(fi)) != 0U) { continue; }
        std::vector<PEcke> neu;
        bool anders = false;
        const std::size_t ke = f.ecken.size();
        for (std::size_t i = 0; i < ke; ++i) {
            const PEcke c = f.ecken[i];
            const PEcke d = f.ecken[(i + 1) % ke];
            neu.push_back(c);
            const std::pair<int, int> key = c.punkt < d.punkt ? std::pair<int, int>{c.punkt, d.punkt} : std::pair<int, int>{d.punkt, c.punkt};
            const auto it = boegen.find(key);
            if (it == boegen.end() || it->second.empty()) { continue; }
            const std::vector<int> folge = bogen(c.punkt, d.punkt);
            const auto uc = uvVon.find({zi(fi), c.punkt});
            const auto ud = uvVon.find({zi(fi), d.punkt});
            for (std::size_t j = 1; j + 1 < folge.size(); ++j) {
                PEcke e;
                e.punkt = folge[j];
                e.e = mischen(c.e, d.e, static_cast<double>(j) / static_cast<double>(folge.size() - 1U));
                if (uc != uvVon.end() && ud != uvVon.end()) {
                    // die Richtung des Punkts als s1 r1 + s2 r2 der Richtungen der Enden (kleinste Quadrate), die UV ebenso
                    const V r1 = vAus(p.bewegungen[bewVon[c.punkt]].richtung);
                    const V r2 = vAus(p.bewegungen[bewVon[d.punkt]].richtung);
                    const V rq = vAus(p.bewegungen[bewVon[folge[j]]].richtung);
                    const double a11 = punkt(r1, r1);
                    const double a12 = punkt(r1, r2);
                    const double a22 = punkt(r2, r2);
                    const double det = a11 * a22 - a12 * a12;
                    double s1 = 0.5;
                    double s2 = 0.5;
                    if (std::fabs(det) > 1e-12) {
                        s1 = (punkt(rq, r1) * a22 - punkt(rq, r2) * a12) / det;
                        s2 = (punkt(rq, r2) * a11 - punkt(rq, r1) * a12) / det;
                    }
                    UvBewegung u;
                    u.flaeche = zi(fi);
                    u.punkt = folge[j];
                    for (int z = 0; z < 2; ++z) {
                        u.basis[z] = uc->second.basis[z];
                        u.richtung[z] = static_cast<float>(s1 * static_cast<double>(uc->second.richtung[z]) + s2 * static_cast<double>(ud->second.richtung[z]));
                        e.e.uv[z] = u.basis[z];
                    }
                    uvNeu.push_back(u);
                }
                neu.push_back(e);
                anders = true;
            }
        }
        if (!anders) { continue; }
        f.ecken = std::move(neu);
        flaecheGeaendert(f);
        n.beruehren(f.teil);
    }
    // bevel_build_trifan (:5971): das Ende einer einzelnen gefasten Kante an einem Punkt mit vier Kanten (drei Randpunkte)
    // wird ein Faecher vom Randpunkt auf der gegenueberliegenden Kante (dem letzten, BM_FACE_FIRST_LOOP(f)->prev)
    for (const int v : info.faecher) {
        const auto fi = info.flicken.find(v);
        if (fi == info.flicken.end() || n.flaechen[uz(fi->second)].weg) { continue; }
        const PFlaeche alt = n.flaechen[uz(fi->second)];
        const int k = zi(alt.ecken.size());
        if (k <= 3) { continue; }
        int spitze = -1;
        for (int i = 0; i < k && spitze < 0; ++i) {
            const int q = alt.ecken[uz(i)].punkt;
            bool amBogen = false;
            for (const auto& [key, ids] : boegen) {
                amBogen = amBogen || key.first == q || key.second == q || std::find(ids.begin(), ids.end(), q) != ids.end();
            }
            if (!amBogen) { spitze = i; }
        }
        if (spitze < 0) { continue; }
        n.flaechen[uz(fi->second)].weg = true;
        std::vector<UvBewegung> mit = p.uvBewegungen;
        mit.insert(mit.end(), uvNeu.begin(), uvNeu.end());
        for (int i = 1; i + 1 < k; ++i) {
            std::vector<PEcke> d = {alt.ecken[uz(spitze)], alt.ecken[uz((spitze + i) % k)], alt.ecken[uz((spitze + i + 1) % k)]};
            const int nf = neueFlaeche(n, std::move(d), alt.teil);
            info.faecherDreiecke.emplace_back(nf, fi->second);
            for (UvBewegung u : mit) {
                if (u.flaeche == fi->second) {
                    u.flaeche = nf;
                    u.ecke = eckeMit(n.flaechen[uz(nf)], u.punkt);
                    if (u.ecke >= 0) { uvNeu.push_back(u); }
                }
            }
        }
        p.geaendert += k - 3;
    }
    for (UvBewegung& u : uvNeu) {
        u.ecke = eckeMit(n.flaechen[uz(u.flaeche)], u.punkt);
        p.uvBewegungen.push_back(u);
    }
    n.kantenBauen();
}
