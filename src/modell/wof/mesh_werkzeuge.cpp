Plan extrudeFlaechen(PolyNetz& n, const std::vector<int>& flaechen, ExtrudeArt art) {
    Plan p;
    n.kantenBauen();
    const auto rs = regionen(n, flaechen, art == ExtrudeArt::JeVieleck);
    if (rs.empty()) {
        p.grund = Ablehnung::LeereAuswahl;
        return p;
    }
    // Richtungen vor dem Heben (auf den alten Punkten)
    std::vector<V> gruppe(rs.size());
    std::vector<char> lokal(rs.size(), art == ExtrudeArt::LokaleNormale ? 1 : 0);
    for (std::size_t ri = 0; ri < rs.size(); ++ri) {
        V s;
        double fl = 0.0;
        for (const int fi : rs[ri]) {
            const V nw = newell(n, n.flaechen[uz(fi)]) * -1.0;
            s = s + nw;
            fl += laenge(nw);
        }
        gruppe[ri] = einheit(s);
        if (art == ExtrudeArt::Gruppe) {
            // WL: mittlere Normale kuerzer als 0,1 (Band, geschlossene Region) oder eine Randkante fast parallel (unter
            // einem Grad) -> lokale Normale
            bool zurueck = !(fl > 0.0) || laenge(s) / fl < 0.1;
            for (const RandKante& k : regionsRand(n, rs[ri])) {
                const V d = einheit(ort(n, k.b) - ort(n, k.a));
                zurueck = zurueck || std::abs(punkt(d, gruppe[ri])) > std::cos(kPi / 180.0);
            }
            if (zurueck) {
                lokal[ri] = 1;
                p.zurueckgefallen = true;
            }
        }
    }
    std::vector<std::map<int, V>> lokaleRichtung(rs.size());
    for (std::size_t ri = 0; ri < rs.size(); ++ri) {
        if (lokal[ri] == 0) { continue; }
        std::map<int, V> s;
        for (const int fi : rs[ri]) {
            const V nn = aussen(n, n.flaechen[uz(fi)]);
            for (const PEcke& c : n.flaechen[uz(fi)].ecken) { s[c.punkt] = s[c.punkt] + nn; }
        }
        for (auto& [pt, v] : s) { lokaleRichtung[ri][pt] = einheit(v); }
    }
    const auto kopien = hebeRegionen(n, rs, p);
    std::set<int> bewegt;
    for (std::size_t ri = 0; ri < rs.size(); ++ri) {
        for (const int fi : rs[ri]) {
            for (const PEcke& c : n.flaechen[uz(fi)].ecken) {
                if (!bewegt.insert(c.punkt).second) { continue; }
                // der alte Punkt (fuer die lokale Richtung)
                int alt = c.punkt;
                for (const auto& [a, b] : kopien[ri]) {
                    if (b == c.punkt) { alt = a; }
                }
                Bewegung m;
                m.punkt = c.punkt;
                std::memcpy(m.basis, n.punkte[uz(c.punkt)].ort, sizeof m.basis);
                const V d = lokal[ri] != 0 ? lokaleRichtung[ri][alt] : gruppe[ri];
                vNach(d, m.richtung);
                p.bewegungen.push_back(m);
            }
            p.auswahl.flaechen.push_back(fi);
        }
    }
    // Normalen an den alten Randpunkten neu (dort stehen jetzt Waende)
    for (const auto& k : kopien) {
        for (const auto& [a, b] : k) {
            (void)b;
            for (const int f : n.punktFlaechen[uz(a)]) { n.flaechen[uz(f)].neu = true; }
        }
    }
    fertig(n, p);
    return p;
}

Plan extrudeRand(PolyNetz& n, const std::vector<std::pair<int, int>>& kanten) {
    Plan p;
    n.kantenBauen();
    struct K {
        int f, i, a, b;
    };
    std::vector<K> ks;
    for (const auto& [x, y] : kanten) {
        const int k = n.kanteVon(x, y);
        if (k < 0 || !n.istRand(k)) { continue; }
        const auto [fi, i] = n.kanten[uz(k)].seiten[0];
        ks.push_back({fi, i, punktVon(n.flaechen[uz(fi)], i), punktVon(n.flaechen[uz(fi)], i + 1)});
    }
    if (ks.empty()) {
        p.grund = kanten.empty() ? Ablehnung::LeereAuswahl : Ablehnung::Rand;
        return p;
    }
    // Richtung je Punkt: Mittel der Aussen-Richtungen seiner gewaehlten Kanten (in der Ebene der Flaeche, rechtwinklig
    // zur Kante, weg von der Mitte der Flaeche dahinter)
    std::map<int, V> richt;
    for (const K& k : ks) {
        const PFlaeche& f = n.flaechen[uz(k.f)];
        const V a = ort(n, k.a), b = ort(n, k.b);
        const V d = einheit(b - a);
        V w = mitte(n, f) - a;
        w = einheit(w - d * punkt(w, d));
        richt[k.a] = richt[k.a] + w * -1.0;
        richt[k.b] = richt[k.b] + w * -1.0;
    }
    std::map<int, int> kopie;
    for (auto& [pt, v] : richt) {
        kopie[pt] = neuerPunkt(n, ort(n, pt), n.punkte[uz(pt)].teil);
        Bewegung m;
        m.punkt = kopie[pt];
        std::memcpy(m.basis, n.punkte[uz(pt)].ort, sizeof m.basis);
        vNach(einheit(v), m.richtung);
        p.bewegungen.push_back(m);
    }
    for (const K& k : ks) {
        const PFlaeche& f = n.flaechen[uz(k.f)];
        const int kk = zi(f.ecken.size());
        const Ecke ea = f.ecken[uz(k.i)].e;
        const Ecke eb = f.ecken[uz((k.i + 1) % kk)].e;
        std::vector<PEcke> w(4);   // b -> a -> a' -> b' (das Vieleck hat a -> b)
        w[0].punkt = k.b;
        w[0].e = eb;
        w[1].punkt = k.a;
        w[1].e = ea;
        w[2].punkt = kopie[k.a];
        w[2].e = ea;
        w[3].punkt = kopie[k.b];
        w[3].e = eb;
        (void)neueFlaeche(n, std::move(w), f.teil);
        p.auswahl.kanten.push_back(kantenPaar(kopie[k.a], kopie[k.b]));
        ++p.geaendert;
    }
    fertig(n, p);
    return p;
}

