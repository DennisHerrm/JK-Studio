// WL Csr: duenne Matrix zeilenweise, mit rechter Seite
struct Csr {
    std::vector<int> zeilenAnfang;
    std::vector<int> spalte;
    std::vector<double> wert;
    std::vector<double> rechts;
    int spalten = 0;
    void zeile() { zeilenAnfang.push_back(static_cast<int>(spalte.size())); }
    void dazu(int s, double v) {
        spalte.push_back(s);
        wert.push_back(v);
    }
    void zeileEnde(double b) { rechts.push_back(b); }
    [[nodiscard]] int zeilen() const { return static_cast<int>(rechts.size()); }
    void schliessen() { zeilenAnfang.push_back(static_cast<int>(spalte.size())); }
    void mal(const std::vector<double>& x, std::vector<double>& aus) const {
        aus.assign(uz(zeilen()), 0.0);
        for (int r = 0; r < zeilen(); ++r) {
            double s = 0.0;
            for (int i = zeilenAnfang[uz(r)]; i < zeilenAnfang[uz(r) + 1]; ++i) { s += wert[uz(i)] * x[uz(spalte[uz(i)])]; }
            aus[uz(r)] = s;
        }
    }
    void malTransponiert(const std::vector<double>& y, std::vector<double>& aus) const {
        aus.assign(uz(spalten), 0.0);
        for (int r = 0; r < zeilen(); ++r) {
            const double f = y[uz(r)];
            if (f == 0.0) { continue; }
            for (int i = zeilenAnfang[uz(r)]; i < zeilenAnfang[uz(r) + 1]; ++i) { aus[uz(spalte[uz(i)])] += wert[uz(i)] * f; }
        }
    }
    [[nodiscard]] std::vector<double> spaltenNormen() const {
        std::vector<double> aus(uz(spalten), 0.0);
        for (std::size_t i = 0; i < spalte.size(); ++i) { aus[uz(spalte[i])] += wert[i] * wert[i]; }
        for (double& v : aus) { v = std::sqrt(v); }
        return aus;
    }
};

double norm2(const std::vector<double>& v) {
    double s = 0.0;
    for (const double x : v) { s += x * x; }
    return s;
}

// WL SolveCgls: CGLS mit Spaltenskalierung, Neustart, wenn der echte Rest nicht faellt
int loeseCgls(const Csr& a, std::vector<double>& x, double toleranz, int maxSchritte, double& restAus, bool& gekapptAus) {
    std::vector<double> skala = a.spaltenNormen();
    for (double& d : skala) { d = d > 0.0 ? 1.0 / d : 0.0; }
    std::vector<double> r;
    std::vector<double> s;
    const auto echterRest = [&]() {
        a.mal(x, r);
        for (int i = 0; i < a.zeilen(); ++i) { r[uz(i)] = a.rechts[uz(i)] - r[uz(i)]; }
        a.malTransponiert(r, s);
        for (int j = 0; j < a.spalten; ++j) { s[uz(j)] *= skala[uz(j)]; }
        return norm2(s);
    };
    double jetzt = echterRest();
    const double start = jetzt;
    gekapptAus = false;
    if (start <= 0.0) {
        restAus = 0.0;
        return 0;
    }
    const double ziel = toleranz * toleranz * start;
    std::vector<double> p;
    std::vector<double> q;
    std::vector<double> dp(uz(a.spalten), 0.0);
    int schritt = 0;
    while (jetzt > ziel && schritt < maxSchritte) {
        p = s;
        double gamma = jetzt;
        for (; schritt < maxSchritte && gamma > 0.0; ++schritt) {
            for (int j = 0; j < a.spalten; ++j) { dp[uz(j)] = skala[uz(j)] * p[uz(j)]; }
            a.mal(dp, q);
            const double qq = norm2(q);
            if (qq <= 0.0) { break; }
            const double alpha = gamma / qq;
            for (int j = 0; j < a.spalten; ++j) { x[uz(j)] += alpha * dp[uz(j)]; }
            for (int i = 0; i < a.zeilen(); ++i) { r[uz(i)] -= alpha * q[uz(i)]; }
            a.malTransponiert(r, s);
            for (int j = 0; j < a.spalten; ++j) { s[uz(j)] *= skala[uz(j)]; }
            const double naechst = norm2(s);
            if (naechst <= ziel) {
                ++schritt;
                break;
            }
            const double beta = naechst / gamma;
            for (int j = 0; j < a.spalten; ++j) { p[uz(j)] = s[uz(j)] + beta * p[uz(j)]; }
            gamma = naechst;
        }
        const double vorher = jetzt;
        jetzt = echterRest();
        if (!(jetzt < vorher)) { break; }
    }
    restAus = std::sqrt(jetzt / start);
    gekapptAus = jetzt > ziel && schritt >= maxSchritte;
    return schritt;
}

// Gekippte Dreiecke gegen die Mehrheit der Insel zaehlen (WL: Schluss von LscmPinning/MinimumStretch)
int gekippteZaehlen(const UvNetz& n, const UvInseln& in, int insel) {
    int bilanz = 0;
    std::vector<float> vz;
    for (const int d : in.dreieckeVon(insel)) {
        const float a = flaecheUv(n.uvVon(d * 3), n.uvVon(d * 3 + 1), n.uvVon(d * 3 + 2));
        if (a == 0.0F) { continue; }
        vz.push_back(a);
        bilanz += a > 0.0F ? 1 : -1;
    }
    const bool positiv = bilanz >= 0;
    int k = 0;
    for (const float a : vz) {
        if ((a > 0.0F) != positiv) { ++k; }
    }
    return k;
}

