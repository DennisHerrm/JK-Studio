AbflachErgebnis lscm(UvNetz& n, const UvInseln& in, int insel, std::span<const int> auchFest, const LscmOptionen& o) {
    AbflachErgebnis erg;
    if (insel < 0 || insel >= in.zahl) {
        erg.absage = Absage::Leer;
        return erg;
    }
    if (in.geschlossen[uz(insel)] != 0) {
        erg.absage = Absage::Geschlossen;
        return erg;
    }
    const std::span<const int> dreiecke = in.dreieckeVon(insel);
    if (dreiecke.empty()) {
        erg.absage = Absage::Leer;
        return erg;
    }
    const std::vector<int> keile = inselKeile(in, insel);
    if (keile.size() < 3U) {
        erg.absage = Absage::Leer;
        return erg;
    }
    std::vector<int> lokal(uz(in.keilZahl), -1);
    for (std::size_t i = 0; i < keile.size(); ++i) { lokal[uz(keile[i])] = static_cast<int>(i); }
    std::vector<u8> fest(keile.size(), 0);
    int pins = 0;
    for (std::size_t i = 0; i < keile.size(); ++i) {
        fest[i] = keilGepinnt(n, in, keile[i]) ? 1 : 0;
        pins += fest[i];
    }
    for (const int w : auchFest) {
        if (w >= 0 && w < in.keilZahl && lokal[uz(w)] >= 0 && fest[uz(lokal[uz(w)])] == 0) {
            fest[uz(lokal[uz(w)])] = 1;
            ++pins;
        }
    }
    std::vector<V2> gehalten(keile.size());
    for (std::size_t i = 0; i < keile.size(); ++i) { gehalten[i] = keilLesen(n, in, keile[i]); }
    bool einpassen = false;
    float alteFlaeche = 0.0F;
    int nutzerPin = -1;
    if (pins == 1) { nutzerPin = static_cast<int>(std::find(fest.begin(), fest.end(), u8{1}) - fest.begin()); }
    if (pins < 2) {
        // Unter zwei Pins: die zwei Randkeile, die am weitesten auseinander liegen (in der UV, wenn sie eine hat)
        std::vector<int> rand;
        for (const int h : in.randVon(insel)) {
            const int w = in.keil(h);
            if (w >= 0 && lokal[uz(w)] >= 0) { rand.push_back(lokal[uz(w)]); }
        }
        rand = sortiert(std::move(rand));
        if (rand.size() < 2U) {
            erg.absage = Absage::ZuWenigPins;
            return erg;
        }
        const InselFlaeche fl = flaechenVon(n, in, insel);
        const bool nachUv = o.halten && fl.uv > 0.0F;
        int besteA = rand[0];
        int besteB = rand[1];
        float beste = -1.0F;
        for (std::size_t i = 0; i < rand.size(); ++i) {
            const V3 pi = n.ort[uz(in.keilPunkt[uz(keile[uz(rand[i])])])];
            const V2 qi = gehalten[uz(rand[i])];
            for (std::size_t j = i + 1; j < rand.size(); ++j) {
                float d;
                if (nachUv) {
                    const V2 qj = gehalten[uz(rand[j])];
                    d = std::sqrt((qj.x - qi.x) * (qj.x - qi.x) + (qj.y - qi.y) * (qj.y - qi.y));
                } else {
                    d = laenge(n.ort[uz(in.keilPunkt[uz(keile[uz(rand[j])])])] - pi);
                }
                if (d > beste) {
                    beste = d;
                    besteA = rand[i];
                    besteB = rand[j];
                }
            }
        }
        if (!nachUv) {
            gehalten[uz(besteA)] = V2{0.0F, 0.0F};
            gehalten[uz(besteB)] = V2{1.0F, 0.0F};
        }
        fest[uz(besteA)] = 1;
        fest[uz(besteB)] = 1;
        pins = 2;
        einpassen = nachUv;
        alteFlaeche = fl.uv;
    }
    std::vector<int> spalteVon(keile.size(), -1);
    int spalten = 0;
    for (std::size_t i = 0; i < keile.size(); ++i) {
        if (fest[i] == 0) {
            spalteVon[i] = spalten;
            spalten += 2;
        }
    }
    if (spalten == 0) { return erg; }
    Csr a;
    a.spalten = spalten;
    for (const int d : dreiecke) {
        double lo[3][2];
        if (!lokalesDreieck(n.ortVon(d * 3), n.ortVon(d * 3 + 1), n.ortVon(d * 3 + 2), lo)) {
            ++erg.entartet;
            continue;
        }
        const double dT = lo[1][0] * lo[2][1] - lo[1][1] * lo[2][0];
        const double sk = 1.0 / std::sqrt(std::abs(dT));
        double wr[3];
        double wi[3];
        for (int k = 0; k < 3; ++k) {
            const int nx = (k + 1) % 3;
            const int la = (k + 2) % 3;
            wr[k] = (lo[la][0] - lo[nx][0]) * sk;
            wi[k] = (lo[la][1] - lo[nx][1]) * sk;
        }
        int l3[3];
        bool ok = true;
        for (int k = 0; k < 3; ++k) {
            const int w = in.keil(d * 3 + k);
            if (w < 0 || lokal[uz(w)] < 0) {
                ok = false;
                break;
            }
            l3[k] = lokal[uz(w)];
        }
        if (!ok) { continue; }
        for (int teil = 0; teil < 2; ++teil) {
            a.zeile();
            double b = 0.0;
            for (int k = 0; k < 3; ++k) {
                const double cu = teil == 0 ? wr[k] : wi[k];
                const double cv = teil == 0 ? -wi[k] : wr[k];
                const int idx = l3[k];
                if (fest[uz(idx)] != 0) {
                    b -= cu * gehalten[uz(idx)].x + cv * gehalten[uz(idx)].y;
                    continue;
                }
                const int s = spalteVon[uz(idx)];
                a.dazu(s, cu);
                a.dazu(s + 1, cv);
            }
            a.zeileEnde(b);
        }
    }
    a.schliessen();
    if (a.zeilen() == 0) {
        erg.absage = Absage::Leer;
        return erg;
    }
    std::vector<double> x(uz(spalten), 0.0);
    for (std::size_t i = 0; i < keile.size(); ++i) {
        if (spalteVon[i] >= 0) {
            x[uz(spalteVon[i])] = gehalten[i].x;
            x[uz(spalteVon[i]) + 1] = gehalten[i].y;
        }
    }
    const int kappe = std::max(32, o.schritteJeUnbekannte * spalten);
    double rest = 0.0;
    erg.schritte = loeseCgls(a, x, o.toleranz, kappe, rest, erg.gekappt);
    erg.rest = static_cast<float>(rest);
    std::vector<V2> geloest(keile.size());
    for (std::size_t i = 0; i < keile.size(); ++i) {
        geloest[i] = fest[i] != 0 ? gehalten[i] : V2{static_cast<float>(x[uz(spalteVon[i])]), static_cast<float>(x[uz(spalteVon[i]) + 1])};
    }
    {
        // Keile ohne eigene Gleichung (nur an entarteten Dreiecken) in die Mitte ihrer Nachbarn
        const std::vector<double> normen = a.spaltenNormen();
        std::vector<u8> schwebt(keile.size(), 0);
        bool irgend = false;
        for (std::size_t i = 0; i < keile.size(); ++i) {
            schwebt[i] = spalteVon[i] >= 0 && normen[uz(spalteVon[i])] == 0.0 ? 1 : 0;
            irgend = irgend || schwebt[i] != 0;
        }
        if (irgend) {
            std::vector<V2> summe(keile.size());
            std::vector<int> zahl(keile.size(), 0);
            for (const int d : dreiecke) {
                int ring[3];
                int rz = 0;
                for (int k = 0; k < 3; ++k) {
                    const int w = in.keil(d * 3 + k);
                    if (w >= 0 && lokal[uz(w)] >= 0) { ring[rz++] = lokal[uz(w)]; }
                }
                for (int i = 0; i < rz; ++i) {
                    if (schwebt[uz(ring[i])] == 0) { continue; }
                    for (int j = 0; j < rz; ++j) {
                        if (schwebt[uz(ring[j])] == 0) {
                            summe[uz(ring[i])] = summe[uz(ring[i])] + geloest[uz(ring[j])];
                            ++zahl[uz(ring[i])];
                        }
                    }
                }
            }
            for (std::size_t i = 0; i < keile.size(); ++i) {
                if (schwebt[i] != 0 && zahl[i] != 0) { geloest[i] = summe[i] * (1.0F / static_cast<float>(zahl[i])); }
            }
        }
    }
    if (einpassen) {
        // zurueck ueber die alte Karte: Drehung (oder Spiegelung), Flaeche, Mitte
        V2 c0{};
        V2 c1{};
        for (std::size_t i = 0; i < keile.size(); ++i) {
            c0 = c0 + geloest[i];
            c1 = c1 + gehalten[i];
        }
        c0 = c0 * (1.0F / static_cast<float>(keile.size()));
        c1 = c1 * (1.0F / static_cast<float>(keile.size()));
        double dRe = 0.0;
        double dIm = 0.0;
        double sRe = 0.0;
        double sIm = 0.0;
        for (std::size_t i = 0; i < keile.size(); ++i) {
            const double px = geloest[i].x - c0.x;
            const double py = geloest[i].y - c0.y;
            const double qx = gehalten[i].x - c1.x;
            const double qy = gehalten[i].y - c1.y;
            dRe += px * qx + py * qy;
            dIm += px * qy - py * qx;
            sRe += px * qx - py * qy;
            sIm += px * qy + py * qx;
        }
        const bool gespiegelt = std::hypot(sRe, sIm) > std::hypot(dRe, dIm);
        const double winkel = gespiegelt ? std::atan2(sIm, sRe) : std::atan2(dIm, dRe);
        const float cs = static_cast<float>(std::cos(winkel));
        const float sn = static_cast<float>(std::sin(winkel));
        for (V2& p : geloest) {
            const V2 d = p - c0;
            const float dy = gespiegelt ? -d.y : d.y;
            p = V2{d.x * cs - dy * sn, d.x * sn + dy * cs};
        }
        for (std::size_t i = 0; i < keile.size(); ++i) { keilSchreiben(n, in, keile[i], geloest[i]); }
        const float neueFlaeche = flaechenVon(n, in, insel).uv;
        const float sk = neueFlaeche > 0.0F ? std::sqrt(alteFlaeche / neueFlaeche) : 1.0F;
        for (V2& p : geloest) { p = c1 + p * sk; }
        if (nutzerPin >= 0 && uz(nutzerPin) < keile.size()) {
            const V2 zurueck = gehalten[uz(nutzerPin)] - geloest[uz(nutzerPin)];
            for (V2& p : geloest) { p = p + zurueck; }
        }
    }
    {
        // Entfalten: ein Keil eines gefalteten Dreiecks zur Mitte seiner Nachbarn, solange das weniger Falten macht
        std::vector<std::array<int, 3>> drei;
        for (const int d : dreiecke) {
            std::array<int, 3> t{};
            bool ok = true;
            for (int k = 0; k < 3 && ok; ++k) {
                const int w = in.keil(d * 3 + k);
                ok = w >= 0 && lokal[uz(w)] >= 0;
                if (ok) { t[uz(k)] = lokal[uz(w)]; }
            }
            if (ok && t[0] != t[1] && t[1] != t[2] && t[0] != t[2]) { drei.push_back(t); }
        }
        const auto flaecheVon = [&](std::size_t t) { return flaecheUv(geloest[uz(drei[t][0])], geloest[uz(drei[t][1])], geloest[uz(drei[t][2])]); };
        long long bilanz = 0;
        for (std::size_t t = 0; t < drei.size(); ++t) {
            const float f = flaecheVon(t);
            bilanz += f > 0.0F ? 1 : (f < 0.0F ? -1 : 0);
        }
        const float vz = bilanz >= 0 ? 1.0F : -1.0F;
        const auto gefaltet = [&](std::size_t t) { return flaecheVon(t) * vz < 0.0F; };
        std::vector<std::vector<int>> dreiVon(keile.size());
        for (std::size_t t = 0; t < drei.size(); ++t) {
            for (const int w : drei[t]) { dreiVon[uz(w)].push_back(static_cast<int>(t)); }
        }
        std::vector<u8> war;
        bool bewegt = true;
        for (int durch = 0; durch < 16 && bewegt; ++durch) {
            bewegt = false;
            for (std::size_t t = 0; t < drei.size(); ++t) {
                if (!gefaltet(t)) { continue; }
                for (const int w : drei[t]) {
                    if (fest[uz(w)] != 0) { continue; }
                    war.clear();
                    int vorher = 0;
                    for (const int u : dreiVon[uz(w)]) {
                        war.push_back(gefaltet(uz(u)) ? 1 : 0);
                        vorher += war.back();
                    }
                    V2 mitte{};
                    int zahl = 0;
                    for (const int u : dreiVon[uz(w)]) {
                        for (const int v : drei[uz(u)]) {
                            if (v != w) {
                                mitte = mitte + geloest[uz(v)];
                                ++zahl;
                            }
                        }
                    }
                    if (vorher == 0 || zahl == 0) { continue; }
                    mitte = mitte * (1.0F / static_cast<float>(zahl));
                    const V2 anfang = geloest[uz(w)];
                    for (const float schritt : {1.0F, 0.5F, 0.25F}) {
                        geloest[uz(w)] = anfang + (mitte - anfang) * schritt;
                        int nachher = 0;
                        bool neuGefaltet = false;
                        for (std::size_t k = 0; k < dreiVon[uz(w)].size(); ++k) {
                            const bool jetzt = gefaltet(uz(dreiVon[uz(w)][k]));
                            nachher += jetzt ? 1 : 0;
                            neuGefaltet = neuGefaltet || (jetzt && war[k] == 0);
                        }
                        if (nachher < vorher && !neuGefaltet) {
                            bewegt = true;
                            break;
                        }
                        geloest[uz(w)] = anfang;
                    }
                }
            }
        }
    }
    for (std::size_t i = 0; i < keile.size(); ++i) { keilSchreiben(n, in, keile[i], geloest[i]); }
    erg.gekippt = gekippteZaehlen(n, in, insel);
    return erg;
}

