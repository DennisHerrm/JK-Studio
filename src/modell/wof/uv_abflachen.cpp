void aufWeite(UvNetz& n, std::span<const int> dreiecke, float weite) {
    if (weite <= 0.0F) { return; }
    const float s = 1.0F / weite;
    for (const int d : dreiecke) {
        for (int k = 0; k < 3; ++k) { n.uv[uz(d * 3 + k)] = n.uv[uz(d * 3 + k)] * s; }
    }
}

// WL projectBox: jede Flaeche zur Achse des Rahmens, der ihre Normale am naechsten ist; Schnitte zwischen den Ebenen
AbflachErgebnis kastenProjektion(UvNetz& n, std::span<const int> dreiecke, const Rahmen& r) {
    AbflachErgebnis erg;
    constexpr u8 kKeine = 0xFF;
    std::vector<u8> seite(uz(n.dreiecke()), kKeine);
    for (const int d : dreiecke) {
        V3 nn{};
        for (int k = 0; k < 3; ++k) {
            const V3 p = n.ortVon(d * 3 + k);
            const V3 q = n.ortVon(d * 3 + (k + 1) % 3);
            nn.x += (p.y - q.y) * (p.z + q.z);
            nn.y += (p.z - q.z) * (p.x + q.x);
            nn.z += (p.x - q.x) * (p.y + q.y);
        }
        const float entlang[3] = {punkt(nn, r.achseU), punkt(nn, r.achseV), punkt(nn, r.achseN)};
        int achse = 0;
        for (int k = 1; k < 3; ++k) {
            if (std::abs(entlang[k]) > std::abs(entlang[achse])) { achse = k; }
        }
        seite[uz(d)] = static_cast<u8>(achse * 2 + (entlang[achse] < 0.0F ? 1 : 0));
        for (int k = 0; k < 3; ++k) {
            const V3 dd = n.ortVon(d * 3 + k) - r.ursprung;
            const float u = punkt(dd, r.achseU);
            const float v = punkt(dd, r.achseV);
            const float w = punkt(dd, r.achseN);
            V2& z = n.uv[uz(d * 3 + k)];
            switch (seite[uz(d)]) {
                case 0: z = V2{w, v}; break;    // +U, rechts
                case 1: z = V2{-w, v}; break;   // -U, links
                case 2: z = V2{u, w}; break;    // +V, unten
                case 3: z = V2{-u, w}; break;   // -V, oben
                case 4: z = V2{-u, v}; break;   // +N, hinten
                default: z = V2{u, v}; break;   // -N, vorn
            }
        }
    }
    std::vector<int> schn;
    for (const int d : dreiecke) {
        for (int k = 0; k < 3; ++k) {
            const int h = d * 3 + k;
            const int g = n.gegen[uz(h)];
            if (g < 0) { continue; }
            const int o = g / 3;
            if (seite[uz(o)] != kKeine && seite[uz(o)] != seite[uz(d)] && o > d) { schn.push_back(h); }
        }
    }
    markieren(n, schn, true);
    return erg;
}

V3 einheitOder(V3 v, V3 ersatz) {
    const float l = laenge(v);
    return l > 1e-6F ? v * (1.0F / l) : ersatz;
}
V3 quer(V3 v, V3 achse) { return v - achse * punkt(v, achse); }
V3 senkrechtZu(V3 achse) {
    const V3 saat = std::abs(achse.x) < 0.9F ? V3{1.0F, 0.0F, 0.0F} : V3{0.0F, 1.0F, 0.0F};
    return einheitOder(kreuz(achse, saat), V3{0.0F, 0.0F, 1.0F});
}

