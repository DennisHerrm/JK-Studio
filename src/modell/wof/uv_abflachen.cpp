AbflachErgebnis projizieren(UvNetz& n, std::span<const int> dreiecke, Form form, const Rahmen& r, bool kappe) {
    AbflachErgebnis erg;
    if (dreiecke.empty()) {
        erg.absage = Absage::Leer;
        return erg;
    }
    if (form == Form::Kasten) {
        erg = kastenProjektion(n, dreiecke, r);
        aufWeite(n, dreiecke, r.weite);
        return erg;
    }
    if (form == Form::Zylinder && kappe) {
        // Max "Cap": Flaechen innerhalb 45 Grad zur Achse werden Deckel (wie die Kasten-Ober- und Unterseite)
        std::vector<int> deckel;
        std::vector<int> mantel;
        for (const int d : dreiecke) {
            V3 nn{};
            for (int k = 0; k < 3; ++k) { nn = nn + kreuz(n.ortVon(d * 3 + k), n.ortVon(d * 3 + (k + 1) % 3)); }
            const float l = laenge(nn);
            (l > 0.0F && std::abs(punkt(nn, r.achseV)) >= 0.70710678F * l ? deckel : mantel).push_back(d);
        }
        if (!deckel.empty()) {
            (void)kastenProjektion(n, deckel, r);
            std::vector<u8> istMantel(uz(n.dreiecke()), 0);
            for (const int d : mantel) { istMantel[uz(d)] = 1; }
            std::vector<int> kante;
            for (const int d : deckel) {
                for (int k = 0; k < 3; ++k) {
                    const int g = n.gegen[uz(d * 3 + k)];
                    if (g >= 0 && istMantel[uz(g / 3)] != 0) { kante.push_back(d * 3 + k); }
                }
            }
            markieren(n, kante, true);
            if (!mantel.empty()) { erg = projizieren(n, mantel, form, r, false); }
            aufWeite(n, deckel, r.weite);
            return erg;
        }
    }
    const auto drehung = [&](V3 d) { return std::atan2(punkt(d, r.achseU), -punkt(d, r.achseN)) / (2.0F * kPi) + 0.5F; };
    const auto abbilden = [&](V3 welt) {
        const V3 d = welt - r.ursprung;
        switch (form) {
            case Form::Eben: return V2{punkt(d, r.achseU), punkt(d, r.achseV)};
            case Form::Zylinder: return V2{drehung(d), punkt(d, r.achseV)};
            case Form::Kugel:
            case Form::Kasten:
            default: {
                const float l = laenge(d);
                const float hoch = l > 0.0F ? -punkt(d, r.achseV) / l : 0.0F;
                return V2{drehung(d), std::acos(std::clamp(hoch, -1.0F, 1.0F)) / kPi};
            }
        }
    };
    std::vector<u8> projiziert(uz(n.dreiecke()), 0);
    std::vector<int> gedreht;
    double radius = 0.0;
    int punkte = 0;
    for (const int d : dreiecke) {
        projiziert[uz(d)] = 1;
        float tiefst = 2.0F;
        float hoechst = -1.0F;
        for (int k = 0; k < 3; ++k) {
            const V3 dd = n.ortVon(d * 3 + k) - r.ursprung;
            const V2 w = abbilden(n.ortVon(d * 3 + k));
            n.uv[uz(d * 3 + k)] = w;
            tiefst = std::min(tiefst, w.x);
            hoechst = std::max(hoechst, w.x);
            radius += form == Form::Zylinder ? laenge(dd - r.achseV * punkt(dd, r.achseV)) : laenge(dd);
            ++punkte;
        }
        if (form != Form::Eben && hoechst - tiefst > 0.5F) {
            for (int k = 0; k < 3; ++k) {
                if (n.uv[uz(d * 3 + k)].x < 0.5F) { n.uv[uz(d * 3 + k)].x += 1.0F; }
            }
            gedreht.push_back(d);
        }
    }
    std::vector<int> umlauf;
    const auto gleich = [&](int a, int b) { return n.uv[uz(a)].x == n.uv[uz(b)].x && n.uv[uz(a)].y == n.uv[uz(b)].y; };
    for (const int d : gedreht) {
        for (int k = 0; k < 3; ++k) {
            const int h = d * 3 + k;
            const int g = n.gegen[uz(h)];
            if (g < 0 || projiziert[uz(g / 3)] == 0) { continue; }
            if (!gleich(h, UvNetz::naechste(g)) || !gleich(UvNetz::naechste(h), g)) { umlauf.push_back(h); }
        }
    }
    if (form != Form::Eben && punkte != 0) {
        const float rr = static_cast<float>(radius / punkte);
        const float rum = 2.0F * kPi * rr;
        const float runter = form == Form::Kugel ? kPi * rr : 1.0F;
        for (const int d : dreiecke) {
            for (int k = 0; k < 3; ++k) {
                V2& z = n.uv[uz(d * 3 + k)];
                z = V2{z.x * rum, z.y * runter};
            }
        }
    }
    markieren(n, umlauf, true);
    aufWeite(n, dreiecke, r.weite);
    return erg;
}

Rahmen aufrechterRahmen(V3 ursprung, V3 blick, V3 oben, V3 vorn) {
    Rahmen r;
    r.ursprung = ursprung;
    const V3 nn = einheitOder(blick, V3{-1.0F, 0.0F, 0.0F});
    V3 top = quer(oben, nn);
    if (laenge(top) < 1e-3F) { top = quer(vorn, nn); }
    top = einheitOder(top, senkrechtZu(nn));
    r.achseN = nn;
    r.achseV = top * -1.0F;
    r.achseU = kreuz(r.achseV, r.achseN);
    return r;
}

Rahmen polRahmen(V3 ursprung, V3 pol, V3 oben, V3 vorn) {
    Rahmen r;
    r.ursprung = ursprung;
    V3 v = einheitOder(pol, V3{0.0F, 0.0F, -1.0F});
    const float steigt = punkt(v, oben);
    const float voraus = punkt(v, vorn);
    if (std::abs(steigt) > 1e-3F ? steigt > 0.0F : voraus > 0.0F) { v = v * -1.0F; }
    V3 nn = quer(vorn, v) * -1.0F;
    if (laenge(nn) < 1e-3F) { nn = quer(oben, v) * -1.0F; }
    nn = einheitOder(nn, senkrechtZu(v));
    r.achseV = v;
    r.achseN = nn;
    r.achseU = kreuz(v, nn);
    return r;
}

std::vector<float> dreieckDehnung(const UvNetz& n, const UvInseln& in) {
    std::vector<float> aus(uz(n.dreiecke()), 0.0F);
    for (int i = 0; i < in.zahl; ++i) {
        const InselFlaeche fl = flaechenVon(n, in, i);
        if (fl.uv <= 0.0F || fl.welt <= 0.0F) { continue; }
        const float sk = std::sqrt(fl.welt / fl.uv);
        for (const int d : in.dreieckeVon(i)) {
            const V3 p[3] = {n.ortVon(d * 3), n.ortVon(d * 3 + 1), n.ortVon(d * 3 + 2)};
            const V2 q[3] = {n.uvVon(d * 3), n.uvVon(d * 3 + 1), n.uvVon(d * 3 + 2)};
            float fl2 = 0.0F;
            const float l2 = std::sqrt(dreieckDehnungL2(p, q, fl2));
            if (fl2 == 0.0F) { continue; }
            aus[uz(d)] = l2 / sk;   // ein Dreieck: das Gewicht seiner Flaeche hebt sich weg
        }
    }
    return aus;
}

