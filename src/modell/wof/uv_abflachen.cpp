AbflachErgebnis entspannen(UvNetz& n, const UvInseln& in, std::span<const int> keile, const EntspannOptionen& o) {
    AbflachErgebnis erg;
    if (keile.empty()) {
        erg.absage = Absage::Leer;
        return erg;
    }
    const std::vector<int> bewegt = sortiert(std::vector<int>(keile.begin(), keile.end()));
    std::vector<int> inseln;
    for (const int w : bewegt) {
        if (w >= 0 && w < in.keilZahl) { inseln.push_back(in.keilInsel[uz(w)]); }
    }
    inseln = sortiert(std::move(inseln));
    std::vector<u8> gehalten(uz(in.keilZahl), 0);
    for (int w = 0; w < in.keilZahl; ++w) { gehalten[uz(w)] = keilGepinnt(n, in, w) ? 1 : 0; }
    if (o.randHalten) {
        for (const int i : inseln) {
            for (const int h : in.randVon(i)) {
                if (const int w = in.keil(h); w >= 0) { gehalten[uz(w)] = 1; }
                if (const int w = in.keil(UvNetz::naechste(h)); w >= 0) { gehalten[uz(w)] = 1; }
            }
        }
    }
    std::vector<RingDreieck> drei;
    std::vector<std::vector<int>> ringVon(uz(in.keilZahl));
    for (const int i : inseln) {
        for (const int d : in.dreieckeVon(i)) {
            RingDreieck r;
            bool ok = true;
            for (int k = 0; k < 3; ++k) {
                r.ecke[k] = d * 3 + k;
                r.keil[k] = in.keil(d * 3 + k);
                r.p[k] = n.ortVon(d * 3 + k);
                ok = ok && r.keil[k] >= 0;
            }
            if (!ok) { continue; }
            r.flaeche = flaeche3d(r.p[0], r.p[1], r.p[2]);
            if (r.flaeche <= 0.0F) {
                ++erg.entartet;
                continue;
            }
            const int idx = static_cast<int>(drei.size());
            drei.push_back(r);
            for (int k = 0; k < 3; ++k) { ringVon[uz(r.keil[k])].push_back(idx); }
        }
    }
    if (drei.empty()) {
        erg.absage = Absage::Leer;
        return erg;
    }
    float spanne = 0.0F;
    for (const int i : inseln) { spanne = std::max(spanne, std::sqrt(std::max(flaechenVon(n, in, i).uv, 0.0F))); }
    if (spanne <= 0.0F) {
        erg.absage = Absage::Leer;
        return erg;
    }
    const float hh = spanne * 1e-4F;
    const auto eckUv = [&](const RingDreieck& t, int k, int keil, V2 neu) { return t.keil[k] == keil ? neu : n.uv[uz(t.ecke[k])]; };
    const auto ringEnergie = [&](int keil, V2 bei, bool& gekippt) {
        float s = 0.0F;
        gekippt = false;
        for (const int idx : ringVon[uz(keil)]) {
            const RingDreieck& t = drei[uz(idx)];
            const V2 q[3] = {eckUv(t, 0, keil, bei), eckUv(t, 1, keil, bei), eckUv(t, 2, keil, bei)};
            float fl = 0.0F;
            const float d = dreieckDehnungL2(t.p, q, fl);
            if (fl == 0.0F) {
                gekippt = true;
                return s;
            }
            s += d * t.flaeche;
        }
        return s;
    };
    std::vector<signed char> vz(drei.size(), 0);
    for (std::size_t i = 0; i < drei.size(); ++i) {
        const float a = flaecheUv(n.uv[uz(drei[i].ecke[0])], n.uv[uz(drei[i].ecke[1])], n.uv[uz(drei[i].ecke[2])]);
        vz[i] = static_cast<signed char>(a > 0.0F ? 1 : (a < 0.0F ? -1 : 0));
    }
    const auto umgedreht = [&](int keil, V2 bei) {
        for (const int idx : ringVon[uz(keil)]) {
            const RingDreieck& t = drei[uz(idx)];
            const float a = flaecheUv(eckUv(t, 0, keil, bei), eckUv(t, 1, keil, bei), eckUv(t, 2, keil, bei));
            if (vz[uz(idx)] != 0 && (a == 0.0F || (a > 0.0F ? 1 : -1) != vz[uz(idx)])) { return true; }
        }
        return false;
    };
    for (int durch = 0; durch < o.durchgaenge; ++durch) {
        ++erg.schritte;
        float gewonnen = 0.0F;
        for (const int keil : bewegt) {
            if (keil < 0 || keil >= in.keilZahl || gehalten[uz(keil)] != 0 || ringVon[uz(keil)].empty()) { continue; }
            const std::span<const int> ecken = in.eckenVon(keil);
            if (ecken.empty()) { continue; }
            const V2 bei = n.uv[uz(ecken[0])];
            bool gekippt = false;
            const float e = ringEnergie(keil, bei, gekippt);
            if (gekippt) { continue; }
            bool egal = false;
            const float dx = (ringEnergie(keil, V2{bei.x + hh, bei.y}, egal) - e) / hh;
            const float dy = (ringEnergie(keil, V2{bei.x, bei.y + hh}, egal) - e) / hh;
            const float grad = std::sqrt(dx * dx + dy * dy);
            if (grad <= 0.0F) { continue; }
            float schritt = spanne * 0.02F / grad;
            for (int zurueck = 0; zurueck < 8; ++zurueck) {
                const V2 neu{bei.x - dx * schritt, bei.y - dy * schritt};
                bool gedreht = false;
                const float versuch = ringEnergie(keil, neu, gedreht);
                if (!gedreht && versuch < e && !umgedreht(keil, neu)) {
                    for (const int h : ecken) { n.uv[uz(h)] = neu; }
                    gewonnen += e - versuch;
                    break;
                }
                schritt *= 0.5F;
            }
        }
        if (gewonnen <= 0.0F) { break; }
    }
    for (std::size_t i = 0; i < drei.size(); ++i) {
        const float a = flaecheUv(n.uv[uz(drei[i].ecke[0])], n.uv[uz(drei[i].ecke[1])], n.uv[uz(drei[i].ecke[2])]);
        if (vz[i] != 0 && a != 0.0F && (a > 0.0F ? 1 : -1) != vz[i]) { ++erg.gekippt; }
    }
    return erg;
}

AbflachErgebnis begradigen(UvNetz& n, const UvInseln& in, std::span<const int> kanten) {
    AbflachErgebnis erg;
    std::vector<std::pair<int, int>> paare;
    for (const int h : kanten) {
        if (h < 0 || h >= n.kanten()) { continue; }
        const int a = in.keil(h);
        const int b = in.keil(UvNetz::naechste(h));
        if (a >= 0 && b >= 0 && a != b) { paare.emplace_back(std::min(a, b), std::max(a, b)); }
    }
    paare = sortiert(std::move(paare));
    if (paare.empty()) {
        erg.absage = Absage::Leer;
        return erg;
    }
    std::map<int, std::vector<int>> nachbarn;
    for (const auto& [a, b] : paare) {
        nachbarn[a].push_back(b);
        nachbarn[b].push_back(a);
    }
    std::map<int, u8> besucht;
    std::vector<int> gepinnt;
    constexpr float kFang = 0.17364817766F;   // zehn Grad (WL kSnap)
    for (int runde = 0; runde < 2; ++runde) {
        for (const auto& [start, nb] : nachbarn) {
            const bool ende = nb.size() <= 1U;
            if (besucht[start] != 0 || (runde == 0) != ende) { continue; }
            std::vector<int> lauf;
            int jetzt = start;
            int vorher = -1;
            while (jetzt >= 0 && besucht[jetzt] == 0) {
                besucht[jetzt] = 1;
                lauf.push_back(jetzt);
                int weiter = -1;
                for (const int kand : nachbarn[jetzt]) {
                    if (kand != vorher && besucht[kand] == 0) {
                        weiter = kand;
                        break;
                    }
                }
                vorher = jetzt;
                jetzt = weiter;
            }
            if (lauf.size() < 3U) {
                gepinnt.insert(gepinnt.end(), lauf.begin(), lauf.end());
                continue;
            }
            const V2 von = n.uv[uz(in.eckenVon(lauf.front())[0])];
            const V2 bis = n.uv[uz(in.eckenVon(lauf.back())[0])];
            V2 r{bis.x - von.x, bis.y - von.y};
            const float l = std::sqrt(r.x * r.x + r.y * r.y);
            if (l <= 0.0F) { continue; }
            r.x /= l;
            r.y /= l;
            if (std::abs(r.y) < kFang) {
                r = V2{r.x > 0.0F ? 1.0F : -1.0F, 0.0F};
            } else if (std::abs(r.x) < kFang) {
                r = V2{0.0F, r.y > 0.0F ? 1.0F : -1.0F};
            }
            for (const int w : lauf) {
                const std::span<const int> ecken = in.eckenVon(w);
                if (ecken.empty()) { continue; }
                const V2 bei = n.uv[uz(ecken[0])];
                const float t = (bei.x - von.x) * r.x + (bei.y - von.y) * r.y;
                const V2 auf{von.x + r.x * t, von.y + r.y * t};
                for (const int h : ecken) { n.uv[uz(h)] = auf; }
                gepinnt.push_back(w);
            }
        }
    }
    if (gepinnt.empty()) {
        erg.absage = Absage::ZuWenigPins;
        return erg;
    }
    std::vector<int> inseln;
    for (const int w : gepinnt) { inseln.push_back(in.keilInsel[uz(w)]); }
    for (const int i : sortiert(std::move(inseln))) {
        const AbflachErgebnis g = lscm(n, in, i, gepinnt);
        erg.gekippt += g.gekippt;
        erg.entartet += g.entartet;
        erg.schritte += g.schritte;
        erg.rest = std::max(erg.rest, g.rest);
        erg.gekappt = erg.gekappt || g.gekappt;
        if (!g.ok()) { erg.absage = g.absage; }
    }
    return erg;
}

RechteckErgebnis rechteck(UvNetz& n, const UvInseln& in, int insel) {
    RechteckErgebnis aus;
    if (insel < 0 || insel >= in.zahl) {
        aus.loesung.absage = Absage::Leer;
        return aus;
    }
    if (in.geschlossen[uz(insel)] != 0) {
        aus.loesung.absage = Absage::Geschlossen;
        return aus;
    }
    if (in.schleifen[uz(insel)] != 1) {
        aus.loesung.absage = Absage::Leer;
        return aus;
    }
    const std::span<const int> schleife = in.randVon(insel);
    const int zahl = static_cast<int>(schleife.size());
    if (zahl < 4) {
        aus.loesung.absage = Absage::Leer;
        return aus;
    }
    const float flaecheVorher = flaechenVon(n, in, insel).uv;
    V2 mitteVorher{};
    {
        V2 t{1e30F, 1e30F};
        V2 h{-1e30F, -1e30F};
        for (const int d : in.dreieckeVon(insel)) {
            for (int k = 0; k < 3; ++k) {
                const V2 w = n.uvVon(d * 3 + k);
                t = V2{std::min(t.x, w.x), std::min(t.y, w.y)};
                h = V2{std::max(h.x, w.x), std::max(h.y, w.y)};
            }
        }
        mitteVorher = (t + h) * 0.5F;
    }
    std::vector<int> ring;
    std::vector<V3> lage;
    for (const int h : schleife) {
        const int w = in.keil(h);
        if (w < 0) {
            aus.loesung.absage = Absage::Leer;
            return aus;
        }
        ring.push_back(w);
        lage.push_back(n.ortVon(h));
    }
    constexpr float kKnick = 1.04719755F;   // sechzig Grad (WL kTurn)
    std::vector<int> ecken;
    for (int i = 0; i < zahl; ++i) {
        const V3 vor = lage[uz(i)] - lage[uz((i + zahl - 1) % zahl)];
        const V3 nach = lage[uz((i + 1) % zahl)] - lage[uz(i)];
        const float ll = laenge(vor) * laenge(nach);
        if (ll <= 0.0F) { continue; }
        const float dreh = std::acos(std::clamp(punkt(vor, nach) / ll, -1.0F, 1.0F));
        if (dreh > kKnick) { ecken.push_back(i); }
    }
    aus.ecken = static_cast<int>(ecken.size());
    if (aus.ecken != 4) {
        aus.loesung.absage = Absage::ZuWenigPins;
        return aus;
    }
    float seiten[4] = {};
    std::vector<float> entlang(uz(zahl), 0.0F);
    for (int s = 0; s < 4; ++s) {
        const int von = ecken[uz(s)];
        const int bis = ecken[uz((s + 1) % 4)];
        float gegangen = 0.0F;
        for (int i = von; i != bis; i = (i + 1) % zahl) {
            entlang[uz(i)] = gegangen;
            gegangen += laenge(lage[uz((i + 1) % zahl)] - lage[uz(i)]);
        }
        seiten[s] = gegangen;
    }
    const float breite = (seiten[0] + seiten[2]) * 0.5F;
    const float hoehe = (seiten[1] + seiten[3]) * 0.5F;
    if (breite <= 0.0F || hoehe <= 0.0F) {
        aus.loesung.absage = Absage::Leer;
        return aus;
    }
    const V2 bei[4] = {{0.0F, 0.0F}, {breite, 0.0F}, {breite, hoehe}, {0.0F, hoehe}};
    std::vector<int> gepinnt;
    for (int s = 0; s < 4; ++s) {
        const int von = ecken[uz(s)];
        const int bis = ecken[uz((s + 1) % 4)];
        const V2 a = bei[s];
        const V2 b = bei[(s + 1) % 4];
        for (int i = von; i != bis; i = (i + 1) % zahl) {
            const float t = seiten[s] > 0.0F ? entlang[uz(i)] / seiten[s] : 0.0F;
            keilSchreiben(n, in, ring[uz(i)], V2{a.x + (b.x - a.x) * t, a.y + (b.y - a.y) * t});
            gepinnt.push_back(ring[uz(i)]);
        }
    }
    aus.loesung = lscm(n, in, insel, gepinnt);
    const float flaecheNachher = flaechenVon(n, in, insel).uv;
    if (aus.loesung.ok() && flaecheVorher > 1e-12F && flaecheNachher > 1e-12F) {
        const float sk = std::sqrt(flaecheVorher / flaecheNachher);
        const V2 mitteNachher{breite * 0.5F, hoehe * 0.5F};
        for (const int d : in.dreieckeVon(insel)) {
            for (int k = 0; k < 3; ++k) { n.uv[uz(d * 3 + k)] = mitteVorher + (n.uv[uz(d * 3 + k)] - mitteNachher) * sk; }
        }
    }
    return aus;
}

