bool inselOhneKarte(const UvNetz& n, const UvInseln& in, int insel) {
    for (const int d : in.dreieckeVon(insel)) {
        for (int k = 0; k < 3; ++k) {
            const V2 w = n.uvVon(d * 3 + k);
            if (w.x != 0.0F || w.y != 0.0F) { return false; }
        }
    }
    return true;
}

UvBefunde pruefen(const UvNetz& n, const UvInseln& in, const PruefOptionen& o) {
    UvBefunde aus;
    const int res = std::max(1, o.aufloesung);
    std::vector<int> gruppeVon(uz(in.zahl), -1);
    for (const std::vector<int>& st : stapelFinden(n, in)) {
        ++aus.stapel;
        for (const int i : st) { gruppeVon[uz(i)] = st.front(); }
    }
    for (int i = 0; i < in.zahl; ++i) {
        if (gruppeVon[uz(i)] < 0) { gruppeVon[uz(i)] = i; }
    }
    std::vector<int> besitzer(uz(res) * uz(res), -1);
    std::vector<u8> ueber(uz(in.zahl), 0);
    std::unordered_set<long long> paare;
    const float texel = static_cast<float>(res);
    for (int i = 0; i < in.zahl; ++i) {
        for (const int d : in.dreieckeVon(i)) {
            const auto bei = [&](int k) { return n.uvVon(d * 3 + k) * texel; };
            rasterDreieck(res, res, bei(0), bei(1), bei(2), false, [&](int x, int y) {
                int& platz = besitzer[uz(y) * uz(res) + uz(x)];
                if (platz < 0) {
                    platz = i;
                } else if (gruppeVon[uz(platz)] != gruppeVon[uz(i)]) {
                    ueber[uz(platz)] = 1;
                    ueber[uz(i)] = 1;
                    aus.ueberlappTexel.push_back(y * res + x);
                    paare.insert((static_cast<long long>(std::min(platz, i)) << 32) | std::max(platz, i));
                }
            });
        }
    }
    aus.ueberlappTexel = sortiert(std::move(aus.ueberlappTexel));
    // AP7 (neu fuer JK Studio): die Ausnutzung der Textur - der Anteil der Texel des Rasters, die eine Insel bedeckt
    aus.ausnutzung = static_cast<float>(static_cast<double>(std::count_if(besitzer.begin(), besitzer.end(), [](int insel) { return insel >= 0; })) /
                                        static_cast<double>(besitzer.size()));
    std::vector<long long> geordnet(paare.begin(), paare.end());
    std::sort(geordnet.begin(), geordnet.end());
    for (const long long p : geordnet) { aus.ueberlappPaare.emplace_back(static_cast<int>(p >> 32), static_cast<int>(p & 0xFFFFFFFFLL)); }
    const std::vector<float> dehnung = dreieckDehnung(n, in);
    std::vector<float> dichten(uz(in.zahl), 0.0F);
    for (int i = 0; i < in.zahl; ++i) {
        if (ueber[uz(i)] != 0) { aus.ueberlappt.push_back(i); }
        const InselFlaeche fl = flaechenVon(n, in, i);
        if (fl.uv <= 1e-12F) {
            (inselOhneKarte(n, in, i) ? aus.ohneKarte : aus.einfarbig).push_back(i);
            continue;
        }
        float plus = 0.0F;
        float minus = 0.0F;
        bool aussen = false;
        bool gedehnt = false;
        for (const int d : in.dreieckeVon(i)) {
            const float a = flaecheUv(n.uvVon(d * 3), n.uvVon(d * 3 + 1), n.uvVon(d * 3 + 2));
            (a > 0.0F ? plus : minus) += std::abs(a);
            for (int k = 0; k < 3; ++k) {
                const V2 p = n.uvVon(d * 3 + k);
                aussen = aussen || p.x < -1e-3F || p.y < -1e-3F || p.x > 1.001F || p.y > 1.001F;
            }
            gedehnt = gedehnt || dehnung[uz(d)] > o.dehnungsGrenze;
        }
        if (std::min(plus, minus) > (plus + minus) * 1e-6F) { aus.gekippt.push_back(i); }
        if (gedehnt) { aus.gedehnt.push_back(i); }
        if (aussen && !o.kacheln) { aus.aussen.push_back(i); }
        if (in.schleifen[uz(i)] >= 2) { aus.ringe.push_back(i); }
        dichten[uz(i)] = texelDichte(n, in, i, res);
    }
    std::vector<float> sort;
    for (const float d : dichten) {
        if (d > 0.0F) { sort.push_back(d); }
    }
    if (!sort.empty()) {
        std::sort(sort.begin(), sort.end());
        const float median = sort[sort.size() / 2];
        for (int i = 0; i < in.zahl; ++i) {
            const float d = dichten[uz(i)];
            if (d > 0.0F && (d < median * 0.5F || d > median * 2.0F)) { aus.dichte.push_back(i); }
        }
    }
    return aus;
}

Verzerrung messen(const UvNetz& n, const UvInseln& in, int aufloesung, std::span<const int> nurDreiecke) {
    Verzerrung v;
    std::vector<u8> mit(uz(n.dreiecke()), nurDreiecke.empty() ? 1 : 0);
    for (const int d : nurDreiecke) { mit[uz(d)] = 1; }
    double gewicht = 0.0;
    double winkel = 0.0;
    double konf = 0.0;
    double flae = 0.0;
    std::vector<float> dichten;
    constexpr double kGrad = 57.29577951308232;
    for (int i = 0; i < in.zahl; ++i) {
        const InselFlaeche fl = flaechenVon(n, in, i);
        bool irgend = false;
        for (const int d : in.dreieckeVon(i)) { irgend = irgend || mit[uz(d)] != 0; }
        if (!irgend || fl.uv <= 0.0F || fl.welt <= 0.0F) { continue; }
        ++v.inseln;
        dichten.push_back(texelDichte(n, in, i, aufloesung));
        const double k = static_cast<double>(fl.uv) / fl.welt;
        const double mehrheit = fl.uvVorzeichen >= 0.0F ? 1.0 : -1.0;
        for (const int d : in.dreieckeVon(i)) {
            if (mit[uz(d)] == 0) { continue; }
            double x[3][2];
            if (!lokalesDreieck(n.ortVon(d * 3), n.ortVon(d * 3 + 1), n.ortVon(d * 3 + 2), x)) { continue; }
            const V2 q0 = n.uvVon(d * 3);
            const V2 q1 = n.uvVon(d * 3 + 1);
            const V2 q2 = n.uvVon(d * 3 + 2);
            // J = [q1-q0 q2-q0] * inv([x1-x0 x2-x0])
            const double a = x[1][0];
            const double b = x[2][0];
            const double c = x[2][1];   // x[1][1] = 0
            const double det = a * c;
            if (det == 0.0) { continue; }
            const double u1 = q1.x - q0.x;
            const double v1 = q1.y - q0.y;
            const double u2 = q2.x - q0.x;
            const double v2 = q2.y - q0.y;
            const double j00 = u1 / a;
            const double j10 = v1 / a;
            const double j01 = (u2 - j00 * b) / c;
            const double j11 = (v2 - j10 * b) / c;
            const double fro = j00 * j00 + j01 * j01 + j10 * j10 + j11 * j11;
            const double dj = j00 * j11 - j01 * j10;
            const double wurzel = std::sqrt(std::max(fro * fro - 4.0 * dj * dj, 0.0));
            const double s1 = std::sqrt(std::max((fro + wurzel) * 0.5, 0.0));
            const double s2 = std::sqrt(std::max((fro - wurzel) * 0.5, 0.0));
            const double flaeche3 = 0.5 * det;
            ++v.dreiecke;
            if (dj * mehrheit < 0.0) { ++v.gekippt; }
            // Winkel je Ecke in 3D (lokal) und in der UV
            const double p3[3][2] = {{x[0][0], x[0][1]}, {x[1][0], x[1][1]}, {x[2][0], x[2][1]}};
            const double p2[3][2] = {{q0.x, q0.y}, {q1.x, q1.y}, {q2.x, q2.y}};
            double fehler = 0.0;
            for (int e = 0; e < 3; ++e) {
                const auto winkelBei = [&](const double (&p)[3][2]) {
                    const double ax = p[(e + 1) % 3][0] - p[e][0];
                    const double ay = p[(e + 1) % 3][1] - p[e][1];
                    const double bx = p[(e + 2) % 3][0] - p[e][0];
                    const double by = p[(e + 2) % 3][1] - p[e][1];
                    return std::atan2(std::abs(ax * by - ay * bx), ax * bx + ay * by);
                };
                const double f = std::abs(winkelBei(p3) - winkelBei(p2)) * kGrad;
                fehler += f / 3.0;
                v.winkelMaxGrad = std::max(v.winkelMaxGrad, static_cast<float>(f));
            }
            gewicht += flaeche3;
            winkel += fehler * flaeche3;
            konf += (s2 > 0.0 ? s1 / s2 : 1e6) * flaeche3;
            flae += std::abs(s1 * s2 / k - 1.0) * flaeche3;
        }
    }
    if (gewicht > 0.0) {
        v.winkelGrad = static_cast<float>(winkel / gewicht);
        v.konform = static_cast<float>(konf / gewicht);
        v.flaeche = static_cast<float>(flae / gewicht);
    }
    if (!dichten.empty()) {
        std::sort(dichten.begin(), dichten.end());
        v.dichteMin = dichten.front();
        v.dichteMax = dichten.back();
        v.dichteMedian = dichten[dichten.size() / 2];
    }
    return v;
}

