UvNetz netzAus(const Inhalt& in, const std::vector<int>& teile, int stufe) {
    UvNetz n;
    n.stufe = stufe;
    std::vector<char> ersterBesuch;
    for (const int t : teile) {
        if (t < 0 || uz(t) >= in.teile.size() || in.teile[uz(t)].istTag() || stufe < 0 || uz(stufe) >= in.teile[uz(t)].stufen.size()) { continue; }
        const Netz& nz = in.teile[uz(t)].stufen[uz(stufe)];
        const int basisPunkt = static_cast<int>(n.ort.size());
        const int basisKante = static_cast<int>(n.von.size());
        n.teile.push_back(t);
        n.ersteDreieck.push_back(basisKante / 3);
        n.ort.resize(n.ort.size() + uz(nz.punktZahl));
        for (std::size_t e = 0; e < nz.ecken.size(); ++e) {
            const float* o = nz.ecken[e].ort;
            n.ort[uz(basisPunkt + nz.punktVon[e])] = V3{o[0], o[1], o[2]};
        }
        const std::size_t k = nz.kanten.size();
        const bool besucht = nz.uvNaht.size() == k && nz.uvDateiNaht.size() == k && nz.uvPin.size() == k && nz.uvFrei.size() == k / 3U;
        for (std::size_t h = 0; h < k; ++h) {
            const Halbkante& hk = nz.kanten[h];
            const Ecke& e = nz.ecken[uz(std::max(hk.ecke, 0))];
            n.von.push_back(basisPunkt + std::max(hk.punkt, 0));
            n.gegen.push_back(hk.gegen >= 0 ? basisKante + hk.gegen : -1);
            n.uv.push_back(V2{e.uv[0], e.uv[1]});
            n.normale.push_back(V3{e.normale[0], e.normale[1], e.normale[2]});
            n.naht.push_back(besucht ? nz.uvNaht[h] : u8{0});
            n.dateiNaht.push_back(besucht ? nz.uvDateiNaht[h] : u8{0});
            n.pin.push_back(besucht ? nz.uvPin[h] : u8{0});
            n.teil.push_back(static_cast<int>(n.teile.size()) - 1);
            n.ecke.push_back(hk.ecke);
            n.knochen.push_back({e.knochen[0], e.knochen[1], e.knochen[2], e.knochen[3]});
            n.gewicht.push_back({e.gewicht[0], e.gewicht[1], e.gewicht[2], e.gewicht[3]});
            ersterBesuch.push_back(besucht ? 0 : 1);
        }
        for (std::size_t d = 0; d < k / 3U; ++d) { n.frei.push_back(besucht ? nz.uvFrei[d] : u8{0}); }
    }
    n.ersteDreieck.push_back(n.dreiecke());
    // WL EnsureUvSet: beim ersten Besuch werden die Schnitte der Datei (ohne Randkanten) zu Marken, und zu Datei-Marken.
    // Die UV der Datei ist da, also ist nichts "frei" (bornFree nur ohne uvN).
    const std::vector<u8> s = schnitte(n);
    for (int h = 0; h < n.kanten(); ++h) {
        if (ersterBesuch[uz(h)] != 0 && s[uz(h)] != 0 && !n.rand(h)) {
            n.naht[uz(h)] = 1;
            n.dateiNaht[uz(h)] = 1;
        }
    }
    return n;
}

bool zurueckschreiben(const UvNetz& n, Inhalt& in, int eckenGrenze, ZurueckBericht* bericht) {
    ZurueckBericht br;
    br.grenze = eckenGrenze;
    struct Neu {
        int teil = -1;
        std::vector<Ecke> ecken;
        std::vector<std::uint32_t> indizes;
        bool geaendert = false;
    };
    std::vector<Neu> neu(n.teile.size());
    for (std::size_t ti = 0; ti < n.teile.size(); ++ti) {
        const int t = n.teile[ti];
        const Netz& nz = in.teile[uz(t)].stufen[uz(n.stufe)];
        Neu& x = neu[ti];
        x.teil = t;
        x.ecken = nz.ecken;
        x.indizes.resize(nz.kanten.size());
        // je Ecke der Datei die UV, die sie schon bekommen hat, und ihre Kopien (Index -> UV)
        std::vector<std::vector<std::pair<V2, int>>> belegt(nz.ecken.size());
        const int h0 = n.ersteDreieck[ti] * 3;
        for (std::size_t h = 0; h < nz.kanten.size(); ++h) {
            const int H = h0 + static_cast<int>(h);
            const int e = n.ecke[uz(H)];
            const V2 w = n.uv[uz(H)];
            auto& liste = belegt[uz(e)];
            int idx = -1;
            for (const auto& [u, i] : liste) {
                if (std::memcmp(&u, &w, sizeof(V2)) == 0) { idx = i; }
            }
            if (idx < 0) {
                if (liste.empty()) {
                    idx = e;   // die erste UV bleibt in der Ecke der Datei
                    if (std::memcmp(x.ecken[uz(e)].uv, &w, sizeof(V2)) != 0) {
                        x.ecken[uz(e)].uv[0] = w.x;
                        x.ecken[uz(e)].uv[1] = w.y;
                        x.geaendert = true;
                    }
                } else {
                    Ecke kopie = nz.ecken[uz(e)];   // Ort, Normale, Knochen, Gewichte und Gewichtsfelder der Datei
                    kopie.uv[0] = w.x;
                    kopie.uv[1] = w.y;
                    idx = static_cast<int>(x.ecken.size());
                    x.ecken.push_back(kopie);
                    x.geaendert = true;
                }
                liste.emplace_back(w, idx);
            }
            x.indizes[h] = static_cast<std::uint32_t>(idx);
        }
        const int zahl = static_cast<int>(x.ecken.size());
        if (zahl > static_cast<int>(nz.ecken.size())) {
            br.neueEcken += zahl - static_cast<int>(nz.ecken.size());
            if (eckenGrenze > 0 && zahl >= eckenGrenze && br.ok) {
                br.ok = false;
                br.teil = t;
                br.ecken = zahl;
            }
        }
    }
    if (!br.ok) {
        if (bericht != nullptr) { *bericht = br; }
        return false;
    }
    for (std::size_t ti = 0; ti < neu.size(); ++ti) {
        Neu& x = neu[ti];
        Netz& nz = in.teile[uz(x.teil)].stufen[uz(n.stufe)];
        const std::size_t alt = nz.ecken.size();
        if (x.geaendert) {
            ++br.geaendert;
            std::vector<GewichtListe> mal = std::move(nz.mal);
            if (mal.size() == alt) {
                for (std::size_t e = alt; e < x.ecken.size(); ++e) {
                    // die Kopie einer Ecke malt wie ihr Vorbild: das Vorbild ist die Ecke derselben Datei-Ecke
                    std::size_t q = 0;
                    for (std::size_t h = 0; h < x.indizes.size(); ++h) {
                        if (x.indizes[h] == e) {
                            q = uz(n.ecke[uz(n.ersteDreieck[ti] * 3 + static_cast<int>(h))]);
                            break;
                        }
                    }
                    mal.push_back(mal[q]);
                }
            }
            nz.aufbauen(std::move(x.ecken), x.indizes);
            nz.mal = std::move(mal);
        }
        const std::size_t h0 = uz(n.ersteDreieck[ti] * 3);
        const std::size_t k = nz.kanten.size();
        nz.uvNaht.assign(n.naht.begin() + static_cast<std::ptrdiff_t>(h0), n.naht.begin() + static_cast<std::ptrdiff_t>(h0 + k));
        nz.uvDateiNaht.assign(n.dateiNaht.begin() + static_cast<std::ptrdiff_t>(h0), n.dateiNaht.begin() + static_cast<std::ptrdiff_t>(h0 + k));
        nz.uvPin.assign(n.pin.begin() + static_cast<std::ptrdiff_t>(h0), n.pin.begin() + static_cast<std::ptrdiff_t>(h0 + k));
        nz.uvFrei.assign(n.frei.begin() + static_cast<std::ptrdiff_t>(h0 / 3U), n.frei.begin() + static_cast<std::ptrdiff_t>((h0 + k) / 3U));
    }
    if (bericht != nullptr) { *bericht = br; }
    return true;
}

