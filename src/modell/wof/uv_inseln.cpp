std::span<const int> UvInseln::dreieckeVon(int i) const {
    if (i < 0 || dreieckAnfang.empty() || uz(i) + 1 >= dreieckAnfang.size()) { return {}; }
    return {dreieckListe.data() + dreieckAnfang[uz(i)], uz(dreieckAnfang[uz(i) + 1] - dreieckAnfang[uz(i)])};
}
std::span<const int> UvInseln::randVon(int i) const {
    if (i < 0 || randAnfang.empty() || uz(i) + 1 >= randAnfang.size()) { return {}; }
    return {randListe.data() + randAnfang[uz(i)], uz(randAnfang[uz(i) + 1] - randAnfang[uz(i)])};
}
std::span<const int> UvInseln::eckenVon(int k) const {
    if (k < 0 || keilAnfang.empty() || uz(k) + 1 >= keilAnfang.size()) { return {}; }
    return {keilListe.data() + keilAnfang[uz(k)], uz(keilAnfang[uz(k) + 1] - keilAnfang[uz(k)])};
}

