std::vector<u8> schnitte(const UvNetz& n) {
    std::vector<u8> s(uz(n.kanten()), 0);
    for (int h = 0; h < n.kanten(); ++h) {
        const int g = n.gegen[uz(h)];
        if (n.naht[uz(h)] != 0 || g < 0) {
            s[uz(h)] = 1;
            continue;
        }
        // WL acrossPairs: (h0, next(h1)) und (next(h0), h1); Teile sind nie verbunden (WL: verschiedene Sections)
        if (uvVerschieden(n, h, UvNetz::naechste(g)) || uvVerschieden(n, UvNetz::naechste(h), g)) { s[uz(h)] = 1; }
    }
    return s;
}

UvInseln inselnBauen(const UvNetz& n) {
    UvInseln out;
    const int dz = n.dreiecke();
    const int kz = n.kanten();
    const std::vector<u8> s = schnitte(n);
    Vereinigung dreiecke(dz);
    Vereinigung ecken(kz);
    for (int h = 0; h < kz; ++h) {
        const int g = n.gegen[uz(h)];
        if (s[uz(h)] != 0 || g < 0 || g < h) { continue; }
        dreiecke.verbinde(h / 3, g / 3);
        ecken.verbinde(h, UvNetz::naechste(g));
        ecken.verbinde(UvNetz::naechste(h), g);
    }
    out.inselVon.assign(uz(dz), -1);
    std::vector<int> inselVonWurzel(uz(dz), -1);
    std::vector<int> zahlJe;
    for (int d = 0; d < dz; ++d) {
        const int w = dreiecke.finde(d);
        if (inselVonWurzel[uz(w)] < 0) {
            inselVonWurzel[uz(w)] = out.zahl++;
            zahlJe.push_back(0);
        }
        out.inselVon[uz(d)] = inselVonWurzel[uz(w)];
        ++zahlJe[uz(inselVonWurzel[uz(w)])];
    }
    out.dreieckAnfang.assign(uz(out.zahl) + 1U, 0);
    for (int i = 0; i < out.zahl; ++i) { out.dreieckAnfang[uz(i) + 1] = out.dreieckAnfang[uz(i)] + zahlJe[uz(i)]; }
    out.dreieckListe.assign(uz(out.dreieckAnfang.back()), 0);
    {
        std::vector<int> zeiger(out.dreieckAnfang.begin(), out.dreieckAnfang.end() - 1);
        for (int d = 0; d < dz; ++d) { out.dreieckListe[uz(zeiger[uz(out.inselVon[uz(d)])]++)] = d; }
    }
    out.keilVon.assign(uz(kz), -1);
    std::vector<int> keilVonWurzel(uz(kz), -1);
    std::vector<int> jeKeil;
    for (int h = 0; h < kz; ++h) {
        const int w = ecken.finde(h);
        if (keilVonWurzel[uz(w)] < 0) {
            keilVonWurzel[uz(w)] = out.keilZahl++;
            jeKeil.push_back(0);
            out.keilPunkt.push_back(n.von[uz(h)]);
            out.keilInsel.push_back(out.inselVon[uz(h / 3)]);
        }
        out.keilVon[uz(h)] = keilVonWurzel[uz(w)];
        ++jeKeil[uz(keilVonWurzel[uz(w)])];
    }
    out.keilAnfang.assign(uz(out.keilZahl) + 1U, 0);
    for (int k = 0; k < out.keilZahl; ++k) { out.keilAnfang[uz(k) + 1] = out.keilAnfang[uz(k)] + jeKeil[uz(k)]; }
    out.keilListe.assign(uz(out.keilAnfang.back()), 0);
    {
        std::vector<int> zeiger(out.keilAnfang.begin(), out.keilAnfang.end() - 1);
        for (int h = 0; h < kz; ++h) { out.keilListe[uz(zeiger[uz(out.keilVon[uz(h)])]++)] = h; }
    }
    // Rand je Insel: von einer geschnittenen Kante um den Faecher der Ecke weiter bis zur naechsten geschnittenen
    out.randAnfang.assign(uz(out.zahl) + 1U, 0);
    out.geschlossen.assign(uz(out.zahl), 0);
    out.schleifen.assign(uz(out.zahl), 0);
    std::vector<u8> besucht(uz(kz), 0);
    std::vector<std::vector<int>> jeInsel(uz(out.zahl));
    for (int start = 0; start < kz; ++start) {
        if (besucht[uz(start)] != 0 || s[uz(start)] == 0) { continue; }
        const int insel = out.inselVon[uz(start / 3)];
        int lauf = start;
        do {
            besucht[uz(lauf)] = 1;
            jeInsel[uz(insel)].push_back(lauf);
            int schritt = UvNetz::naechste(lauf);
            for (int wache = 0; wache < kz; ++wache) {
                if (s[uz(schritt)] != 0) { break; }
                const int quer = n.gegen[uz(schritt)];
                if (quer < 0) { break; }
                schritt = UvNetz::naechste(quer);
            }
            lauf = schritt;
        } while (lauf != start && besucht[uz(lauf)] == 0);
        ++out.schleifen[uz(insel)];
    }
    for (int i = 0; i < out.zahl; ++i) {
        out.randAnfang[uz(i) + 1] = out.randAnfang[uz(i)] + static_cast<int>(jeInsel[uz(i)].size());
        out.geschlossen[uz(i)] = jeInsel[uz(i)].empty() ? 1 : 0;
        out.randListe.insert(out.randListe.end(), jeInsel[uz(i)].begin(), jeInsel[uz(i)].end());
    }
    return out;
}

std::vector<int> inselKeile(const UvInseln& in, int insel) {
    std::vector<int> out;
    for (const int d : in.dreieckeVon(insel)) {
        for (int k = 0; k < 3; ++k) {
            const int w = in.keil(d * 3 + k);
            if (w >= 0) { out.push_back(w); }
        }
    }
    std::sort(out.begin(), out.end());
    out.erase(std::unique(out.begin(), out.end()), out.end());
    return out;
}

std::vector<int> inselnVonDreiecken(const UvInseln& in, std::span<const int> dreiecke) {
    std::vector<int> out;
    for (const int d : dreiecke) {
        const int i = in.inselVonDreieck(d);
        if (i >= 0) { out.push_back(i); }
    }
    std::sort(out.begin(), out.end());
    out.erase(std::unique(out.begin(), out.end()), out.end());
    return out;
}

void markieren(UvNetz& n, std::span<const int> kanten, bool an) {
    for (const int h : kanten) {
        if (h < 0 || h >= n.kanten()) { continue; }
        n.naht[uz(h)] = an ? 1 : 0;
        n.dateiNaht[uz(h)] = 0;
        const int g = n.gegen[uz(h)];
        if (g >= 0) {
            n.naht[uz(g)] = an ? 1 : 0;
            n.dateiNaht[uz(g)] = 0;
        }
    }
}

bool seitenGleich(const UvNetz& n, int h) {
    const int g = n.gegen[uz(h)];
    if (g < 0) { return false; }
    return !uvVerschieden(n, h, UvNetz::naechste(g)) && !uvVerschieden(n, UvNetz::naechste(h), g);
}

bool markeOffen(const UvNetz& n, const UvInseln& in, int h) {
    const int g = n.gegen[uz(h)];
    if (n.naht[uz(h)] == 0 || g < 0) { return false; }
    const bool teilt = in.keil(h) != in.keil(UvNetz::naechste(g)) || in.keil(UvNetz::naechste(h)) != in.keil(g);
    return in.inselVonDreieck(h / 3) == in.inselVonDreieck(g / 3) && teilt && seitenGleich(n, h);
}

