std::size_t uz(int i) { return static_cast<std::size_t>(i); }

// WL islands.cpp: UnionFind
class Vereinigung {
public:
    explicit Vereinigung(int n) : eltern_(uz(n)), rang_(uz(n), 0) {
        for (int i = 0; i < n; ++i) { eltern_[uz(i)] = i; }
    }
    int finde(int a) {
        while (eltern_[uz(a)] != a) {
            eltern_[uz(a)] = eltern_[uz(eltern_[uz(a)])];
            a = eltern_[uz(a)];
        }
        return a;
    }
    void verbinde(int a, int b) {
        a = finde(a);
        b = finde(b);
        if (a == b) { return; }
        if (rang_[uz(a)] < rang_[uz(b)]) { std::swap(a, b); }
        eltern_[uz(b)] = a;
        if (rang_[uz(a)] == rang_[uz(b)]) { ++rang_[uz(a)]; }
    }

private:
    std::vector<int> eltern_;
    std::vector<u8> rang_;
};

bool uvVerschieden(const UvNetz& n, int a, int b) { return std::memcmp(&n.uv[uz(a)], &n.uv[uz(b)], sizeof(V2)) != 0; }

