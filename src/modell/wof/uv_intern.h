inline std::size_t uz(int i) { return static_cast<std::size_t>(i); }

inline float flaeche3d(V3 a, V3 b, V3 c) { return laenge(kreuz(b - a, c - a)) * 0.5F; }
// vorzeichenbehaftet: ein gekipptes Dreieck ist ein Vorzeichen, keine Groesse
inline float flaecheUv(V2 a, V2 b, V2 c) { return ((b.x - a.x) * (c.y - a.y) - (b.y - a.y) * (c.x - a.x)) * 0.5F; }

// WL LocalTriangle: das Dreieck in seiner eigenen Ebene, in double; erste Ecke im Ursprung, erste Kante auf x
inline bool lokalesDreieck(V3 a, V3 b, V3 c, double (&aus)[3][2]) {
    const double e1[3] = {static_cast<double>(b.x) - a.x, static_cast<double>(b.y) - a.y, static_cast<double>(b.z) - a.z};
    const double e2[3] = {static_cast<double>(c.x) - a.x, static_cast<double>(c.y) - a.y, static_cast<double>(c.z) - a.z};
    const double nn[3] = {e1[1] * e2[2] - e1[2] * e2[1], e1[2] * e2[0] - e1[0] * e2[2], e1[0] * e2[1] - e1[1] * e2[0]};
    const double doppelt = std::sqrt(nn[0] * nn[0] + nn[1] * nn[1] + nn[2] * nn[2]);
    const double l = std::sqrt(e1[0] * e1[0] + e1[1] * e1[1] + e1[2] * e1[2]);
    if (!(doppelt > 0.0) || !(l > 0.0)) { return false; }
    const double x = (e2[0] * e1[0] + e2[1] * e1[1] + e2[2] * e1[2]) / l;
    const double y = doppelt / l;
    aus[0][0] = 0.0;
    aus[0][1] = 0.0;
    aus[1][0] = l;
    aus[1][1] = 0.0;
    aus[2][0] = x;
    aus[2][1] = y;
    return l * y != 0.0;
}

// WL RasterTriangle: die Texel eines breite x hoehe-Rasters, die ein Dreieck (in Texeln) deckt; mit `ring` auch der
// Ring darum (die vorsichtige Deckung des Packers)
template <class Fuelle>
void rasterDreieck(int breite, int hoehe, V2 a, V2 b, V2 c, bool ring, Fuelle&& fuelle) {
    const float tx = std::min(a.x, std::min(b.x, c.x));
    const float hx = std::max(a.x, std::max(b.x, c.x));
    const float ty = std::min(a.y, std::min(b.y, c.y));
    const float hy = std::max(a.y, std::max(b.y, c.y));
    const int x0 = std::max(0, static_cast<int>(std::floor(tx)) - 1);
    const int x1 = std::min(breite - 1, static_cast<int>(std::ceil(hx)));
    const int y0 = std::max(0, static_cast<int>(std::floor(ty)) - 1);
    const int y1 = std::min(hoehe - 1, static_cast<int>(std::ceil(hy)));
    const float f = (b.x - a.x) * (c.y - a.y) - (b.y - a.y) * (c.x - a.x);
    if (f == 0.0F) { return; }
    const float inv = 1.0F / f;
    const float kante = ring ? -0.5F : 0.0F;
    for (int y = y0; y <= y1; ++y) {
        for (int x = x0; x <= x1; ++x) {
            const float px = static_cast<float>(x) + 0.5F;
            const float py = static_cast<float>(y) + 0.5F;
            const float w0 = ((b.x - a.x) * (py - a.y) - (b.y - a.y) * (px - a.x)) * inv;
            const float w1 = ((c.x - b.x) * (py - b.y) - (c.y - b.y) * (px - b.x)) * inv;
            const float w2 = ((a.x - c.x) * (py - c.y) - (a.y - c.y) * (px - c.x)) * inv;
            if (w0 >= kante && w1 >= kante && w2 >= kante) { fuelle(x, y); }
        }
    }
}

// WL IslandArea / AreasOf
struct InselFlaeche {
    float welt = 0.0F;
    float uv = 0.0F;   // Betrag: auch ein gekipptes Dreieck zaehlt
    float uvVorzeichen = 0.0F;
};
inline InselFlaeche flaechenVon(const UvNetz& n, const UvInseln& in, int insel) {
    InselFlaeche aus;
    for (const int d : in.dreieckeVon(insel)) {
        aus.welt += flaeche3d(n.ortVon(d * 3), n.ortVon(d * 3 + 1), n.ortVon(d * 3 + 2));
        const float a = flaecheUv(n.uvVon(d * 3), n.uvVon(d * 3 + 1), n.uvVon(d * 3 + 2));
        aus.uv += std::abs(a);
        aus.uvVorzeichen += a;
    }
    return aus;
}

// WL writeWedge / readWedge
inline void keilSchreiben(UvNetz& n, const UvInseln& in, int keil, V2 w) {
    for (const int h : in.eckenVon(keil)) { n.uv[uz(h)] = w; }
}
inline V2 keilLesen(const UvNetz& n, const UvInseln& in, int keil) {
    const std::span<const int> e = in.eckenVon(keil);
    return e.empty() ? V2{} : n.uv[uz(e[0])];
}
inline bool keilGepinnt(const UvNetz& n, const UvInseln& in, int keil) {
    for (const int h : in.eckenVon(keil)) {
        if (n.pin[uz(h)] != 0) { return true; }
    }
    return false;
}

template <class T>
std::vector<T> sortiert(std::vector<T> v) {
    std::sort(v.begin(), v.end());
    v.erase(std::unique(v.begin(), v.end()), v.end());
    return v;
}

