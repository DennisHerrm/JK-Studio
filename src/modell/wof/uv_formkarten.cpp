int stumm(const char*, ...) { return 0; }   // xatlas spricht sonst auf stdout (WF: auf stderr)

class Atlas {
public:
    Atlas() : a_(xatlas::Create()) { xatlas::SetPrint(stumm, false); }
    ~Atlas() {
        if (a_ != nullptr) { xatlas::Destroy(a_); }
    }
    Atlas(const Atlas&) = delete;
    Atlas& operator=(const Atlas&) = delete;
    [[nodiscard]] xatlas::Atlas* get() const { return a_; }

private:
    xatlas::Atlas* a_ = nullptr;
};

float deckungsToleranz(const UvNetz& n) {
    if (n.ort.empty()) { return 0.0F; }
    V3 t = n.ort[0];
    V3 h = n.ort[0];
    for (const V3& p : n.ort) {
        t = V3{std::min(t.x, p.x), std::min(t.y, p.y), std::min(t.z, p.z)};
        h = V3{std::max(h.x, p.x), std::max(h.y, p.y), std::max(h.z, p.z)};
    }
    return laenge(h - t) * 1e-5F;
}

