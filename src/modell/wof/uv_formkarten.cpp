int formKarten(UvNetz& n, std::span<const int> dreiecke, float detail) {
    if (n.dreiecke() == 0) { return 0; }
    std::vector<u8> gefragt(uz(n.dreiecke()), dreiecke.empty() ? 1 : 0);
    for (const int d : dreiecke) { gefragt[uz(d)] = 1; }
    const UvInseln gebiete = inselnBauen(n);
    std::vector<std::uint32_t> idx(uz(n.kanten()));
    for (int h = 0; h < n.kanten(); ++h) { idx[uz(h)] = static_cast<std::uint32_t>(n.von[uz(h)]); }
    std::vector<std::uint8_t> ignorieren(uz(n.dreiecke()));
    std::vector<std::uint32_t> material(uz(n.dreiecke()));
    for (int d = 0; d < n.dreiecke(); ++d) {
        ignorieren[uz(d)] = gefragt[uz(d)] == 0 ? 1 : 0;
        material[uz(d)] = static_cast<std::uint32_t>(std::max(gebiete.inselVonDreieck(d), 0));
    }
    // xatlas will bool[] (std::vector<bool> hat keine Daten am Stueck)
    std::unique_ptr<bool[]> ign(new bool[ignorieren.size()]);
    for (std::size_t i = 0; i < ignorieren.size(); ++i) { ign[i] = ignorieren[i] != 0; }
    xatlas::MeshDecl decl;
    decl.vertexCount = static_cast<std::uint32_t>(n.ort.size());
    decl.vertexPositionData = n.ort.data();
    decl.vertexPositionStride = sizeof(V3);
    decl.indexCount = static_cast<std::uint32_t>(idx.size());
    decl.indexData = idx.data();
    decl.indexFormat = xatlas::IndexFormat::UInt32;
    decl.faceIgnoreData = ign.get();
    decl.faceMaterialData = material.data();
    decl.epsilon = deckungsToleranz(n);
    Atlas atlas;
    if (xatlas::AddMesh(atlas.get(), decl, 1) != xatlas::AddMeshError::Success) { return -1; }
    xatlas::AddMeshJoin(atlas.get());
    xatlas::ChartOptions o;
    o.maxCost = detail;
    xatlas::ComputeCharts(atlas.get(), o);
    // erst PackCharts fuellt atlas->meshes (WF: Aufloesung 64, ohne Drehen, Bloecke ausgerichtet)
    xatlas::PackOptions p;
    p.resolution = 64;
    p.bilinear = false;
    p.blockAlign = true;
    p.rotateCharts = false;
    p.rotateChartsToAxis = false;
    xatlas::PackCharts(atlas.get(), p);
    if (atlas.get()->meshCount == 0) { return 0; }
    const xatlas::Mesh& m = atlas.get()->meshes[0];
    std::vector<int> karteVon(uz(n.dreiecke()), -1);
    for (std::uint32_t c = 0; c < m.chartCount; ++c) {
        const xatlas::Chart& k = m.chartArray[c];
        for (std::uint32_t i = 0; i < k.faceCount; ++i) {
            const std::uint32_t d = k.faceArray[i];
            if (d < karteVon.size() && karteVon[d] < 0) { karteVon[d] = static_cast<int>(c); }
        }
    }
    std::vector<int> grenzen;
    for (int h = 0; h < n.kanten(); ++h) {
        const int g = n.gegen[uz(h)];
        if (g < 0 || h > g || gefragt[uz(h / 3)] == 0 || gefragt[uz(g / 3)] == 0) { continue; }
        const int a = karteVon[uz(h / 3)];
        const int b = karteVon[uz(g / 3)];
        if (a >= 0 && b >= 0 && a != b) { grenzen.push_back(h); }
    }
    markieren(n, grenzen, true);
    return static_cast<int>(m.chartCount);
}

