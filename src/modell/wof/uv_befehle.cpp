std::vector<int> gewaehlteDreiecke(const UvNetz& n, const UvInseln& in, const UvAuswahl& a) {
    std::vector<int> aus;
    if (a.ebene == UvEbene::Flaeche || a.ebene == UvEbene::Insel) {
        for (int d = 0; d < n.dreiecke(); ++d) {
            if (dreieckGanz(a, d)) { aus.push_back(d); }
        }
        if (a.ebene == UvEbene::Insel) {
            std::vector<int> ganz;
            for (const int i : inselnVonDreiecken(in, aus)) {
                for (const int d : in.dreieckeVon(i)) { ganz.push_back(d); }
            }
            aus = sortiert(std::move(ganz));
        }
        return aus;
    }
    for (int h = 0; h < n.kanten(); ++h) {
        const bool ja = a.ebene == UvEbene::Ecke ? gewaehlt(a, h) : gewaehlt(a, h) && gewaehlt(a, UvNetz::naechste(h));
        if (ja) { aus.push_back(h / 3); }
    }
    return sortiert(std::move(aus));
}

std::vector<int> gewaehlteKanten(const UvNetz& n, const UvAuswahl& a) {
    std::vector<int> aus;
    const auto kante = [&](int h) {
        const int g = n.gegen[uz(h)];
        return g >= 0 ? std::min(h, g) : h;
    };
    if (a.ebene == UvEbene::Kante) {
        for (int h = 0; h < n.kanten(); ++h) {
            if (gewaehlt(a, h) && gewaehlt(a, UvNetz::naechste(h))) { aus.push_back(kante(h)); }
        }
        return sortiert(std::move(aus));
    }
    if (a.ebene == UvEbene::Ecke) {
        std::vector<u8> gehalten(n.ort.size(), 0);
        for (int h = 0; h < n.kanten(); ++h) {
            if (gewaehlt(a, h)) { gehalten[uz(n.von[uz(h)])] = 1; }
        }
        for (int h = 0; h < n.kanten(); ++h) {
            if (gehalten[uz(n.von[uz(h)])] != 0 && gehalten[uz(n.nach(h))] != 0) { aus.push_back(kante(h)); }
        }
        return sortiert(std::move(aus));
    }
    std::vector<int> d;
    for (int t = 0; t < n.dreiecke(); ++t) {
        if (dreieckGanz(a, t)) { d.push_back(t); }
    }
    return randKanten(n, d);
}

std::vector<int> gewaehlteKeile(const UvInseln& in, const UvAuswahl& a) {
    std::vector<int> aus;
    for (std::size_t h = 0; h < a.ecke.size(); ++h) {
        if (a.ecke[h] != 0) {
            if (const int w = in.keil(static_cast<int>(h)); w >= 0) { aus.push_back(w); }
        }
    }
    return sortiert(std::move(aus));
}

std::vector<int> gewaehlteInseln(const UvNetz& n, const UvInseln& in, const UvAuswahl& a) {
    return inselnVonDreiecken(in, gewaehlteDreiecke(n, in, a));
}

