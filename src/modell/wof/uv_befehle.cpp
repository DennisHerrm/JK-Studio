UvAntwort befehlRingAufschneiden(UvNetz& n, const UvAuswahl& a, const UvKontext& k) {
    Beruehrt b(n);
    UvAntwort aus;
    const UvInseln in = inselnBauen(n);
    std::vector<int> inseln = gewaehlteInseln(n, in, a);
    if (inseln.empty()) {
        for (int i = 0; i < in.zahl; ++i) { inseln.push_back(i); }
    }
    NahtWegOptionen o;
    o.sichtbar = k.vorn;
    std::vector<int> schn;
    for (const int i : inseln) {
        if (in.schleifen[uz(i)] < 2) { continue; }
        const NahtWeg w = ringNaht(n, in, i, o);
        if (!w.gestoppt) {
            schn.insert(schn.end(), w.kanten.begin(), w.kanten.end());
            ++aus.zahl;
        }
    }
    if (schn.empty()) {
        aus.meldung = UvMeldung::NichtsZuTun;
        return aus;
    }
    markieren(n, schn, true);
    return aus;
}

UvAntwort befehlSchnellAbwickeln(UvNetz& n, const UvAuswahl& a, Vorlage v, const UvKontext& k) {
    const UvNetz sicher = n;
    Beruehrt b(n);
    UvAntwort aus;
    std::vector<int> d = a.leer() ? alleDreiecke(n) : gewaehlteDreiecke(n, inselnBauen(n), a);
    if (d.empty()) {
        aus.meldung = UvMeldung::NichtsGewaehlt;
        return aus;
    }
    switch (v) {
        case Vorlage::Figur: {
            if (!k.glieder) {
                aus.meldung = UvMeldung::KeineGlieder;   // WF: "edit.uv.refused.no_limbs", weiter mit Requisit
                return aus;
            }
            (void)naehteAusSkelett(n, d, k.faltung, k.spiegel, k.vorn);
            // Die Flaechen einer .glm sind offene Rohre (Arme, Beine: die Kappen sind eigene Flaechen) - ein Teil ohne
            // zweite Grenzkante bleibt ein Ring. WF bietet dafuer "Cut ring" als Meldung an; hier im selben Schritt
            // (WF CutRingCmd: RingSeam zwischen den zwei laengsten Schleifen, an der verdeckten Seite).
            const UvInseln ri = inselnBauen(n);
            NahtWegOptionen o;
            o.sichtbar = k.vorn;
            std::vector<int> schn;
            for (const int i : inselnVonDreiecken(ri, d)) {
                if (ri.schleifen[uz(i)] < 2) { continue; }
                const NahtWeg w = ringNaht(n, ri, i, o);
                if (!w.gestoppt) { schn.insert(schn.end(), w.kanten.begin(), w.kanten.end()); }
            }
            markieren(n, schn, true);
            break;
        }
        case Vorlage::Requisit:
            if (formKarten(n, d, 2.0F) < 0) {   // WF UvViewOptions::detail = 2
                n = sicher;
                aus.meldung = UvMeldung::KeineFormKarten;
                return aus;
            }
            break;
        case Vorlage::HarteFlaeche: (void)naehteNachWinkel(n, d, 60.0F); break;   // WF UvViewOptions::seamAngle = 60
    }
    const UvAntwort eins = dreieckeAbwickeln(n, d, k);
    if (eins.meldung == UvMeldung::Ungeloest) { aus = eins; }
    const UvInseln in = inselnBauen(n);
    const std::vector<int> liste = inselnVonDreiecken(in, d);
    if (v == Vorlage::Figur) {
        std::vector<u8> fertig(uz(in.zahl), 0);
        for (const int i : liste) {
            const int z = zwillingVon(n, in, i, k.spiegel);
            if (fertig[uz(i)] != 0 || z < 0 || fertig[uz(z)] != 0 || !std::binary_search(liste.begin(), liste.end(), z)) { continue; }
            fertig[uz(i)] = fertig[uz(z)] = 1;
            (void)stapeln(n, in, i, z, k.spiegel);
        }
    } else {
        for (const int i : liste) {
            (void)inselAusrichten(n, in, i);
            if (v == Vorlage::HarteFlaeche) { (void)rechteck(n, in, i); }
        }
    }
    const float dichte = mittlereDichte(n, in, k.aufloesung, false);
    if (dichte > 0.0F) { dichteAngleichen(n, in, liste, dichte, k.aufloesung); }
    PackOptionen o = packOptionen(k);
    o.kachelnAbweisen = false;
    o.beweglich.assign(uz(in.zahl), 0);
    for (const int i : liste) { o.beweglich[uz(i)] = 1; }
    (void)packen(n, in, o);
    if (aus.meldung == UvMeldung::Keine) { aus.zahl = static_cast<int>(liste.size()); }
    return aus;
}

void uvBewegen(UvNetz& n, const UvInseln& in, const UvAuswahl& a, V2 mitte, V2 weg, float bogen, V2 massstab) {
    const float s = std::sin(bogen);
    const float c = std::cos(bogen);
    for (const int w : gewaehlteKeile(in, a)) {
        for (const int h : in.eckenVon(w)) {
            const float dx = (n.uv[uz(h)].x - mitte.x) * massstab.x;
            const float dy = (n.uv[uz(h)].y - mitte.y) * massstab.y;
            n.uv[uz(h)] = V2{mitte.x + dx * c - dy * s + weg.x, mitte.y + dx * s + dy * c + weg.y};
        }
    }
}

void beruehrtMarkieren(const UvNetz& vorher, UvNetz& nachher) {
    if (vorher.kanten() != nachher.kanten()) { return; }
    std::vector<int> geaendert;
    for (int d = 0; d < nachher.dreiecke(); ++d) {
        for (int k = 0; k < 3; ++k) {
            const int h = d * 3 + k;
            if (std::memcmp(&vorher.uv[uz(h)], &nachher.uv[uz(h)], sizeof(V2)) != 0 || vorher.pin[uz(h)] != nachher.pin[uz(h)]) {
                geaendert.push_back(d);
                break;
            }
        }
    }
    if (geaendert.empty()) { return; }
    const UvInseln in = inselnBauen(nachher);
    for (const int i : inselnVonDreiecken(in, geaendert)) {
        for (const int d : in.dreieckeVon(i)) { nachher.frei[uz(d)] = 1; }
    }
}

