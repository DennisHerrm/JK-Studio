bool gewaehlt(const UvAuswahl& a, int h) { return uz(h) < a.ecke.size() && a.ecke[uz(h)] != 0; }
bool dreieckGanz(const UvAuswahl& a, int d) { return gewaehlt(a, d * 3) && gewaehlt(a, d * 3 + 1) && gewaehlt(a, d * 3 + 2); }

// RAII: am Ende eines Befehls die beruehrten Inseln frei machen (WF CommitUvEdit -> MarkTouched)
class Beruehrt {
public:
    explicit Beruehrt(UvNetz& n) : n_(n), vorher_(n) {}
    ~Beruehrt() { beruehrtMarkieren(vorher_, n_); }
    Beruehrt(const Beruehrt&) = delete;
    Beruehrt& operator=(const Beruehrt&) = delete;
    [[nodiscard]] const UvNetz& vorher() const { return vorher_; }

private:
    UvNetz& n_;
    UvNetz vorher_;
};

bool istNaht(const UvNetz& n, int h) { return n.naht[uz(h)] != 0 || !seitenGleich(n, h); }   // WF IsSeam (Marke oder Schnitt)

std::vector<int> alleDreiecke(const UvNetz& n) {
    std::vector<int> d(uz(n.dreiecke()));
    for (int i = 0; i < n.dreiecke(); ++i) { d[uz(i)] = i; }
    return d;
}

// WF NewIslandDensity: der Median der festen Inseln, sonst aller, sonst die Kachel halb gefuellt
float neueDichte(const UvNetz& n, const UvInseln& in, std::span<const int> liste, int res) {
    float d = mittlereDichte(n, in, res, true);
    if (d <= 0.0F) { d = mittlereDichte(n, in, res, false); }
    if (d > 0.0F) { return d; }
    double welt = 0.0;
    for (const int i : liste) {
        for (const int t : in.dreieckeVon(i)) { welt += flaeche3d(n.ortVon(t * 3), n.ortVon(t * 3 + 1), n.ortVon(t * 3 + 2)); }
    }
    return welt > 0.0 ? static_cast<float>(res * std::sqrt(0.5 / welt)) : 0.0F;
}

// WF FitTile: hoechstens 0,9 der Kachel
void kachelEinpassen(UvNetz& n, const UvInseln& in, int insel) {
    constexpr float kMeist = 0.9F;
    const UvKasten k = kastenVon(n, in, insel);
    const float weit = std::max(k.breite(), k.hoehe());
    if (!k.leer && weit > kMeist) { inselVersetzen(n, in, insel, kMeist / weit, V2{}); }
}

// WF PlaceNew: in den freien Platz der Kachel um die anderen, was nicht passt in den Streifen
void neuSetzen(UvNetz& n, const UvInseln& in, std::span<const int> liste, float dichte, bool zusammen, int res, int abstand) {
    if (liste.empty()) { return; }
    std::vector<u8> beweglich(uz(in.zahl), 0);
    std::vector<int> gruppe(zusammen ? uz(in.zahl) : 0U, -1);
    for (const int i : liste) {
        beweglich[uz(i)] = 1;
        if (zusammen) { gruppe[uz(i)] = 0; }
    }
    for (const int i : inFreienPlatz(n, in, beweglich, gruppe, res, abstand)) { inStreifen(n, in, i, dichte, res); }
}

// WF PartClosedMarks: eine Marke innerhalb einer Insel, deren Seiten noch gleich sind, bekommt verschiedene UV
void geschlosseneMarkenTrennen(UvNetz& n, const UvInseln& in, int insel) {
    std::unordered_map<int, std::vector<int>> keileBei;
    const auto teilen = [&](int keil) {
        if (keileBei.empty()) {
            for (const int d : in.dreieckeVon(insel)) {
                for (int k = 0; k < 3; ++k) {
                    std::vector<int>& rund = keileBei[n.von[uz(d * 3 + k)]];
                    const int w = in.keil(d * 3 + k);
                    if (std::find(rund.begin(), rund.end(), w) == rund.end()) { rund.push_back(w); }
                }
            }
        }
        const std::span<const int> ecken = in.eckenVon(keil);
        V2 p = n.uv[uz(ecken.front())];
        const std::vector<int>& rund = keileBei[in.keilPunkt[uz(keil)]];
        const auto belegt = [&]() {
            return std::any_of(rund.begin(), rund.end(), [&](int w) {
                const V2 q = n.uv[uz(in.eckenVon(w).front())];
                return w != keil && q.x == p.x && q.y == p.y;
            });
        };
        do {
            p.x = std::nextafter(p.x, std::numeric_limits<float>::infinity());
        } while (belegt());
        for (const int h : ecken) { n.uv[uz(h)] = p; }
    };
    for (const int d : in.dreieckeVon(insel)) {
        for (int k = 0; k < 3; ++k) {
            const int h = d * 3 + k;
            const int o = n.gegen[uz(h)];
            if (n.naht[uz(h)] == 0 || o < 0 || o < h || in.inselVonDreieck(o / 3) != insel || !seitenGleich(n, h)) { continue; }
            for (const auto& [mein, ihr] : {std::pair{o, UvNetz::naechste(h)}, std::pair{UvNetz::naechste(o), h}}) {
                const int w = in.keil(mein);
                if (w < 0 || w == in.keil(ihr) || keilGepinnt(n, in, w)) { continue; }
                teilen(w);
                break;
            }
        }
    }
}

AbflachErgebnis loesen(UvNetz& n, const UvInseln& in, int insel, UvMethode m) {
    return m == UvMethode::MinimaleDehnung ? minimaleDehnung(n, in, insel) : lscm(n, in, insel);
}

// WF Flatten: jede Insel loesen; eine ohne Karte auf die Dichte der anderen, in den freien Platz
int abflachen(UvNetz& n, const UvInseln& in, std::span<const int> liste, const UvKontext& k, std::vector<int>* ungeloest) {
    int geschlossen = 0;
    float dichte = neueDichte(n, in, liste, k.aufloesung);
    const bool bezug = mittlereDichte(n, in, k.aufloesung, false) > 0.0F;
    std::vector<int> ohneKarte;
    std::vector<int> geloest;
    const float median = mittlereDichte(n, in, k.aufloesung, false);
    for (const int i : liste) {
        if (in.geschlossen[uz(i)] != 0) {
            ++geschlossen;
            continue;
        }
        const float hatte = texelDichte(n, in, i, k.aufloesung);
        const bool hatteKarte = hatte > 0.0F && (median <= 0.0F || hatte >= median / 16.0F);
        if (const AbflachErgebnis e = loesen(n, in, i, k.methode); e.ok()) {
            geloest.push_back(i);
            if (ungeloest != nullptr && e.gekappt) { ungeloest->push_back(in.dreieckeVon(i).front()); }
        }
        if (!hatteKarte && dichte > 0.0F) {
            const float jetzt = texelDichte(n, in, i, k.aufloesung);
            if (jetzt > 0.0F) { inselVersetzen(n, in, i, dichte / jetzt, V2{}); }
            if (!bezug) { kachelEinpassen(n, in, i); }
            ohneKarte.push_back(i);
        }
    }
    neuSetzen(n, in, ohneKarte, dichte, false, k.aufloesung, k.abstand);
    for (const int i : geloest) { geschlosseneMarkenTrennen(n, in, i); }
    return geschlossen;
}

// WF WeldAcross: die Seite `move` jeder Kante auf die Seite `keep`
void ueberSchweissen(UvNetz& n, const UvInseln& in, std::span<const int> kanten) {
    for (const int h0 : kanten) {
        const int h1 = n.gegen[uz(h0)];
        if (h1 < 0) { continue; }
        const std::pair<int, int> enden[2] = {{h0, UvNetz::naechste(h1)}, {UvNetz::naechste(h0), h1}};
        for (const auto& [halten, ziehen] : enden) {
            const int w = in.keil(ziehen);
            if (w < 0) { continue; }
            const V2 wert = n.uv[uz(halten)];
            for (const int c : in.eckenVon(w)) { n.uv[uz(c)] = wert; }
        }
    }
}

// WF StaleCuts: ungemarkte Schnitte innerhalb einer Insel (verschiedene UV ohne Marke)
std::vector<int> alteSchnitte(const UvNetz& n, const UvInseln& in, int insel) {
    std::vector<int> aus;
    for (const int d : in.dreieckeVon(insel)) {
        for (int k = 0; k < 3; ++k) {
            const int h = d * 3 + k;
            const int g = n.gegen[uz(h)];
            if (g < 0 || g / 3 < d || in.inselVonDreieck(g / 3) != insel) { continue; }
            if (n.naht[uz(h)] != 0 || seitenGleich(n, h)) { continue; }
            aus.push_back(h);
        }
    }
    return sortiert(std::move(aus));
}

void neuLoesenEine(UvNetz& n, int dreieck, const UvKontext& k) {
    UvInseln in = inselnBauen(n);
    int insel = in.inselVonDreieck(dreieck);
    const std::vector<int> alt = alteSchnitte(n, in, insel);
    if (!alt.empty()) {
        ueberSchweissen(n, in, alt);
        in = inselnBauen(n);
        insel = in.inselVonDreieck(dreieck);
    }
    const int eine[] = {insel};
    (void)abflachen(n, in, eine, k, nullptr);
}

// WF SewJoins: wo eine geloeschte Naht zwei Inseln verbindet, kommt die kleinere an die groessere
void naehteZusammennaehen(UvNetz& n, std::span<const int> kanten) {
    const UvInseln vorher = inselnBauen(n);
    std::vector<std::pair<int, int>> verbunden;
    for (const int h : kanten) {
        const int g = n.gegen[uz(h)];
        if (g < 0) { continue; }
        const int ia = vorher.inselVonDreieck(h / 3);
        const int ib = vorher.inselVonDreieck(g / 3);
        if (ia != ib && ia >= 0 && ib >= 0) { verbunden.emplace_back(ia, ib); }
    }
    std::vector<int> groessere;
    for (const auto& [ia, ib] : verbunden) {
        const int gross = vorher.dreieckeVon(ia).size() >= vorher.dreieckeVon(ib).size() ? ia : ib;
        groessere.push_back(gross);
        for (const int h0 : kanten) {
            const int h1 = n.gegen[uz(h0)];
            if (h1 < 0) { continue; }
            const bool grossZuerst = vorher.inselVonDreieck(h0 / 3) == gross;
            if (!grossZuerst && vorher.inselVonDreieck(h1 / 3) != gross) { continue; }
            const int von = grossZuerst ? h0 : h1;
            const int in = grossZuerst ? h1 : h0;
            const std::pair<int, int> enden[2] = {{von, UvNetz::naechste(in)}, {UvNetz::naechste(von), in}};
            for (const auto& [grossEcke, kleinEcke] : enden) {
                const int w = vorher.keil(kleinEcke);
                if (w < 0) { continue; }
                for (const int c : vorher.eckenVon(w)) { n.uv[uz(c)] = n.uv[uz(grossEcke)]; }
            }
        }
    }
    const UvInseln nachher = inselnBauen(n);
    std::vector<int> gepinnt;
    for (const int gross : groessere) {
        for (const int d : vorher.dreieckeVon(gross)) {
            for (int k = 0; k < 3; ++k) {
                if (const int w = nachher.keil(d * 3 + k); w >= 0) { gepinnt.push_back(w); }
            }
        }
    }
    gepinnt = sortiert(std::move(gepinnt));
    std::vector<int> zusammen;
    for (const int gross : groessere) {
        if (!vorher.dreieckeVon(gross).empty()) { zusammen.push_back(nachher.inselVonDreieck(vorher.dreieckeVon(gross).front())); }
    }
    for (const int i : sortiert(std::move(zusammen))) {
        LscmOptionen o;
        o.halten = true;
        (void)lscm(n, nachher, i, gepinnt, o);
    }
}

// WF CloseCuts: zusammennaehen, Schlitze schweissen und neu loesen; eine Insel, die dadurch geschlossen wuerde, bleibt
int schnitteSchliessen(UvNetz& n, std::span<const int> kanten, const UvKontext& k) {
    naehteZusammennaehen(n, kanten);
    const UvInseln in = inselnBauen(n);
    std::map<int, std::vector<int>> schlitze;
    for (const int h : kanten) {
        const int g = n.gegen[uz(h)];
        if (g < 0 || seitenGleich(n, h)) { continue; }
        const int i = in.inselVonDreieck(h / 3);
        if (i >= 0 && i == in.inselVonDreieck(g / 3)) { schlitze[in.dreieckeVon(i).front()].push_back(h); }
    }
    int geschlossen = -1;
    for (const auto& [d, schnitt] : schlitze) {
        UvNetz versuch = n;
        const UvInseln jetzt = inselnBauen(versuch);
        ueberSchweissen(versuch, jetzt, schnitt);
        const UvInseln geschweisst = inselnBauen(versuch);
        const int i = geschweisst.inselVonDreieck(d);
        if (i >= 0 && geschweisst.geschlossen[uz(i)] != 0) {
            geschlossen = d;
            continue;
        }
        n = std::move(versuch);
        neuLoesenEine(n, d, k);
    }
    return geschlossen;
}

std::vector<int> mitSpiegel(const UvNetz& n, std::vector<int> kanten, const UvKontext& k) {
    if (!k.spiegeln || k.spiegel.empty()) { return kanten; }
    std::map<std::pair<int, int>, int> kanteVon;
    for (int h = 0; h < n.kanten(); ++h) { kanteVon.emplace(std::make_pair(n.von[uz(h)], n.nach(h)), h); }
    const std::size_t zahl = kanten.size();
    for (std::size_t i = 0; i < zahl; ++i) {
        const int a = n.von[uz(kanten[i])];
        const int b = n.nach(kanten[i]);
        if (uz(a) >= k.spiegel.size() || uz(b) >= k.spiegel.size() || k.spiegel[uz(a)] < 0 || k.spiegel[uz(b)] < 0) { continue; }
        auto it = kanteVon.find({k.spiegel[uz(a)], k.spiegel[uz(b)]});
        if (it == kanteVon.end()) { it = kanteVon.find({k.spiegel[uz(b)], k.spiegel[uz(a)]}); }
        if (it != kanteVon.end()) { kanten.push_back(it->second); }
    }
    return sortiert(std::move(kanten));
}

// WF ClearFileSeamsInside: die Datei-Marken mit beiden Seiten unter `dreiecke` loeschen
int dateiNaehteInnenLoeschen(UvNetz& n, std::span<const int> dreiecke) {
    std::vector<u8> drin(uz(n.dreiecke()), 0);
    for (const int d : dreiecke) { drin[uz(d)] = 1; }
    std::vector<int> innen;
    for (int h = 0; h < n.kanten(); ++h) {
        const int g = n.gegen[uz(h)];
        if (n.dateiNaht[uz(h)] == 0 || g < 0 || h > g) { continue; }
        if (drin[uz(h / 3)] != 0 && drin[uz(g / 3)] != 0) { innen.push_back(h); }
    }
    markieren(n, innen, false);
    return static_cast<int>(innen.size());
}

// WF UnwrapFaces: geschlossene Stuecke an der verdeckten Seite schneiden, alte Schnitte schweissen, abflachen
UvAntwort dreieckeAbwickeln(UvNetz& n, std::span<const int> dreiecke, const UvKontext& k) {
    UvAntwort aus;
    UvInseln in = inselnBauen(n);
    std::vector<int> liste = inselnVonDreiecken(in, dreiecke);
    std::vector<int> dazu;
    for (const int i : liste) {
        if (in.geschlossen[uz(i)] == 0) { continue; }
        NahtWegOptionen o;
        o.sichtbar = k.vorn;
        const std::vector<int> gebiet(in.dreieckeVon(i).begin(), in.dreieckeVon(i).end());
        const NahtWeg w = schliessendeNaht(n, gebiet, o);
        if (w.gestoppt) { continue; }
        dazu.insert(dazu.end(), w.kanten.begin(), w.kanten.end());
        if (aus.meldung == UvMeldung::Keine) {
            aus.meldung = UvMeldung::Geschlossen;
            aus.zahl = n.teil[uz(in.dreieckeVon(i).front() * 3)];
        }
    }
    if (!dazu.empty()) {
        markieren(n, dazu, true);
        in = inselnBauen(n);
        liste = inselnVonDreiecken(in, dreiecke);
    }
    std::vector<int> erste;
    for (const int i : liste) { erste.push_back(in.dreieckeVon(i).front()); }
    for (const int d : erste) {
        const UvInseln jetzt = inselnBauen(n);
        const std::vector<int> alt = alteSchnitte(n, jetzt, jetzt.inselVonDreieck(d));
        if (!alt.empty()) { ueberSchweissen(n, jetzt, alt); }
    }
    in = inselnBauen(n);
    liste = inselnVonDreiecken(in, dreiecke);
    std::vector<int> ungeloest;
    (void)abflachen(n, in, liste, k, &ungeloest);
    if (!ungeloest.empty() && aus.meldung == UvMeldung::Keine) {
        aus.meldung = UvMeldung::Ungeloest;
        aus.zahl = static_cast<int>(ungeloest.size());
    }
    return aus;
}

std::vector<int> randKanten(const UvNetz& n, std::span<const int> dreiecke) {
    std::set<int> drin(dreiecke.begin(), dreiecke.end());
    std::vector<int> aus;
    for (const int d : drin) {
        for (int k = 0; k < 3; ++k) {
            const int g = n.gegen[uz(d * 3 + k)];
            if (g >= 0 && drin.count(g / 3) == 0) { aus.push_back(d * 3 + k); }
        }
    }
    return sortiert(std::move(aus));
}

// WF TwinOf: die Insel, auf die die Kanten dieser Insel durch den Spiegel fallen (mehr als die Haelfte der Dreiecke)
int zwillingVon(const UvNetz& n, const UvInseln& in, int insel, std::span<const int> spiegel) {
    if (spiegel.empty()) { return -1; }
    std::map<std::pair<int, int>, int> kanteVon;
    for (int h = 0; h < n.kanten(); ++h) { kanteVon.emplace(std::make_pair(n.von[uz(h)], n.nach(h)), h); }
    std::map<int, int> stimmen;
    for (const int d : in.dreieckeVon(insel)) {
        for (int k = 0; k < 3; ++k) {
            const int a = n.von[uz(d * 3 + k)];
            const int b = n.nach(d * 3 + k);
            if (uz(a) >= spiegel.size() || uz(b) >= spiegel.size() || spiegel[uz(a)] < 0 || spiegel[uz(b)] < 0) { continue; }
            const auto it = kanteVon.find({spiegel[uz(b)], spiegel[uz(a)]});
            if (it == kanteVon.end()) { continue; }
            ++stimmen[in.inselVonDreieck(it->second / 3)];
            break;
        }
    }
    int beste = -1;
    int meiste = 0;
    for (const auto& [z, zahl] : stimmen) {
        if (zahl > meiste) {
            meiste = zahl;
            beste = z;
        }
    }
    if (beste == insel || uz(meiste) * 2U < in.dreieckeVon(insel).size()) { return -1; }
    return beste;
}

