Ecke mischen(const Ecke& a, const Ecke& b, double t);
bool eckeGleich(const Ecke& a, const Ecke& b);

// Neue Flaeche aus Ecken (Teil von der Vorlage), markiert neu
int neueFlaeche(PolyNetz& n, std::vector<PEcke> ecken, int teil);
void flaecheGeaendert(PFlaeche& f);

// Die affine UV-Abbildung eines Vielecks (aus drei gut gestellten Ecken): uv(ort); false wenn entartet
struct UvAbbild {
    V o, u, v;            // Ursprung und Achsen in der Ebene
    double m[2][3]{};     // uv = m * (s, t, 1), s/t in den Achsen
    bool gut = false;
};
UvAbbild uvAbbild(const PolyNetz& n, const PFlaeche& f);
void uvBei(const UvAbbild& a, V ort, float uv[2]);

