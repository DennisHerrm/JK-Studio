V mitte(const PolyNetz& n, const PFlaeche& f);
// Index der Ecke mit dem Punkt im Vieleck, -1 keine
int eckeMit(const PFlaeche& f, int punkt);

int neuerPunkt(PolyNetz& n, V ort, int teil);
// Ecke a nach b gemischt (UV, Normale linear; Knochen und Gewichte zusammengelegt, die vier groessten, Summe 1 -
