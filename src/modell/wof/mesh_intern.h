inline std::size_t uz(int i) { return static_cast<std::size_t>(i); }
inline int zi(std::size_t i) { return static_cast<int>(i); }

struct V {
    double x = 0.0, y = 0.0, z = 0.0;
};
inline V vAus(const float p[3]) { return V{p[0], p[1], p[2]}; }
inline void vNach(const V& v, float p[3]) {
    p[0] = static_cast<float>(v.x);
    p[1] = static_cast<float>(v.y);
    p[2] = static_cast<float>(v.z);
}
inline V operator+(V a, V b) { return V{a.x + b.x, a.y + b.y, a.z + b.z}; }
inline V operator-(V a, V b) { return V{a.x - b.x, a.y - b.y, a.z - b.z}; }
inline V operator*(V a, double s) { return V{a.x * s, a.y * s, a.z * s}; }
inline double punkt(V a, V b) { return a.x * b.x + a.y * b.y + a.z * b.z; }
inline V kreuz(V a, V b) { return V{a.y * b.z - a.z * b.y, a.z * b.x - a.x * b.z, a.x * b.y - a.y * b.x}; }
inline double laenge(V a) { return std::sqrt(punkt(a, a)); }
inline V einheit(V a) {
    const double l = laenge(a);
    return l > 0.0 ? a * (1.0 / l) : V{};
}
inline double winkel(V a, V b) {
    const double la = laenge(a), lb = laenge(b);
    if (!(la > 0.0) || !(lb > 0.0)) { return 0.0; }
    return std::acos(std::clamp(punkt(a, b) / (la * lb), -1.0, 1.0));
}

inline V ort(const PolyNetz& n, int p) { return vAus(n.punkte[uz(p)].ort); }
inline int punktVon(const PFlaeche& f, int i) {
    const int k = zi(f.ecken.size());
    return f.ecken[uz(((i % k) + k) % k)].punkt;
}
// Newell-Normale eines Vielecks (nicht normiert: Laenge = doppelte Flaeche)
