struct TeilGrenze {
    int teil = -1;
    FlaechenMass mass;
    bool nameZuLang = false;
    bool shaderZuLang = false;
    bool tagKeinDreieck = false;
};
[[nodiscard]] std::vector<TeilGrenze> grenzenPruefen(const Inhalt& in, int stufe);
// Max Ecken je Datei: wie polyZurueck die Ecken zaehlen wuerde (gleiche Punkte, gleiche Werte = eine Ecke)
[[nodiscard]] int eckenNachZurueck(const PolyNetz& n, int teil);

// --- LODs ---------------------------------------------------------------------------------------------------------
