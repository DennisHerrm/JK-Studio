// --- Aufbau -------------------------------------------------------------------------------------------------------
//
//   PolyNetz   das Arbeitsnetz: alle Flaechen (Teile, ohne Tags) EINER LOD-Stufe als Vielecke. Ein Punkt ist ein Ort
//              (Netz::punktVon), eine Ecke eines Vielecks traegt, was die Datei je Ecke hat (UV, Normale, Knochen,
//              Gewichte, Rohfelder: modell::Ecke). Zwei Teile teilen nie einen Punkt (die .glm fuehrt jede Flaeche fuer
//              sich). Die Vielecke kommen aus den Dreiecken und Netz::polyVon (Dreiecke eines Vielecks), sonst ist jedes
//              Dreieck ein Vieleck. Zurueck geschrieben werden nur die Teile, die ein Werkzeug beruehrt hat; die
//              anderen bleiben Byte fuer Byte (so bleibt ein Rundlauf ohne Aenderung dieselbe Datei).
//   Plan       wie WL ModelPlan (modelling.h, "The contract every tool keeps"): die Topologie des Werkzeugs liegt fest,
//              der Betrag bewegt nur Orte (base + amount * direction, VertexMotion) und die UV der bewegten Ecken in
//              ihrer Quellflaeche (Resample); Ablehnung mit Grund (ModelRefusal) laesst das Netz unberuehrt.
//   Auswahl    Punkte, Kanten (als Punktpaar) und Vielecke - je Ebene eine Liste wie 3ds Max (jede Unterebene behaelt
//              ihre Auswahl).
