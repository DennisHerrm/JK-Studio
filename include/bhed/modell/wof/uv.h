// --- Aufbau -------------------------------------------------------------------------------------------------------
//
//   UvNetz     das Arbeitsnetz: alle Flaechen einer Gruppe (die Teile, die eine Textur zeichnen) EINER LOD-Stufe in einem
//              Halbkanten-Netz. Eine Halbkante ist eine Ecke eines Dreiecks (WL: corner = halfedge) und traegt die UV;
//              die Punkte sind die Orte (Netz::punktVon, Ecken mit gleichem Ort). Zwei Teile beruehren sich nie - jede
//              Insel liegt in genau einem Teil. Naehte (Marken), Pins und "frei" stehen je Halbkante bzw. Dreieck im
//              Dokument (Netz::uvNaht ...), nicht in der Datei: JKA kennt je Ecke genau einen UV-Satz.
//   Inseln     UvInseln wie WL BuildUvIslands: aus den Schnitten (Marke oder verschiedene UV an einer Kante); ein Keil
//              (wedge) ist eine UV-Ecke - die Halbkanten um einen Punkt, die kein Schnitt trennt.
//   Zurueck    zurueckschreiben: je Ecke der Datei so viele Ecken, wie ihre Halbkanten verschiedene UV haben (Ort,
//              Normale, Knochen und Gewichte gleich - die geteilten Ecken behalten die Gewichtsfelder der Datei);
//              ueber der Eckengrenze des Zielspiels (SHADER_MAX_VERTEXES) wird nichts geschrieben.
