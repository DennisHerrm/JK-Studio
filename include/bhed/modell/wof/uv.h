using u8 = std::uint8_t;

struct V2 {
    float x = 0.0F;
    float y = 0.0F;
};
struct V3 {
    float x = 0.0F;
    float y = 0.0F;
    float z = 0.0F;
};
inline V2 operator+(V2 a, V2 b) { return {a.x + b.x, a.y + b.y}; }
inline V2 operator-(V2 a, V2 b) { return {a.x - b.x, a.y - b.y}; }
inline V2 operator*(V2 a, float s) { return {a.x * s, a.y * s}; }
inline V3 operator+(V3 a, V3 b) { return {a.x + b.x, a.y + b.y, a.z + b.z}; }
inline V3 operator-(V3 a, V3 b) { return {a.x - b.x, a.y - b.y, a.z - b.z}; }
inline V3 operator*(V3 a, float s) { return {a.x * s, a.y * s, a.z * s}; }
inline float punkt(V3 a, V3 b) { return a.x * b.x + a.y * b.y + a.z * b.z; }
inline V3 kreuz(V3 a, V3 b) { return {a.y * b.z - a.z * b.y, a.z * b.x - a.x * b.z, a.x * b.y - a.y * b.x}; }
inline float laenge(V3 a) { return std::sqrt(punkt(a, a)); }

// --- Das Arbeitsnetz -------------------------------------------------------------------------------------------------
struct UvNetz {
    std::vector<V3> ort;          // je Punkt
    std::vector<int> von;         // je Halbkante: der Punkt, an dem sie beginnt
    std::vector<int> gegen;       // je Halbkante: die Gegenkante, -1 = Rand (auch nicht mannigfaltig)
    std::vector<V2> uv;           // je Halbkante
    std::vector<V3> normale;      // je Halbkante (die Normale der Ecke)
    std::vector<u8> naht;         // je Halbkante: Marke (beide Seiten gleich) - WL uvSeamN
    std::vector<u8> dateiNaht;    // je Halbkante: eine Marke, die aus der Datei kam - WL uvFileSeamN
    std::vector<u8> pin;          // je Halbkante - WL uvPinN
    std::vector<u8> frei;         // je Dreieck: seit dem Laden bearbeitet - WL uvFreeN
    std::vector<int> teil;        // je Halbkante: Index in teile
    std::vector<int> ecke;        // je Halbkante: die Ecke im Netz ihres Teils
    std::vector<std::array<std::uint8_t, 4>> knochen;   // je Halbkante (Haut der Ecke)
    std::vector<std::array<float, 4>> gewicht;
    std::vector<int> teile;       // die Teile des Inhalts (Index), in der Reihenfolge der Dreiecke
    std::vector<int> ersteDreieck;   // je Teil das erste Dreieck, dazu am Ende die Gesamtzahl
    int stufe = 0;

    [[nodiscard]] int dreiecke() const noexcept { return static_cast<int>(von.size() / 3U); }
    [[nodiscard]] int kanten() const noexcept { return static_cast<int>(von.size()); }
    [[nodiscard]] static int naechste(int h) noexcept { return h - h % 3 + (h % 3 + 1) % 3; }
    [[nodiscard]] int nach(int h) const { return von[static_cast<std::size_t>(naechste(h))]; }
    [[nodiscard]] bool rand(int h) const { return gegen[static_cast<std::size_t>(h)] < 0; }
    [[nodiscard]] V2 uvVon(int h) const { return uv[static_cast<std::size_t>(h)]; }
    [[nodiscard]] V3 ortVon(int h) const { return ort[static_cast<std::size_t>(von[static_cast<std::size_t>(h)])]; }
};

