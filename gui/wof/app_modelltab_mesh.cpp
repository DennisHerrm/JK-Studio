void ringLoop(bool ring) {
    ModellMesh& z = mz();
    modellMeshNetzAktualisieren();
    w::PAuswahl a = z.auswahl;
    for (const auto& k : z.auswahl.kanten) {
        const int ki = z.netz.kanteVon(k.first, k.second);
        for (const int r : ring ? w::kantenRing(z.netz, ki) : w::kantenSchleife(z.netz, ki)) {
            a.kanten.emplace_back(z.netz.kanten[uz(r)].a, z.netz.kanten[uz(r)].b);
        }
    }
    auswahlSetzen(a);
}
// MRESTE: Blender Strg+L (mesh.select_linked): die Auswahl waechst auf alles, was ueber Kanten an ihr haengt (die
// Elemente der gewaehlten Punkte, Kanten und Vielecke), in der Ebene der Auswahl
void verbundeneWaehlen() {
    ModellMesh& z = mz();
    modellMeshNetzAktualisieren();
    const w::PolyNetz& n = z.netz;
    std::set<int> flaechen;
    const auto vonPunkt = [&](int p) {
        if (p < 0 || uz(p) >= n.punktFlaechen.size()) { return; }
        for (const int f : n.punktFlaechen[uz(p)]) {
            if (flaechen.count(f) != 0U) { continue; }
            for (const int g : w::element(n, f)) { flaechen.insert(g); }
        }
    };
    for (const int p : w::auswahlPunkte(n, z.auswahl)) { vonPunkt(p); }
    if (flaechen.empty()) {
        melden(tr(Str::MrNichtsGewaehlt));
        return;
    }
    std::set<int> punkte;
    std::set<std::pair<int, int>> kanten;
    for (const int f : flaechen) {
        const auto& e = n.flaechen[uz(f)].ecken;
        for (std::size_t i = 0; i < e.size(); ++i) {
            punkte.insert(e[i].punkt);
            kanten.insert(w::kantenPaar(e[i].punkt, e[(i + 1) % e.size()].punkt));
        }
    }
    w::PAuswahl a;
    if (ebene() == w::PEbene::Punkt) {
        a.punkte.assign(punkte.begin(), punkte.end());
    } else if (kantenEbene()) {
        a.kanten.assign(kanten.begin(), kanten.end());
    } else {
        a.flaechen.assign(flaechen.begin(), flaechen.end());
    }
    z.punktFolge = a.punkte;
    auswahlSetzen(a);
}
void allesWaehlen(bool alles) {
    ModellMesh& z = mz();
    modellMeshNetzAktualisieren();
    w::PAuswahl a;
    if (alles) {
        if (ebene() == w::PEbene::Punkt) {
            for (std::size_t i = 0; i < z.netz.punkte.size(); ++i) { a.punkte.push_back(zi(i)); }
        } else if (kantenEbene()) {
            for (const w::PKante& k : z.netz.kanten) { a.kanten.emplace_back(k.a, k.b); }
        } else {
            for (std::size_t i = 0; i < z.netz.flaechen.size(); ++i) { a.flaechen.push_back(zi(i)); }
        }
    }
    z.punktFolge = a.punkte;
    auswahlSetzen(a);
}
void lodsAngleichen() {
    ModellTab& t = mt();
    if (t.dok.inhalt().stufenZahl <= 1) {
        melden(tr(Str::MdLodEins));
        return;
    }
    const int von = t.lodJetzt;
    t.dok.aendern(tr(Str::MdLods), [von](modell::Inhalt& x) { w::stufenAngleichen(x, von); });
    melden(format(Str::MdLodsFertig, von + 1, t.dok.inhalt().stufenZahl));
}

