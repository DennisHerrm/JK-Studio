// Slice: die Ebene durch die Mitte des Kastens der Auswahl (nichts gewaehlt: des ganzen Netzes) - wie Max die Slice Plane
// in die Mitte des Objekts legt
float schnittVorgabe(const w::PolyNetz& n, const w::PAuswahl& a, int achse) {
    std::vector<int> p = w::auswahlPunkte(n, a);
    if (p.empty()) {
        for (std::size_t i = 0; i < n.punkte.size(); ++i) {
            if (!n.punkte[i].weg) { p.push_back(zi(i)); }
        }
    }
    if (p.empty()) { return 0.0F; }
    const int ax = std::clamp(achse, 0, 2);
    float lo = n.punkte[uz(p[0])].ort[ax], hi = lo;
    for (const int x : p) {
        lo = std::min(lo, n.punkte[uz(x)].ort[ax]);
        hi = std::max(hi, n.punkte[uz(x)].ort[ax]);
    }
    return 0.5F * (lo + hi);
}

// Eine sinnvolle Vorgabe fuer den Betrag: ein Zehntel der Kantenlaenge der Auswahl (sofort sichtbar)
float betragVorgabe(const w::PolyNetz& n, const w::PAuswahl& a) {
    const std::vector<int> p = w::auswahlPunkte(n, a);
    double l = 0.0;
    int z = 0;
    for (const w::PKante& k : n.kanten) {
        if (!std::binary_search(p.begin(), p.end(), k.a) || !std::binary_search(p.begin(), p.end(), k.b)) { continue; }
        const float* x = n.punkte[uz(k.a)].ort;
        const float* y = n.punkte[uz(k.b)].ort;
        l += std::sqrt(static_cast<double>((x[0] - y[0]) * (x[0] - y[0]) + (x[1] - y[1]) * (x[1] - y[1]) + (x[2] - y[2]) * (x[2] - y[2])));
        ++z;
    }
    return z > 0 ? static_cast<float>(l / z * 0.2) : 4.0F;
}

// Der Teil, in den ein Grundkoerper kommt: der des ersten gewaehlten Vielecks, sonst der letzte, der kein Tag ist
int grundTeil(const modell::Inhalt& in) {
    const ModellMesh& z = mz();
    if (!z.auswahl.flaechen.empty() && uz(z.auswahl.flaechen[0]) < z.netz.flaechen.size()) { return z.netz.flaechen[uz(z.auswahl.flaechen[0])].teil; }
    for (std::size_t i = in.teile.size(); i-- > 0;) {
        if (!in.teile[i].istTag()) { return zi(i); }
    }
    return -1;
}

// Ein neuer Teil im Inhalt (Kopie von Name, Shader und Platz in der Hierarchie der Vorlage, leere Netze in jeder Stufe)
int neuerTeil(modell::Inhalt& x, int vorlage, const std::string& zusatz) {
    modell::Teil t;
    if (vorlage >= 0 && uz(vorlage) < x.teile.size()) {
        const modell::Teil& v = x.teile[uz(vorlage)];
        t.name = v.name;
        t.shader = v.shader;
        t.flaggen = v.flaggen;
        t.eltern = v.eltern;
    } else {
        t.name = "prop";
        t.shader = x.teile.empty() ? std::string("textures/common/white") : x.teile[0].shader;
    }
    t.name = (t.name + zusatz).substr(0, 63);   // MAX_QPATH
    t.stufen.resize(uz(std::max(1, x.stufenZahl)));
    const int neu = zi(x.teile.size());
    if (t.eltern >= 0 && uz(t.eltern) < x.teile.size()) { x.teile[uz(t.eltern)].kinder.push_back(neu); }
    x.teile.push_back(std::move(t));
    return neu;
}

w::Plan planen(w::PolyNetz& n, const w::PAuswahl& a, modell::Inhalt& x) {
    ModellMesh& z = mz();
    const w::PEbene e = ebene();
    switch (z.werkzeug) {
        case MeshWerkzeug::Extrude:
            if (kantenEbene()) { return w::extrudeRand(n, a.kanten); }
            return w::extrudeFlaechen(n, a.flaechen, static_cast<w::ExtrudeArt>(std::clamp(z.art, 0, 2)));
        case MeshWerkzeug::Inset: return w::inset(n, a.flaechen, z.art == 1 ? w::InsetArt::JeVieleck : w::InsetArt::Gruppe);
        case MeshWerkzeug::Bevel: return w::bevel(n, a.flaechen, static_cast<w::ExtrudeArt>(std::clamp(z.art, 0, 2)), z.hoehe);
        case MeshWerkzeug::Chamfer: return e == w::PEbene::Punkt ? w::chamferPunkte(n, a.punkte) : w::chamferKanten(n, a.kanten, z.segmente, z.profil);
        case MeshWerkzeug::Connect: return w::connectKanten(n, a.kanten, z.segmente);
        case MeshWerkzeug::LoopCut: {
            if (a.kanten.empty()) {
                w::Plan p;
                p.grund = w::Ablehnung::LeereAuswahl;
                return p;
            }
            return w::loopCut(n, a.kanten[0], z.segmente);
        }
        case MeshWerkzeug::Weld: return w::weld(n, w::auswahlPunkte(n, a), z.schwelle > 0.0F ? z.schwelle : w::weldSchwelleVorgabe(n));
        case MeshWerkzeug::Bridge: {
            if (flaechenEbene()) {
                if (a.flaechen.size() < 2U) {
                    w::Plan p;
                    p.grund = w::Ablehnung::LeereAuswahl;
                    return p;
                }
                return w::bridgeFlaechen(n, a.flaechen[0], a.flaechen[1], z.segmente, z.verdrehen);
            }
            // zwei Randschleifen: die erste Kante und die erste, die nicht auf ihrer Schleife liegt
            if (a.kanten.empty()) {
                w::Plan p;
                p.grund = w::Ablehnung::LeereAuswahl;
                return p;
            }
            const auto erste = w::randSchleife(n, n.kanteVon(a.kanten[0].first, a.kanten[0].second));
            std::pair<int, int> zweite{-1, -1};
            for (const auto& k : a.kanten) {
                if (std::find(erste.begin(), erste.end(), k) == erste.end()) {
                    zweite = k;
                    break;
                }
            }
            if (zweite.first < 0) {
                w::Plan p;
                p.grund = w::Ablehnung::GleicheSchleife;
                return p;
            }
            return w::bridgeRaender(n, a.kanten[0], zweite, z.segmente, z.verdrehen);
        }
        case MeshWerkzeug::Detach: {
            int ziel = -1;
            if (z.art == 1 && !a.flaechen.empty() && uz(a.flaechen[0]) < n.flaechen.size()) { ziel = neuerTeil(x, n.flaechen[uz(a.flaechen[0])].teil, "_detach"); }
            return w::detach(n, a.flaechen, ziel);
        }
        case MeshWerkzeug::Symmetrize: {
            w::SymmetrieParam sp;
            sp.achse = z.achse;
            sp.vonPlus = z.vonPlus;
            sp.knochenSpiegel = knochenSpiegel();
            std::vector<int> teile;
            for (const int f : a.flaechen) {
                if (uz(f) < n.flaechen.size()) { teile.push_back(n.flaechen[uz(f)].teil); }
            }
            return w::symmetrisieren(n, sp, teile);
        }
        case MeshWerkzeug::ToQuads: return w::zuVierecken(n, a.flaechen, z.quad);
        case MeshWerkzeug::Merge: return w::mergen(n, z.art == 0 ? w::auswahlPunkte(n, a) : z.punktFolge, static_cast<w::MergeArt>(std::clamp(z.art, 0, 2)));
        case MeshWerkzeug::Create: {
            int teil = grundTeil(x);
            if (teil < 0 || z.grundNeuerTeil) { teil = neuerTeil(x, teil, z.grundNeuerTeil ? "_" + std::to_string(x.teile.size()) : std::string()); }
            return w::grundkoerper(n, z.grund, teil);
        }
        case MeshWerkzeug::Slice: return w::schneiden(n, flaechenEbene() ? a.flaechen : std::vector<int>{}, z.achse, z.schnittOrt);
        case MeshWerkzeug::Hinge: {
            // die Scharnierkante: eine Randkante der Auswahl (Max "Pick Hinge"); im Kaestchen durchzuschalten
            const auto kanten = w::hingeKanten(n, a.flaechen);
            z.hingeZahl = zi(kanten.size());
            if (kanten.empty()) {
                w::Plan p;
                p.grund = w::Ablehnung::LeereAuswahl;
                return p;
            }
            z.hingeNr = std::clamp(z.hingeNr, 0, z.hingeZahl - 1);
            return w::hinge(n, a.flaechen, kanten[uz(z.hingeNr)], z.hingeWinkel);
        }
        case MeshWerkzeug::Keins: break;
    }
    return {};
}

// Die Pruefung der Grenzen gleich mit der Vorschau (eine Zeile im Kaestchen)
std::string grenzZeile(const modell::Inhalt& in) {
    const modell::Grenzen& g = modell::grenzen(static_cast<modell::Zielspiel>(mt().zielspiel));
    for (const w::TeilGrenze& x : w::grenzenPruefen(in, mt().lodJetzt)) {
        const std::string& n = in.teile[uz(x.teil)].name;
        if (x.mass.ecken >= g.eckenJeFlaeche) { return format(Str::MdGrenzeEcken, n.c_str(), x.mass.ecken, g.eckenJeFlaeche); }
        if (x.mass.knochen > g.knochenJeFlaeche) { return format(Str::MdGrenzeKnochen, n.c_str(), x.mass.knochen, g.knochenJeFlaeche); }
        if (x.mass.gewichteMax > g.gewichteJeEcke) { return format(Str::MdGrenzeGewichte, n.c_str(), x.mass.gewichteMax, g.gewichteJeEcke); }
        if (x.nameZuLang || x.shaderZuLang) { return format(Str::MdGrenzeName, n.c_str()); }
        if (x.tagKeinDreieck) { return format(Str::MdGrenzeTag, n.c_str()); }
    }
    return {};
}

