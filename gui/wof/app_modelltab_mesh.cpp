// Die Ebene des Arbeitsnetzes aus der Unterobjekt-Art des Model-Tabs (Max 1-5: Scheitelpunkt, Kante, Rand, Polygon,
// Element; Blender 1-3)
w::PEbene ebene() {
    switch (mt().auswahlArt) {
        case AuswahlArt::Ecke: return w::PEbene::Punkt;
        case AuswahlArt::Kante: return w::PEbene::Kante;
        case AuswahlArt::Rand: return w::PEbene::Rand;
        case AuswahlArt::Dreieck: return w::PEbene::Vieleck;
        case AuswahlArt::Element: return w::PEbene::Element;
        case AuswahlArt::Objekt: break;
    }
    return w::PEbene::Vieleck;
}
bool kantenEbene() { return ebene() == w::PEbene::Kante || ebene() == w::PEbene::Rand; }
bool flaechenEbene() { return ebene() == w::PEbene::Vieleck || ebene() == w::PEbene::Element; }
void ebeneSetzen(AuswahlArt a) {
    if (mt().bereich != ModellBereich::Modellieren) { mt().bereich = ModellBereich::Modellieren; }
    modellAuswahlArtSetzen(a);
}

