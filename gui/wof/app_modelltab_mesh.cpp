bool modellMeshQuickSlice(const ModellAnsicht& a, ImVec2 von, ImVec2 nach) {
    // WL SliceParams: "The plane is the gizmo's widget, or QuickSlice's two clicks" - die Ebene enthaelt die Linie zwischen
    // den Klicks und die Blickrichtung (beide Sichtstrahlen)
    double a0[3], a1[3], b0[3], b1[3];
    if (!schirmStrahl(a, von, a0, a1) || !schirmStrahl(a, nach, b0, b1)) { return false; }
    const double u[3] = {a1[0] - a0[0], a1[1] - a0[1], a1[2] - a0[2]};
    const double v[3] = {b0[0] - a0[0], b0[1] - a0[1], b0[2] - a0[2]};
    const float nn[3] = {static_cast<float>(u[1] * v[2] - u[2] * v[1]), static_cast<float>(u[2] * v[0] - u[0] * v[2]), static_cast<float>(u[0] * v[1] - u[1] * v[0])};
    const float o[3] = {static_cast<float>(a0[0]), static_cast<float>(a0[1]), static_cast<float>(a0[2])};
    const std::vector<int> f = flaechenEbene() ? mz().auswahl.flaechen : std::vector<int>{};
    return befehl(Str::MdQuickSlice, [&](w::PolyNetz& n) { return w::schneidenEbene(n, f, o, nn); });
}

bool modellMeshKlick(const ModellAnsicht& a, bool klick, ImVec2 start, ImVec2 ende) {
    ModellTab& t = mt();
    ModellMesh& z = mz();
    if (g_app->model.empty() || t.auswahlArt == AuswahlArt::Objekt) { return false; }
    modellMeshNetzAktualisieren();
    if (z.kaestchenOffen) { return true; }   // waehrend der Vorschau aendert ein Klick die Auswahl nicht
    if (z.quickAn) {   // Max QuickSlice: erster Klick setzt den Anfang, der zweite schneidet
        if (!klick) { return true; }
        if (!z.quickHatVon) {
            z.quickVon = ende;
            z.quickHatVon = true;
            melden(tr(Str::MdQuickWeiter));
            return true;
        }
        z.quickAn = z.quickHatVon = false;
        (void)modellMeshQuickSlice(a, z.quickVon, ende);
        return true;
    }
    if (z.cutAn || z.zielWeldAn) {
        if (!klick) { return true; }
        std::pair<int, int> k{-1, -1};
        float u = 0.5F, pd = 1e30F;
        int p = -1;
        if (!kanteUnter(a, ende, k, u, p, pd)) { return true; }
        if (z.zielWeldAn) {
            const int q = z.zielQuelle;
            z.zielWeldAn = false;
            (void)befehl(Str::MdTargetWeld, [&](w::PolyNetz& n) { return w::targetWeld(n, q, p); });
            return true;
        }
        w::SchnittPunkt sp;
        if (pd <= 8.0F * std::max(1.0F, ImGui::GetFontSize() / 13.0F)) {   // nah an einem Punkt: der Punkt (Max fangt die Ecke)
            sp.punkt = p;
        } else {
            sp.kante = k;
            sp.t = u;
        }
        if (!z.cutHatVon) {
            z.cutVon = sp;
            z.cutHatVon = true;
            melden(tr(Str::MdCutWeiter));
            return true;
        }
        const w::SchnittPunkt von = z.cutVon;
        (void)befehl(Str::MdCut, [&](w::PolyNetz& n) { return w::schnitt(n, von, sp); });
        modellMeshNetzAktualisieren();
        // weiter vom Endpunkt (Max Cut laeuft weiter, bis Esc oder Rechtsklick)
        if (!z.auswahl.punkte.empty()) {
            z.cutVon = w::SchnittPunkt{};
            z.cutVon.punkt = z.auswahl.punkte.back();
        } else {
            z.cutHatVon = false;
        }
        return true;
    }
    // Auswahl: Max Strg dazu, Alt weg; Blender Umschalt dazu (auf schon Gewaehltes: heraus)
    const ImGuiIO& io = ImGui::GetIO();
    const bool blender = blenderModus();
    const bool dazu = blender ? io.KeyShift : io.KeyCtrl;
    const bool weg = !blender && io.KeyAlt;
    w::PAuswahl treffer;
    const w::PolyNetz& n = z.netz;
    const w::PEbene e = ebene();
    if (klick) {
        std::pair<int, int> k{-1, -1};
        float u = 0.0F, pd = 1e30F;
        int p = -1;
        const int f = vieleckUnter(a, ende);
        if (f >= 0 && kanteUnter(a, ende, k, u, p, pd)) {
            switch (e) {
                case w::PEbene::Punkt: treffer.punkte.push_back(p); break;
                case w::PEbene::Kante: treffer.kanten.push_back(w::kantenPaar(k.first, k.second)); break;
                case w::PEbene::Rand: {
                    const auto r = w::randSchleife(n, n.kanteVon(k.first, k.second));
                    treffer.kanten = r;
                    break;
                }
                case w::PEbene::Vieleck: treffer.flaechen.push_back(f); break;
                case w::PEbene::Element: treffer.flaechen = w::element(n, f); break;
            }
            // MRESTE: wie Blender Alt+Klick (mesh.loop_select) bzw. Strg+Alt+Klick (mesh.edgering_select) an der Kante unter
            // der Maus: die Kantenschleife bzw. der Kantenring; Punkte: deren Punkte; Vielecke: die Vielecke am Ring (die
            // Flaechenschleife quer zur Kante, wie Blender im Flaechenmodus)
            if (blender && io.KeyAlt) {
                const int ki = n.kanteVon(k.first, k.second);
                const bool ring = io.KeyCtrl;
                if (ki >= 0) {
                    treffer = w::PAuswahl{};
                    const std::vector<int> kk = (ring || e == w::PEbene::Vieleck || e == w::PEbene::Element) ? w::kantenRing(n, ki) : w::kantenSchleife(n, ki);
                    std::set<int> pp;
                    std::set<int> ff;
                    for (const int r : kk) {
                        const w::PKante& kr = n.kanten[uz(r)];
                        pp.insert(kr.a);
                        pp.insert(kr.b);
                        for (const auto& [fl, i] : kr.seiten) {
                            (void)i;
                            ff.insert(fl);
                        }
                        if (e == w::PEbene::Kante || e == w::PEbene::Rand) { treffer.kanten.emplace_back(kr.a, kr.b); }
                    }
                    if (e == w::PEbene::Punkt) { treffer.punkte.assign(pp.begin(), pp.end()); }
                    if (e == w::PEbene::Vieleck || e == w::PEbene::Element) { treffer.flaechen.assign(ff.begin(), ff.end()); }
                }
            }
        }
    } else {   // Rahmen: Kreuzen wie Max (ein Punkt im Rahmen genuegt)
        const ImVec2 lo{std::min(start.x, ende.x), std::min(start.y, ende.y)};
        const ImVec2 hi{std::max(start.x, ende.x), std::max(start.y, ende.y)};
        std::vector<char> drin(n.punkte.size(), 0);
        for (std::size_t p = 0; p < n.punkte.size(); ++p) {
            ImVec2 s;
            if (n.punkte[p].weg || uz(n.punkte[p].teil) >= t.gezeichnet.size() || !modellTeilGezeichnet(n.punkte[p].teil) || !punktSchirm(a, zi(p), s)) { continue; }
            drin[p] = s.x >= lo.x && s.x <= hi.x && s.y >= lo.y && s.y <= hi.y ? 1 : 0;
        }
        if (e == w::PEbene::Punkt) {
            for (std::size_t p = 0; p < drin.size(); ++p) {
                if (drin[p] != 0) { treffer.punkte.push_back(zi(p)); }
            }
        } else if (e == w::PEbene::Kante || e == w::PEbene::Rand) {
            for (const w::PKante& k : n.kanten) {
                if ((drin[uz(k.a)] != 0 || drin[uz(k.b)] != 0) && (e == w::PEbene::Kante || k.seiten.size() == 1U)) { treffer.kanten.emplace_back(k.a, k.b); }
            }
        } else {
            for (std::size_t f = 0; f < n.flaechen.size(); ++f) {
                bool any = false;
                for (const w::PEcke& c : n.flaechen[f].ecken) { any = any || drin[uz(c.punkt)] != 0; }
                if (any) { treffer.flaechen.push_back(zi(f)); }
            }
        }
    }
    w::PAuswahl neu = (dazu || weg) ? z.auswahl : w::PAuswahl{};
    if (!(dazu || weg)) { z.punktFolge.clear(); }
    const auto aendern = [&](auto& liste, const auto& dazuListe) {
        using T = typename std::decay_t<decltype(liste)>::value_type;
        const bool alleDrin = blender && dazu && !dazuListe.empty() &&
                              std::all_of(dazuListe.begin(), dazuListe.end(), [&](const T& x) { return std::find(liste.begin(), liste.end(), x) != liste.end(); });
        for (const T& x : dazuListe) {
            const auto it = std::find(liste.begin(), liste.end(), x);
            if (weg || alleDrin) {
                if (it != liste.end()) { liste.erase(it); }
            } else if (it == liste.end()) {
                liste.push_back(x);
            }
        }
    };
    aendern(neu.punkte, treffer.punkte);
    aendern(neu.kanten, treffer.kanten);
    aendern(neu.flaechen, treffer.flaechen);
    for (const int p : treffer.punkte) {
        if (!weg && std::find(z.punktFolge.begin(), z.punktFolge.end(), p) == z.punktFolge.end()) { z.punktFolge.push_back(p); }
    }
    z.punktFolge.erase(std::remove_if(z.punktFolge.begin(), z.punktFolge.end(), [&](int p) { return std::find(neu.punkte.begin(), neu.punkte.end(), p) == neu.punkte.end(); }),
                       z.punktFolge.end());
    auswahlSetzen(neu);
    return true;
}

void modellMeshUeberlagerung(const ModellAnsicht& a, ImDrawList* dl) {
    ModellMesh& z = mz();
    modellMeshNetzAktualisieren();
    const w::PolyNetz& n = z.netz;
    z.kantenGezeichnet = 0;
    // je Punkt einmal auf den Schirm (eine Kante fragte sonst zweimal, ein Punkt hat im Mittel vier Kanten): dasselbe Bild
    std::vector<ImVec2> schirm(n.punkte.size());
    std::vector<char> da(n.punkte.size(), 0);
    for (std::size_t p = 0; p < n.punkte.size(); ++p) {
        da[p] = !n.punkte[p].weg && modellTeilGezeichnet(n.punkte[p].teil) && punktSchirm(a, zi(p), schirm[p]) ? 1 : 0;
    }
    const std::set<std::pair<int, int>> kSel(z.auswahl.kanten.begin(), z.auswahl.kanten.end());
    std::vector<char> fSel(n.flaechen.size(), 0);
    for (const int f : z.auswahl.flaechen) {
        if (f >= 0 && uz(f) < fSel.size()) { fSel[uz(f)] = 1; }
    }
    const ImU32 kante = IM_COL32(220, 225, 235, 150);
    const ImU32 orange = IM_COL32(255, 160, 40, 255);
    // gewaehlte Vielecke halb durchsichtig (Max: rot getoent, hier in der Farbe der Auswahl)
    std::vector<ImVec2> p;
    for (const int f : z.auswahl.flaechen) {
        if (uz(f) >= n.flaechen.size()) { continue; }
        const w::PFlaeche& fl = n.flaechen[uz(f)];
        p.clear();
        bool ok = true;
        for (const w::PEcke& c : fl.ecken) {
            ok = ok && da[uz(c.punkt)] != 0;
            p.push_back(schirm[uz(c.punkt)]);
        }
        if (!ok) { continue; }
        for (std::size_t i = 1; i + 1 < p.size(); ++i) { dl->AddTriangleFilled(p[0], p[i], p[i + 1], IM_COL32(255, 140, 30, 70)); }
    }
    for (const w::PKante& k : n.kanten) {
        if (k.seiten.empty() || da[uz(k.a)] == 0 || da[uz(k.b)] == 0) { continue; }
        bool sel = !kSel.empty() && kSel.count({k.a, k.b}) != 0U;
        for (const auto& [f, i] : k.seiten) {
            (void)i;
            sel = sel || fSel[uz(f)] != 0;
        }
        dl->AddLine(schirm[uz(k.a)], schirm[uz(k.b)], sel ? orange : kante, sel ? 2.0F : 1.0F);
        ++z.kantenGezeichnet;
    }
    if (ebene() == w::PEbene::Punkt) {   // Punkte als kleine Kaestchen (Max: blau, gewaehlt rot; hier gewaehlt orange)
        for (std::size_t q = 0; q < n.punkte.size(); ++q) {
            if (da[q] == 0) { continue; }
            const ImVec2 s = schirm[q];
            dl->AddRectFilled(ImVec2{s.x - 1.5F, s.y - 1.5F}, ImVec2{s.x + 1.5F, s.y + 1.5F}, IM_COL32(90, 150, 255, 220));
        }
    }
    if (z.quickAn && z.quickHatVon) { dl->AddLine(z.quickVon, ImGui::GetIO().MousePos, orange, 1.5F); }   // QuickSlice: die Linie
    if (z.cutAn && z.cutHatVon && z.cutVon.punkt >= 0 && uz(z.cutVon.punkt) < da.size() && da[uz(z.cutVon.punkt)] != 0) {   // Cut: Linie vom letzten Punkt zur Maus
        dl->AddLine(schirm[uz(z.cutVon.punkt)], ImGui::GetIO().MousePos, orange, 1.5F);
    }
}

