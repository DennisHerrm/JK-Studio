// Die Auswahl als Ecken des Model-Tabs (Gizmo, G/R/S und die orangen Ecken der Ansicht nehmen sie): jede Ecke jedes
// gewaehlten Punkts, damit ein Punkt nie auseinandergezogen wird
void eckenAbgleichen() {
    ModellTab& t = mt();
    const w::PolyNetz& n = mz().netz;
    const std::vector<int> pt = w::auswahlPunkte(n, mz().auswahl);
    std::set<int> s(pt.begin(), pt.end());
    t.eckenWahl.clear();
    const modell::Inhalt& in = t.dok.inhalt();
    for (std::size_t ti = 0; ti < in.teile.size() && ti < n.teilPunkte.size(); ++ti) {
        if (uz(t.lodJetzt) >= in.teile[ti].stufen.size() || in.teile[ti].istTag()) { continue; }
        const modell::Netz& nz = in.teile[ti].stufen[uz(t.lodJetzt)];
        for (std::size_t e = 0; e < nz.ecken.size(); ++e) {
            if (s.count(n.teilPunkte[ti] + nz.punktVon[e]) != 0U) { t.eckenWahl.push_back(modell::EckOrt{zi(ti), zi(e)}); }
        }
    }
}

void auswahlSetzen(const w::PAuswahl& a) {
    mz().auswahl = a;
    mz().auswahl.sortieren();
    eckenAbgleichen();
}

// Die Auswahl eines Plans auf die Nummern nach dem Verdichten
w::PAuswahl umnummern(const w::PAuswahl& a, const std::vector<int>& pn, const std::vector<int>& fn) {
    w::PAuswahl o;
    const auto p = [&](int i) { return i >= 0 && uz(i) < pn.size() ? pn[uz(i)] : -1; };
    for (const int i : a.punkte) {
        if (p(i) >= 0) { o.punkte.push_back(p(i)); }
    }
    for (const auto& [x, y] : a.kanten) {
        if (p(x) >= 0 && p(y) >= 0) { o.kanten.push_back(w::kantenPaar(p(x), p(y))); }
    }
    for (const int f : a.flaechen) {
        if (f >= 0 && uz(f) < fn.size() && fn[uz(f)] >= 0) { o.flaechen.push_back(fn[uz(f)]); }
    }
    o.sortieren();
    return o;
}

// mbvers: die Pose, in der ein Werkzeug arbeitet - die gezeigte (wie der Gizmo: was man sieht, aendert sich so, wie man es
// angibt; Richtungen, Ebenen, Abstaende und Schwellen gelten im Gezeigten). Leer ohne Skelett und in der exakten Bindepose
// (dann rechnet alles wie bisher) - und fuer Symmetrize: es spiegelt die Daten an der Symmetrieebene des Modells, die es
// nur in der Bindepose gibt (eine Pose ist nicht symmetrisch; auch Blender > Mesh > Symmetrize arbeitet auf den Orten des
// Netzes, nicht auf dem verformten Kaefig).
const std::vector<BoneMatrix>& werkzeugPose(MeshWerkzeug wz) {
    static const std::vector<BoneMatrix> keine;
    return wz == MeshWerkzeug::Symmetrize ? keine : modellBearbeitungsPose();
}

// Abschluss jedes Werkzeugs: Normalen der beruehrten Vielecke (WL FinishTool), verdichten, ins Dokument. mbvers: ein Netz in
// der Pose (`pose` aktiv, mit den Knochen `knochen`) geht vor dem Verdichten in die Bindepose zurueck (posiert.h).
w::PAuswahl abschliessen(w::PolyNetz& n, const w::Plan& p, modell::Inhalt& x, const w::NetzPose& pose, const std::vector<BoneMatrix>& knochen) {
    const std::vector<char> neueNormalen = pose.aktiv ? w::normalenPunkte(n) : std::vector<char>{};
    w::normalenNeu(n, 60.0F);
    if (pose.aktiv) {
        const int nichtUmkehrbar = w::ausPose(n, pose, knochen, neueNormalen);
        if (nichtUmkehrbar > 0) { melden(format(Str::MbvEntartet, nichtUmkehrbar)); }
    }
    std::vector<int> pn, fn;
    n.verdichten(&pn, &fn);
    w::polyZurueck(n, x);
    return umnummern(p.auswahl, pn, fn);
}

std::string ablehnung(w::Ablehnung a) {
    static const std::map<w::Ablehnung, Str> k = {
        {w::Ablehnung::LeereAuswahl, Str::MdAblLeer},       {w::Ablehnung::Rand, Str::MdAblRand},
        {w::Ablehnung::WuerdeKneifen, Str::MdAblKneifen},   {w::Ablehnung::WuerdeDoppeln, Str::MdAblDoppeln},
        {w::Ablehnung::NichtBenachbart, Str::MdAblNachbar}, {w::Ablehnung::NichtEinVieleck, Str::MdAblEinVieleck},
        {w::Ablehnung::SchonVerbunden, Str::MdAblVerbunden}, {w::Ablehnung::AlleFlaechen, Str::MdAblAlle},
        {w::Ablehnung::Ungleich, Str::MdAblUngleich},       {w::Ablehnung::GleicheSchleife, Str::MdAblGleich},
        {w::Ablehnung::KeineQuelle, Str::MdAblQuelle},      {w::Ablehnung::KeinViereck, Str::MdAblViereck},
        {w::Ablehnung::Tag, Str::MdAblTag},                 {w::Ablehnung::VerschiedeneTeile, Str::MdAblTeile},
        {w::Ablehnung::NichtsGeschnitten, Str::MdAblSchnitt}, {w::Ablehnung::HingeNichtAmRand, Str::MdAblHinge},
    };
    const auto it = k.find(a);
    return it == k.end() ? std::string() : std::string(tr(it->second));
}

// Ein Befehl ohne Kaestchen: ein Rueckgaengig-Schritt, abgelehnt -> kein Schritt und eine Meldung
bool befehl(Str name, const std::function<w::Plan(w::PolyNetz&)>& f) {
    ModellTab& t = mt();
    // pfix H1: ein offenes Kaestchen zuerst uebernehmen (wie 3ds Max: ein anderer Befehl schliesst den Caddy) - sonst laege
    // sein Schritt unter dem Befehl, der naechste Regelwert ueberschriebe den Befehl und Esc naehme ihn zurueck
    if (mz().kaestchenOffen) { modellMeshUebernehmen(false); }
    modellMeshNetzAktualisieren();
    w::Plan p;
    w::PAuswahl neu;
    const std::uint64_t schritt = t.dok.aendern(tr(name), [&](modell::Inhalt& x) {
        w::PolyNetz n = w::polyAus(x, t.lodJetzt);
        const std::vector<BoneMatrix>& knochen = werkzeugPose(MeshWerkzeug::Keins);
        const w::NetzPose pose = w::inPose(n, knochen);   // mbvers: in der gezeigten Pose (ohne: nichts)
        p = f(n);
        if (!p.abgelehnt()) { neu = abschliessen(n, p, x, pose, knochen); }
    });
    if (p.abgelehnt()) {
        (void)t.dok.abbrechen(schritt);
        melden(format(Str::MdAbgelehnt, tr(name), ablehnung(p.grund).c_str()));
        return false;
    }
    modellMeshNetzAktualisieren();
    auswahlSetzen(neu);
    ++mz().befehle;
    mz().letzterBefehl = tr(name);
    melden(format(Str::MdFertig, tr(name), p.geaendert));
    g_app->modelDirty = true;
    return true;
}

// Der Spiegel jedes Knochens nach dem Namen (l_ <-> r_, wie die Spiegelpartner der Weights), -1 keiner
std::vector<int> knochenSpiegel() {
    std::vector<int> out;
    const auto& b = g_app->anim.bones;
    for (std::size_t i = 0; i < b.size(); ++i) {
        std::string n = b[i].name;
        int sp = -1;
        if (n.rfind("l_", 0) == 0 || n.rfind("r_", 0) == 0) {
            n[0] = n[0] == 'l' ? 'r' : 'l';
            for (std::size_t j = 0; j < b.size(); ++j) {
                if (b[j].name == n) { sp = zi(j); }
            }
        }
        out.push_back(sp);
    }
    return out;
}

