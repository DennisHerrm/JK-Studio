bool punktSchirm(const ModellAnsicht& a, int p, ImVec2& out) {
    const w::PolyNetz& n = mz().netz;
    if (p < 0 || uz(p) >= n.punktEcke.size()) { return false; }
    const auto [teil, ecke] = n.punktEcke[uz(p)];
    const auto& h = modellHaut();
    if (teil < 0 || uz(teil) >= h.size() || ecke < 0 || uz(ecke) >= h[uz(teil)].size()) { return false; }
    return modellAufSchirm(a, h[uz(teil)][uz(ecke)].data(), out);
}

float abstandStrecke(ImVec2 p, ImVec2 a, ImVec2 b, float* t) {
    const float dx = b.x - a.x, dy = b.y - a.y;
    const float l2 = dx * dx + dy * dy;
    float u = l2 > 0.0F ? ((p.x - a.x) * dx + (p.y - a.y) * dy) / l2 : 0.0F;
    u = std::clamp(u, 0.0F, 1.0F);
    if (t != nullptr) { *t = u; }
    return std::hypot(p.x - (a.x + u * dx), p.y - (a.y + u * dy));
}

// Das Vieleck unter der Maus (ueber das vorderste Dreieck der Ansicht)
int vieleckUnter(const ModellAnsicht& a, ImVec2 m) {
    int teil = -1, dr = -1;
    if (!modellDreieckUnter(a, m, teil, dr)) { return -1; }
    const w::PolyNetz& n = mz().netz;
    if (uz(teil) >= n.flaecheVonDreieck.size() || dr < 0 || uz(dr) >= n.flaecheVonDreieck[uz(teil)].size()) { return -1; }
    return n.flaecheVonDreieck[uz(teil)][uz(dr)];
}

// Die naechste Kante des Vielecks unter der Maus (mit dem Ort darauf) und der naechste Punkt
bool kanteUnter(const ModellAnsicht& a, ImVec2 m, std::pair<int, int>& kante, float& t, int& punkt, float& punktAbstand) {
    const int f = vieleckUnter(a, m);
    if (f < 0) { return false; }
    const w::PFlaeche& fl = mz().netz.flaechen[uz(f)];
    float best = 1e30F;
    punktAbstand = 1e30F;
    const std::size_t k = fl.ecken.size();
    for (std::size_t i = 0; i < k; ++i) {
        ImVec2 p, q;
        if (!punktSchirm(a, fl.ecken[i].punkt, p) || !punktSchirm(a, fl.ecken[(i + 1) % k].punkt, q)) { continue; }
        float u = 0.0F;
        const float d = abstandStrecke(m, p, q, &u);
        if (d < best) {
            best = d;
            kante = {fl.ecken[i].punkt, fl.ecken[(i + 1) % k].punkt};
            t = u;
        }
        const float dp = std::hypot(m.x - p.x, m.y - p.y);
        if (dp < punktAbstand) {
            punktAbstand = dp;
            punkt = fl.ecken[i].punkt;
        }
    }
    return best < 1e29F;
}

