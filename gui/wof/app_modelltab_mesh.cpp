// Eine .md3 im Model-Tab: das gezeichnete Modell bekommt neue Teile (Grundkoerper, Detach) und geaenderte Shader mit ihren
// Bildern (texturesFor nach den Flaechen von App::model) - eine .glm behaelt ihre Haut und Flaechen aus der Datei
void md3TexturenAbgleichen() {
    const modell::Inhalt& in = mt().dok.inhalt();
    if (in.herkunft != modell::Herkunft::Md3) { return; }
    bool gleich = g_app->model.surfaces.size() == in.teile.size();
    for (std::size_t i = 0; gleich && i < in.teile.size(); ++i) { gleich = g_app->model.surfaces[i].shader == in.teile[i].shader; }
    if (gleich) { return; }
    GlmModel gm = modell::zuGlm(in, 0);
    for (std::size_t i = 0; i < gm.surfaces.size() && i < in.teile.size(); ++i) { gm.surfaces[i].shader = in.teile[i].shader; }
    g_app->model = std::move(gm);
    mt().anzeigeSchluessel.clear();
    loadModelTextures();
}

// pfix H2: eine .glm behaelt Haut und Flaechen der Datei; neue Teile des Dokuments kommen hinten dazu (mit dem Bild der
// Flaeche, von der sie stammen: neuerTeil nennt sie nach ihr), zurueckgenommene fallen hinten weg
void modellFlaechenAbgleichen() {
    const modell::Inhalt& in = mt().dok.inhalt();
    if (in.herkunft != modell::Herkunft::Glm) {
        md3TexturenAbgleichen();
        return;
    }
    std::vector<GlmSurface>& f = g_app->model.surfaces;
    if (f.size() == in.teile.size()) { return; }
    if (f.size() > in.teile.size()) {
        f.resize(in.teile.size());
    } else {
        const GlmModel gm = modell::zuGlm(in, 0);
        for (std::size_t i = f.size(); i < in.teile.size() && i < gm.surfaces.size(); ++i) {
            GlmSurface s = gm.surfaces[i];
            std::size_t laenge = 0;
            for (const GlmSurface& v : f) {
                if (!v.name.empty() && v.name.size() > laenge && s.name.rfind(v.name, 0) == 0) {
                    s.texture = v.texture;
                    laenge = v.name.size();
                }
            }
            f.push_back(std::move(s));
        }
    }
    mt().anzeigeSchluessel.clear();
    loadModelTextures();
}

void modellMeshNetzAktualisieren() {
    ModellMesh& z = mz();
    const std::string k = netzSchluessel();
    if (k == z.fuer) { return; }
    z.fuer = k;
    md3TexturenAbgleichen();
    z.netz = w::polyAus(mt().dok.inhalt(), mt().lodJetzt);
    // Auswahl, die es nicht mehr gibt, faellt weg
    w::PAuswahl a = z.auswahl;
    const auto gut = [&](int p) { return p >= 0 && uz(p) < z.netz.punkte.size(); };
    a.punkte.erase(std::remove_if(a.punkte.begin(), a.punkte.end(), [&](int p) { return !gut(p); }), a.punkte.end());
    a.kanten.erase(std::remove_if(a.kanten.begin(), a.kanten.end(), [&](const std::pair<int, int>& e) { return !gut(e.first) || !gut(e.second) || z.netz.kanteVon(e.first, e.second) < 0; }),
                   a.kanten.end());
    a.flaechen.erase(std::remove_if(a.flaechen.begin(), a.flaechen.end(), [&](int f) { return f < 0 || uz(f) >= z.netz.flaechen.size(); }), a.flaechen.end());
    z.auswahl = a;
}

bool modellMeshWerkzeugStarten(MeshWerkzeug wz) {
    ModellTab& t = mt();
    ModellMesh& z = mz();
    if (z.kaestchenOffen) { modellMeshUebernehmen(false); }
    if (t.bereich != ModellBereich::Modellieren) { t.bereich = ModellBereich::Modellieren; }
    if (t.dok.inhalt().leer() && wz != MeshWerkzeug::Create) {
        melden(tr(Str::MdKeinModell));
        return false;
    }
    if (t.dok.inhalt().leer()) { (void)modellNeuesRequisit(); }
    modellMeshNetzAktualisieren();
    z.werkzeug = wz;
    z.basis = t.dok.inhalt();
    z.basisNetz = z.netz;
    z.basisAuswahl = z.auswahl;
    if (wz == MeshWerkzeug::Merge && z.art != 0 && z.punktFolge.size() < 2U) { z.punktFolge = z.auswahl.punkte; }
    if (hatBetrag(wz)) {
        z.betrag = wz == MeshWerkzeug::Connect || wz == MeshWerkzeug::LoopCut ? 0.0F : betragVorgabe(netzFuer(z.netz, wz), z.auswahl);
        if (wz == MeshWerkzeug::Bevel) { z.betrag = -z.betrag; }
    }
    if (wz == MeshWerkzeug::Weld && z.schwelle <= 0.0F) { z.schwelle = w::weldSchwelleVorgabe(netzFuer(z.netz, wz)); }
    if (wz == MeshWerkzeug::Slice) { z.schnittOrt = schnittVorgabe(netzFuer(z.netz, wz), z.auswahl, z.achse); }
    if (wz == MeshWerkzeug::Hinge) {   // eine gewaehlte Kante auf dem Rand der Auswahl ist das Scharnier, sonst die erste
        z.hingeNr = 0;
        const auto kanten = w::hingeKanten(z.netz, z.auswahl.flaechen);
        for (std::size_t i = 0; i < kanten.size(); ++i) {
            if (std::find(z.auswahl.kanten.begin(), z.auswahl.kanten.end(), kanten[i]) != z.auswahl.kanten.end()) { z.hingeNr = zi(i); }
        }
    }
    z.schritt = t.dok.aendern(tr(werkzeugName(wz)), [](modell::Inhalt&) {});
    z.kaestchenOffen = true;
    z.neuPlanen = true;
    modellMeshVorschau();
    return true;
}

void modellMeshVorschau() {
    ModellTab& t = mt();
    ModellMesh& z = mz();
    if (!z.kaestchenOffen) { return; }
    modell::Inhalt x = z.basis;
    if (z.neuPlanen) {
        z.planNetz = z.basisNetz;
        // mbvers: in der Pose dieses Bilds planen - sie gilt fuer den ganzen Plan, auch wenn die Animation weiterlaeuft
        z.planKnochen = werkzeugPose(z.werkzeug);
        z.planPose = w::inPose(z.planNetz, z.planKnochen);
        z.plan = planen(z.planNetz, z.basisAuswahl, x);
        z.neuPlanen = false;
        z.basisMitTeil = x;
    }
    x = z.basisMitTeil;
    w::PolyNetz n = z.planNetz;
    w::PAuswahl neu = z.basisAuswahl;
    if (!z.plan.abgelehnt()) {
        if (hatBetrag(z.werkzeug)) {
            z.betrag = std::clamp(z.betrag, z.plan.betragMin, z.plan.betragMax);
            w::betragAnwenden(n, z.plan, z.betrag);
        }
        neu = abschliessen(n, z.plan, x, z.planPose, z.planKnochen);
    }
    t.dok.vorschau([&](modell::Inhalt& in) { in = x; });
    modellMeshNetzAktualisieren();
    auswahlSetzen(neu);
    g_app->modelDirty = true;
}

void modellMeshUebernehmen(bool weiter) {
    ModellMesh& z = mz();
    if (!z.kaestchenOffen) { return; }
    const MeshWerkzeug wz = z.werkzeug;
    const bool abgelehnt = z.plan.abgelehnt();
    z.kaestchenOffen = false;
    z.werkzeug = MeshWerkzeug::Keins;
    if (abgelehnt) {
        (void)mt().dok.abbrechen(z.schritt);
        melden(format(Str::MdAbgelehnt, tr(werkzeugName(wz)), ablehnung(z.plan.grund).c_str()));
        auswahlSetzen(z.basisAuswahl);
        return;
    }
    ++z.befehle;
    z.letzterBefehl = tr(werkzeugName(wz));
    melden(format(Str::MdFertig, tr(werkzeugName(wz)), z.plan.geaendert));
    // "+" (WF tool caddy: Apply and continue): dasselbe Werkzeug noch einmal auf dem Ergebnis
    if (weiter) { (void)modellMeshWerkzeugStarten(wz); }
}

void modellMeshAbbrechen() {
    ModellMesh& z = mz();
    if (!z.kaestchenOffen) { return; }
    z.kaestchenOffen = false;
    z.werkzeug = MeshWerkzeug::Keins;
    (void)mt().dok.abbrechen(z.schritt);
    modellMeshNetzAktualisieren();
    auswahlSetzen(z.basisAuswahl);
    g_app->modelDirty = true;
}

