// Die Tasten: im UV-Editor (Maus darueber) alle; in der Ansicht im Bereich UV nur Blenders U (VIEW3D_MT_uv_map)
bool modellUvTasten() {
    ModellTab& t = mt();
    if (t.bereich != ModellBereich::Uv || ImGui::GetIO().WantTextInput) { return false; }
    const bool blender = blenderModus();
    ModellUv& u = uvz();
    if (!u.hover) {
        if (blender && ImGui::IsKeyChordPressed(ImGuiKey_U)) {
            u.menueOeffnen = true;
            return true;
        }
        return false;
    }
    if (blender && ImGui::IsKeyChordPressed(ImGuiKey_W)) {   // IMAGE_MT_uvs_context_menu
        u.kontextOeffnen = true;
        return true;
    }
    for (const UvAktion& a : aktionen()) {
        const ImGuiKeyChord c = blender ? a.blenderChord : a.maxChord;
        if (c != 0 && ImGui::IsKeyChordPressed(c)) {
            ausloesen(a);
            return true;
        }
    }
    return false;
}

