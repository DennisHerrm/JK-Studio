// --- Gruppen: die Flaechen, die eine Textur zeichnen -------------------------------------------------------------------

struct Gruppe {
    std::string shader;
    std::vector<int> teile;
    int dreiecke = 0;
};

std::string shaderVon(int teil) {
    if (teil >= 0 && uz(teil) < g_app->model.surfaces.size()) {
        // nach der Haut, wie die Vorschau: applySkin traegt den Shader der .skin in texture ein, die Datei behaelt ihren
        // (Sturmtruppler: "[nomaterial]" in der .glm, die Haut nennt torso_legs, helmet, armor ...)
        const GlmSurface& f = g_app->model.surfaces[uz(teil)];
        if (!f.texture.empty()) { return f.texture; }
        if (!f.shader.empty()) { return f.shader; }
    }
    const modell::Inhalt& in = mt().dok.inhalt();
    return teil >= 0 && uz(teil) < in.teile.size() ? in.teile[uz(teil)].shader : std::string();
}

std::vector<Gruppe> gruppen() {
    const modell::Inhalt& in = mt().dok.inhalt();
    const int stufe = mt().lodJetzt;
    std::vector<Gruppe> g;
    for (std::size_t i = 0; i < in.teile.size(); ++i) {
        const modell::Teil& t = in.teile[i];
        if (t.istTag() || uz(stufe) >= t.stufen.size() || t.stufen[uz(stufe)].dreiecke() == 0) { continue; }
        const std::string s = shaderVon(static_cast<int>(i));
        auto it = std::find_if(g.begin(), g.end(), [&](const Gruppe& x) { return x.shader == s; });
        if (it == g.end()) {
            g.push_back(Gruppe{s, {}, 0});
            it = g.end() - 1;
        }
        it->teile.push_back(static_cast<int>(i));
        it->dreiecke += t.stufen[uz(stufe)].dreiecke();
    }
    return g;
}

// Die Gruppe: gewaehlt, sonst die der ersten gewaehlten Flaeche oder Ecke, sonst die groesste
int gruppeJetzt(const std::vector<Gruppe>& g) {
    if (g.empty()) { return -1; }
    const ModellUv& u = uvz();
    if (u.gruppe >= 0 && uz(u.gruppe) < g.size()) { return u.gruppe; }
    const ModellTab& t = mt();
    int teil = -1;
    if (!t.eckenWahl.empty()) {
        teil = t.eckenWahl.front().teil;
    } else if (!t.auswahl.empty()) {
        teil = t.auswahl.front();
    }
    for (std::size_t i = 0; teil >= 0 && i < g.size(); ++i) {
        if (std::find(g[i].teile.begin(), g[i].teile.end(), teil) != g[i].teile.end()) { return static_cast<int>(i); }
    }
    int beste = 0;
    for (std::size_t i = 1; i < g.size(); ++i) {
        if (g[i].dreiecke > g[uz(beste)].dreiecke) { beste = static_cast<int>(i); }
    }
    return beste;
}

// --- Auswahl: die Ecken des Model-Tabs <-> Halbkanten des Netzes ---------------------------------------------------

w::UvAuswahl auswahlAus(const w::UvNetz& n) {
    const ModellTab& t = mt();
    w::UvAuswahl a;
    a.ebene = static_cast<w::UvEbene>(std::clamp(uvz().ebene, 0, 3));
    a.ecke.assign(uz(n.kanten()), 0);
    std::set<std::pair<int, int>> wahl;
    for (const modell::EckOrt& o : t.eckenWahl) { wahl.insert({o.teil, o.ecke}); }
    std::set<int> flaechen(t.auswahl.begin(), t.auswahl.end());
    const bool ganzeFlaechen = wahl.empty();
    for (int h = 0; h < n.kanten(); ++h) {
        const int teil = n.teile[uz(n.teil[uz(h)])];
        a.ecke[uz(h)] = (ganzeFlaechen ? flaechen.count(teil) != 0 : wahl.count({teil, n.ecke[uz(h)]}) != 0) ? 1 : 0;
    }
    return a;
}

std::vector<modell::EckOrt> eckenVonHalbkanten(const w::UvNetz& n, const std::vector<int>& kanten) {
    std::set<std::pair<int, int>> s;
    for (const int h : kanten) { s.insert({n.teile[uz(n.teil[uz(h)])], n.ecke[uz(h)]}); }
    std::vector<modell::EckOrt> aus;
    for (const auto& [teil, ecke] : s) { aus.push_back(modell::EckOrt{teil, ecke}); }
    return aus;
}

// wie die 3D-Ansicht (eckenWahlAendern): Blender Umschalt schaltet um, 3ds Max Strg dazu und Alt weg
void wahlAendern(const std::vector<modell::EckOrt>& treffer) {
    ModellTab& t = mt();
    const ImGuiIO& io = ImGui::GetIO();
    const bool blender = blenderModus();
    const bool dazu = blender ? io.KeyShift : io.KeyCtrl;
    const bool weg = !blender && io.KeyAlt;
    const auto gleich = [](const modell::EckOrt& x, const modell::EckOrt& y) { return x.teil == y.teil && x.ecke == y.ecke; };
    const auto drin = [&](const modell::EckOrt& o) { return std::any_of(t.eckenWahl.begin(), t.eckenWahl.end(), [&](const modell::EckOrt& x) { return gleich(o, x); }); };
    const bool alleDrin = blender && dazu && !treffer.empty() && std::all_of(treffer.begin(), treffer.end(), drin);
    if (!dazu && !weg) {
        t.eckenWahl.clear();
        t.auswahl.clear();
    }
    for (const modell::EckOrt& o : treffer) {
        const auto it = std::find_if(t.eckenWahl.begin(), t.eckenWahl.end(), [&](const modell::EckOrt& x) { return gleich(o, x); });
        if (weg || alleDrin) {
            if (it != t.eckenWahl.end()) { t.eckenWahl.erase(it); }
        } else if (it == t.eckenWahl.end()) {
            t.eckenWahl.push_back(o);
        }
    }
    g_app->modelDirty = true;
}

// Die Ebene des UV-Editors und die Unterobjekte der Ansicht gleich (Blender: UV Sync Selection; Max: Unterobjekt-Ebene)
void ebeneSetzen(int e) {
    ModellTab& t = mt();
    uvz().ebene = std::clamp(e, 0, 3);
    static const AuswahlArt kArt[4] = {AuswahlArt::Ecke, AuswahlArt::Kante, AuswahlArt::Dreieck, AuswahlArt::Element};
    t.auswahlArt = kArt[uvz().ebene];
    t.editArt = t.auswahlArt;
    g_app->modelDirty = true;
}

// --- Arbeitsnetz ---------------------------------------------------------------------------------------------------

std::vector<int> teileJetzt() {
    const std::vector<Gruppe> g = gruppen();
    const int i = gruppeJetzt(g);
    return i >= 0 ? g[uz(i)].teile : std::vector<int>{};
}

int bildBreite(int teil) {
    const auto& b = g_app->modelTextures.bySurface;
    return teil >= 0 && uz(teil) < b.size() && b[uz(teil)].width > 0 ? b[uz(teil)].width : 1024;
}

w::UvKontext kontext(const w::UvNetz& n) {
    const ModellUv& u = uvz();
    w::UvKontext k;
    k.methode = static_cast<w::UvMethode>(std::clamp(u.methode, 0, 1));
    // REST M9: die Vorderseite der Figur wie Rig, IK und Retarget (modell::figurVorn: die Richtung der Gesichtsknochen
    // vom Kopf, sonst -Y wie die Figuren der Spiele) - bis hier fest +Y, die "verdeckten" Naehte lagen vorn
    float vorn[3] = {0.0F, -1.0F, 0.0F};
    if (!g_app->anim.empty()) { modell::figurVorn(g_app->anim, modell::erkenneKnochen(g_app->anim), vorn); }
    k.vorn = w::V3{vorn[0], vorn[1], vorn[2]};
    k.oben = w::V3{0.0F, 0.0F, 1.0F};
    // das Raster der Packung und der Dichte: die Breite der Textur (WF: die Aufloesung der Karte)
    k.aufloesung = n.teile.empty() ? 1024 : bildBreite(n.teile.front());
    k.abstand = u.abstand;
    k.drehen = u.drehen;
    k.spiegeln = u.spiegeln;
    k.spiegel = w::punktSpiegel(n, 0.1F);   // kSpiegelToleranz der Weights (app_modelltab_ansicht.cpp)
    std::vector<int> eltern;
    for (const GlaBone& b : g_app->anim.bones) { eltern.push_back(b.parent); }
    if (!g_app->anim.bones.empty()) {
        const modell::Erkennung e = modell::erkenneKnochen(g_app->anim, mt().dok.inhalt().rig.zuordnung, &mt().dok.inhalt(), mt().lodJetzt);
        std::vector<modell::Rolle> rollen;
        for (const modell::KnochenErkennung& x : e.knochen) { rollen.push_back(x.rolle); }
        k.faltung = w::knochenFaltung(rollen, eltern, &k.glieder);
    }
    return k;
}

std::string netzSchluessel() {
    const ModellTab& t = mt();
    std::string s = std::to_string(t.dok.stand()) + "|" + std::to_string(t.lodJetzt) + "|" + g_app->modelPath + "|" + std::to_string(g_app->modelSkinIndex) + "|";
    for (const int i : teileJetzt()) { s += std::to_string(i) + ","; }
    return s;
}

