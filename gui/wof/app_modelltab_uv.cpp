const char* tasteVon(const UvAktion& a) { return blenderModus() ? a.blenderTaste : a.maxTaste; }

std::string aktionText(const UvAktion& a) {
    std::string s = tr(a.text);
    const char* k = tasteVon(a);
    if (k[0] != '\0') { s += std::string(" (") + k + ")"; }
    return s;
}

void ausloesen(const UvAktion& a) {
    if (mt().bereich != ModellBereich::Uv) {
        mt().bereich = ModellBereich::Uv;   // eine UV-Aktion von woanders (Suche, Menue) fuehrt in den Bereich UV
    }
    a.tun();
    ++mt().tastenZaehler;
    mt().letzteTaste = tr(a.text);
    g_app->modelDirty = true;
}

std::string tooltip(const UvAktion& a) {
    std::string s = tr(a.hinweis);
    const char* k = tasteVon(a);
    if (k[0] != '\0') { s += "\n" + format(Str::UvTasteHint, k); }
    return s;
}

void alsMenue(int nurGruppe) {
    static const Str kGruppen[6] = {Str::UvGrAuswahl, Str::UvGrNaehte, Str::UvGrAbwickeln, Str::UvGrAnordnen, Str::UvGrSchnell, Str::UvGrAnzeige};
    const auto& liste = aktionen();
    int gruppe = -1;
    bool unter = false;
    for (std::size_t i = 0; i < liste.size(); ++i) {
        const UvAktion& a = liste[i];
        if (nurGruppe >= 0 && a.gruppe != nurGruppe) { continue; }
        if (a.gruppe != gruppe) {
            if (unter) { ImGui::EndMenu(); }
            unter = false;
            gruppe = a.gruppe;
            if (nurGruppe < 0) {
                // jede Gruppe ein Untermenue: Platz nur, wenn noetig (wie die Weights im Rechtsklick)
                unter = ui::menue(tr(kGruppen[uz(gruppe)]));
                if (!unter) {
                    while (i + 1 < liste.size() && liste[i + 1].gruppe == gruppe) { ++i; }
                    continue;
                }
            }
        }
        ImGui::PushID(static_cast<int>(i));
        const char* k = tasteVon(a);
        if (ImGui::MenuItem(tr(a.text), k[0] != '\0' ? k : nullptr, a.an ? a.an() : false)) { ausloesen(a); }
        ImGui::SetItemTooltip("%s", tooltip(a).c_str());
        ImGui::PopID();
    }
    if (unter) { ImGui::EndMenu(); }
}

// Ein Knopf einer Aktion (Rollout, Leiste) mit Tooltip und Taste
bool knopf(Str text, float breite = 0.0F) {
    const auto& liste = aktionen();
    const auto it = std::find_if(liste.begin(), liste.end(), [&](const UvAktion& a) { return a.text == text; });
    const bool an = it != liste.end() && it->an && it->an();
    if (an) { ImGui::PushStyleColor(ImGuiCol_Button, ImGui::GetStyleColorVec4(ImGuiCol_ButtonActive)); }
    const bool k = ImGui::Button(tr(text), ImVec2{breite, 0.0F});
    if (an) { ImGui::PopStyleColor(); }
    if (it != liste.end()) {
        ImGui::SetItemTooltip("%s", tooltip(*it).c_str());
        if (k) { ausloesen(*it); }
    }
    return k;
}

