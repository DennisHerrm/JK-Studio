// --- 3D-Ansicht: Naehte auf dem Modell ----------------------------------------------------------------------------

const std::vector<std::array<int, 3>>& modellUvNahtStriche() {
    static std::vector<std::array<int, 3>> striche;
    static std::string fuer;
    ModellUv& u = uvz();
    if (mt().bereich != ModellBereich::Uv || g_app->model.empty()) {
        striche.clear();
        fuer.clear();
        return striche;
    }
    modellUvNetzAktualisieren();
    if (fuer == u.fuer && u.zug == 0) { return striche; }   // waehrend eines Zugs wandern die Naehte nicht, das Netz aber
    striche.clear();
    const w::UvNetz& n = u.netz;
    for (int h = 0; h < n.kanten(); ++h) {
        const int g = n.gegen[uz(h)];
        if (n.naht[uz(h)] == 0 || (g >= 0 && g < h)) { continue; }
        striche.push_back({n.teile[uz(n.teil[uz(h)])], n.ecke[uz(h)], n.ecke[uz(w::UvNetz::naechste(h))]});
    }
    fuer = u.fuer;
    return striche;
}

