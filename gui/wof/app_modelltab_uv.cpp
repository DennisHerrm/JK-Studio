// Einen Befehl auf dem Arbeitsnetz ausfuehren und als EINEN Rueckgaengig-Schritt ins Dokument (WF CommitUvEdit: ohne
// Aenderung kein Schritt); die gewaehlten Halbkanten bleiben gewaehlt (auch die neuen Ecken an Naehten).
void meldungZeigen(const w::UvAntwort& a, const w::UvNetz& n);

bool befehl(Str name, const std::function<w::UvAntwort(w::UvNetz&, const w::UvAuswahl&, const w::UvKontext&)>& f) {
    ModellTab& t = mt();
    ModellUv& u = uvz();
    if (g_app->model.empty()) { return false; }
    modellUvNetzAktualisieren();
    modell::Inhalt kopie = t.dok.inhalt();
    w::UvNetz n = w::netzAus(kopie, teileJetzt(), t.lodJetzt);
    if (n.kanten() == 0) {
        melden(tr(Str::UvKeineFlaeche));
        return false;
    }
    const w::UvAuswahl a = auswahlAus(n);
    const w::UvKontext k = kontext(n);
    const w::UvNetz vorher = n;
    const w::UvAntwort r = f(n, a, k);
    ++u.befehle;
    u.letzterBefehl = tr(name);
    if (r.abgewiesen()) {
        meldungZeigen(r, n);
        return false;
    }
    const bool gleich = vorher.uv.size() == n.uv.size() && std::memcmp(vorher.uv.data(), n.uv.data(), n.uv.size() * sizeof(w::V2)) == 0 && vorher.naht == n.naht &&
                        vorher.pin == n.pin && vorher.frei == n.frei;
    if (gleich) {
        melden(format(Str::UvNichtsGeaendert, tr(name)));
        return false;
    }
    w::ZurueckBericht br;
    const modell::Grenzen& g = modell::grenzen(static_cast<modell::Zielspiel>(t.zielspiel));
    if (!w::zurueckschreiben(n, kopie, g.eckenJeFlaeche, &br)) {
        melden(format(Str::UvGrenze, br.teil >= 0 && uz(br.teil) < kopie.teile.size() ? kopie.teile[uz(br.teil)].name.c_str() : "?", br.ecken, g.name, br.grenze));
        return false;
    }
    std::vector<int> gewaehlt;
    for (int h = 0; h < n.kanten(); ++h) {
        if (a.ecke[uz(h)] != 0) { gewaehlt.push_back(h); }
    }
    t.dok.aendern(tr(name), [&](modell::Inhalt& x) { x = std::move(kopie); });
    // die Auswahl ueber die Halbkanten neu (eine geteilte Ecke hat jetzt zwei Nummern)
    modellUvNetzAktualisieren();
    if (!t.eckenWahl.empty()) { t.eckenWahl = eckenVonHalbkanten(u.netz, gewaehlt); }
    meldungZeigen(r, u.netz);
    g_app->modelDirty = true;
    return true;
}

void meldungZeigen(const w::UvAntwort& a, const w::UvNetz& n) {
    const modell::Inhalt& in = mt().dok.inhalt();
    const auto teilName = [&](int ti) {
        const int t = ti >= 0 && uz(ti) < n.teile.size() ? n.teile[uz(ti)] : -1;
        return t >= 0 && uz(t) < in.teile.size() ? in.teile[uz(t)].name : std::string("?");
    };
    switch (a.meldung) {
        case w::UvMeldung::NichtsGewaehlt: melden(tr(Str::UvMNichtsGewaehlt)); return;
        case w::UvMeldung::KeineNaehte: melden(tr(Str::UvMKeineNaehte)); return;
        case w::UvMeldung::NichtsZuTun: melden(tr(Str::UvMNichtsZuTun)); return;
        case w::UvMeldung::Geschlossen: melden(format(Str::UvMGeschlossen, teilName(a.zahl).c_str())); return;
        case w::UvMeldung::OffenGeblieben: melden(format(Str::UvMOffenGeblieben, teilName(a.zahl).c_str())); return;
        case w::UvMeldung::DateiNaehteGeloescht: melden(format(Str::UvMDateiNaehte, a.zahl, a.andere)); return;
        case w::UvMeldung::KeineGlieder: melden(tr(Str::UvMKeineGlieder)); return;
        case w::UvMeldung::NichtGleich: melden(format(Str::UvMNichtGleich, a.zahl, a.andere)); return;
        case w::UvMeldung::KeinGegenstueck: melden(tr(Str::UvMKeinGegenstueck)); return;
        case w::UvMeldung::KeinRechteck: melden(format(Str::UvMKeinRechteck, a.zahl)); return;
        case w::UvMeldung::KeineFormKarten: melden(tr(Str::UvMKeineFormKarten)); return;
        case w::UvMeldung::NichtGesetzt: melden(format(Str::UvMNichtGesetzt, a.zahl)); return;
        case w::UvMeldung::KachelnAbgewiesen: melden(tr(Str::UvMKacheln)); return;
        case w::UvMeldung::Ungeloest: melden(format(Str::UvMUngeloest, a.zahl)); return;
        case w::UvMeldung::Keine: break;
    }
    const ModellUv& u = uvz();
    melden(format(Str::UvFertig, u.letzterBefehl.c_str(), u.inseln.zahl, static_cast<double>(u.mass.winkelGrad), static_cast<double>(u.mass.flaeche),
                  static_cast<double>(u.mass.dichteMedian)));
}

