bool modellMd3Oeffnen(const std::string& bytes, const std::string& name, std::string* fehler) {
    Md3Model m;
    if (!readMd3(bytes, m, fehler)) { return false; }
    modell::Inhalt in;
    modell::ausMd3(m, in, 0);
    in.md3Datei = std::make_shared<const std::string>(bytes);
    GlmModel gm = modell::zuGlm(in, 0);
    for (std::size_t i = 0; i < gm.surfaces.size() && i < m.surfaces.size(); ++i) { gm.surfaces[i].shader = m.surfaces[i].shader; }
    g_app->model = std::move(gm);
    g_app->modelPath = name;
    g_app->modelDir = directoryOf(name);
    modellEnt3aVorLaden(bytes, in);   // ENTSCHEID3A (E3): der Stapel aus der Begleitdatei neben der .md3 (Fehler: ohne, mit Meldung)
    ModellTab& t = mt();
    in.kinoBelegung = t.dok.inhalt().kinoBelegung;   // REST N10: die Belegung der Ziel-GLA bleibt
    t.dok.laden(std::move(in));
    modellEnt3aNachLaden();   // ENTSCHEID3A (B11, E3): der Inhalt wie geladen (Auge von Edit Poly), Meldung zur Begleitdatei
    t.dokModell = name;
    t.g2 = modell::G2Zustand{};
    t.verstecktTeil.clear();
    t.verstecktKnochen.clear();
    ++t.verstecktStand;
    t.hautAus.clear();
    t.anzeigeSchluessel.clear();
    t.auswahl.clear();
    t.eckenWahl.clear();
    t.knochenWahl = -1;
    t.tagWahl = -1;
    t.anbauten.clear();
    t.speicherPfad.clear();
    t.gespeichertStand = -1;
    uvz().fuer.clear();
    g_app->modelDirty = true;
    return true;
}

