void modellUvNetzAktualisieren() {
    ModellUv& u = uvz();
    const std::string s = netzSchluessel();
    if (s == u.fuer && u.zug == 0) { return; }
    if (u.zug != 0) { return; }   // waehrend des Ziehens gilt das gezogene Netz
    u.fuer = s;
    u.netz = w::netzAus(mt().dok.inhalt(), teileJetzt(), mt().lodJetzt);
    u.inseln = w::inselnBauen(u.netz);
    w::PruefOptionen po;
    po.aufloesung = u.netz.teile.empty() ? 1024 : bildBreite(u.netz.teile.front());
    u.befunde = w::pruefen(u.netz, u.inseln, po);
    u.mass = w::messen(u.netz, u.inseln, po.aufloesung);
    u.dehnung = w::dreieckDehnung(u.netz, u.inseln);
}

